def _接触高度(h, k):
    """式6-1/6-2 的接触高度 k：给 k 就用 k（半圆键按标准查，k≠h/2）；
    否则由 k≈0.5h 得 k。两者都没给时抛 ValueError。"""
    if k is not None:
        return k
    if h is None:
        raise ValueError("需给键高 h（k≈0.5h）或接触高度 k")
    return 0.5 * h


def _要求正数(**项):
    """分母/参数为 0 或负时报错（公式只在物理正值的区间有意义）。"""
    for 名, 值 in 项.items():
        if 值 is None or 值 <= 0:
            raise ValueError("%s 必须为正，收到 %r" % (名, 值))


def eq6_1(T, d, l, h=None, k=None):
    """
    式(6-1) 普通平键（静连接）的挤压强度条件：
        σbs = 2000T/(kld) = 4000T/(hld) ≤ [σbs]

    适用条件：普通平键连接（静连接），假定载荷在键的工作面上均匀分布；
    主要失效形式是工作面被压溃，故通常只按工作面挤压应力校核（除非严重
    过载，一般不校键的剪断）。半圆键的强度条件同此式，但 k 按标准查取
    （k≠h/2）、l≈L（见 ``半圆键工作长度说明``）。
    T: 传递的转矩，**N·m**（课本 T=Fy≈F d/2；分子 2000/4000 就是把 N·m 与
       mm 换算成 MPa 的系数，不是 2/4，T 直接按 N·m 代入）；
    d: 轴的直径，mm；
    l: 键的工作长度，mm（圆头平键 l=L-b、单圆头 l=L-0.5b、平头 l=L，
       见 ``平键工作长度``；双键按 1.5 个键折算，见 ``双键折算工作长度``）；
    h: 键的高度，mm（给 h 时按 k≈0.5h 换算；两式等价：
       2000T/(kld)=4000T/(hld)）；
    k: 键与轮毂键槽的接触高度，mm（k≈h/2；半圆键按标准查，k≠h/2）。
       同时给 h 与 k 时以 k 为准。
    返回 σbs，MPa。分母含 0 或负值时抛 ValueError。
    [核:p115]
    """
    kk = _接触高度(h, k)
    _要求正数(T=T, d=d, l=l, k=kk)
    return 2000.0 * T / (kk * l * d)


def eq6_2(T, d, l, h=None, k=None):
    """
    式(6-2) 导向平键/滑键（动连接）的压力条件性强度校核：
        p = 2000T/(kld) = 4000T/(hld) ≤ [p]

    适用条件：导向平键连接和滑键连接（动连接）——工作面有相对滑动，主要
    失效形式是工作面过度磨损，故按工作面上的压力 p（不是挤压应力 σbs）做
    条件性校核；假定载荷在键的工作面上均匀分布。分母与式(6-1) 完全相同，
    同一组 T、k（或 h）、l、d 下本函数与 ``eq6_1`` 的数值严格相等，只因
    左端符号与右端许用值不同而含义不同（[p] 见 ``查表6_2`` 的动连接列）。
    T: 传递的转矩，N·m（2000/4000 为 N·m+mm→MPa 的换算系数）；
    d: 轴的直径，mm；l: 键的工作长度，mm；
    h: 键的高度，mm（按 k≈0.5h）；k: 接触高度，mm（同时给 h 与 k 时以 k 为准）。
    返回 p，MPa。分母含 0 或负值时抛 ValueError。
    [核:p115]
    """
    kk = _接触高度(h, k)
    _要求正数(T=T, d=d, l=l, k=kk)
    return 2000.0 * T / (kk * l * d)


# ------------------------------------------------ 楔键 / 切向键（非编号）
def 楔键压力合力F(T, b, d, f):
    """
    楔键简化计算：工作面上压力合力 F（**非编号式，p.116**）。

    适用条件：楔键连接简化计算——把键和轴视为一体，将下方分布在半圆柱面
    上的径向压力用集中力 F 代替；假设压力沿键长均匀分布、沿键宽为三角形
    分布，取偏心距 x≈b/6、y≈d/2；由键和轴一体对轴心的受力平衡
    T = Fx + fFy + fF d/2 得课本印刷式
        F = T/(x+fy+f d/2) = 6T/(b+6fd)
    T: 传递的转矩，N·m；b: 键的宽度，mm；d: 轴的直径，mm；
    f: 摩擦因数，一般取 0.12~0.17。
    返回 F，**N**。注意：印刷式 6T/(b+6fd) 在 T 用 N·m、b/d 用 mm 直接
    代入时，数值上是 **kN**（课本随后在式6-3 里乘 10³ 还原），本库统一乘
    1000 返回 N，使 2F/(bl) 直接得 MPa（与式6-3 的 12×10³T 一致）。
    [核:p116]
    """
    _要求正数(T=T, b=b, d=d, f=f)
    if f <= 0:
        raise ValueError("f 必须为正，收到 %r" % (f,))
    return 1000.0 * 6.0 * T / (b + 6.0 * f * d)


def eq6_3(T, b, l, f, d):
    """
    式(6-3) 楔键连接的挤压强度条件：
        σbs = 2F/(bl) = 12×10³T/(bl(b+6fd)) ≤ [σbs]

    适用条件：楔键连接；主要失效形式是相互楔紧的工作面被压溃，故校核各
    工作面的抗挤压强度（图6-8）；上下两个工作面各受合力 F，故乘 2。
    T: 传递的转矩，N·m（分子 12×10³ 是 N·m+mm→MPa 的换算）；
    b: 键的宽度，mm；l: 键的工作长度，mm；d: 轴的直径，mm；
    f: 摩擦因数，一般取 0.12~0.17。
    返回 σbs，MPa。与 ``2*楔键压力合力F(T,b,d,f)/(b*l)`` 严格相等。
    [核:p117]
    """
    _要求正数(T=T, b=b, l=l, d=d, f=f)
    return 12.0e3 * T / (b * l * (b + 6.0 * f * d))


def 切向键压力合力F(T, d, f):
    """
    切向键简化计算：工作面上压力合力 F（**非编号式，p.117**）。

    适用条件：切向键连接简化计算——把键和轴看成一体，假定压力在键的工作
    面上均匀分布，取压力合力作用点距轴心的径向距离 y=(d-t)/2、键槽深度
    t=d/10（故 y=0.45d）；按一个切向键、由键和轴一体对轴心的受力平衡
    T = fF d/2 + Fy 得课本印刷式
        F = T/(f d/2+y) = T/(d(0.5f+0.45))
    T: 传递的转矩，N·m；d: 轴的直径，mm；f: 摩擦因数，一般取 0.12~0.17。
    返回 F，**N**。印刷式直接代入时数值上是 kN，本库乘 1000 返回 N
    （理由同 ``楔键压力合力F``，与式6-4 的 ×10³ 一致）。
    [核:p117]
    """
    _要求正数(T=T, d=d, f=f)
    return 1000.0 * T / (d * (0.5 * f + 0.45))


def eq6_4(T, d, l, t, C, f):
    """
    式(6-4) 切向键连接的挤压强度条件：
        σbs = F/((t-C)l) = T×10³/((t-C)dl(0.5f+0.45)) ≤ [σbs]

    适用条件：切向键连接；主要失效形式是工作面被压溃；承压面积取 (t-C)l
    （扣去键的倒角 C）。承压高度是 (t-C) 而不是键高 h，这是切向键与平键
    式(6-1) 的关键差别。
    T: 传递的转矩，N·m（分子 10³ 为 N·m+mm→MPa 的换算）；
    d: 轴的直径，mm；l: 键的工作长度，mm；
    t: 键槽的深度，mm（课本简化计算取 t=d/10）；
    C: 键的倒角尺寸，mm；
    f: 摩擦因数，一般取 0.12~0.17。
    返回 σbs，MPa。(t-C)≤0 时抛 ValueError。
    [核:p117]
    """
    _要求正数(T=T, d=d, l=l, f=f)
    if t - C <= 0:
        raise ValueError("式6-4 的承压高度 (t-C) 必须为正，收到 t=%r、C=%r"
                         % (t, C))
    return T * 1.0e3 / ((t - C) * d * l * (0.5 * f + 0.45))


# ---------------------------------------------------------------- 花键
def 矩形花键参数(D, d, C):
    """
    矩形花键的齿侧工作高度 h 与平均直径 d_m（**非编号，p.120 符号说明**）。

    适用条件：矩形花键（图6-13）；h=(D-d)/2-2C；d_m=(D+d)/2。
    D: 外花键大径，mm；d: 内花键小径，mm；C: 倒角尺寸，mm。
    返回 (h, d_m)，mm。h≤0 时抛 ValueError。
    [核:p120]
    """
    h = (D - d) / 2.0 - 2.0 * C
    if h <= 0:
        raise ValueError("矩形花键工作高度 h=(D-d)/2-2C 必须为正，收到 %r"
                         % (h,))
    return h, (D + d) / 2.0


def 渐开线花键参数(m, α, d_i):
    """
    渐开线花键的齿侧工作高度 h 与平均直径 d_m（**非编号，p.120 符号说明**）。

    适用条件：渐开线花键；α=30° 时 h=m，α=45° 时 h=0.8m；d_m=d_i
    （d_i 为分度圆直径）。
    m: 模数，mm；α: 压力角，**度（°）**（课本只给 30° 与 45° 两种）；
    d_i: 分度圆直径，mm。
    返回 (h, d_m)，mm。α 不是 30 或 45 时抛 ValueError（课本未给其它取值）。
    [核:p120]
    """
    if abs(α - 30.0) < 1e-9:
        h = float(m)
    elif abs(α - 45.0) < 1e-9:
        h = 0.8 * m
    else:
        raise ValueError("渐开线花键课本只给 α=30°（h=m）与 α=45°（h=0.8m），"
                         "收到 α=%r" % (α,))
    return h, float(d_i)


def eq6_5(T, ψ, z, h, l, d_m):
    """
    式(6-5) 花键连接（静连接）的挤压强度条件：
        σbs = 2000T/(ψzhld_m) ≤ [σbs]

    适用条件：花键连接的静连接；主要失效形式为工作面被压溃，按工作面挤压
    应力计算；假定载荷在键的工作面上均匀分布，再以载荷分配不均系数 ψ 修正
    各齿分配不均。
    T: 传递的转矩，N·m（2000 为 N·m+mm→MPa 的换算；p.119 正文 T=zF d_m/2）；
    ψ: 载荷分配不均系数，一般取 0.7~0.8，齿数多时取偏小值（无量纲）；
    z: 花键的齿数；
    h: 花键齿侧面的工作高度，mm（矩形花键 h=(D-d)/2-2C，见 ``矩形花键参数``；
       渐开线 α=30° 时 h=m、α=45° 时 h=0.8m，见 ``渐开线花键参数``）；
    l: 齿的工作长度，mm；
    d_m: 花键的平均直径，mm（矩形 d_m=(D+d)/2；渐开线 d_m=d_i）。
    返回 σbs，MPa。分母含 0 或负值时抛 ValueError。
    注：p.119 指出高速重载（如直升机主减速器）中花键静连接也会发生微动磨损，
    需按微动疲劳强度计算（课本只给文献[25]，无式）。
    [核:p120]
    """
    _要求正数(T=T, ψ=ψ, z=z, h=h, l=l, d_m=d_m)
    return 2000.0 * T / (ψ * z * h * l * d_m)


def eq6_6(T, ψ, z, h, l, d_m):
    """
    式(6-6) 花键连接（动连接）的压力条件性强度条件：
        p = 2000T/(ψzhld_m) ≤ [p]

    适用条件：花键连接的动连接（工作面有相对滑动）；主要失效形式为工作面
    过度磨损，故按工作面上的压力 p 做条件性强度计算。分母与式(6-5) 逐字
    相同（ψ z h l d_m），同一组参数下本函数与 ``eq6_5`` 数值严格相等，区别
    只在左端符号与右端许用值（[p] 见 ``查表6_3``）。
    T: 传递的转矩，N·m；ψ: 载荷分配不均系数（0.7~0.8）；z: 齿数；
    h: 齿侧工作高度，mm；l: 齿的工作长度，mm；d_m: 平均直径，mm
    （h、d_m 取法同式6-5）。
    返回 p，MPa。分母含 0 或负值时抛 ValueError。
    [核:p120]
    """
    _要求正数(T=T, ψ=ψ, z=z, h=h, l=l, d_m=d_m)
    return 2000.0 * T / (ψ * z * h * l * d_m)



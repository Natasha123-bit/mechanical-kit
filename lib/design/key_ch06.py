def _区间(文本):
    """把表里的 "a~b" / "a" 解析成 (a, b) 浮点二元组（"50"→(50.0, 50.0)）。"""
    if 文本 is None:
        return None
    s = str(文本).strip()
    if "~" in s:
        lo, hi = s.split("~")
        return float(lo), float(hi)
    v = float(s)
    return v, v


def _档号(文本):
    """把轴径档 "6~8" / ">8~10" 解析成 (下限, 上限, 左端是否含)。"""
    s = str(文本).strip()
    含左 = not s.startswith(">")
    lo, hi = s.lstrip(">").split("~")
    return float(lo), float(hi), 含左


def 查表6_1(d):
    """
    按轴径 d 查表6-1 的普通平键截面尺寸与键长范围（**分档查，档内不插值**）。

    表6-1 表注：d 单位为 mm；第一档 6~8 两端含，其余档 ">下限~上限" 左开右闭。
    d: 轴的直径，mm。
    返回 dict：{"档", "b", "h", "L_min", "L_max"}（b、h、L_min、L_max 均为
    float，d 落在档内即整档取同一组值，不做任何插值）。
    d 小于 6 或大于 130（表6-1 覆盖范围）时抛 ValueError。
    [核:p115]
    """
    for 档, 行 in zip(表6_1_平键尺寸["rows"], 表6_1_平键尺寸["data"]):
        lo, hi, 含左 = _档号(档)
        命中 = (lo <= d <= hi) if 含左 else (lo < d <= hi)
        if 命中:
            b, h = (float(x) for x in 行[0].split("×"))
            L_min, L_max = _区间(行[1])
            return {"档": 档, "b": b, "h": h,
                    "L_min": L_min, "L_max": L_max}
    raise ValueError("表6-1 只覆盖 6≤d≤130 mm，收到 d=%r" % (d,))


def 查平键尺寸(d, L=None):
    """
    按轴径 d 查表6-1 并（可选）把键长 L 圆整到“键的长度系列”的标准值。

    分档查、档内不插值：b、h 由 d 所在档唯一确定。
    L: 期望的键长，mm；给 None 时不做圆整，只返回档内的 L 范围。
    L 给定时：若 L 本身就在标准键长系列中且落在本档 [L_min, L_max] 内，
    原样返回；否则向下取“不超过 L 的最大标准键长”，并仍须落在本档范围内，
    否则抛 ValueError。这是**取标准值（向下圆整）**，不是插值——不产生系列
    外的数（例6-1：轮毂宽 100 → 取 L=90，90 在系列内）。
    返回 dict：在原 ``查表6_1`` 结果上增加 "L"（标准键长，未给 L 时为 None）
    与 "键长系列"（整条系列）。
    [核:p115]
    """
    结果 = 查表6_1(d)
    结果["L"] = None
    结果["键长系列"] = tuple(表6_1_平键尺寸["键长系列"])
    if L is None:
        return 结果
    候选 = [x for x in 表6_1_平键尺寸["键长系列"]
            if 结果["L_min"] <= x <= 结果["L_max"] and x <= L]
    if not 候选:
        raise ValueError("d=%r 档 (%s) 内没有不超过 L=%r 的标准键长"
                         % (d, 结果["档"], L))
    结果["L"] = float(max(候选))
    return 结果



def 平键工作长度(L, b, 型式="A"):
    """
    平键的工作长度 l（**非编号，p.115 式6-1 符号说明**）。

    适用条件：普通平键。圆头平键（A 型）l=L-b（两端各去半个圆弧）；
    单圆头平键（C 型）l=L-0.5b；平头平键（B 型）l=L。
    L: 键的公称长度，mm；b: 键的宽度，mm；
    型式: "A"/"圆头"（默认）、"B"/"平头"、"C"/"单圆头"。
    返回 l，mm。l≤0 时抛 ValueError。
    例6-1 易错点：b=20、L=90 的 A 型键 l=70，直接拿 L=90 代入会把应力算小。
    [核:p115]
    """
    型式 = {"圆头": "A", "圆头平键": "A", "平头": "B", "单圆头": "C"}.get(
        型式, 型式)
    if 型式 == "A":
        l = L - b
    elif 型式 == "B":
        l = L
    elif 型式 == "C":
        l = L - 0.5 * b
    else:
        raise ValueError("平键型式只有 A/B/C（圆头/平头/单圆头），收到 %r"
                         % (型式,))
    if l <= 0:
        raise ValueError("平键工作长度必须为正，收到 l=%r" % (l,))
    return l


def 双键折算工作长度(l单):
    """
    双键强度校核时的工作长度（**非编号，p.117 文字规定**）。

    适用条件：需要两个键的场合（强度不够且相差较大时）。考虑两键载荷分配
    不均匀，强度校核中**只按 1.5 个键计算**，故 l=1.5×l单。课本同时规定
    布置：两个平键最好沿周向相隔 180°，两个半圆键布置在轴的同一条母线上，
    两个楔键沿周向相隔 90°~120°；键长不宜超过 (1.6~1.8)d。
    l单: 单个键的工作长度，mm。
    返回 l，mm。本函数只实现课本给出的“两键→1.5”这一种折算，不推广到
    三个及以上键。
    例6-1：l=1.5×70=105 mm，σbs 由 149.7 降到 99.8 MPa（≤110，合适）。
    [核:p117]
    """
    if l单 <= 0:
        raise ValueError("l单 必须为正，收到 %r" % (l单,))
    return 1.5 * l单


def 平键标记(b, h, L, 型式="A"):
    """
    平键的标记写法（**非编号，例6-1 结论，p.118**）。

    适用条件：普通平键（GB/T 1096）。标记顺序为 宽×高×长（b×h×L）；
    一般 A 型键可不标出“A”，B 型或 C 型键须把“键”标为“键B”或“键C”。
    b、h、L: 键宽、键高、键长，mm；型式: "A"/"B"/"C"。
    返回标记字符串，如 "GB/T 1096 键 20×12×90"。
    例6-1 结论行只写标记，不含数量信息——实际按两件、相隔 180° 使用，
    数量须由前一步（双键）承接。
    [核:p118]
    """
    def _数(x):
        return str(int(x)) if abs(x - round(x)) < 1e-9 else ("%g" % x)

    if 型式 == "A":
        体 = "键"
    elif 型式 in ("B", "C"):
        体 = "键" + 型式
    else:
        raise ValueError("平键型式只有 A/B/C，收到 %r" % (型式,))
    return "GB/T 1096 %s %s×%s×%s" % (体, _数(b), _数(h), _数(L))



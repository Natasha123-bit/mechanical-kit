def 胀套当量轴向力(F_a, T, d):
    """
    式(6-9) 根号内的当量轴向力（**式6-9 的未编号子式**）：
        F_eq = √(F_a² + (2000T/d)²)

    适用条件：胀套连接同时传递转矩与轴向力时，把转矩折算为当量轴向力
    2000T/d 后与 F_a 按平方和合成（2000 使 T 以 N·m、d 以 mm 代入即得 N）。
    F_a: 传递的轴向力，N；T: 传递的转矩，N·m；d: 胀套内径，mm。
    返回 F_eq，N。d≤0 时抛 ValueError。
    F_a=0 时退化为 2000T/d；T=0 时退化为 F_a。
    [核:p122]
    """
    if d <= 0:
        raise ValueError("d 必须为正，收到 %r" % (d,))
    return math.hypot(F_a, 2000.0 * T / d)


def eq6_9(F_a, T, d, F_a额定):
    """
    式(6-9) 胀套连接选型条件之三（同时传递转矩和轴向力时）：
        √(F_a² + (2000T/d)²) ≤ [F_a]

    适用条件：胀套连接同时传递转矩与轴向力；转矩折算为当量轴向力 2000T/d，
    与 F_a 平方和合成后与一个胀套的额定轴向力比较（右端限值原文就是 [F_a]，
    不是另设的合成许用值）。
    F_a: 传递的轴向力，N；T: 传递的转矩，N·m；d: 胀套内径，mm；
    F_a额定: 一个胀套的额定轴向力 [F_a]，N。
    返回 bool：True 表示满足上式。F_a=0 时等价于 2000T/d≤[F_a]；T=0 时
    等价于 ``eq6_8``。
    [核:p122]
    """
    if F_a额定 <= 0:
        raise ValueError("[F_a] 必须为正，收到 %r" % (F_a额定,))
    return 胀套当量轴向力(F_a, T, d) <= F_a额定


def eq6_10(T额定, m=None, n=None, 型号="ZJ1"):
    """
    式(6-10) n 个胀套串联时的总额定转矩：
        [T_n] = m[T]

    适用条件：一个胀套满足不了要求时用两个以上胀套串联；单个胀套传递载荷的
    能力随数目增加而降低，故胀套不宜过多。m 由表6-4 按 n 与型号查取
    （m 不是 n 的简单倍数）。
    T额定: 一个胀套的额定转矩 [T]，N·m；
    m: 额定载荷系数（无量纲）；给 None 时按 n、型号 查表6-4；
    n: 连接中胀套的数量（查表时必给，1~4）；
    型号: "ZJ1" / "ZJ2" / "ZJ12"（表6-4 右半表原样写法）。
    返回 [T_n]，N·m。m 查表为 None（原表“—”或结构性缺格）时抛 ValueError。
    [核:p122]（m 的取值 [核:p123]）
    """
    if m is None:
        if n is None:
            raise ValueError("式6-10 需给 m，或给 n 与型号 以查表6-4")
        m = 查表6_4(n, 型号)
        if m is None:
            raise ValueError("表6-4 中 n=%r、型号=%r 一格无值（原表“—”或"
                             "左右分块缺格）" % (n, 型号))
    if T额定 <= 0:
        raise ValueError("[T] 必须为正，收到 %r" % (T额定,))
    return m * T额定



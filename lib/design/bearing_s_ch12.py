def 查表12_6_Cp(B_d: float, ε: float, 插值: bool = True) -> float:
    """表12-6 有限宽轴承的承载量系数 C_p，按 (B/d, ε) 查表 + 双向线性插值
    （配合式12-21、式12-23、式12-24） [核:p308]。

    适用条件：包角 180°、非承载区内无压力供油的有限宽径向滑动轴承
    （正文 p.307）。C_p 定义见式(12-23)。
    B_d: 宽径比 B/d（无量纲），表内 0.3~2.0 共 13 档；
    ε: 偏心率（无量纲），表内 0.3~0.99 共 14 档；
    插值: True（默认）在相邻 B/d 行、相邻 ε 列之间做双线性插值；False 时
          只接受恰在印刷格上的点，否则抛 ValueError。
    返回 C_p（量纲为一）。
    插值只取包围查询点的**表内四格**做双线性，绝不外推；B/d 或 ε 超范围
    抛 ValueError。表值本身不改写。
    例12-1：查表12_6_Cp(1.0, 0.714)=2.08 附近；反查见 反查表12_6_偏心率()。
    """
    i, j, tB = _定位(_CP_B_D, float(B_d), "B/d")
    k, l, tE = _定位(_CP_E, float(ε), "ε")
    if not 插值:
        if tB != 0.0 or tE != 0.0:
            raise ValueError("表12-6 无 (B/d=%.6g, ε=%.6g) 印刷格（插值=False）"
                             % (float(B_d), float(ε)))
        return _cp格(i, k)
    c00, c01 = _cp格(i, k), _cp格(i, l)
    c10, c11 = _cp格(j, k), _cp格(j, l)
    return ((1 - tB) * (1 - tE) * c00 + (1 - tB) * tE * c01
            + tB * (1 - tE) * c10 + tB * tE * c11)


def _cp行反查ε(行号: int, Cp: float) -> float:
    """在表12-6 的某一 B/d 行内，由 C_p 线性反查 ε（C_p 随 ε 单调增）。"""
    值 = [_cp格(行号, m) for m in range(len(_CP_E))]
    if Cp < 值[0] - 1e-12 or Cp > 值[-1] + 1e-12:
        raise ValueError("C_p=%.6g 不在表12-6 B/d=%.3g 行的 %.6g~%.6g 内"
                         "（不插值、不外推）"
                         % (Cp, _CP_B_D[行号], 值[0], 值[-1]))
    for m in range(len(_CP_E) - 1):
        c0, c1 = 值[m], 值[m + 1]
        if c0 - 1e-12 <= Cp <= c1 + 1e-12:
            if abs(c1 - c0) < 1e-15:
                return _CP_E[m]
            return _CP_E[m] + (Cp - c0) / (c1 - c0) * (_CP_E[m + 1] - _CP_E[m])
    return _CP_E[-1]


def 反查表12_6_偏心率(Cp: float, B_d: float) -> float:
    """表12-6 由承载量系数 C_p 与宽径比 B/d 反查偏心率 ε
    （配合式12-25：h_min=rψ(1−ε)） [核:p308]。

    适用条件：同 查表12_6_Cp()（包角 180°、非承载区无压力供油的有限宽轴承）。
    Cp: 承载量系数（无量纲），由式(12-23) 算出；
    B_d: 宽径比 B/d（无量纲），表内 0.3~2.0。
    返回 ε（无量纲，未圆整）。
    做法（例12-1 第(15)步“经过插值求出”）：先在 B/d 的上下两条印刷行内各自
    沿 ε 相邻格线性反查，再按 B/d 在两行之间线性插值；B/d 恰在印刷格上时
    只做一维反查。只在表内做，不外推。
    例12-1：Cp=2.075、B/d=1 → ε=0.7135，取三位小数 0.714。
    """
    i, j, tB = _定位(_CP_B_D, float(B_d), "B/d")
    εi = _cp行反查ε(i, float(Cp))
    if i == j or tB == 0.0:
        return εi
    εj = _cp行反查ε(j, float(Cp))
    return εi + tB * (εj - εi)



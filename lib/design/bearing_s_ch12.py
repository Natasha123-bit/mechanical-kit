def 系数ξ(B_d: float) -> float:
    """未编号辅助式（p.309，式12-28 下方）：ξ 随宽径比变化。

    B/d<1 时 ξ=(d/B)^(3/2)；B/d≥1 时 ξ=1。ξ 量纲为一。
    B_d: 宽径比 B/d。返回 ξ。
    非编号公式，只为 摩擦因数() 提供 ξ；不是本章编号式。
    [核:p309]
    """
    B_d = float(B_d)
    if B_d <= 0:
        raise ValueError("ξ 的宽径比 B/d 必须为正")
    return (1.0 / B_d) ** 1.5 if B_d < 1.0 else 1.0


def 摩擦因数(η: float, ω: float, ψ: float, p: float,
             B_d: float = 1.0) -> float:
    """未编号辅助式（p.309，式12-28 下方）：f = πηω/(ψp) + 0.55ψξ。

    适用条件：流体动力润滑径向滑动轴承的摩擦因数估算；ξ 随宽径比变化
    （B/d<1 时 ξ=(d/B)^(3/2)，B/d≥1 时 ξ=1）。
    η: 动力黏度，Pa·s；ω: 轴颈角速度，rad/s；ψ: 相对间隙；
    p: 轴承平均压力，Pa；
    B_d: 宽径比 B/d（默认 1，此时 ξ=1）。
    返回 f（量纲为一）。
    非编号公式（例12-1 第(19)步用它算 f=0.00258），不属于式12-27~12-32，
    docstring 不标式号，只标本页与用途。
    [核:p309]
    """
    if float(ψ) <= 0 or float(p) <= 0:
        raise ValueError("摩擦因数需要 ψ>0、p>0")
    return (math.pi * float(η) * float(ω) / (float(ψ) * float(p))
            + 0.55 * float(ψ) * 系数ξ(B_d))



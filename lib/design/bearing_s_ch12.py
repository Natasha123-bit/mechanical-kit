# 6. 12-7 节 最小油膜厚度判据与许用值 式(12-25) ~ 式(12-26)
# =====================================================================

def eq12_25(r: float, ψ: float, ε: float) -> float:
    """式(12-25) 最小油膜厚度判据的左侧：h_min = rψ(1−ε) ≥ [h]。

    适用条件：为确保轴承处于液体摩擦状态，h_min 必须≥许用油膜厚度 [h]；
    h_min 不能无限缩小（受表面粗糙度、轴刚性、几何形状误差限制）。由式(12-12)
    及表12-6，其他条件不变时 h_min 越小→ε 越大→承载能力越大。
    r: 轴颈半径，mm；ψ: 相对间隙；ε: 偏心率。
    返回 h_min，mm（与 r 同单位）。判据用 判据12_25()。
    [核:p308]
    """
    if float(r) <= 0:
        raise ValueError("式12-25 的 r 必须为正")
    return float(r) * float(ψ) * (1.0 - float(ε))


def 判据12_25(最小油膜厚度: float, 许用油膜厚度: float) -> bool:
    """式(12-25) 的判据形式：h_min ≥ [h] 是否成立 [核:p308]。

    最小油膜厚度: 由 eq12_25()/eq12_12() 算出的 h_min（mm 或 μm）；
    许用油膜厚度: [h]，由 eq12_26() 算出（与 h_min 同单位）。
    返回 bool。
    """
    return float(最小油膜厚度) >= float(许用油膜厚度)


def eq12_26(S: float, Ra_1: float, Ra_2: float) -> float:
    """式(12-26) 许用油膜厚度：[h] = 4S(Ra₁+Ra₂)。

    适用条件：流体动力润滑径向滑动轴承；S 为安全系数，考虑表面几何形状误差
    和轴颈挠曲变形等，常取 S≥2。
    S: 安全系数（量纲为一，常取 ≥2）；
    Ra_1: 轴颈表面评定轮廓的算术平均偏差，μm（或 mm）；
    Ra_2: 轴承孔表面评定轮廓的算术平均偏差，同一单位（一般取 Ra₁=0.8 μm、
          Ra₂=1.6 μm，或 0.4/0.8；重要轴承 0.2/0.4 或 0.05/0.1）。
    返回 [h]，与 Ra 同单位（Ra 用 μm 即 μm，用 mm 即 mm）。
    例12-1 第(18)步：S=2、Ra₁=0.0008 mm、Ra₂=0.0016 mm → 0.0192 mm=19.2 μm。
    [核:p308]
    """
    return 4.0 * float(S) * (float(Ra_1) + float(Ra_2))



def eq12_1(F: float, d: float, B: float) -> float:
    """式(12-1) 平均压力：p = F/(dB) ≤ [p]。

    适用条件：不完全流体润滑（混合润滑）的径向滑动轴承——用润滑脂、油绳或
    滴油润滑，轴承中得不到足够润滑剂、难以产生完整承载油膜的场合；属简化的
    条件性计算，只适用于一般对工作可靠性要求不高的低速、重载或间歇工作轴承。
    F: 轴承所受径向载荷，N；
    d: 轴颈直径，mm；
    B: 轴承宽度，mm（按宽径比 B/d 确定）；
    [p]: 轴瓦材料许用压力，MPa（表12-2，本函数不查表）。
    返回 p，MPa（N/mm² 数值上等于 MPa）。
    判据 p≤[p] 由调用方与表12-2 的 [p] 比较。
    [核:p300]
    """
    if float(d) <= 0 or float(B) <= 0:
        raise ValueError("式12-1 的 d、B 必须为正（mm）")
    return float(F) / (float(d) * float(B))


def eq12_2(F: float, n: float, B: float, d: float = None) -> float:
    """式(12-2) 单位面积摩擦功耗：pv = F/(Bd)·πdn/(60×1000) = Fn/(19100B) ≤ [pv]。

    适用条件：同式(12-1) 的混合润滑径向轴承；pv 与发热量成正比，限制 pv
    即限制轴承温升。
    F: 径向载荷，N；
    n: 轴颈转速，r/min；
    B: 轴承宽度，mm；
    d: 轴颈直径，mm（**可选**）。不给 d 时按书本第二等号的取整常数
       19100 计算（π/(60×1000)=1/19098.59，书本取整印作 19100）；
       给 d 时按未取整的 p·v 计算（v=πdn/(60×1000)），使 pv≡p·v 严格成立
       ——两者相差 7.4×10⁻⁵（19100 的取整量）。
    [pv]: 材料许用值，MPa·m/s（表12-2）。
    返回 pv，MPa·m/s。
    [核:p300]
    """
    if float(B) <= 0:
        raise ValueError("式12-2 的 B 必须为正（mm）")
    if d is None:
        return float(F) * float(n) / (常数19100 * float(B))
    return eq12_1(F, d, B) * eq12_3(n, d)


def eq12_3(n: float, d: float) -> float:
    """式(12-3) 滑动速度（轴颈圆周速度）：v = πdn/(60×1000) ≤ [v]。

    适用条件：混合润滑径向滑动轴承；p、pv 合格后仍需校核——滑动速度过高
    也会加速磨损而使轴承报废（轴弯曲/不同心会使边缘局部 pv 超限）。
    n: 轴颈转速，r/min；
    d: 轴颈直径，mm（故分母为 60×1000，把 mm→m、min→s）；
    [v]: 许用滑动速度，m/s（表12-2）。
    返回 v，m/s。
    [核:p300]
    """
    if float(n) < 0 or float(d) <= 0:
        raise ValueError("式12-3 要求 n≥0、d>0")
    return math.pi * float(d) * float(n) / (60.0 * 1000.0)


def eq12_4(F_a: float, z: float, d_1: float, d_2: float) -> float:
    """式(12-4) 止推轴承平均压力：p = F_a/[z·(π/4)(d₂²−d₁²)] ≤ [p]。

    适用条件：混合润滑状态的止推（推力）滑动轴承，需校核 p 与 pv；
    多环式许用压力 [p] 比单环式降低 50%（查表12-5 时用 多环式=True）。
    F_a: 轴向载荷，N；
    z: 轴环数目（量纲为一）；
    d_1: 轴承孔直径，mm；
    d_2: 轴环直径，mm；
    [p]: 许用压力，MPa（表12-5）。
    返回 p，MPa。
    [核:p301]
    """
    if float(z) <= 0 or float(d_2) <= float(d_1):
        raise ValueError("式12-4 要求 z>0 且 d₂>d₁")
    return float(F_a) / (float(z) * math.pi / 4.0
                         * (float(d_2) ** 2 - float(d_1) ** 2))


def 止推平均圆周速度(n: float, d_1: float, d_2: float) -> float:
    """无编号过渡式（p.301）：v = πn(d₁+d₂)/(60×1000×2)，环形支承面平均直径处。

    非编号式，列在式(12-5) 的推导里，供 pv=p·v 校核用。
    n: 轴颈转速，r/min；d_1: 轴承孔直径，mm；d_2: 轴环直径，mm。
    返回 v，m/s（平均直径 (d₁+d₂)/2 处）。
    [核:p301]
    """
    return math.pi * float(n) * (float(d_1) + float(d_2)) / (60.0 * 1000.0 * 2.0)


def eq12_5(F_a: float, n: float, z: float, d_1: float, d_2: float) -> float:
    """式(12-5) 止推轴承 pv：pv = 4F_a/[zπ(d₂²−d₁²)]·πn(d₁+d₂)/(60×1000×2)
    = nF_a/[30000z(d₂−d₁)] ≤ [pv]。

    适用条件：混合润滑止推滑动轴承；v 取环形支承面平均直径 (d₁+d₂)/2 处；
    多环式 [pv] 比单环式降低 50%（表12-5，多环式=True）。
    F_a: 轴向载荷，N；
    n: 轴颈转速，r/min；
    z: 轴环数目；
    d_1: 轴承孔直径，mm；
    d_2: 轴环直径，mm；
    [pv]: 许用值，MPa·m/s（表12-5）。
    返回 pv，MPa·m/s；按书本化简式 nF_a/[30000z(d₂−d₁)] 计算（与第一等号
    代数恒等，30000=60×1000×2/4）。
    [核:p301]
    """
    if float(z) <= 0 or float(d_2) <= float(d_1):
        raise ValueError("式12-5 要求 z>0 且 d₂>d₁")
    return (float(n) * float(F_a)
            / (常数30000 * float(z) * (float(d_2) - float(d_1))))



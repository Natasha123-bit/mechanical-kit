def _压力积分形状(ε: float, φ_0: float, φ_1: float, φ: float, n: int) -> float:
    """式(12-16) 被积函数的定积分 ∫φ₁^φ ε(cosφ−cosφ₀)/(1+εcosφ)³ dφ（无量纲）。"""
    def 被积(t):
        return (float(ε) * (math.cos(t) - math.cos(float(φ_0)))
                / (1.0 + float(ε) * math.cos(t)) ** 3)
    return _simpson(被积, float(φ_1), float(φ), n)


def eq12_15(η: float, ω: float, ψ: float, ε: float,
            φ: float, φ_0: float) -> float:
    """式(12-15) 极坐标形式的雷诺方程：
    dp/dφ = 6η(ω/ψ²)·ε(cosφ−cosφ₀)/(1+εcosφ)³。

    适用条件：无限宽轴承（沿轴向无流动）+ 流体动力润滑基本假设（牛顿流体、
    层流、忽略压力对黏度影响、略去惯性力及重力、不可压缩、压力沿膜厚不变）；
    由式(12-8) 代换 dx=r dφ、v=rω 及式(12-13)、(12-14) 得到。
    η: 润滑油动力黏度，Pa·s；
    ω: 轴颈角速度，rad/s；
    ψ: 相对间隙（量纲为一）；
    ε: 偏心率（量纲为一）；
    φ: 极角，rad；φ_0: 最大压力处极角，rad。
    返回 dp/dφ，Pa/rad。
    [核:p306]
    """
    if float(ψ) <= 0:
        raise ValueError("式12-15 的相对间隙 ψ 必须为正")
    return (6.0 * float(η) * float(ω) / float(ψ) ** 2
            * float(ε) * (math.cos(float(φ)) - math.cos(float(φ_0)))
            / (1.0 + float(ε) * math.cos(float(φ))) ** 3)


def eq12_16(η: float, ω: float, ψ: float, ε: float,
            φ_0: float, φ_1: float, φ: float, n: int = 200) -> float:
    """式(12-16) 任意角位置的压力：
    p_φ = 6η(ω/ψ²)∫φ₁^φ ε(cosφ−cosφ₀)/(1+εcosφ)³ dφ。

    适用条件：同式(12-15) 的无限宽轴承假设；由油膜起始角 φ₁ 积到任意角 φ。
    η: Pa·s；ω: rad/s；ψ: 相对间隙；ε: 偏心率；
    φ_0: 最大压力处极角，rad；φ_1: 油膜起始角，rad；φ: 任意角位置，rad；
    n: Simpson 积分分段数（偶数化，默认 200）。
    返回 p_φ，Pa。书中被积变量与积分上限同名 φ，本库用 t 作哑变量。
    [核:p306]
    """
    if float(ψ) <= 0:
        raise ValueError("式12-16 的相对间隙 ψ 必须为正")
    return (6.0 * float(η) * float(ω) / float(ψ) ** 2
            * _压力积分形状(ε, φ_0, φ_1, φ, n))


def eq12_17(p_φ: float, φ_a: float, φ: float) -> float:
    """式(12-17) 压力在外载荷方向的分量：
    P_φy = p_φcos[180°−(φ_a+φ)] = −p_φcos(φ_a+φ)。

    适用条件：同式(12-15) 的无限宽轴承假设；压力沿外载荷方向分解。
    p_φ: 任意角位置 φ 处的油膜压力，Pa；
    φ_a: 偏位角（连心线 OO₁ 与外载荷 F 方向所夹的角），rad；
    φ: 极角，rad。
    返回 P_φy，Pa。
    [核:p306]
    """
    return -float(p_φ) * math.cos(float(φ_a) + float(φ))


def eq12_18(η: float, ω: float, r: float, ψ: float, ε: float, φ_0: float,
            φ_a: float, φ_1: float, φ_2: float, n: int = 200) -> float:
    """式(12-18) 无限宽轴承单位宽度上的油膜承载力：
    p_y = ∫φ₁^φ₂ P_φy·r dφ = −∫φ₁^φ₂ p_φcos(φ_a+φ)·r dφ
        = (6ηωr/ψ²)∫φ₁^φ₂[∫φ₁^φ ε(cosφ−cosφ₀)/(1+εcosφ)³dφ][−cos(φ_a+φ)]dφ。

    适用条件：无限宽轴承（沿轴向无流动）；由式(12-17) 在 φ₁~φ₂ 积分。
    η: Pa·s；ω: rad/s；
    r: 轴颈半径，m；
    ψ: 相对间隙；ε: 偏心率；
    φ_0: 最大压力处极角，rad；φ_a: 偏位角，rad；
    φ_1: 油膜起始角，rad；φ_2: 油膜终止角，rad（书未单列定义，仅作积分限）；
    n: Simpson 分段数（内外两层各自偶数化，默认 200）。
    返回 p_y，N/m（单位宽度承载力）。页图未标注单位，本库按 SI 量纲实现。
    [核:p306]
    """
    if float(ψ) <= 0:
        raise ValueError("式12-18 的相对间隙 ψ 必须为正")

    def 外(φ):
        return (_压力积分形状(ε, φ_0, φ_1, φ, n)
                * (-math.cos(float(φ_a) + φ)))

    系数 = 6.0 * float(η) * float(ω) * float(r) / float(ψ) ** 2
    return 系数 * _simpson(外, float(φ_1), float(φ_2), n)


def eq12_19(p_y: float, C_: float, B: float, z: float) -> float:
    """式(12-19) 距轴承中线 z 处的油膜压力（有限宽、计端泄）：
    p′_y = p_y·C′[1−(2z/B)²]。

    适用条件：有限宽轴承，必须考虑润滑油从两端面流出（端泄）；压力沿轴承
    宽度呈抛物线分布，且比无限宽轴承低（图12-15），乘端泄影响系数 C′。
    p_y: 单位宽度承载力（式12-18），N/m；
    C_: 端泄影响系数 C′（取决于宽径比 B/d 与偏心率 ε，量纲为一）；
    B: 轴承宽度，m；
    z: 距轴承中线的轴向坐标，m（−B/2≤z≤B/2）。
    返回 p′_y，N/m（书称“油膜压力”，按式12-20 沿 z 积分后为 N）。
    [核:p306]
    """
    return (float(p_y) * float(C_)
            * (1.0 - (2.0 * float(z) / float(B)) ** 2))


def eq12_20(η: float, ω: float, r: float, ψ: float, ε: float, φ_0: float,
            φ_a: float, φ_1: float, φ_2: float, C_: float, B: float,
            n: int = 200) -> float:
    """式(12-20) 有限宽轴承油膜总承载能力：
    F = ∫_{−B/2}^{+B/2} p′_y dz
      = (6ηωr/ψ²)∫_{−B/2}^{B/2}∫φ₁^φ₂[∫φ₁^φ ε(cosφ−cosφ₀)/(1+εcosφ)³dφ]
        [−cos(φ_a+φ)dφ]C′[1−(2z/B)²]dz。

    适用条件：有限宽径向滑动轴承，考虑端泄（沿 z 抛物线压力分布）；
    对式(12-19) 沿 z 从 −B/2 积到 +B/2。
    η: Pa·s；ω: rad/s；r: 轴径半径，m；ψ: 相对间隙；ε: 偏心率；
    φ_0: 最大压力处极角，rad；φ_a: 偏位角，rad；
    φ_1、φ_2: 油膜起、止角，rad；
    C_: 端泄影响系数（量纲为一）；B: 轴承宽度，m；
    n: Simpson 分段数，默认 200。
    返回 F，N。z 向积分用 Simpson 数值完成（被积函数为二次式，数值解与
    (2/3)C′B·p_y 一致，测试按 1e-9 校验）。
    [核:p306]
    """
    if float(B) <= 0:
        raise ValueError("式12-20 的 B 必须为正（m）")
    p_y = eq12_18(η, ω, r, ψ, ε, φ_0, φ_a, φ_1, φ_2, n)
    return p_y * float(C_) * _simpson(lambda z: 1.0 - (2.0 * z / float(B)) ** 2,
                                     -float(B) / 2.0, float(B) / 2.0, n)


def eq12_21(η: float, ω: float, d: float, B: float,
            ψ: float, C_p: float) -> float:
    """式(12-21) 承载能力：F = ηωdB·C_p/ψ²。

    适用条件：有限宽径向滑动轴承；由式(12-20) 改写（“将上式改写为”）。
    η: 润滑油在轴承平均工作温度下的动力黏度，Pa·s（N·s/m²）；
    ω: 轴颈角速度，rad/s；
    d: 轴颈直径，m；
    B: 轴承宽度，m；
    ψ: 相对间隙（量纲为一）；
    C_p: 承载量系数（量纲为一，表12-6）。
    返回 F，N。
    [核:p307]
    """
    if float(ψ) <= 0:
        raise ValueError("式12-21 的相对间隙 ψ 必须为正")
    return (float(η) * float(ω) * float(d) * float(B) * float(C_p)
            / float(ψ) ** 2)


def eq12_22(ε: float, φ_0: float, φ_a: float, φ_1: float, φ_2: float,
            C_: float, B: float, n: int = 120) -> float:
    """式(12-22) 承载量系数 C_p 的积分定义：
    C_p = 3∫_{−B/2}^{B/2}∫φ₁^φ₂[∫φ₁^φ ε(cosφ−cosφ₀)/(B(1+εcosφ)³)dφ]
          [−cos(φ_a+φ)dφ]C′[1−(2z/B)²]dz。

    适用条件：由式(12-21) 与式(12-20) 联立得出；给定边界条件时 C_p 是轴颈
    在轴承中位置的函数。C_p 的积分非常困难，实际用数值积分做成线图/表格
    （表12-6）供设计应用。
    ε: 偏心率；φ_0: 最大压力处极角，rad；φ_a: 偏位角，rad；
    φ_1、φ_2: 油膜起、止角，rad；C_: 端泄影响系数；
    B: 轴承宽度，m（本式被积函数分母含 B）；n: Simpson 分段数，默认 120。
    返回 C_p（量纲为一）。
    推导式，不单独调用：设计计算用式(12-23) 算 C_p 后查表12-6；本函数只按
    原式做数值积分，用于理解/校验，不参与查表路径。
    [核:p307]
    """
    if float(B) <= 0:
        raise ValueError("式12-22 的 B 必须为正（m）")

    def 内层(φ):
        return _simpson(
            lambda t: (float(ε) * (math.cos(t) - math.cos(float(φ_0)))
                       / (float(B) * (1.0 + float(ε) * math.cos(t)) ** 3)),
            float(φ_1), φ, n)

    def 中层(φ):
        return 内层(φ) * (-math.cos(float(φ_a) + φ))

    角积分 = _simpson(中层, float(φ_1), float(φ_2), n)
    return 3.0 * float(C_) * _simpson(
        lambda z: 角积分 * (1.0 - (2.0 * z / float(B)) ** 2),
        -float(B) / 2.0, float(B) / 2.0, n)


def eq12_23(F: float, ψ: float, η: float, ω: float = None, d: float = None,
            B: float = None, v: float = None) -> float:
    """式(12-23) 承载量系数：C_p = Fψ²/(ηωdB) = Fψ²/(2ηvB)。

    适用条件：流体动力润滑径向滑动轴承；第二等号用 ωd=2v 换算。
    F: 外载荷，N；
    ψ: 相对间隙（量纲为一）；
    η: 润滑油在轴承平均工作温度下的动力黏度，Pa·s（N·s/m²）；
    给法一：ω 轴颈角速度 rad/s、d 轴颈直径 m、B 轴承宽度 m；
    给法二：v 轴颈圆周速度 m/s、B 轴承宽度 m。
    返回 C_p（量纲为一），供查表12-6/反查 ε。
    例12-1 第(14)步：F=100000、ψ=0.00125、η=0.036、v=5.23、B=0.2 → 2.075。
    [核:p307]
    """
    if float(ψ) <= 0 or float(η) <= 0:
        raise ValueError("式12-23 的 ψ、η 必须为正")
    if v is not None and B is not None:
        return float(F) * float(ψ) ** 2 / (2.0 * float(η) * float(v) * float(B))
    if None not in (ω, d, B):
        return (float(F) * float(ψ) ** 2
                / (float(η) * float(ω) * float(d) * float(B)))
    raise ValueError("式12-23 需要 (v, B) 或 (ω, d, B)")



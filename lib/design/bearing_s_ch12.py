# 7. 12-7 节 热平衡与参数初估 式(12-27a) ~ 式(12-32)
# =====================================================================

def eq12_27a(f: float, F: float, v: float) -> float:
    """式(12-27a) 轴承中产生的热量：Q = fFv。

    适用条件：轴承中的热量由摩擦损失的功转变而来；用于热平衡 Q=Q₁+Q₂。
    f: 摩擦因数（量纲为一，见 摩擦因数()）；
    F: 轴承承受的径向载荷，N；
    v: 轴颈圆周速度，m/s。
    返回 Q，W。
    [核:p309]
    """
    return float(f) * float(F) * float(v)


def eq12_27b(q: float, ρ: float, c: float,
             t_o: float, t_i: float) -> float:
    """式(12-27b) 流动的润滑油带走的热量：Q₁ = qρc(t_o−t_i)。

    适用条件：只计流动的润滑油带走的热量；q 按润滑油流量系数 q/(ψvBd) 求出。
    q: 润滑油流量，m³/s（= 流量系数 × ψvBd）；
    ρ: 润滑油密度，kg/m³（矿物油 850~900）；
    c: 润滑油比热容，J/(kg·℃)（矿物油 1675~2090）；
    t_o: 润滑油出口温度，℃；
    t_i: 润滑油入口温度，℃（通常因冷却设备限制取 35~40℃）。
    返回 Q₁，W。
    [核:p309]
    """
    return float(q) * float(ρ) * float(c) * (float(t_o) - float(t_i))


def eq12_27c(α_s: float, d: float, B: float,
             t_o: float, t_i: float) -> float:
    """式(12-27c) 轴承金属表面传导和辐射散出的热量：Q₂ = α_s·πdB·(t_o−t_i)。

    适用条件：近似计算——以润滑油出口温度 t_o 代表轴承温度、入口温度 t_i 代表
    周围介质温度；散热量与散热面积、空气流速等有关，难以精确计算。
    α_s: 轴承表面传热系数，W/(m²·℃)：轻型结构或高温/难散热环境（如轧钢机）
         取 50；中型结构或一般通风条件取 80；良好冷却的重型轴承可取 140；
    d: 轴颈直径，mm（书本式此处为 mm，函数内部换算为 m 才得 W）；
    B: 轴承宽度，mm（同上换算）；
    t_o: 润滑油出口温度，℃；t_i: 润滑油入口温度（周围介质温度），℃。
    返回 Q₂，W。
    [核:p309]
    """
    return (float(α_s) * math.pi * (float(d) / 1000.0) * (float(B) / 1000.0)
            * (float(t_o) - float(t_i)))


def eq12_28(f: float, ψ: float, p: float, c: float, ρ: float,
            流量系数: float, α_s: float, v: float) -> float:
    """式(12-28) 润滑油温升：
    Δt = t_o−t_i = [(f/ψ)p] / [cρ·q/(ψvBd) + πα_s/(ψv)]。

    适用条件：由热平衡 Q=Q₁+Q₂ 导出；只考虑速度供油量（旋转轴颈从油槽带入
    间隙的油量），忽略油泵压力供油量；适用于一般用途流体动力润滑径向轴承，
    重要流体动压轴承需查参考文献[63]第3卷。
    f: 摩擦因数（量纲为一）；
    ψ: 相对间隙（量纲为一）；
    p: 轴承平均压力，Pa；
    c: 润滑油比热容，J/(kg·℃)；
    ρ: 润滑油密度，kg/m³；
    流量系数: q/(ψvBd)，量纲为一（查图12-16，按 B/d 与 ε）；
    α_s: 轴承表面传热系数，W/(m²·℃)；
    v: 轴颈圆周速度，m/s。
    返回 Δt，℃（因各点温度不同，此为平均温升）。
    例12-1 第(21)步：f=0.00258、ψ=0.00125、p=2.5×10⁶、c=1800、ρ=900、
    流量系数 0.145、α_s=80、v=5.24 → 18.882℃。
    [核:p309]
    """
    if float(ψ) <= 0 or float(v) <= 0:
        raise ValueError("式12-28 的 ψ、v 必须为正")
    return ((float(f) / float(ψ) * float(p))
            / (float(c) * float(ρ) * float(流量系数)
               + math.pi * float(α_s) / (float(ψ) * float(v))))


def eq12_29(t_i: float, Δt: float) -> float:
    """式(12-29) 润滑油平均温度：t_m = t_i + Δt/2。

    适用条件：由 t_m=(t_i+t_o)/2 与 Δt=t_o−t_i 联立；用于按平均温度确定
    润滑油黏度（式12-21 计算承载能力时采用平均温度下的黏度）。书中建议
    平均温度不超过 75℃ 以保证承载能力。
    t_i: 润滑油入口温度，℃；Δt: 温升，℃。
    返回 t_m，℃。
    [核:p310]
    """
    return float(t_i) + float(Δt) / 2.0


def eq12_30(t_m: float, Δt: float) -> float:
    """式(12-30) 由平均温度反求入口温度：t_i = t_m − Δt/2。

    适用条件：设计时先给定 t_m，用式(12-28) 的 Δt 反求 t_i 校核：
    t_i>35~40℃ 表示热平衡易于建立、承载能力尚未用尽，应降低给定平均温度并
    允许适当加大表面粗糙度后重算；t_i<35~40℃ 表示不易达到热平衡，需加大
    间隙并适当降低表面粗糙度后重算。
    t_m: 设计时先给定的润滑油平均温度，℃；Δt: 式(12-28) 求出的温升，℃。
    返回 t_i，℃。例12-1 第(22)步：50−18.882/2=40.559℃。
    [核:p310]
    """
    return float(t_m) - float(Δt) / 2.0


def eq12_31(n: float) -> float:
    """式(12-31) 一般轴承按转速取相对间隙的经验式：
    ψ ≈ (n/60)^(4/9) / 10^(31/9)。

    适用条件：一般轴承的经验近似式；ψ 主要按载荷和速度选取——速度越高 ψ
    越大，载荷越大 ψ 越小；直径大、宽径比小、调心性能好、加工精度高时取小值。
    n: 轴颈转速，r/min。
    返回 ψ（量纲为一）。书本常用值：汽轮机/电动机/齿轮减速器 0.001~0.002；
    轧钢机/铁路车辆 0.0002~0.0015；机床/内燃机 0.0002~0.00125；
    鼓风机/离心泵 0.001~0.003。
    例12-1 第(12)步：n=500 → 0.00092，随后按机床常用范围圆整取 0.00125
    （圆整不是本式结果，测试单独注明）。
    [核:p311]
    """
    if float(n) <= 0:
        raise ValueError("式12-31 的转速 n 必须为正")
    return (float(n) / 60.0) ** (4.0 / 9.0) / 10.0 ** (31.0 / 9.0)


def eq12_32(n: float) -> float:
    """式(12-32) 初估润滑油动力黏度：η′ = (n/60)^(−1/3) / 10^(7/6)。

    适用条件：一般轴承初估动力黏度；之后由式(4-4) 算运动黏度 ν′、参照表4-1
    选黏度等级，再查图4-7 重新确定 t_m 时的 ν_tm 与 η_tm，最后验算入口油温。
    设计初期先假定平均温度 t_m（一般 50~75℃）。
    n: 轴颈转速，r/min。
    返回 η′，Pa·s。例12-1 第(6)步：n=500 → 0.0336，书取两位有效数字 0.034。
    [核:p311]
    """
    if float(n) <= 0:
        raise ValueError("式12-32 的转速 n 必须为正")
    return (float(n) / 60.0) ** (-1.0 / 3.0) / 10.0 ** (7.0 / 6.0)



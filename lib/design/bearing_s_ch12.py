def _区间(文本) -> tuple:
    """把“2.0~2.5”“1~2.5”解析为 (低, 高)；只读数、不插值、不改写。"""
    s = str(文本).replace(" ", "").replace("～", "~")
    if "~" not in s:
        raise ValueError("表值“%s”不是 a~b 形式的区间" % (文本,))
    左, 右 = s.split("~", 1)
    return float(左), float(右)


def _simpson(f, a: float, b: float, n: int = 200) -> float:
    """复合 Simpson 积分（纯标准库；n 取偶数，n<2 时退化为梯形）。"""
    n = int(n)
    if n < 2:
        return 0.5 * (b - a) * (f(a) + f(b))
    if n % 2:
        n += 1
    h = (b - a) / n
    和 = f(a) + f(b)
    for i in range(1, n):
        和 += (4.0 if i % 2 else 2.0) * f(a + i * h)
    return 和 * h / 3.0


def _定位(轴: list, x: float, 名称: str):
    """在升序网格 轴 上定位 x：返回 (下界序号, 上界序号, 比例 t)。

    命中印刷格时返回 (i, i, 0.0)；落在两格之间返回 (i, i+1, t)；
    超出表范围抛 ValueError（**不外推**）。
    """
    x = float(x)
    if x < 轴[0] - 1e-12 or x > 轴[-1] + 1e-12:
        raise ValueError("%s=%.6g 超出表范围 %.6g~%.6g（不插值、不外推）"
                         % (名称, x, 轴[0], 轴[-1]))
    for i in range(len(轴) - 1):
        if abs(x - 轴[i]) < 1e-12:
            return i, i, 0.0
        if 轴[i] < x < 轴[i + 1]:
            return i, i + 1, (x - 轴[i]) / (轴[i + 1] - 轴[i])
    return len(轴) - 1, len(轴) - 1, 0.0



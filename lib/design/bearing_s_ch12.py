def eq12_6(切应力梯度: float) -> float:
    """式(12-6) 微元体 x 向力平衡：∂p/∂x = −∂τ/∂y。

    适用条件：流体动力润滑理论基本方程（微单元体受力平衡）。假设：牛顿流体、
    层流、忽略压力对黏度的影响、略去惯性力及重力、流体不可压缩、压力沿膜厚
    方向不变、沿 z 向无流动。
    切应力梯度: ∂τ/∂y，单位随所用单位制（SI 为 Pa/m）；
    返回 压力梯度 ∂p/∂x，单位同上（SI 为 Pa/m）。
    推导式，不单独调用：本函数只表达“压力梯度与切应力梯度反号相等”的符号
    关系，实际压力场由式(12-8) 雷诺方程给出。
    [核:p302]
    """
    return -float(切应力梯度)


def eq12_7(压力梯度: float, η: float) -> float:
    """式(12-7) 牛顿黏性定律代入后的基本方程：∂p/∂x = η·∂²u/∂y²。

    适用条件：同式(12-6) 的流体动力润滑基本假设；由牛顿黏性流体摩擦定律
    （第4章式(4-3)）对 y 求导得 ∂τ/∂y=−η∂²u/∂y²，再代入式(12-6)。
    压力梯度: ∂p/∂x（SI 为 Pa/m）；
    η: 流体（润滑油）动力黏度（SI 为 Pa·s）；
    返回 速度二阶导 ∂²u/∂y²（SI 为 1/(m·s)）。
    推导式，不单独调用：本函数给出“压力梯度→速度分布曲率”的换算，速度分布
    u(y) 的积分结果见 p.303 正文（书未编号）。
    [核:p302]
    """
    if float(η) <= 0:
        raise ValueError("式12-7 的黏度 η 必须为正")
    return float(压力梯度) / float(η)


def eq12_8(η: float, v: float, h: float, h_0: float) -> float:
    """式(12-8) 一维雷诺方程：∂p/∂x = 6ηv(h−h₀)/h³。

    适用条件：流体动力润滑（动压油膜）成立需三条：①两表面形成收敛楔形间隙；
    ②有足够相对滑动速度且方向使油由大口进、小口出；③油有一定黏度、供油充分。
    本式为计算流体动力润滑滑动轴承的基本方程。
    η: 润滑油动力黏度，Pa·s；
    v: 表面滑动速度（两平板相对速度），m/s；
    h: 所取微元体处的油膜厚度，m；
    h_0: p=p_max 处（∂p/∂x=0）的油膜厚度，m。
    返回 ∂p/∂x，Pa/m。h=h₀ 时返回 0（压力最大处）。
    [核:p304]
    """
    h = float(h)
    if h <= 0:
        raise ValueError("式12-8 的油膜厚度 h 必须为正（m）")
    return 6.0 * float(η) * float(v) * (h - float(h_0)) / h ** 3


def eq12_9(D: float, d: float) -> float:
    """式(12-9) 直径间隙：Δ = D − d。

    适用条件：径向（圆柱）滑动轴承的几何关系（图12-14）。
    D: 轴承孔直径，mm；
    d: 轴颈直径，mm；
    返回 Δ，mm（与 D、d 同单位）。
    [核:p305]
    """
    return float(D) - float(d)


def eq12_10(Δ: float = None, R: float = None, r: float = None) -> float:
    """式(12-10) 半径间隙：δ = R − r = Δ/2。

    适用条件：径向（圆柱）滑动轴承的几何关系。
    Δ: 直径间隙，mm（给 Δ 即返回 Δ/2）；
    或给 R: 轴承孔半径，mm；r: 轴颈半径，mm（返回 R−r）；
    返回 δ，mm（与输入同单位）。
    两种给法二选一：给 Δ 优先。
    [核:p305]
    """
    if Δ is not None:
        return float(Δ) / 2.0
    if R is None or r is None:
        raise ValueError("式12-10 需要 Δ，或同时给 R、r")
    return float(R) - float(r)


def eq12_11(Δ: float = None, d: float = None,
            δ: float = None, r: float = None) -> float:
    """式(12-11) 相对间隙：ψ = Δ/d = δ/r。

    适用条件：径向（圆柱）滑动轴承的几何关系（Δ=2δ、d=2r）。
    Δ: 直径间隙，mm；d: 轴颈直径，mm；
    或 δ: 半径间隙，mm；r: 轴颈半径，mm；
    返回 ψ（量纲为一）。给 Δ、d 优先。
    [核:p305]
    """
    if Δ is not None and d is not None:
        if float(d) <= 0:
            raise ValueError("式12-11 的 d 必须为正")
        return float(Δ) / float(d)
    if δ is not None and r is not None:
        if float(r) <= 0:
            raise ValueError("式12-11 的 r 必须为正")
        return float(δ) / float(r)
    raise ValueError("式12-11 需要 (Δ, d) 或 (δ, r)")


def eq12_12(δ: float = None, ε: float = None, r: float = None,
            ψ: float = None, e: float = None) -> float:
    """式(12-12) 最小油膜厚度：h_min = δ − e = δ(1−ε) = rψ(1−ε)。

    适用条件：径向（圆柱）滑动轴承，轴颈稳定运转时的几何关系（图12-14）；
    h_min 位于连心线 OO₁ 的负向一侧。
    δ: 半径间隙，mm；ε: 偏心率（ε=e/δ，量纲为一）；e: 偏心距，mm；
    r: 轴颈半径，mm；ψ: 相对间隙（式12-11）。
    返回 h_min，mm（与 δ、r 同单位）。
    给法：δ+ε（或 δ+e，此时 ε=e/δ）优先；否则 r+ψ+ε。
    [核:p305]
    """
    if δ is not None:
        δ = float(δ)
        if ε is None:
            if e is None:
                raise ValueError("式12-12 给 δ 时需再给 ε 或 e")
            ε = float(e) / δ
        return δ * (1.0 - float(ε))
    if r is None or ψ is None or ε is None:
        raise ValueError("式12-12 需要 δ+(ε 或 e)，或 r+ψ+ε")
    return float(r) * float(ψ) * (1.0 - float(ε))


def eq12_13(ε: float, φ: float, δ: float = None,
            r: float = None, ψ: float = None) -> float:
    """式(12-13) 任意位置的油膜厚度：h = δ(1+εcosφ) = rψ(1+εcosφ)。

    适用条件：径向滑动轴承，以轴颈中心 O 为极点、连心线 OO₁ 为极轴的极坐标；
    推导时略去微量 (e/R)²sin²φ 并取根式正号。
    ε: 偏心率（量纲为一）；
    φ: 任意极角，rad（φ_0、φ_1、φ_2 均自 OO₁ 连线算起）；
    δ: 半径间隙，mm；或 r: 轴颈半径 mm、ψ: 相对间隙；
    返回 h，mm（与 δ、r 同单位）。φ=π 时返回 h_min。
    [核:p305]
    """
    系数 = None
    if δ is not None:
        系数 = float(δ)
    elif r is not None and ψ is not None:
        系数 = float(r) * float(ψ)
    else:
        raise ValueError("式12-13 需要 δ，或 (r, ψ)")
    return 系数 * (1.0 + float(ε) * math.cos(float(φ)))


def eq12_14(δ: float, ε: float, φ_0: float) -> float:
    """式(12-14) 压力最大处的油膜厚度：h_0 = δ(1+εcosφ₀)。

    适用条件：径向滑动轴承流体动力润滑；φ₀ 为对应最大压力处的极角。
    δ: 半径间隙，mm；ε: 偏心率（量纲为一）；φ_0: 最大压力处极角，rad。
    返回 h_0，mm（与 δ 同单位）。
    [核:p305]
    """
    return float(δ) * (1.0 + float(ε) * math.cos(float(φ_0)))



"""
bearing_r_ch13.py 的测试：以课本例13-1 ~ 例13-4（p.355~p.358）的已知条件、
中间结果与选型结论为基准，抽查表13-1~13-11 的原始格值（含原表 None 格），
并校验 13-4↔13-5↔13-6、13-4a/5a/6a、13-18↔13-19、13-13/14↔13-15、
13-11/13-12 与表13-7 派生力的自洽关系。

圆整说明（单独注明，不塞回公式冒充计算值）：
  · 例13-1 的 Y=1.597 是表13-5 注④线性插值后取 3 位小数（精确 1.59649…），
    不是表值；C=61699 N 是式(13-6) 的计算值，6310（C=61.8 kN）与 6311 都是
    按手册标准值**选型**，6310→6311 这一步的 6311 的 C 不在 handoff 内，
    因此只验证“6310 寿命不足、须换大一档”，不复算 6311 的寿命。
  · 例13-2 的 e1=0.384、e2=0.409 是插值后取 3 位小数（精确 0.38359/0.40879），
    判定 X、Y 时课本用取整后的 e 与 Fa/Fr 比较（336.25/875.65 记作 0.384=e1），
    本测试按此给 e 覆盖值，不把 0.384 说成插值原值。
  · 例13-3 的 P2=14566 N 保留四位有效数字；C=58505.76 N 与手册成对值
    7209AC(59.5 kN)、7009AC(41.8 kN) 比较属选型，成对 C 不在式(13-6) 内。

运行：
    python3 bearing_r_ch13_tests.py    全部通过则退出码 0，有失败则退出码 1。
    （末行输出“合计：通过 N 项，失败 0 项”。）
"""

from __future__ import annotations

import math

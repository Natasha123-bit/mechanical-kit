import bearing_r_ch13 as c

失败 = []
通过 = 0


def 校验(名称: str, 计算值: float, 书上值: float,
         容差: float = 0.005, 单位: str = "", 备注: str = ""):
    """容差为相对误差（默认 0.5%）；书上值可能只保留 2~4 位有效数字。"""
    global 通过
    if 书上值 == 0:
        ok = abs(计算值) < 1e-9
        rel = 0.0
    else:
        rel = abs(计算值 - 书上值) / abs(书上值)
        ok = rel <= 容差
    if ok:
        通过 += 1
    else:
        失败.append((名称, 计算值, 书上值, rel))
    print("%s %-52s 计算=%14.6f  书上=%14.6f  Δ=%7.4f%% %-5s %s"
          % ("[OK]  " if ok else "[FAIL]", 名称, 计算值, 书上值,
             rel * 100, 单位, 备注))


def 校验文本(名称: str, 计算值, 书上值):
    """字符串/整数/布尔/None 等精确相等。"""
    global 通过
    ok = 计算值 == 书上值
    if ok:
        通过 += 1
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
    print("%s %-52s 计算=%s  书上=%s"
          % ("[OK]  " if ok else "[FAIL]", 名称, 计算值, 书上值))


def 校验真(名称: str, 条件: bool, 说明: str = ""):
    """任意布尔断言（结构、范围、None 格等）。"""
    global 通过
    if 条件:
        通过 += 1
        print("[OK]   %-52s %s" % (名称, 说明))
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
        print("[FAIL] %-52s %s" % (名称, 说明))


def 校验异常(名称: str, 函数, 异常类=ValueError):
    """确认“原表空白/表外/未知档”输入按约定抛异常（不猜值、不外推）。"""
    global 通过
    try:
        函数()
    except 异常类:
        通过 += 1
        print("[OK]   %-52s 按预期抛出 %s" % (名称, 异常类.__name__))
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
        print("[FAIL] %-52s 未抛出 %s" % (名称, 异常类.__name__))


# =====================================================================
# 例13-1 深沟球轴承选择（课本 p.355）
# 已知：Fr=5500 N，Fa=2700 N，n=1250 r/min，轴颈 50~60 mm，轻微冲击，
#       Lh'=5000 h
# =====================================================================
def 例13_1():
    print("\n=== 例13-1 深沟球轴承选择（课本 p.355）===")
    Fr, Fa, n, Lh_要求 = 5500.0, 2700.0, 1250.0, 5000.0
    ε = c.球轴承指数

    # (1) 求 Fa/Fr 并与 e_max 比较
    比值 = Fa / Fr
    校验("步骤(1) Fa/Fr=2700/5500", 比值, 0.49, 0.005)
    e_max = c.查表13_5_最大e("深沟球")
    校验("步骤(1) 表13-5 深沟球 e_max", e_max, 0.44, 1e-12)
    校验真("步骤(1) Fa/Fr>e_max", 比值 > e_max, "0.49>0.44 → 按 Fa/Fr>e 档取 X、Y")

    # (2) 初步计算当量动载荷（Y 暂取 1.5）
    f_d = c.查表13_6_载荷系数("轻微冲击", 取="上限")
    校验("步骤(2) 表13-6 轻微冲击 f_d 取上限", f_d, 1.2, 1e-12)
    P初 = c.eq13_8a(f_d, 0.56, 1.5, Fr, Fa)
    校验("步骤(2) 式(13-8a) P初=1.2(0.56×5500+1.5×2700)", P初, 8556.0,
         0.005, "N", "精确 8556")

    # (3) 反求所需 C
    C需 = c.eq13_6(P初, n, Lh_要求, ε)
    校验("步骤(3) 式(13-6) C需", C需, 61699.0, 0.005, "N",
         "ε=3，根号内 60×1250×5000/10⁶")
    校验真("步骤(3) 根号内=375，C=P×375^(1/3)",
           abs(60.0 * n * Lh_要求 / 1e6 - 375.0) < 1e-9)

    # (4)-1) 选 6310：C=61.8 kN、C0=38 kN，求 Fa/C0
    C6310, C0_6310 = 61800.0, 38000.0
    校验真("步骤(4) 6310 的 C=61.8 kN 略大于 C需",
           C需 <= C6310, "C需=%.0f N ≤ 61800 N（选型，非公式结果）" % C需)
    Fa_C0 = Fa / C0_6310
    校验("步骤(4)-1) Fa/C0=2700/38000", Fa_C0, 0.07105, 0.005)

    # (4)-2) 插值求 Y
    Y查 = c.查表13_5_XY系数("深沟球", Fa=Fa, Fr=Fr, C0=C0_6310)
    校验("步骤(4)-2) 表13-5 插值 Y", Y查["Y"], 1.597, 0.005,
         "", "表注④线性插值，精确 1.59649")
    校验("步骤(4)-2) 插值公式（书上写法）",
         1.4 + (1.6 - 1.4) * (0.13 - 0.07105) / (0.13 - 0.07), 1.597, 0.005)
    校验文本("步骤(4)-2) 判据为 Fa/Fr>e", Y查["判据"], "Fa/Fr>e")
    校验("步骤(4)-2) X=0.56", Y查["X"], 0.56, 1e-12)

    # (4)-3) 实际当量动载荷
    P书 = c.eq13_8a(f_d, 0.56, 1.597, Fr, Fa)
    校验("步骤(4)-3) 式(13-8a) P(书 Y=1.597)", P书, 8870.28, 1e-12, "N",
         "1.2(0.56×5500+1.597×2700)")
    P插 = c.eq13_8a(f_d, Y查["X"], Y查["Y"], Fr, Fa)
    校验("步骤(4)-3) P(插值 Y 回代)", P插, 8870.28, 0.005, "N")

    # (4)-4) 验算 6310 寿命
    Lh = c.eq13_5(C6310, P书, n, ε)
    校验("步骤(4)-4) 式(13-5) 6310 寿命", Lh, 4509.12, 0.005, "h",
         "C=61800，P=8870.28")
    校验真("步骤(4)-4) 6310 寿命 < Lh'=5000 h", Lh < Lh_要求,
           "%.2f h < 5000 h → 6310 不合格" % Lh)

    # 结论：轴颈允许 50~60 mm → 改用 6311
    校验真("结论 6310→6311（选型步，6311 的 C 不在 handoff）",
           Lh < Lh_要求 and C需 <= C6310,
           "书上原文“可改用 6311（或 6312），验算从略”")


# =====================================================================
# 例13-2 7207C 角接触球轴承验算（课本 p.356~p.357）
# 已知：Fte=2200 N，Fre=900 N，Fae=400 N，d=314 mm，n=1440 r/min，
#       中等冲击，Lh'=15000 h，7207C：C=30.5 kN，C0=20 kN
# 几何：左支承 2—齿轮 200 mm，齿轮—右支承 1 320 mm（跨距 520 mm）
# =====================================================================
def 例13_2():
    print("\n=== 例13-2 7207C 角接触球轴承验算（课本 p.356~p.357）===")
    Fte, Fre, Fae, d齿 = 2200.0, 900.0, 400.0, 314.0
    n, Lh_要求 = 1440.0, 15000.0
    C, C0 = 30500.0, 20000.0
    ε = c.球轴承指数

    # (1) 两轴承径向载荷（题目几何的力矩平衡，非本章编号公式）
    Fr1V = (Fre * 200.0 - Fae * d齿 / 2.0) / 520.0
    Fr2V = Fre - Fr1V
    校验("步骤(1) Fr1V=(900×200−400×157)/520", Fr1V, 225.38, 0.005, "N")
    校验("步骤(1) Fr2V=Fre−Fr1V", Fr2V, 674.62, 0.005, "N")
    Fr1H = 200.0 / 520.0 * Fte
    Fr2H = Fte - Fr1H
    校验("步骤(1) Fr1H=200/520×2200", Fr1H, 846.15, 0.005, "N")
    校验("步骤(1) Fr2H=Fte−Fr1H", Fr2H, 1353.85, 0.005, "N")
    Fr1 = math.hypot(Fr1V, Fr1H)
    Fr2 = math.hypot(Fr2V, Fr2H)
    校验("步骤(1) Fr1=√(Fr1V²+Fr1H²)", Fr1, 875.65, 0.005, "N")
    校验("步骤(1) Fr2=√(Fr2V²+Fr2H²)", Fr2, 1512.62, 0.005, "N")

    # (2) 派生轴向力：先初取 e=0.4
    Fd1初 = c.派生轴向力("70000C", Fr1, e=0.4)
    Fd2初 = c.派生轴向力("70000C", Fr2, e=0.4)
    校验("步骤(2) 初取 e=0.4 → Fd1", Fd1初, 350.26, 0.005, "N")
    校验("步骤(2) 初取 e=0.4 → Fd2", Fd2初, 605.05, 0.005, "N")
    校验("步骤(2) Fd2−Fae=205.05", Fd2初 - Fae, 205.05, 0.005, "N")
    校验真("步骤(2) Fd2−Fae < Fd1（轴承1放松）", Fd2初 - Fae < Fd1初)

    # 由 Fa/C0 插值 e（表13-5 注④）
    e1 = c.查表13_5_XY系数("70000C", Fa=Fd1初, Fr=Fr1, C0=C0)["e"]
    e2 = c.查表13_5_XY系数("70000C", Fa=Fd1初 + Fae, Fr=Fr2, C0=C0)["e"]
    校验("步骤(2) 表13-5 插值 e1", e1, 0.384, 0.005, "", "精确 0.38359")
    校验("步骤(2) 表13-5 插值 e2", e2, 0.409, 0.005, "", "精确 0.40879")

    # 用 e1/e2 重算，再判平衡（书取 3 位小数）
    Fd1 = c.派生轴向力("70000C", Fr1, e=0.384)
    Fd2 = c.派生轴向力("70000C", Fr2, e=0.409)
    校验("步骤(2) Fd1=e1Fr1=0.384×875.65", Fd1, 336.25, 0.005, "N")
    校验("步骤(2) Fd2=e2Fr2=0.409×1512.62", Fd2, 618.66, 0.005, "N")
    校验真("步骤(2) Fd2−Fae=218.66 < Fd1=336.25",
           Fd2 - Fae < Fd1, "轴承1放松、轴承2压紧")

    # 轴向力分配：式13-11 的“轴承1”=本图被压紧的轴承2（换标号，见 docstring）
    Fa1式, Fa2式 = c.eq13_11(Fae, Fd2, Fd1, 校验=True)
    校验("步骤(2) Fa(放松)=Fd1=336.25（=书的 Fa1）", Fa2式, 336.25, 0.005, "N")
    校验("步骤(2) Fa(压紧)=Fd1+Fae=736.25（=书的 Fa2）", Fa1式, 736.25,
         0.005, "N")
    校验("步骤(2) 书值 Fa1=336.25 复核", min(Fa1式, Fa2式), 336.25, 0.005, "N")
    校验("步骤(2) 书值 Fa2=736.25 复核", max(Fa1式, Fa2式), 736.25, 0.005, "N")
    校验真("步骤(2) 换标号后满足轴向平衡 |Fa2−Fa1|=Fae",
           abs(736.25 - 336.25 - Fae) < 1e-9)

    # (3) 当量动载荷
    Fa_C0_2 = 736.25 / C0
    校验("步骤(2) 复核 Fa2/C0=736.25/20000", Fa_C0_2, 0.0368, 0.005)
    查1 = c.查表13_5_XY系数("70000C", Fa=336.25, Fr=Fr1, C0=C0, e=0.384)
    查2 = c.查表13_5_XY系数("70000C", Fa=736.25, Fr=Fr2, C0=C0, e=0.409)
    校验文本("步骤(3) 轴承1 Fa/Fr=e1 → Fa/Fr≤e", 查1["判据"], "Fa/Fr≤e")
    校验("步骤(3) 轴承1 X1", 查1["X"], 1.0, 1e-12)
    校验("步骤(3) 轴承1 Y1", 查1["Y"], 0.0, 1e-12)
    校验文本("步骤(3) 轴承2 Fa/Fr>e2", 查2["判据"], "Fa/Fr>e")
    校验("步骤(3) 轴承2 X2", 查2["X"], 0.44, 1e-12)
    校验("步骤(3) 轴承2 Y2（插值）", 查2["Y"], 1.37, 0.005,
         "", "精确 1.3731")
    f_d = c.查表13_6_载荷系数("中等冲击", 取="中值")
    校验("步骤(3) 表13-6 中等冲击取 f_d=1.5", f_d, 1.5, 1e-12)
    P1 = c.eq13_8a(f_d, 1.0, 0.0, Fr1, 336.25)
    校验("步骤(3) P1=1.5(1×875.65+0×336.25)", P1, 1313.48, 0.005, "N")
    P2 = c.eq13_8a(f_d, 0.44, 1.37, Fr2, 736.25)
    校验("步骤(3) P2=1.5(0.44×1512.62+1.37×736.25)", P2, 2511.32, 0.005, "N")
    P2查 = c.eq13_8a(f_d, 查2["X"], 查2["Y"], Fr2, 736.25)
    校验("步骤(3) P2（插值 Y2 回代）", P2查, 2511.32, 0.005, "N")

    # (4) 按受力大的轴承2 验算寿命
    Lh = c.eq13_5(C, P2, n, ε)
    校验("步骤(4) 式(13-5) 7207C 寿命", Lh, 20733.83, 0.005, "h",
         "C=30500，P=2511.32")
    校验真("步骤(4) Lh>Lh'=15000 h", Lh > Lh_要求 and P1 < P2,
           "%.2f h > 15000 h，7207C 满足" % Lh)



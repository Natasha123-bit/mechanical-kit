def _解析区间文本(文本: str) -> tuple:
    """把“300~3 000”“1.0~1.2”解析为 (300.0, 3000.0)；只读数、不插值。"""
    s = str(文本).replace(" ", "").replace("～", "~")
    if "~" not in s:
        raise ValueError("表值“%s”不是 a~b 形式的区间" % (文本,))
    左, 右 = s.split("~", 1)
    return float(左), float(右)



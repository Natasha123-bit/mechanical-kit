def eq13_13(P列表, n列表, q列表, ε: float = 球轴承指数,
            n_m: float = None) -> float:
    """式(13-13) 不稳定载荷/转速时的计算载荷：
    P_m = [Σ(n_i q_i P_i^ε)/n_m]^(1/ε)。

    适用条件：载荷 P_i 与转速 n_i 频繁改变的轴承（如金属切削机床、起重机），
    按不稳定变应力疲劳损伤累积理论求计算载荷 P_m 与计算转速 n_m，再由
    式(13-15) 算寿命。
    P列表: 各工况当量动载荷 P_i，N；n列表: 各工况转速 n_i，r/min；
    q列表: 各工况运转时间与总运转时间之比 q_i（无量纲，Σq_i=1）；
    ε: 指数，球轴承 3、滚子轴承 10/3；
    n_m: 计算转速，r/min（缺省时按式13-14 由 n_i、q_i 算）。
    返回 P_m，N。注意分子是 Σ n_i q_i P_i^ε，**除以 n_m** 后才开 ε 次方。
    [核:p339]
    """
    if not (len(P列表) == len(n列表) == len(q列表)):
        raise ValueError("式13-13 要求 P、n、q 三个列表等长")
    if n_m is None:
        n_m = eq13_14(n列表, q列表)
    if n_m <= 0:
        raise ValueError("式13-13 的计算转速 n_m 必须为正")
    分子 = sum(float(ni) * float(qi) * float(Pi) ** ε
               for Pi, ni, qi in zip(P列表, n列表, q列表))
    return (分子 / n_m) ** (1.0 / ε)


def eq13_14(n列表, q列表) -> float:
    """式(13-14) 计算转速：n_m = Σ n_i q_i（相当于转速的平均值）。

    适用条件：与式(13-13) 配套，用于不稳定载荷和转速工况。
    n列表: 各工况转速 n_i，r/min；q列表: 各工况时间比 q_i（无量纲）。
    返回 n_m，r/min。
    [核:p339]
    """
    if len(n列表) != len(q列表):
        raise ValueError("式13-14 要求 n 与 q 两个列表等长")
    return sum(float(ni) * float(qi) for ni, qi in zip(n列表, q列表))


def eq13_15(C: float, P_m: float, n_m: float,
            ε: float = 球轴承指数) -> float:
    """式(13-15) 不稳定载荷/转速下的小时寿命：L_h = 10⁶/(60n_m)·(C/P_m)^ε。

    适用条件：将式(13-13)、(13-14) 代入式(13-5)，用于不稳定载荷/转速下的
    基本额定寿命计算。
    C: 基本额定动载荷，N；P_m: 计算载荷（式13-13），N；
    n_m: 计算转速（式13-14），r/min；ε: 指数，球轴承 3、滚子轴承 10/3。
    返回 L_h，h。
    [核:p340]
    """
    return 1e6 / (60.0 * n_m) * (C / P_m) ** ε



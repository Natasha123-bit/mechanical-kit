def eq5_1(d_2: float = None, P: float = None, n: float = None,
          P_h: float = None) -> float:
    """式(5-1) 螺纹升角：φ = arctan(P_h/(π d_2)) = arctan(nP/(π d_2))，**返回弧度**。

    适用条件：圆柱普通外螺纹的几何关系（图5-1）；单线螺纹 P_h=P，多线螺纹 P_h=nP。
    通用式，无载荷条件。
    d_2: 中径 mm（通过螺纹轴向截面内牙型上沟槽和凸起宽度相等处的假想圆柱直径）；
    P: 螺距 mm（相邻两牙在中径线上对应两点间的轴向距离）；
    n: 线数（螺纹的螺旋线数目）；
    P_h: 导程 mm（同一条螺旋线上相邻两牙在中径线上对应两点间的轴向距离）。
    返回 φ，**rad**（课本 p.75 以度分给 M10~M64 粗钢制螺栓的参考范围 3°2′~1°49′）。
    给 P_h 时优先用它，否则用 n·P；缺 P_h 且缺 n/P 抛 ValueError。
    [核:p70]
    """
    if d_2 is None:
        raise ValueError("式5-1 需要中径 d_2")
    if P_h is None:
        if P is None or n is None:
            raise ValueError("式5-1 需要导程 P_h，或线数 n 与螺距 P")
        P_h = n * P
    return math.atan(P_h / (math.pi * d_2))


def eq5_2(σ_s: float, A_1: float = None, d_1: float = None,
          材料: str = "碳钢", 取: str = "下限") -> float:
    """式(5-2) 预紧力上限：碳钢 F_0 ≤ (0.6~0.7)σ_s A_1；合金钢 F_0 ≤ (0.5~0.6)σ_s A_1。

    适用条件：一般连接用的钢制螺栓连接；拧紧后预紧应力不得超过材料屈服极限 σ_s
    的 80%（分材料给出上下限）。两式在课本上共用右侧一个花括号与编号(5-2)。
    σ_s: 螺栓材料屈服极限 MPa；A_1: 螺栓危险截面面积 mm²（≈πd_1²/4）；
    d_1: 螺纹小径 mm（未给 A_1 时用它算 A_1）；
    材料: "碳钢"/"合金钢"（也接受“碳钢螺栓”“合金钢螺栓”）；
    取: "下限"（默认，0.6 / 0.5）或 "上限"（0.7 / 0.6）。
    返回上限值（系数·σ_s·A_1），N。
    例5-1 步骤(5)：0.6×240×80.214=11 550.8 N，与 F_0=6520 N 比较。
    材料或取法不认识抛 ValueError。
    [核:p74]
    """
    范围 = {"碳钢": (0.6, 0.7), "合金钢": (0.5, 0.6),
            "碳钢螺栓": (0.6, 0.7), "合金钢螺栓": (0.5, 0.6)}
    if 材料 not in 范围:
        raise ValueError("式5-2 材料只有碳钢(0.6~0.7)、合金钢(0.5~0.6)，收到 %s"
                         % (材料,))
    if A_1 is None:
        if d_1 is None:
            raise ValueError("式5-2 需要 A_1 或 d_1")
        A_1 = 螺栓危险截面面积A_1(d_1)
    if 取 in ("下限", "小值"):
        系数 = 范围[材料][0]
    elif 取 in ("上限", "大值"):
        系数 = 范围[材料][1]
    else:
        raise ValueError("式5-2 取只能是“上限”或“下限”，收到 %s" % (取,))
    return 系数 * σ_s * A_1


def eq5_3(T: float = None, T_1: float = None, T_2: float = None,
          解: str = "T") -> float:
    """式(5-3) 拧紧力矩：T = T_1 + T_2。

    适用条件：拧紧螺栓时螺栓与被连接件间产生预紧力 F_0；拧紧力矩等于螺纹副摩擦
    阻力矩与螺母环形支承面摩擦阻力矩之和（图5-10）。
    T: 拧紧力矩 N·mm；T_1: 螺纹副间摩擦阻力矩 N·mm；
    T_2: 螺母环形端面与被连接件（或垫圈）支承面间摩擦阻力矩 N·mm。
    等式型，默认解 T。解: "T" / "T_1"（=T−T_2）/ "T_2"（=T−T_1）。
    返回所求解 N·mm。
    [核:p75]
    """
    if 解 == "T":
        return T_1 + T_2
    if 解 == "T_1":
        return T - T_2
    if 解 == "T_2":
        return T - T_1
    raise ValueError("式5-3 只能解 T/T_1/T_2，收到 %s" % (解,))


def eq5_4(F_0: float, d_2: float, φ: float, φ_v: float) -> float:
    """式(5-4) 螺纹副摩擦阻力矩：T_1 = F_0 (d_2/2) tan(φ+φ_v)。

    适用条件：拧紧时螺纹副间的摩擦阻力矩；对 M10~M64 粗牙普通螺纹钢制螺栓，
    课本给经验取值 d_2≈0.9d、φ=3°2′~1°49′、φ_v=arctan1.155f（无润滑 f≈0.1~0.2）。
    F_0: 预紧力 N；d_2: 螺纹中径 mm；φ: 螺纹升角 rad；φ_v: 当量摩擦角 rad。
    返回 T_1，N·mm。
    [核:p75]
    """
    return F_0 * d_2 / 2.0 * math.tan(φ + φ_v)


def eq5_5(f_c: float, F_0: float, D_0: float, d_0: float) -> float:
    """式(5-5) 螺母支承面摩擦阻力矩：T_2 = (1/3) f_c F_0 (D_0³−d_0³)/(D_0²−d_0²)。

    适用条件：螺母与被连接件（或垫圈）环形支承面间的摩擦力矩；f_c=0.15、
    D_0≈1.5d、d_0≈1.1d 为 M10~M64 粗牙普通螺纹钢制螺栓的整理取值。
    f_c: 螺母与支承面间摩擦因数；F_0: 预紧力 N；
    D_0: 螺母环形支承面外径 mm；d_0: 螺栓孔直径 mm。
    返回 T_2，N·mm。分母为 D_0²−d_0²（二次方差），分子为三次方差。
    [核:p75]
    """
    return (1.0 / 3.0) * f_c * F_0 * (D_0 ** 3 - d_0 ** 3) / (D_0 ** 2 - d_0 ** 2)


def eq5_6(F_0: float, d_2: float, φ: float, φ_v: float, f_c: float,
          D_0: float, d_0: float) -> float:
    """式(5-6) 拧紧力矩：
    T = (1/2) F_0 [d_2 tan(φ+φ_v) + (2/3) f_c (D_0³−d_0³)/(D_0²−d_0²)]。

    适用条件：由式(5-4)、(5-5) 代入式(5-3) 所得；M10~M64 粗牙普通螺纹钢制螺栓，
    进一步取 tanφ_v≈0.17、d_2/d_1=1.04~1.08、tanφ≈0.05、f_c=0.15、d_2≈0.9d、
    D_0≈1.5d、d_0≈1.1d 后可整理为式(5-7)。
    F_0: 预紧力 N；d_2: 中径 mm；φ: 升角 rad；φ_v: 当量摩擦角 rad；
    f_c: 支承面摩擦因数；D_0: 支承面外径 mm；d_0: 螺栓孔直径 mm。
    返回 T，N·mm。方括号内第一项为螺纹副项，第二项前系数为 2/3。
    [核:p75]
    """
    螺纹副项 = d_2 * math.tan(φ + φ_v)
    支承面项 = (2.0 / 3.0) * f_c * (D_0 ** 3 - d_0 ** 3) / (D_0 ** 2 - d_0 ** 2)
    return 0.5 * F_0 * (螺纹副项 + 支承面项)


def eq5_7(F_0: float = None, d: float = None, T: float = None,
          解: str = "T") -> float:
    """式(5-7) 拧紧力矩近似式：T ≈ 0.2 F_0 d。

    适用条件：把式(5-6) 中各参数（tanφ_v≈0.17、d_2/d_1=1.04~1.08、tanφ≈0.05、
    f_c=0.15、d_2≈0.9d、D_0≈1.5d、d_0≈1.1d）代入整理而得；适用于 M10~M64
    粗牙普通螺纹的钢制螺栓。课本用近似号 ≈。
    F_0: 预紧力 N；d: 螺栓公称直径（大径）mm；T: 拧紧力矩 N·mm。
    等式型，默认解 T。解: "T" / "F_0"（=T/(0.2d)）/ "d"（=T/(0.2F_0)）。
    返回所求解（N·mm、N 或 mm）。
    [核:p76]
    """
    if 解 == "T":
        return 0.2 * F_0 * d
    if 解 == "F_0":
        return T / (0.2 * d)
    if 解 == "d":
        return T / (0.2 * F_0)
    raise ValueError("式5-7 只能解 T/F_0/d，收到 %s" % (解,))


def eq5_8(L_s: float = None, F_0: float = None, C_b: float = None,
          L_M: float = None, 解: str = "L_M") -> float:
    """式(5-8) 拧紧后螺栓长度：L_M = L_s + F_0/C_b。

    适用条件：采用测定螺栓伸长量的方法控制预紧力（图5-11）；适用于测力/定力扳手
    控制准确性较差或大型螺栓连接。
    L_M: 拧紧后螺栓长度 mm（按所需预紧力 F_0 拧紧后的长度）；
    L_s: 螺母刚拧到与被连接件贴紧时测得的螺栓原始长度 mm；
    F_0: 预紧力 N；C_b: 螺栓刚度系数 N/mm。
    等式型，默认解 L_M。解: "L_M" / "F_0"（=(L_M−L_s)C_b）/ "L_s"（=L_M−F_0/C_b）/
        "C_b"（=F_0/(L_M−L_s)）。
    返回所求解（mm、N 或 N/mm）。
    [核:p76]
    """
    if 解 == "L_M":
        return L_s + F_0 / C_b
    if 解 == "F_0":
        return (L_M - L_s) * C_b
    if 解 == "L_s":
        return L_M - F_0 / C_b
    if 解 == "C_b":
        return F_0 / (L_M - L_s)
    raise ValueError("式5-8 只能解 L_M/F_0/L_s/C_b，收到 %s" % (解,))


def eq5_9(P: float, F_0: float, C_b: float, 单位: str = "°") -> float:
    """式(5-9) 螺母所需转角：θ = (360°/P)(F_0/C_b)（直接计算式）。

    适用条件：对于不重要的螺栓连接，根据拧紧螺母时的转角 θ 估计预紧力 F_0。
    本式自带 360°，故**默认返回度（°）**——这是本库唯一以度为默认输出的角度量；
    需要弧度时传 ``单位="rad"``（内部乘 π/180）。
    P: 螺距 mm；F_0: 预紧力 N；C_b: 螺栓刚度系数 N/mm（同式5-8）。
    返回 θ，°（或 rad）。本式为直接计算，不设 ``解=`` 分支。
    [核:p76]
    """
    换算 = math.pi / 180.0 if 单位 in ("rad", "弧度") else 1.0
    return (360.0 / P) * (F_0 / C_b) * 换算


def eq5_10(F: float, d_1: float) -> float:
    """式(5-10) 松螺栓连接的拉伸应力：σ = F/((π/4)d_1²)，条件 σ ≤ [σ]。

    适用条件：松螺栓连接（装配时螺母不需要拧紧，承受工作载荷前螺栓不受力），
    例如拉杆、起重吊钩等的螺纹连接；危险截面取螺纹牙根圆柱的横截面（图5-12）。
    F: 工作载荷 N；d_1: 螺栓危险截面直径（螺纹小径）mm。
    返回 σ，MPa。是否 ≤[σ] 由调用方按式(5-10) 判据比较（本函数只算应力）。
    [核:p79]
    """
    return F / (math.pi / 4.0 * d_1 ** 2)


def eq5_11(F: float, 许用σ: float) -> float:
    """式(5-11) 松螺栓连接的设计式：d_1 ≥ √(4F/(π[σ]))。

    适用条件：由式(5-10) 改写，已知载荷求螺栓小径（松螺栓连接）。
    F: 工作载荷 N；许用σ: 螺栓材料许用拉应力 MPa。
    返回 d_1 下限，mm（未圆整；圆整到标准螺纹由调用方按标准查取）。
    [核:p80]
    """
    return math.sqrt(4.0 * F / (math.pi * 许用σ))


def eq5_12(F_0: float, d_1: float) -> float:
    """式(5-12) 仅受预紧力紧螺栓的拉伸应力：σ = F_0/((π/4)d_1²)。

    适用条件：紧螺栓连接（1）仅承受预紧力的紧螺栓连接——拧紧时螺栓除受预紧力
    F_0 拉伸外，还受螺纹摩擦力矩 T_1 的扭转，处于拉伸与扭转复合应力状态；
    本式只是其中的拉伸应力部分（扭转切应力见式5-13）。
    F_0: 预紧力 N；d_1: 螺纹小径 mm。返回 σ，MPa。
    [核:p80]
    """
    return F_0 / (math.pi / 4.0 * d_1 ** 2)


def eq5_13(F_0: float, d_2: float, d_1: float, φ: float, φ_v: float) -> float:
    """式(5-13) 紧螺栓的扭转切应力：
    τ = F_0 tan(φ+φ_v)(d_2/2) / ((π/16)d_1³)
      = [(tanφ+tanφ_v)/(1−tanφ·tanφ_v)]·(2d_2/d_1)·F_0/((π/4)d_1²)。

    适用条件：仅承受预紧力的紧螺栓连接；扭转切应力由螺纹摩擦力矩 T_1（式5-4）
    产生；第二等号用 tan(φ+φ_v) 的和角展开与抗扭截面系数 πd_1³/16 变换。
    F_0: 预紧力 N；d_2: 中径 mm；d_1: 小径 mm；
    φ: 螺纹升角 rad；φ_v: 当量摩擦角 rad。
    返回 τ，MPa。本函数按第一等号计算，第二等号为等价变形（测试中互验）。
    [核:p80]
    """
    分子 = F_0 * math.tan(φ + φ_v) * (d_2 / 2.0)
    分母 = math.pi / 16.0 * d_1 ** 3
    return 分子 / 分母


def eq5_14(σ: float = None, τ: float = None, 解: str = "τ") -> float:
    """式(5-14) 扭转切应力近似：τ ≈ 0.5σ。

    适用条件：M10~M64 普通螺纹的钢制螺栓，取 tanφ_v≈0.17、d_2/d_1=1.04~1.08、
    tanφ≈0.05 后由式(5-13) 化简所得。课本用近似号 ≈。
    σ: 拉伸应力 MPa；τ: 扭转切应力 MPa。
    等式型，默认解 τ。解: "τ"（=0.5σ）/ "σ"（=2τ）。
    返回 MPa。
    [核:p80]
    """
    if 解 == "τ":
        return 0.5 * σ
    if 解 == "σ":
        return 2.0 * τ
    raise ValueError("式5-14 只能解 τ/σ，收到 %s" % (解,))


def eq5_15(σ: float, τ: float = None) -> float:
    """式(5-15) 预紧状态下的计算应力（第四强度理论）：
    σ_ca = √(σ²+3τ²) ≈ 1.3σ（取 τ≈0.5σ 时 √(σ²+3×0.25σ²)=√1.75σ≈1.3σ）。

    适用条件：螺栓材料为塑性材料，按最大畸变能理论；适用于 M10~M64 普通螺纹的
    钢制紧螺栓连接——故计算时可只按拉伸强度计算，并把拉力（预紧力）增大 30%
    以考虑扭转影响。
    σ: 拉伸应力 MPa；τ: 扭转切应力 MPa；不给 τ 时按课本整理式返回 1.3σ。
    返回 σ_ca，MPa。给 τ 时用精确式，不给时用近似式（docstring 明示）。
    [核:p80]
    """
    if τ is None:
        return 1.3 * σ
    return math.sqrt(σ ** 2 + 3.0 * τ ** 2)


def eq5_16(F_1: float = None, F: float = None, F_2: float = None,
           解: str = "F_2") -> float:
    """式(5-16) 螺栓总拉力：F_2 = F_1 + F。

    适用条件：承受轴向载荷的紧螺栓连接（图5-13c、5-14c）：螺栓和被连接件材料在
    弹性变形范围内，受力与变形符合拉（压）胡克定律；总拉力不简单地等于预紧力与
    轴向载荷之和（F_2 ≠ F_0 + F）。
    F_2: 螺栓总拉力 N；F_1: 残余预紧力（被连接件剩余压缩力）N；F: 轴向载荷 N。
    等式型，默认解 F_2。解: "F_2" / "F_1"（=F_2−F）/ "F"（=F_2−F_1）。
    返回 N。
    [核:p81]
    """
    if 解 == "F_2":
        return F_1 + F
    if 解 == "F_1":
        return F_2 - F
    if 解 == "F":
        return F_2 - F_1
    raise ValueError("式5-16 只能解 F_2/F_1/F，收到 %s" % (解,))


def eq5_17(F_0: float = None, C_b: float = None, C_m: float = None,
           λ_b: float = None, λ_m: float = None, 解: str = "C_b") -> float:
    """式(5-17) 刚度与变形的关系：F_0/λ_b = tanθ_b = C_b；F_0/λ_m = tanθ_m = C_m。

    适用条件：紧螺栓连接承受轴向载荷前（预紧状态），由图5-14 的几何关系推出；
    螺栓与被连接件均处于弹性变形范围。一个编号对应并列两式（两行一组）。
    F_0: 预紧力 N；λ_b: 螺栓伸长量 mm；λ_m: 被连接件压缩量 mm；
    θ_b/θ_m: 螺栓/被连接件受力变形线倾角 rad（tan 即刚度）；
    C_b/C_m: 螺栓/被连接件刚度 N/mm。
    等式型，默认解 C_b。解: "C_b"（=F_0/λ_b）/ "C_m"（=F_0/λ_m）/
        "λ_b"（=F_0/C_b）/ "λ_m"（=F_0/C_m）/ "F_0"（=C_b λ_b，或 C_m λ_m）。
    返回所求解（N/mm、mm 或 N）。
    [核:p82]
    """
    if 解 == "C_b":
        return F_0 / λ_b
    if 解 == "C_m":
        return F_0 / λ_m
    if 解 == "λ_b":
        return F_0 / C_b
    if 解 == "λ_m":
        return F_0 / C_m
    if 解 == "F_0":
        if C_b is not None and λ_b is not None:
            return C_b * λ_b
        return C_m * λ_m
    raise ValueError("式5-17 只能解 C_b/C_m/λ_b/λ_m/F_0，收到 %s" % (解,))


def eq5_18(F_1: float = None, F: float = None, C_b: float = None,
           C_m: float = None, F_0: float = None, 解: str = "F_0") -> float:
    """式(5-18) 预紧力：F_0 = F_1 + (1−C_b/(C_b+C_m))F = F_1 + (C_m/(C_b+C_m))F。

    适用条件：承受轴向载荷的紧螺栓连接；由图5-14 几何关系 F_0=F_1+(F−ΔF)（页图
    标 (a)）与 ΔF=C_b/(C_b+C_m)F（页图标 (b)）联立得出。
    F_0: 预紧力 N；F_1: 残余预紧力 N；F: 轴向载荷 N；
    C_b/C_m: 螺栓/被连接件刚度 N/mm。
    等式型，默认解 F_0。解: "F_0" / "F_1"（=F_0−(C_m/(C_b+C_m))F）/
        "F"（=(F_0−F_1)(C_b+C_m)/C_m）。
    返回 N。C_m=0 时解 F 抛 ValueError（退化，无解）。
    [核:p82]
    """
    被连接件比 = C_m / (C_b + C_m)
    if 解 == "F_0":
        return F_1 + 被连接件比 * F
    if 解 == "F_1":
        return F_0 - 被连接件比 * F
    if 解 == "F":
        if C_m == 0:
            raise ValueError("式5-18 解 F 需要 C_m≠0（C_m=0 时该式退化）")
        return (F_0 - F_1) / 被连接件比
    raise ValueError("式5-18 只能解 F_0/F_1/F，收到 %s" % (解,))


def eq5_19(F_0: float = None, F: float = None, C_b: float = None,
           C_m: float = None, F_2: float = None, 解: str = "F_2") -> float:
    """式(5-19) 螺栓总拉力的另一种表达：F_2 = F_0 + (C_b/(C_b+C_m))F。

    适用条件：承受轴向载荷的紧螺栓连接；页图先给出 F_2=F_0+ΔF（未编号），
    再给出本式。C_b/(C_b+C_m) 称为螺栓的相对刚度，其值在 0~1 范围变动。
    F_2: 螺栓总拉力 N；F_0: 预紧力 N；F: 轴向载荷 N；
    C_b/C_m: 螺栓/被连接件刚度 N/mm。
    等式型，默认解 F_2。解: "F_2" / "F_0"（=F_2−相对刚度·F）/
        "F"（=(F_2−F_0)/相对刚度）。
    返回 N。相对刚度为 0 时解 F 抛 ValueError。
    [核:p82]
    """
    相对 = C_b / (C_b + C_m)
    if 解 == "F_2":
        return F_0 + 相对 * F
    if 解 == "F_0":
        return F_2 - 相对 * F
    if 解 == "F":
        if 相对 == 0:
            raise ValueError("式5-19 解 F 需要 C_b≠0（相对刚度为 0 时该式退化）")
        return (F_2 - F_0) / 相对
    raise ValueError("式5-19 只能解 F_2/F_0/F，收到 %s" % (解,))


def eq5_20(F_2: float, d_1: float) -> float:
    """式(5-20) 承受轴向载荷紧螺栓的计算应力：
    σ_ca = 1.3F_2/((π/4)d_1²)，条件 σ_ca ≤ [σ]。

    适用条件：受轴向载荷的紧螺栓连接，按式(5-16) 求得 F_2 后作强度计算；考虑
    螺栓在总拉力下可能需补充拧紧（应尽量避免），将总拉力增大 30% 以考虑扭转
    切应力的影响。
    F_2: 螺栓总拉力 N；d_1: 螺纹小径 mm。返回 σ_ca，MPa。
    [核:p83]
    """
    return 1.3 * F_2 / (math.pi / 4.0 * d_1 ** 2)


def eq5_21(F_2: float, 许用σ: float) -> float:
    """式(5-21) 承受轴向载荷紧螺栓的设计式：d_1 ≥ √(4×1.3F_2/(π[σ]))。

    适用条件：由式(5-20) 改写（承受轴向载荷的紧螺栓连接），已知总拉力求小径。
    F_2: 螺栓总拉力 N；许用σ: 螺栓材料许用拉应力 MPa。
    返回 d_1 下限，mm（未圆整；例5-1 得 8.6 mm，按 GB/T 196 粗牙取 M12，
    d_1=10.106 mm，圆整步骤不属于本式）。
    [核:p83]
    """
    return math.sqrt(4.0 * 1.3 * F_2 / (math.pi * 许用σ))


def eq5_22(F_0: float, d_1: float) -> float:
    """式(5-22) 受轴向变载荷螺栓的最小拉应力：σ_min = F_0/((π/4)d_1²)。

    适用条件：受轴向变载荷的重要连接（如内燃机气缸盖的螺栓连接）；轴向载荷在
    0~F 范围内变化时，螺栓总拉力在 F_0~F_2 范围内变化；不考虑螺纹摩擦力矩的
    扭转作用；此时螺栓应力的变化规律是 σ_min 保持不变（图5-15）。
    F_0: 预紧力 N；d_1: 螺纹小径 mm。返回 σ_min，MPa。
    配套的最大拉应力 σ_max=F_2/((π/4)d_1²) 在页图上未编号，可由本函数同形算得
    （把 F_0 换成 F_2）；式(5-23) 需要它。
    [核:p83]
    """
    return F_0 / (math.pi / 4.0 * d_1 ** 2)


def eq5_23(σ_max: float = None, σ_min: float = None, σ_a: float = None,
           C_b: float = None, C_m: float = None, F: float = None,
           d_1: float = None, 解: str = "σ_a") -> float:
    """式(5-23) 应力幅：σ_a = (σ_max−σ_min)/2 = (C_b/(C_b+C_m))·2F/(πd_1²)。

    适用条件：受轴向变载荷的重要连接，轴向载荷在 0~F 范围内变化；不考虑螺纹
    摩擦力矩的扭转作用；用于按图3-8 极限应力线图校核疲劳强度。
    σ_max: 最大拉应力 MPa（σ_max=F_2/((π/4)d_1²)）；σ_min: 最小拉应力 MPa
    （式5-22）；σ_a: 应力幅 MPa；C_b/C_m: 螺栓/被连接件刚度 N/mm；
    F: 轴向载荷上限 N；d_1: 螺纹小径 mm。
    等式型，默认解 σ_a：给 σ_max、σ_min 时用第一等号，否则用第二等号
    （需 C_b、C_m、F、d_1）。
    解: "σ_a" / "σ_max"（=σ_min+2σ_a）/ "σ_min"（=σ_max−2σ_a）/
        "F"（=σ_a(C_b+C_m)πd_1²/(2C_b)）。
    返回所求解（MPa 或 N）。
    [核:p83]
    """
    if C_b is not None and C_m is not None:
        相对 = C_b / (C_b + C_m)
    else:
        相对 = None
    if 解 == "σ_a":
        if σ_max is not None and σ_min is not None:
            return (σ_max - σ_min) / 2.0
        if 相对 is None:
            raise ValueError("式5-23 第二等号需要 C_b、C_m")
        return 相对 * 2.0 * F / (math.pi * d_1 ** 2)
    if 解 == "σ_max":
        return σ_min + 2.0 * σ_a
    if 解 == "σ_min":
        return σ_max - 2.0 * σ_a
    if 解 == "F":
        if 相对 is None:
            raise ValueError("式5-23 解 F 需要 C_b、C_m")
        return σ_a / 相对 * (math.pi * d_1 ** 2) / 2.0
    raise ValueError("式5-23 只能解 σ_a/σ_max/σ_min/F，收到 %s" % (解,))


def eq5_24(σ_1tc: float, K_σ: float, φ_σ: float, σ_min: float,
           σ_a: float) -> float:
    """式(5-24) 螺栓疲劳强度的计算安全系数：
    S_ca = [2σ_{-1tc} + (K_σ−φ_σ)σ_min] / [(K_σ+φ_σ)(2σ_a+σ_min)] ≥ S。

    适用条件：受轴向变载荷的重要连接（如内燃机气缸盖螺栓连接），在按式(5-20)
    或(5-21) 做静强度计算之外，对螺栓疲劳强度作精确校核；不考虑螺纹摩擦力矩的
    扭转作用。设工作应力点在 OGJI 区域内，应力线与极限应力线 AG 相交（图3-8），
    仿式(3-26) 校核；若在 GIC 区域则只需仿式(3-20) 校核静强度。
    σ_1tc: 螺栓材料的对称循环拉压疲劳极限 MPa（课本记 σ_{-1tc}，见表5-4）；
    K_σ: 拉压疲劳强度综合影响系数（忽略加工方法时 K_σ=k_σ/ε_σ）；
    φ_σ: 材料常数（平均应力折算系数）：碳钢 0.1~0.2，合金钢 0.2~0.3；
    σ_min: 最小拉应力 MPa（式5-22）；σ_a: 应力幅 MPa（式5-23）。
    返回 S_ca（无量纲）；是否 ≥S（表5-5）由调用方比较。
    注意分母是 (K_σ+φ_σ) 与 (2σ_a+σ_min) 两个括号**相乘**；分子第二项为
    (K_σ−φ_σ)σ_min（减号）。
    [核:p84]
    """
    分子 = 2.0 * σ_1tc + (K_σ - φ_σ) * σ_min
    分母 = (K_σ + φ_σ) * (2.0 * σ_a + σ_min)
    return 分子 / 分母


def eq5_25(F: float, d_0: float, L_min: float) -> float:
    """式(5-25) 铰制孔（加强杆）螺栓的挤压强度：
    σ_bs = F/(d_0 L_min) ≤ [σ_bs]。

    适用条件：承受横向载荷的加强杆（铰制孔）螺栓连接（图5-16）——螺栓杆与孔壁
    无间隙，接触表面受挤压、接合面处螺栓杆受剪切，故分别按挤压与剪切（式5-26）
    计算；假设压力在挤压面上均匀分布，且预紧力很小、不计预紧力与螺纹摩擦力矩。
    F: 螺栓杆所受的工作剪力 N；d_0: 剪切面直径 mm（可取螺栓孔直径）；
    L_min: 螺栓杆与孔壁挤压面的最小高度 mm（设计时应使 L_min≥1.25d_0，
    该限制只作提示，本函数不校验）。
    返回 σ_bs，MPa。
    [核:p85]
    """
    return F / (d_0 * L_min)


def eq5_26(F: float, d_0: float) -> float:
    """式(5-26) 铰制孔（加强杆）螺栓的剪切强度：
    τ = F/((π/4)d_0²) ≤ [τ]。

    适用条件：承受横向载荷的加强杆（铰制孔）螺栓连接（图5-16），与式(5-25)
    配对使用；不考虑预紧力和螺纹摩擦力矩的影响。分子是 F（不带 1.3）。
    F: 螺栓杆所受的工作剪力 N；d_0: 剪切面直径 mm（可取螺栓孔直径）。
    返回 τ，MPa。
    [核:p85]
    """
    return F / (math.pi / 4.0 * d_0 ** 2)


def eq5_27(F_0: float, d_1: float) -> float:
    """式(5-27) 承受横向载荷的普通螺栓的拉伸强度：
    σ_ca = 1.3F_0/((π/4)d_1²) ≤ [σ]。

    适用条件：承受横向载荷的普通螺栓连接（图5-17）——靠连接预紧后接合面间摩擦力
    抵抗横向载荷；螺栓仅受预紧力，且预紧力不受横向载荷影响、加载后保持不变；
    F_0 按接合面不滑移条件（式5-29）确定。
    F_0: 螺栓所受预紧力 N；d_1: 螺纹小径 mm。返回 σ_ca，MPa。
    课本风险提示：要求较大预紧力（F_0>F/f，f=0.2 时 F_0>5F）会使结构尺寸增加；
    振动/冲击/变载荷下 f 变动会降低可靠性，可能松脱。
    [核:p85]
    """
    return 1.3 * F_0 / (math.pi / 4.0 * d_1 ** 2)


def eq5_28(F_Σ: float = None, z: float = None, F: float = None,
           解: str = "F") -> float:
    """式(5-28) 受横向载荷螺栓组中每个螺栓的工作剪力：F = F_Σ/z。

    适用条件：图5-24 由 4 个螺栓组成，横向载荷作用线与螺栓轴线垂直并通过螺栓组
    对称中心；普通螺栓连接靠预紧后接合面摩擦力抵抗，加强杆螺栓连接靠螺栓杆剪切
    和挤压抵抗；计算时近似认为各螺栓承担的横向载荷均等。本式用于加强杆螺栓连接
    （每个螺栓所受的横向工作剪力）。
    F_Σ: 横向总载荷 N；z: 螺栓数目；F: 每个螺栓的横向工作剪力 N。
    等式型，默认解 F。解: "F" / "F_Σ"（=Fz）/ "z"（=F_Σ/F）。
    返回所求解（N 或无量纲）。
    [核:p88]
    """
    if 解 == "F":
        return F_Σ / z
    if 解 == "F_Σ":
        return F * z
    if 解 == "z":
        return F_Σ / F
    raise ValueError("式5-28 只能解 F/F_Σ/z，收到 %s" % (解,))


def eq5_29(K_s: float, F_Σ: float, f: float, z: float, i: float) -> float:
    """式(5-29) 受横向载荷普通螺栓组的预紧力：F_0 ≥ K_s F_Σ/(f z i)。

    适用条件：受横向载荷的普通螺栓组连接——应保证连接预紧后接合面间产生的最大
    摩擦力大于或等于横向载荷；平衡条件为 f·F_0·z·i ≥ K_s·F_Σ（未编号）。
    K_s: 防滑系数（1.1~1.3）；F_Σ: 横向总载荷 N；f: 接合面摩擦因数（表5-7）；
    z: 螺栓数目；i: 接合面数（图5-24 中 i=2）。
    返回 F_0 下限，N。分母为 f·z·i 三者连乘。
    [核:p89]
    """
    return K_s * F_Σ / (f * z * i)


def eq5_30(K_s: float, T: float, f: float, r列表: list = None,
           Σr: float = None) -> float:
    """式(5-30) 受转矩普通螺栓组的预紧力：
    F_0 ≥ K_s T/(f(r_1+r_2+…+r_z)) = K_s T/(f Σ_{i=1}^{z} r_i)。

    适用条件：受转矩的螺栓组连接采用普通螺栓时（图5-25a）——靠预紧后接合面间
    摩擦力矩抵抗转矩 T；假设各螺栓预紧力均为 F_0、摩擦力相等且集中作用在螺栓
    中心处，各摩擦力与力臂 r_i 垂直。力矩平衡条件
    f F_0 r_1+…+f F_0 r_z ≥ K_s T（未编号）。
    K_s: 防滑系数；T: 作用在接合面内的转矩 N·mm；f: 摩擦因数（表5-7）；
    r列表: 各螺栓轴线到对称中心 O 的距离 mm；Σr: 可直接给 Σr_i（与 r列表 二选一）。
    返回 F_0 下限，N。分母是 f·Σr_i（r_i 一次方，与式5-33 的 r_i² 不同）。
    [核:p89]
    """
    if r列表 is not None:
        总和 = float(sum(r列表))
    elif Σr is not None:
        总和 = float(Σr)
    else:
        raise ValueError("式5-30 需要 r列表 或 Σr")
    return K_s * T / (f * 总和)


def eq5_31(F_max: float = None, r_max: float = None, F_i: float = None,
           r_i: float = None, 解: str = "F_i") -> float:
    """式(5-31) 受转矩加强杆螺栓组的剪力分配：
    F_max/r_max = F_i/r_i，或 F_i = F_max r_i/r_max，i=1,2,…,z。

    适用条件：受转矩的螺栓组连接采用加强杆螺栓时（图5-25b）——转矩 T 下各螺栓
    受剪切和挤压，工作剪力与力臂 r_i 垂直；假定底板为刚体、受载后接合面保持平面，
    各螺栓剪切变形量与 r_i 成正比；剪切刚度相同时变形越大剪力越大。
    F_max: 受力最大螺栓的工作剪力 N；r_max: 其轴线到对称中心 O 的距离 mm；
    F_i: 第 i 个螺栓的工作剪力 N；r_i: 其轴线到 O 的距离 mm。
    等式型，默认解 F_i。解: "F_i" / "F_max"（=F_i r_max/r_i）/
        "r_i"（=F_i r_max/F_max）/ "r_max"（=F_max r_i/F_i）。
    返回所求解（N 或 mm）。
    [核:p90]
    """
    if 解 == "F_i":
        return F_max * r_i / r_max
    if 解 == "F_max":
        return F_i * r_max / r_i
    if 解 == "r_i":
        return F_i * r_max / F_max
    if 解 == "r_max":
        return F_max * r_i / F_i
    raise ValueError("式5-31 只能解 F_i/F_max/r_i/r_max，收到 %s" % (解,))


def eq5_32(F列表: list, r列表: list) -> float:
    """式(5-32) 受转矩加强杆螺栓组的力矩平衡：Σ_{i=1}^{z} F_i r_i = T。

    适用条件：受转矩的加强杆螺栓组连接；与式(5-31) 联解得出式(5-33)。
    F列表: 各螺栓工作剪力 N；r列表: 对应力臂 mm（两列表等长）。
    返回 T，N·mm。列表长度不等抛 ValueError。
    [核:p90]
    """
    if len(F列表) != len(r列表):
        raise ValueError("式5-32 的 F 与 r 列表长度必须相同")
    return float(sum(F * r for F, r in zip(F列表, r列表)))


def eq5_33(T: float, r列表: list, r_max: float = None) -> float:
    """式(5-33) 受转矩加强杆螺栓组的最大工作剪力：F_max = T r_max/Σ_{i=1}^{z} r_i²。

    适用条件：受转矩的加强杆螺栓组连接，联解式(5-31) 与式(5-32) 求得。图5-25c 的
    凸缘联轴器是典型部件，各螺栓 r_1=…=r_z 时按连接类型代入式(5-30) 或本式。
    T: 接合面内转矩 N·mm；r列表: 各螺栓轴线到对称中心 O 的距离 mm（可取负值，
    平方后同号）；r_max: 受力最大螺栓的力臂 mm（默认取 max(r列表)）。
    返回 F_max，N。分母为 Σr_i²（平方，与式5-30 的 Σr_i 必须区分）。
    [核:p90]
    """
    if r_max is None:
        r_max = max(r列表)
    分母 = float(sum(r * r for r in r列表))
    return T * r_max / 分母


def eq5_34(F_Σ: float = None, z: float = None, F: float = None,
           解: str = "F") -> float:
    """式(5-34) 受轴向载荷螺栓组中每个螺栓的轴向载荷：F = F_Σ/z。

    适用条件：图5-26 气缸盖螺栓组连接，轴向总载荷 F_Σ 的作用线与螺栓轴线平行并
    通过对称中心；计算时认为各螺栓平均受载。各螺栓除承受轴向载荷 F 外还承受预紧
    力 F_0，工作时总拉力并不等于 F 与 F_0 之和（见式5-19）。
    F_Σ: 轴向总载荷 N；z: 螺栓数目；F: 每个螺栓的轴向载荷 N。
    等式型，默认解 F。解: "F" / "F_Σ"（=Fz）/ "z"（=F_Σ/F）。
    形式与式(5-28) 相同，但载荷方向不同（此处为轴向、式5-28 为横向）。
    返回所求解（N 或无量纲）。
    [核:p90]
    """
    if 解 == "F":
        return F_Σ / z
    if 解 == "F_Σ":
        return F * z
    if 解 == "z":
        return F_Σ / F
    raise ValueError("式5-34 只能解 F/F_Σ/z，收到 %s" % (解,))


def eq5_35(F列表: list, L列表: list) -> float:
    """式(5-35) 受倾覆力矩螺栓组的力矩平衡：M = Σ_{i=1}^{z} F_i L_i。

    适用条件：图5-27a 受倾覆力矩的底板螺栓组连接，倾覆力矩 M 作用在通过 x-x 并
    垂直于连接接合面的对称平面内；O-O 两侧底板上的两个总合力（F 与 F_m）对 O-O
    形成的力矩应与 M 平衡。
    F列表: 各螺栓所受工作载荷 N；L列表: 各螺栓轴线到底板中心线 O-O 的距离 mm。
    返回 M，N·mm。列表长度不等抛 ValueError。
    [核:p92]
    """
    if len(F列表) != len(L列表):
        raise ValueError("式5-35 的 F 与 L 列表长度必须相同")
    return float(sum(F * L for F, L in zip(F列表, L列表)))


def eq5_36(F_max: float = None, L_max: float = None, F_i: float = None,
           L_i: float = None, 解: str = "F_i") -> float:
    """式(5-36) 受倾覆力矩螺栓组的工作载荷分配：
    F_max/L_max = F_i/L_i，或 F_i = F_max L_i/L_max，i=1,2,…,z。

    适用条件：受倾覆力矩的底板螺栓组连接——底板受载后仍保持为平面，按变形协调
    各螺栓变形与到 O-O 的距离成正比；各螺栓刚度相同时工作载荷也与该距离成正比。
    符号与式(5-31) 同型，只是把半径 r 换成距离 L。
    F_max: 受力最大螺栓的工作载荷 N；L_max: L_i 中的最大值 mm；
    F_i: 第 i 个螺栓的工作载荷 N；L_i: 其轴线到 O-O 的距离 mm。
    等式型，默认解 F_i。解: "F_i" / "F_max" / "L_i" / "L_max"。
    返回所求解（N 或 mm）。
    [核:p92]
    """
    if 解 == "F_i":
        return F_max * L_i / L_max
    if 解 == "F_max":
        return F_i * L_max / L_i
    if 解 == "L_i":
        return F_i * L_max / F_max
    if 解 == "L_max":
        return F_max * L_i / F_i
    raise ValueError("式5-36 只能解 F_i/F_max/L_i/L_max，收到 %s" % (解,))


def eq5_37(M: float, L列表: list, L_max: float = None) -> float:
    """式(5-37) 受倾覆力矩螺栓组的最大工作载荷：F_max = M L_max/Σ_{i=1}^{z} L_i²。

    适用条件：受倾覆力矩的底板螺栓组连接，联解式(5-35) 与式(5-36) 求得。
    M: 外加倾覆力矩 N·mm；L列表: 各螺栓轴线到底板中心线 O-O 的距离 mm
    （对称布置时可取 ±值，平方后同号；例5-1 取 [140,−140,140,−140]）；
    L_max: L_i 中的最大值 mm（默认取 max(L列表)）。
    返回 F_max，N。与式(5-33) 同型（T→M、r→L）。
    [核:p92]
    """
    if L_max is None:
        L_max = max(L列表)
    分母 = float(sum(L * L for L in L列表))
    return M * L_max / 分母


def eq5_38(σ_bs: float, Δσ_bsmax: float) -> float:
    """式(5-38) 接合面最大压应力：σ_bsmax = σ_bs + Δσ_bsmax ≤ [σ_bs]。

    适用条件：受倾覆力矩的螺栓组连接，防止接合面受压最大处被压碎；σ_bs 为预紧
    产生的挤压应力（σ_bs=zF_0/A，A 为接合面有效面积）。
    σ_bs: 预紧挤压应力 MPa；Δσ_bsmax: 加载附加挤压应力最大值 MPa。
    返回 σ_bsmax，MPa。是否 ≤[σ_bs]（表5-8）用 ``判据5_38`` 判定。
    [核:p92]
    """
    return σ_bs + Δσ_bsmax


def eq5_39(σ_bs: float, Δσ_bsmax: float) -> float:
    """式(5-39) 接合面最小压应力：σ_bsmin = σ_bs − Δσ_bsmax > 0。

    适用条件：同式(5-38)，防止受压最小处出现间隙。关系符是严格大于 0。
    σ_bs: 预紧挤压应力 MPa；Δσ_bsmax: 加载附加挤压应力最大值 MPa。
    返回 σ_bsmin，MPa。是否 >0 用 ``判据5_39`` 判定。
    [核:p92]
    """
    return σ_bs - Δσ_bsmax


def eq5_40(M: float, W: float) -> float:
    """式(5-40) 加载附加挤压应力最大值（近似）：Δσ_bsmax ≈ M/W。

    适用条件：刚性大的地基、螺栓刚度相对较小，可用本式近似；再代入式(5-38)、
    (5-39) 即写成式(5-41)、(5-42)。课本用约等号 ≈。
    M: 外加倾覆力矩 N·mm；W: 接合面有效抗弯截面系数 mm³。
    返回 Δσ_bsmax，MPa。分母是 W（不是 A）。
    [核:p92]
    """
    return M / W


def eq5_41(z: float, F_0: float, A: float, M: float, W: float) -> float:
    """式(5-41) 接合面最大压应力（近似）：
    σ_bsmax ≈ zF_0/A + M/W ≤ [σ_bs]。

    适用条件：由式(5-40) 代入式(5-38) 写成；受倾覆力矩螺栓组连接的接合面压应力
    校核（防止受压最大处被压碎）。[σ_bs] 查表5-8。
    z: 螺栓数目；F_0: 各螺栓预紧力 N；A: 接合面有效面积 mm²；
    M: 倾覆力矩 N·mm；W: 接合面有效抗弯截面系数 mm³。
    返回 σ_bsmax，MPa。是否 ≤[σ_bs] 用 ``判据5_38`` 判定（把 M/W 当 Δσ）。
    注：例5-1 步骤(4)-1) 的第一项还扣除了轴向载荷使接合面减压的量
    (C_m/(C_b+C_m))F_Σh/A；把它并入 F_0（即用 F_0−(C_m/(C_b+C_m))F_Σh/z）
    即可用本式复现书值。
    [核:p92]
    """
    return z * F_0 / A + M / W


def eq5_42(z: float, F_0: float, A: float, M: float, W: float) -> float:
    """式(5-42) 接合面最小压应力（近似）：
    σ_bsmin ≈ zF_0/A − M/W > 0。

    适用条件：由式(5-40) 代入式(5-39) 写成；受倾覆力矩螺栓组连接的接合面压应力
    校核（防止受压最小处出现间隙）。关系符严格大于 0。
    z: 螺栓数目；F_0: 各螺栓预紧力 N；A: 接合面有效面积 mm²；
    M: 倾覆力矩 N·mm；W: 接合面有效抗弯截面系数 mm³。
    返回 σ_bsmin，MPa。是否 >0 用 ``判据5_39`` 判定。
    [核:p92]
    """
    return z * F_0 / A - M / W


def eq5_43(σ_S: float, S: float) -> float:
    """式(5-43) 螺纹连接件许用拉应力：[σ] = σ_S/S。

    适用条件：螺纹连接件的许用应力与载荷性质（静/变载荷）、装配情况（松/紧连接）、
    材料与结构尺寸有关；本式给许用拉应力。
    σ_S: 螺纹连接件材料屈服极限 MPa（表5-9）；
    S: 安全系数（表5-5）。
    返回 [σ]，MPa。例5-1：σ_s=240（4.6 级）、S=1.5 → 160 MPa。
    [核:p94]
    """
    return σ_S / S


def eq5_44(σ_S: float, S_τ: float) -> float:
    """式(5-44) 螺纹连接件许用切应力：[τ] = σ_S/S_τ。

    适用条件：同上（载荷性质、装配、材料、尺寸）；分子仍是 σ_S（屈服极限，
    不是 τ_S），分母 S 带下标 τ。
    σ_S: 屈服极限 MPa；S_τ: 安全系数（表5-5）。返回 [τ]，MPa。
    [核:p94]
    """
    return σ_S / S_τ


def eq5_45(σ_S: float, S_bs: float) -> float:
    """式(5-45) 钢制螺纹连接件的许用挤压应力：[σ_bs] = σ_S/S_bs（“对于钢”）。

    适用条件：螺纹连接件为钢；对铸铁改用式(5-46)（分子换成强度极限 σ_B）。
    σ_S: 屈服极限 MPa（表5-9）；S_bs: 安全系数（表5-5）。
    返回 [σ_bs]，MPa。
    [核:p94]
    """
    return σ_S / S_bs


def eq5_46(σ_B: float, S_bs: float) -> float:
    """式(5-46) 铸铁螺纹连接件的许用挤压应力：[σ_bs] = σ_B/S_bs（“对于铸铁”）。

    适用条件：螺纹连接件为铸铁；与式(5-45)（对于钢）并列，区别仅在分子取强度
    极限 σ_B。常用铸铁被连接件的 σ_B 可取 200~250 MPa。
    σ_B: 强度极限 MPa；S_bs: 安全系数（表5-5）。返回 [σ_bs]，MPa。
    例5-1 步骤(4)-1)：[σ_bs]=0.5σ_B=0.5×250=125 MPa（此 0.5 取自表5-8 的
    “铸铁 (0.4~0.5)σ_B”，非本式）。
    [核:p94]
    """
    return σ_B / S_bs


def eq5_47(F: float, d_2: float, h: float, u: float = None,
           P: float = None, H: float = None) -> float:
    """式(5-47) 滑动螺旋的耐磨性条件（螺纹工作面上的压力）：
    p = F/A = F/(π d_2 h u) = FP/(π d_2 h H) ≤ [p]。

    适用条件：滑动螺旋副的耐磨性计算（校核计算）；u=H/P 为螺纹工作圈数，
    A=πd_2 h u 为螺纹承压面积；工作圈数不宜超过 10 圈。
    F: 作用于螺杆的轴向力 N；d_2: 螺纹中径 mm；h: 螺纹工作高度 mm；
    u: 螺纹工作圈数（给 u 时用第一式）；P: 螺距 mm；H: 螺母高度 mm
    （不给 u 时需 P 与 H，用第二式）。
    返回 p，MPa。是否 ≤[p]（表5-12）由调用方比较。
    u 与 (P,H) 都缺时抛 ValueError。
    [核:p103]
    """
    if u is not None:
        return F / (math.pi * d_2 * h * u)
    if P is None or H is None:
        raise ValueError("式5-47 需要 u，或 P 与 H")
    return F * P / (math.pi * d_2 * h * H)


def eq5_48(F: float, P: float, h: float, φ: float, 许用p: float) -> float:
    """式(5-48) 滑动螺旋耐磨性设计式：d_2 ≥ √(FP/(π h φ[p]))。

    适用条件：由式(5-47) 令 φ=H/d_2（即 H=φd_2）代入整理而得；通用牙型
    （矩形/梯形用式5-49、30°锯齿形用式5-50）。
    F: 轴向力 N；P: 螺距 mm；h: 螺纹工作高度 mm；φ: 螺母高度系数（=H/d_2）；
    许用p: 许用压力 MPa（表5-12）。
    返回 d_2 下限，mm（未圆整；算出后按国家标准选取公称直径 d 与螺距 P）。
    [核:p103]
    """
    return math.sqrt(F * P / (math.pi * h * φ * 许用p))


def eq5_49(F: float, φ: float, 许用p: float) -> float:
    """式(5-49) 矩形/梯形螺纹的耐磨性设计式：d_2 ≥ 0.8√(F/(φ[p]))。

    适用条件：矩形螺纹和梯形螺纹，取 h=0.5P，由式(5-48) 化简而得。
    F: 轴向力 N；φ: 螺母高度系数（=H/d_2，一般 1.2~3.5）；许用p: 许用压力 MPa。
    返回 d_2 下限，mm。系数 0.8 为课本原印。
    [核:p103]
    """
    return 0.8 * math.sqrt(F / (φ * 许用p))


def eq5_50(F: float, φ: float, 许用p: float) -> float:
    """式(5-50) 30°锯齿形螺纹的耐磨性设计式：d_2 ≥ 0.65√(F/(φ[p]))。

    适用条件：30°锯齿形螺纹，取 h=0.75P，由式(5-48) 化简而得。
    F: 轴向力 N；φ: 螺母高度系数（=H/d_2）；许用p: 许用压力 MPa。
    返回 d_2 下限，mm。系数 0.65 为课本原印。
    [核:p103]
    """
    return 0.65 * math.sqrt(F / (φ * 许用p))


def eq5_51(φ: float = None, d_2: float = None, H: float = None,
           解: str = "H") -> float:
    """式(5-51) 螺母高度：H = φ d_2。

    适用条件：螺母高度设计式。φ 一般 1.2~3.5；整体螺母（磨损后不能调整间隙）
    φ=1.2~2.5；剖分螺母和兼作支承的螺母 φ=2.5~3.5；只有传动精度较高、载荷较大、
    寿命要求长时才允许 φ=4。工作圈数不宜超过 10 圈。算出 d_2 后应按国家标准
    选取公称直径 d 及螺距 P。
    φ: 螺母高度系数；d_2: 螺纹中径 mm；H: 螺母高度 mm。
    等式型，默认解 H。解: "H" / "φ"（=H/d_2）/ "d_2"（=H/φ）。
    返回所求解（mm 或无量纲）。
    [核:p103]
    """
    if 解 == "H":
        return φ * d_2
    if 解 == "φ":
        return H / d_2
    if 解 == "d_2":
        return H / φ
    raise ValueError("式5-51 只能解 H/φ/d_2，收到 %s" % (解,))


def eq5_52(f: float = None, β: float = None, f_v: float = None) -> float:
    """式(5-52) 螺旋副自锁条件与当量摩擦角：
    φ ≤ φ_v = arctan(f/cos β) = arctan f_v，**返回弧度**。

    适用条件：对有自锁性要求的螺旋副，螺纹几何参数确定后校核是否满足自锁条件。
    摩擦因数 f 见表5-12（钢-青铜 0.08~0.10；淬火钢-青铜 0.06~0.08；
    钢-铸铁 0.12~0.15；钢-钢 0.11~0.17）。
    f: 摩擦因数；β: **本书未给 β 定义，照式收录，使用前需确认来源**（本库不自行
    解释其含义）；f_v: 螺旋副的当量摩擦因数（可直接给，此时无需 f、β）。
    返回 φ_v，**rad**。
    给 f_v 时取 arctan(f_v)；否则需 f 与 β。二者都缺抛 ValueError。
    [核:p104]
    """
    if f_v is None:
        if f is None or β is None:
            raise ValueError("式5-52 需要 f_v，或 f 与 β（β 本书未给定义）")
        f_v = f / math.cos(β)
    return math.atan(f_v)


def eq5_53(F: float, T: float, d_1: float) -> float:
    """式(5-53) 螺杆危险截面的计算应力（第四强度理论）：
    σ_ca = √(σ²+3τ²) = √((F/A)²+3(T/W_T)²)
         = (1/A)√(F²+3(4T/d_1)²) ≤ [σ]。

    适用条件：受力较大的螺杆需作强度计算；螺杆工作时承受轴向压力（或拉力）F 和
    扭矩 T，危险截面上既有压缩（或拉伸）应力又有扭转切应力；A=πd_1²/4，
    W_T=πd_1³/16=A d_1/4。[σ] 见表5-13（螺杆钢 [σ]=σ_S/(3~5)）。
    F: 螺杆所受轴向压力（或拉力）N；T: 螺杆所受扭矩 N·mm；d_1: 螺纹小径 mm。
    返回 σ_ca，MPa。本函数按 (1/A)√(F²+3(4T/d_1)²) 计算，与第一写法等价。
    [核:p104]
    """
    A = math.pi / 4.0 * d_1 ** 2
    return math.sqrt(F ** 2 + 3.0 * (4.0 * T / d_1) ** 2) / A


def eq5_54(F: float, D: float, b: float, u: float) -> float:
    """式(5-54) 螺母螺纹牙的剪切强度：τ = F/(π D b u) ≤ [τ]。

    适用条件：螺纹牙多发生剪切和挤压破坏；一般螺母材料强度低于螺杆，故只需校核
    螺母螺纹牙。把一圈螺纹沿螺母螺纹大径 D 展开视作宽 πD 的悬臂梁，每圈承受平均
    压力 F/u，作用在以中径 D_2 为直径的圆周上；本式为危险截面 a-a 的剪切条件。
    F: 轴向力 N；D: 螺母螺纹大径 mm；b: 螺纹牙根部厚度 mm；
    u: 螺纹工作圈数。[τ] 见表5-13。
    返回 τ，MPa。
    补充（课本）：螺杆与螺母材料相同时，因 d_1<D，应改校核螺杆螺纹牙，此时
    本式的 D 改为 d_1。
    [核:p105]
    """
    return F / (math.pi * D * b * u)


def eq5_55(F: float, D: float, b: float, u: float, D_2: float = None,
           l: float = None) -> float:
    """式(5-55) 螺母螺纹牙的弯曲强度：σ_b = 6Fl/(π D b² u) ≤ [σ_b]。

    适用条件：螺纹牙危险截面 a-a 的弯曲强度条件；l 为弯曲力臂 l=(D−D_2)/2。
    F: 轴向力 N；D: 螺母螺纹大径 mm；b: 螺纹牙根部厚度 mm——矩形螺纹 b=0.5P、
    梯形 b=0.65P、30°锯齿形 b=0.75P（P 为螺距）；u: 螺纹工作圈数；
    D_2: 螺母螺纹中径 mm（未给 l 时须给）；l: 弯曲力臂 mm。
    [σ_b] 见表5-13（青铜 40~60、铸铁 45~55、钢 (1.0~1.2)[σ]）。
    返回 σ_b，MPa。l 与 D_2 都缺抛 ValueError。
    补充：螺杆与螺母材料相同时应改校核螺杆螺纹牙，本式的 D 改为 d_1。
    [核:p105]
    """
    if l is None:
        if D_2 is None:
            raise ValueError("式5-55 需要 l，或 D_2（l=(D−D_2)/2）")
        l = (D - D_2) / 2.0
    return 6.0 * F * l / (math.pi * D * b ** 2 * u)


def eq5_56(F_cr: float, F: float) -> float:
    """式(5-56) 螺杆稳定性安全系数：S_sc = F_cr/F ≥ S_s。

    适用条件：长径比大的受压螺杆，当轴向压力 F 大于某临界值时螺杆侧向弯曲丧失
    稳定性，故正常情况下 F 必须小于 F_cr。
    F_cr: 螺杆临界载荷 N（λ_s≥100 用式5-57，λ_s<100 用式5-58）；
    F: 螺杆承受的轴向压力 N。
    返回 S_sc（无量纲）。是否 ≥S_s 用 ``判据5_56`` 判定——
    传力螺旋（如起重螺旋）3.5~5.0；传导螺旋 2.5~4.0；精密螺杆或水平螺杆 >4.0。
    [核:p106]
    """
    return F_cr / F


def eq5_57(E: float, d_1: float, μ: float, l: float) -> float:
    """式(5-57) 欧拉临界载荷（λ_s≥100）：F_cr = π²EI/(μl)²，I=πd_1⁴/64。

    适用条件：**当 λ_s≥100 时**临界载荷按欧拉公式计算。
    E: 螺杆材料拉压弹性模量 MPa（课本取 E=2.06×10⁵ MPa）；
    d_1: 螺纹小径 mm；μ: 长度系数（表5-14）；
    l: 螺杆工作长度 mm（两端支承取两支点间距离；一端以螺母支承取螺母中点到
    另一端支点的距离）。
    返回 F_cr，N。I 由 d_1 按 πd_1⁴/64 内算。
    [核:p106]
    """
    I = math.pi * d_1 ** 4 / 64.0
    return math.pi ** 2 * E * I / (μ * l) ** 2


def eq5_58(λ_s: float, d_1: float, a: float = None, b: float = None,
           材料: str = None) -> float:
    """式(5-58) 中小柔度临界载荷（λ_s<100）：F_cr = (a − b λ_s)(π/4)d_1²。

    适用条件：**当 λ_s<100 时**临界载荷按本式计算。系数（课本给出）：
    对强度极限 σ_B≥380 MPa 的普通碳钢（如 Q235、Q275 等）取 a=304、b=1.12；
    对强度极限 σ_B≥480 MPa 的优质碳钢（如 35、45、50 钢等）取 a=461、b=2.57。
    当 λ_s<40 时可不必进行稳定性校核；若稳定性不足应适当增加 d_1。
    λ_s: 螺杆柔度（=μl/i，见 ``螺杆柔度``）；d_1: 螺纹小径 mm；
    a, b: 与材料有关的系数（可直接给）；材料: "普通碳钢"/"碳钢"/"Q235"/"Q275" →
    (304, 1.12)；"优质碳钢"/"35"/"45"/"50" → (461, 2.57)。
    返回 F_cr，N。a、b 既未直接给、材料也未给时抛 ValueError。
    [核:p106]
    """
    if a is None or b is None:
        表 = {"普通碳钢": (304.0, 1.12), "碳钢": (304.0, 1.12),
              "Q235": (304.0, 1.12), "Q275": (304.0, 1.12),
              "优质碳钢": (461.0, 2.57), "35": (461.0, 2.57),
              "45": (461.0, 2.57), "50": (461.0, 2.57)}
        if 材料 not in 表:
            raise ValueError("式5-58 需给 a、b，或材料属于 %s" % (list(表),))
        a, b = 表[材料]
    return (a - b * λ_s) * (math.pi / 4.0) * d_1 ** 2



def _牌号组(文本: str) -> list:
    """把表5-11 的“Q235、Q275、45、50”或带“；”的双牌号格切成单个牌号。

    括号内的旧牌号说明（如“（10-1 锡青铜）”）保留在牌号串里，供 startswith 匹配。
    [核:p102]
    """
    规范 = 文本.replace("；", "\n").replace("、", "\n")
    return [项.strip() for 项 in 规范.split("\n") if 项.strip()]


def _解析区间(文本: str) -> tuple:
    """把表值字符串“0.10~0.16”解析为 (0.10, 0.16)；非区间形式抛 ValueError。

    只做字符串到两个端点的读取，**不插值**。[核:p89]
    """
    if "~" not in 文本:
        raise ValueError("表值“%s”不是 a~b 形式的区间" % (文本,))
    左, 右 = 文本.split("~", 1)
    return float(左), float(右)


def _速度档匹配(档: str, v: float) -> bool:
    """判断数值速度 v 是否落在表5-12 印刷的速度档内（只认印刷档，不补空档）。

    档: "低速" / "≤3.0" / "6~12" / ">15" / "<2.4"。
    “低速”无数值定义，数值查询时一律视为不匹配（不猜）。[核:p104]
    """
    档 = 档.strip()
    if 档 == "低速":
        return False
    if 档.startswith("≤"):
        return v <= float(档[1:])
    if 档.startswith("<"):
        return v < float(档[1:])
    if 档.startswith(">"):
        return v > float(档[1:])
    if "~" in 档:
        左, 右 = 档.split("~", 1)
        return float(左) <= v <= float(右)
    raise ValueError("表5-12 无法识别的速度档“%s”" % (档,))



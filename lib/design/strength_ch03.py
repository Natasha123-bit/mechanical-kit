def _区间(文本) -> tuple:
    """把“2.0~2.5”“1.3～1.6”“0.7~2.2”解析为 (低, 高)；只读数、不改写。"""
    s = str(文本).replace(" ", "").replace("～", "~").replace("mm", "")
    if "~" not in s:
        raise ValueError("表值“%s”不是 a~b 形式的区间" % (文本,))
    左, 右 = s.split("~", 1)
    return float(左), float(右)


def _区间或单值(文本) -> tuple:
    """区间表值返回 (低, 高)；原表只印一个数时返回 (值, 值)，不改写数值。

    附表3-10 的氰化格原文为“1.8”（单值），其余为“1.15～1.25”式区间。
    """
    s = str(文本)
    if "~" in s or "～" in s:
        return _区间(s)
    v = float(_规整(s))
    return (v, v)


def _规整(文本) -> str:
    """去掉单位与千分位空格：“1 000 MPa”→"1000"，“≤16 mm”→"≤16"。"""
    return (str(文本).replace(" ", "").replace("mm", "").replace("MPa", "")
            .replace("～", "~"))


def _匹配(轴: list, x: float, 名称: str) -> int:
    """在印刷档位表 轴 上精确匹配 x；支持“>2”“≤16”“7~20”三类档位。

    只认原表档位：不落在任何印刷档位上即抛 ValueError（不插值、不外推）。
    """
    x = float(x)
    for i, 原文 in enumerate(轴):
        t = _规整(原文)
        if t.startswith(">"):
            if x > float(t[1:]):
                return i
        elif t.startswith("≤"):
            if x <= float(t[1:]):
                return i
        elif "~" in t:
            低, 高 = _区间(t)
            if 低 - 1e-9 <= x <= 高 + 1e-9:
                return i
        elif abs(float(t) - x) < 1e-9:
            return i
    raise ValueError("%s=%.6g 不在原表档位 %s 上（不插值、不外推）"
                     % (名称, x, [str(s) for s in 轴]))


def _格(块: dict, 行号: int, 列号: int):
    """按 块 的“取值方向”取印刷格（默认 data[列][行]，附表3-9 为 data[行][列]）。"""
    if 块.get("取值方向") == "data[row][col]":
        return 块["data"][行号][列号]
    return 块["data"][列号][行号]


def _输出(值, 表号: str, 行: str, 列: str) -> float:
    """把印刷格转成 float；原表空白/“—”（None）一律拒绝，不补值。"""
    if 值 is None:
        raise ValueError("附表%s 的 %s × %s 格原表为空白/“—”，无数据"
                         "（不插值、不补值）" % (表号, 行, 列))
    return float(_规整(值))


def _块(表: dict, 应力类型: str) -> dict:
    """取多块表的某一块（拉伸/弯曲/扭转）。"""
    if 应力类型 not in 表["块"]:
        raise ValueError("%s 只有 %s 三种块，收到“%s”"
                         % (表["表名"], list(表["块"]), 应力类型))
    return 表["块"][应力类型]


def _r_d列号(块: dict, r_d: float) -> int:
    """r/d 列号：列标题形如“r/d=0.10”。"""
    return _匹配([str(c).split("=")[1] for c in 块["cols"]], r_d, "r/d")


def _类型列号(表: dict, 应力类型: str) -> int:
    """附表3-3/3-4/3-5 的类型列号（按 cols 前缀判定）。"""
    for j, c in enumerate(表["cols"]):
        c = str(c)
        if 应力类型 in ("α_σ", "σ", "弯曲", "k_σ") and \
                (c.startswith("α_σ") or c.startswith("k_σ")):
            return j
        if 应力类型 in ("α_τ", "τ", "扭转", "k_τ") and \
                (c.startswith("α_τ") or c.startswith("k_τ")):
            return j
    for j, c in enumerate(表["cols"]):
        if str(c).startswith(str(应力类型)):
            return j
    raise ValueError("%s 无“%s”列，可选 %s"
                     % (表["表名"], 应力类型, 表["cols"]))



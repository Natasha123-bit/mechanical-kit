def eq3_1(σ_rN: float, m: float, N: float) -> float:
    """式(3-1) 有限寿命区疲劳曲线方程：σ_rN^m · N = C。

    适用条件：σ-N 曲线 CD 段（有限寿命疲劳阶段），N_C ≤ N ≤ N_D；C 与 m
    均为材料常数，疲劳极限随循环次数增加而降低。
    σ_rN: 有限寿命疲劳极限，MPa（脚标 r 表示该变应力的应力比，N 表示循环
          次数）；
    m: 材料常数（指数，无量纲；钢材弯曲与拉压 6~20，初算中等尺寸取 9）；
    N: 应力循环次数（次）。
    返回 C = σ_rN^m·N（材料常数，量纲随 m 而定，本库只作校核用，例如与
    eq3_1a() 的结果比对）。
    [核:p025]
    """
    if float(m) <= 0 or float(N) <= 0 or float(σ_rN) <= 0:
        raise ValueError("式3-1 要求 σ_rN>0、m>0、N>0")
    return float(σ_rN) ** float(m) * float(N)


def eq3_1a(σ_r: float, m: float, N_0: float) -> float:
    """式(3-1a) 以循环基数表示的疲劳曲线方程：σ_rN^m·N = σ_r^m·N_0 = C。

    适用条件：由式(3-1) 改写，用 N_0 与 σ_r 近似代表 N_D 与 σ_r∞；
    适用于有限寿命区 N_C ≤ N ≤ N_D。
    σ_r: 与循环基数 N_0 相对应的疲劳极限（σ_rN_0 的简写），MPa；
    m: 材料常数（指数，无量纲）；
    N_0: 循环基数（次）；钢材 N_0=(1~10)×10^6，初算中等尺寸取 5×10^6、
         大尺寸取 10^7。
    返回 C = σ_r^m·N_0（材料常数）。
    [核:p025]
    """
    if float(m) <= 0 or float(N_0) <= 0 or float(σ_r) <= 0:
        raise ValueError("式3-1a 要求 σ_r>0、m>0、N_0>0")
    return float(σ_r) ** float(m) * float(N_0)


def eq3_2(σ_r_inf: float, N: float, N_D: float) -> float:
    """式(3-2) 无限寿命区疲劳极限：σ_rN = σ_r∞（N > N_D）。

    适用条件：点 D 以后的线段（无限寿命疲劳阶段）。若作用的变应力最大值
    小于点 D 的应力值，则无论变化多少次材料都不会破坏。
    σ_r_inf: 点 D 对应的疲劳极限（持久疲劳极限 σ_r∞），MPa；
    N: 应力循环次数（次）；
    N_D: 点 D 的循环次数（次）；钢材 N_D 为 10^6~10^8。
    返回 σ_r∞，MPa。N ≤ N_D 时不属本式（应改用式3-3），抛 ValueError。
    [核:p025]
    """
    if float(N) <= float(N_D):
        raise ValueError("式3-2 只适用于 N>N_D（N=%g、N_D=%g），"
                         "N≤N_D 请用 eq3_3()" % (float(N), float(N_D)))
    return float(σ_r_inf)


def 寿命系数K_N(N_0: float, N: float, m: float,
                N_D: float = None) -> float:
    """式(3-3) 中的寿命系数：K_N = (N_0/N)^(1/m)（书内未单独编号）。

    适用条件：有限寿命区 N_C ≤ N ≤ N_D；当 N > N_D 时式中的 N 取为 N_D 而
    不再增加（即 σ_rN = σ_rN_D），由参数 N_D 施加该截断。
    N_0: 循环基数（次）；
    N: 应力循环次数（次）；
    m: 材料常数（指数，无量纲）——注意 m 是**指数**，不是寿命系数；
    N_D: 持久寿命起点（次，可选）；给定且 N>N_D 时按 N_D 计算。
    返回 K_N（无量纲，σ_rN 与 σ_r 的比值）。
    [核:p025]
    """
    if float(m) <= 0 or float(N) <= 0 or float(N_0) <= 0:
        raise ValueError("寿命系数要求 N_0>0、N>0、m>0")
    if N_D is not None and float(N) > float(N_D):
        N = N_D
    return (float(N_0) / float(N)) ** (1.0 / float(m))


def eq3_3(σ_r: float, N_0: float, N: float, m: float,
          N_D: float = None) -> float:
    """式(3-3) 有限寿命区任意循环次数下的疲劳极限：
    σ_rN = σ_r·(N_0/N)^(1/m) = K_N·σ_r。

    适用条件：有限寿命区 N_C ≤ N ≤ N_D；N > N_D 时式中的 N 取为 N_D（不再
    增加），由参数 N_D 施加截断（不给 N_D 则按 N_0 近似、不截断）。
    σ_r: 与循环基数 N_0 对应的疲劳极限，MPa；
    N_0: 循环基数（次）；
    N: 应力循环次数（次）；
    m: 材料常数（指数，无量纲）；
    N_D: 持久寿命起点（次，可选）。
    返回 σ_rN，MPa。K_N 见 寿命系数K_N()。
    [核:p025]
    """
    return 寿命系数K_N(N_0, N, m, N_D) * float(σ_r)


def 寿命次数N_i(σ_r: float, σ_i: float, N_0: float, m: float) -> float:
    """式(3-1a) 的逆用（书内未编号，例3-1 第(4)步用）：
    N_i = N_0·(σ_r/σ_i)^m。

    适用条件：有限寿命区；σ_i > σ_r 时 N_i < N_0。
    σ_r: 与循环基数 N_0 对应的疲劳极限，MPa；
    σ_i: 第 i 级对称循环变应力幅，MPa；
    N_0: 循环基数（次）；
    m: 材料常数（指数，无量纲）。
    返回 N_i（次）——仅有 σ_i 作用时使材料疲劳破坏的循环次数。
    例3-1：σ_r=307、σ_i=500、N_0=5×10⁶、m=9 → 0.062×10⁶ 次。
    [核:p025]
    """
    if float(σ_i) <= 0 or float(σ_r) <= 0:
        raise ValueError("寿命次数要求 σ_r>0、σ_i>0")
    return float(N_0) * (float(σ_r) / float(σ_i)) ** float(m)



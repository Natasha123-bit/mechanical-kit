def eq3_17(σ_max: float = None, σ_min: float = None,
           r: float = None) -> float:
    """式(3-17) 应力比条件化为应力幅/平均应力之比：
    σ_a/σ_m = (σ_max − σ_min)/(σ_max + σ_min) = (1 − r)/(1 + r) = C'。

    适用条件：r=C 的情况——变应力的应力比保持不变（如绝大多数转轴中的
    应力状态）；用于在极限应力图上由原点引射线通过工作应力点求极限点。
    σ_max: 交变工作应力最大值，MPa；
    σ_min: 交变工作应力最小值，MPa；
    r: 应力比（循环特性）r=σ_min/σ_max（无量纲），可与 σ_max/σ_min 二选一。
    返回 C'=σ_a/σ_m（无量纲）。
    [核:p029]
    """
    if r is not None:
        if abs(1.0 + float(r)) < 1e-15:
            raise ValueError("式3-17 的 r=−1 时分母为 0")
        return (1.0 - float(r)) / (1.0 + float(r))
    if σ_max is None or σ_min is None:
        raise ValueError("式3-17 需要 (σ_max, σ_min) 或 r")
    if abs(float(σ_max) + float(σ_min)) < 1e-15:
        raise ValueError("式3-17 的 σ_max+σ_min=0 时分母为 0")
    return ((float(σ_max) - float(σ_min))
            / (float(σ_max) + float(σ_min)))


def eq3_18(σ_负1: float, σ_m: float, σ_a: float,
           K_σ: float, φ_σ: float) -> float:
    """式(3-18) r=C 时零件的疲劳极限（最大应力）：
    σ'_max = σ'_ae + σ'_me = σ_负1(σ_m+σ_a)/(K_σ σ_a + φ_σ σ_m)。

    适用条件：r=C；联解射线 OM 与直线 AG 得 M'_1 坐标后相加。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    σ_m: 平均工作应力，MPa；
    σ_a: 工作应力幅，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲，书中此处未加脚标 e）。
    返回 σ'_max，MPa。σ_max=σ_m+σ_a。
    [核:p029]
    """
    分母 = float(K_σ) * float(σ_a) + float(φ_σ) * float(σ_m)
    if 分母 <= 0:
        raise ValueError("式3-18 的分母 K_σσ_a+φ_σσ_m 必须为正")
    return float(σ_负1) * (float(σ_m) + float(σ_a)) / 分母


def eq3_19(σ_负1: float, K_σ: float, σ_a: float,
           φ_σ: float, σ_m: float) -> float:
    """式(3-19) r=C 时的计算安全系数：
    S_ca = σ_lim/σ = σ'_max/σ_max = σ_负1/(K_σ σ_a + φ_σ σ_m) ≥ S。

    适用条件：r=C；工作应力点 M 的射线与疲劳极限折线 AG 相交（非 CG 段）。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    σ_a: 工作应力幅，MPa；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲）；
    σ_m: 平均工作应力，MPa。
    返回计算安全系数 S_ca（无量纲）；判据 S_ca≥S 由调用方比较。
    [核:p029]
    """
    分母 = float(K_σ) * float(σ_a) + float(φ_σ) * float(σ_m)
    if 分母 <= 0:
        raise ValueError("式3-19 的分母 K_σσ_a+φ_σσ_m 必须为正")
    return float(σ_负1) / 分母


def eq3_20(σ_S: float, σ_a: float, σ_m: float) -> float:
    """式(3-20) 静强度计算安全系数：
    S_ca = σ_lim/σ = σ_S/σ_max = σ_S/(σ_a + σ_m) ≥ S。

    适用条件：单向应力；工作应力点位于 OGC 区域（及 CGH、GIC 区域）内，
    应力比等于常数条件下极限应力统为屈服极限，只需作静强度计算。
    σ_S: 材料的屈服极限，MPa；
    σ_a: 工作应力幅，MPa；
    σ_m: 平均工作应力，MPa。
    返回 S_ca（无量纲）。
    [核:p030]
    """
    if float(σ_a) + float(σ_m) <= 0:
        raise ValueError("式3-20 要求 σ_a+σ_m>0")
    return float(σ_S) / (float(σ_a) + float(σ_m))


def eq3_21(σ_负1: float, K_σ: float, φ_σ: float,
           σ_m: float) -> float:
    """式(3-21) σ_m=C 时零件的疲劳极限：
    σ'_max = σ_负1e + σ_m(1 − φ_σ/K_σ)
           = [σ_负1 + (K_σ − φ_σ)σ_m]/K_σ。

    适用条件：σ_m=C 的情况——平均应力保持不变（如振动着的受载弹簧）；
    联解 MM'_2（σ'_me=σ_m）与 AG 两直线方程后相加。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲）；
    σ_m: 平均工作应力（此处 σ'_me=σ_m），MPa。
    返回 σ'_max，MPa。
    [核:p030]
    """
    if float(K_σ) <= 0:
        raise ValueError("式3-21 的 K_σ 必须为正")
    # σ_负1e = σ_负1/K_σ（式3-8），再叠加平均应力项
    return (float(σ_负1) / float(K_σ)
            + float(σ_m) * (1.0 - float(φ_σ) / float(K_σ)))


def eq3_22(σ_负1: float, φ_σ: float, σ_m: float,
           K_σ: float) -> float:
    """式(3-22) σ_m=C 时的极限应力幅：
    σ'_ae = (σ_负1 − φ_σ σ_m)/K_σ。

    适用条件：σ_m=C 的情况。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲）；
    σ_m: 平均工作应力，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）。
    返回 σ'_ae，MPa。
    [核:p030]
    """
    if float(K_σ) <= 0:
        raise ValueError("式3-22 的 K_σ 必须为正")
    return (float(σ_负1) - float(φ_σ) * float(σ_m)) / float(K_σ)


def eq3_23(σ_负1: float, K_σ: float, φ_σ: float,
           σ_m: float, σ_a: float) -> float:
    """式(3-23) σ_m=C 时按最大应力的计算安全系数：
    S_ca = σ'_max/σ_max = [σ_负1 + (K_σ − φ_σ)σ_m]/[K_σ(σ_m + σ_a)] ≥ S。

    适用条件：σ_m=C 的情况；由最大应力求计算安全系数。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲）；
    σ_m: 平均工作应力，MPa；
    σ_a: 工作应力幅，MPa。
    返回 S_ca（无量纲）。
    [核:p030]
    """
    分母 = float(K_σ) * (float(σ_m) + float(σ_a))
    if 分母 <= 0:
        raise ValueError("式3-23 的分母 K_σ(σ_m+σ_a) 必须为正")
    return (float(σ_负1) + (float(K_σ) - float(φ_σ)) * float(σ_m)) / 分母


def eq3_24(σ_负1: float, φ_σ: float, σ_m: float,
           K_σ: float, σ_a: float) -> float:
    """式(3-24) σ_m=C 时按应力幅的计算安全系数：
    S'_a = σ'_ae/σ_a = (σ_负1 − φ_σ σ_m)/(K_σ σ_a) ≥ S。

    适用条件：σ_m=C 的情况；也有文献建议按应力幅校核零件的疲劳强度。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲）；
    σ_m: 平均工作应力，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    σ_a: 工作应力幅，MPa。
    返回 S'_a（无量纲）。
    [核:p030]
    """
    if float(K_σ) * float(σ_a) <= 0:
        raise ValueError("式3-24 的分母 K_σσ_a 必须为正")
    return ((float(σ_负1) - float(φ_σ) * float(σ_m))
            / (float(K_σ) * float(σ_a)))


def eq3_25(σ_m: float, σ_a: float) -> float:
    """式(3-25) σ_min=C 的条件：σ_min = σ_m − σ_a = C。

    适用条件：最小应力保持不变（如紧螺栓连接中螺栓受轴向变载荷）；用于在
    图3-8 中过工作应力点作与横坐标轴夹角 45° 的直线求极限应力点。
    σ_m: 平均工作应力，MPa；
    σ_a: 工作应力幅，MPa。
    返回 σ_min，MPa（该常数值）。
    [核:p030]
    """
    return float(σ_m) - float(σ_a)


def eq3_26(σ_负1: float, K_σ: float, φ_σ: float,
           σ_min: float, σ_a: float) -> float:
    """式(3-26) σ_min=C 时按最大应力的计算安全系数：
    S_ca = σ'_max/σ_max
         = [2σ_负1 + (K_σ − φ_σ)σ_min]/[(K_σ + φ_σ)(2σ_a + σ_min)] ≥ S。

    适用条件：σ_min=C；工作应力点位于 OJGI 区域内，极限应力在折线 AG 上。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲）；
    σ_min: 交变工作应力最小值，MPa；
    σ_a: 工作应力幅，MPa（σ_max=2σ_a+σ_min）。
    返回 S_ca（无量纲）。位于 GIC 区域时改按式(3-20) 静强度计算。
    [核:p031]
    """
    分母 = (float(K_σ) + float(φ_σ)) * (2.0 * float(σ_a) + float(σ_min))
    if 分母 <= 0:
        raise ValueError("式3-26 的分母 (K_σ+φ_σ)(2σ_a+σ_min) 必须为正")
    return ((2.0 * float(σ_负1) + (float(K_σ) - float(φ_σ)) * float(σ_min))
            / 分母)


def eq3_27(σ_负1: float, φ_σ: float, σ_min: float,
           K_σ: float, σ_a: float) -> float:
    """式(3-27) σ_min=C 时按极限应力幅的计算安全系数：
    S'_a = σ'_ae/σ_a = (σ_负1 − φ_σ σ_min)/[(K_σ + φ_σ)σ_a] ≥ S_a。

    适用条件：σ_min=C 的条件，按极限应力幅求计算安全系数。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    φ_σ: 试件受循环弯曲应力时的材料常数（无量纲）；
    σ_min: 交变工作应力最小值，MPa；
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    σ_a: 工作应力幅，MPa。
    返回 S'_a（无量纲）。书中不等号右侧排印为 S_a，照录。
    [核:p031]
    """
    分母 = (float(K_σ) + float(φ_σ)) * float(σ_a)
    if 分母 <= 0:
        raise ValueError("式3-27 的分母 (K_σ+φ_σ)σ_a 必须为正")
    return ((float(σ_负1) - float(φ_σ) * float(σ_min)) / 分母)


def eq3_28(K_σ: float, σ_a: float, φ_σ: float, σ_m: float) -> float:
    """式(3-28) 等效对称循环变应力（应力幅）：σ_ad = K_σ σ_a + φ_σ σ_m。

    适用条件：应力等效转化——把 K_σ σ_a + φ_σ σ_m 看作与原来不对称循环
    变应力等效的对称循环变应力；对 r=C、σ_m=C、σ_min=C 各情况通用。
    K_σ: 弯曲疲劳极限综合影响系数（无量纲）；
    σ_a: 工作应力幅，MPa；
    φ_σ: 把平均应力折算为等效应力幅的折算系数（无量纲）；
    σ_m: 平均工作应力，MPa。
    返回 σ_ad，MPa。
    [核:p031]
    """
    return (float(K_σ) * float(σ_a)
            + float(φ_σ) * float(σ_m))


def eq3_29(σ_负1: float, σ_ad: float) -> float:
    """式(3-29) 由等效对称循环变应力求安全系数：S_ca = σ_负1/σ_ad。

    适用条件：等效对称循环变应力法；切应力时把 σ 换为 τ 即可。当零件应力
    循环次数 10^4<N<N_0 时，应以式(3-3) 的 σ_rN 代替 σ_r（即 σ_负1N 代替
    σ_负1、σ_0N 代替 σ_0），此时计算安全系数会增大。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    σ_ad: 等效对称循环变应力（应力幅），MPa。
    返回 S_ca（无量纲）。
    [核:p031]
    """
    if float(σ_ad) <= 0:
        raise ValueError("式3-29 的 σ_ad 必须为正")
    return float(σ_负1) / float(σ_ad)



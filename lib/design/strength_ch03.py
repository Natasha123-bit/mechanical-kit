def eq3_12(k_σ: float, ε_σ: float, β_σ: float, β_q: float) -> float:
    """式(3-12) 综合影响系数：K_σ = (k_σ/ε_σ + 1/β_σ − 1)/β_q。

    适用条件：正应力（弯曲）条件；各系数值见本章附录或有关资料。
    k_σ: 零件的有效应力集中系数（无量纲，附表3-1~3-6）；
    ε_σ: 零件的尺寸及截面形状系数（无量纲，附表3-7 等）；
    β_σ: 零件的表面质量系数（无量纲）；
    β_q: 零件的强化系数（无量纲，附表3-9~3-11）。
    返回 K_σ（无量纲）。
    [核:p028]
    """
    if float(ε_σ) <= 0 or float(β_σ) <= 0 or float(β_q) <= 0:
        raise ValueError("式3-12 要求 ε_σ>0、β_σ>0、β_q>0")
    return (float(k_σ) / float(ε_σ) + 1.0 / float(β_σ) - 1.0) / float(β_q)


def eq3_13(τ_ae_prime: float, φ_τe: float, τ_me_prime: float) -> float:
    """式(3-13) 零件循环切应力极限应力线 AG 的方程：
    τ_负1e = τ_负1/K_τ = τ'_ae + φ_τe·τ'_me。

    适用条件：切应力条件；仿照式(3-9) 并以 τ 代换 σ 得出。
    τ_ae_prime: 零件受循环切应力时的极限切应力幅 τ'_ae，MPa；
    φ_τe: 零件受循环切应力时的材料常数（无量纲，见式3-15）；
    τ_me_prime: 零件受循环切应力时的极限平均切应力 τ'_me，MPa。
    返回零件对称循环剪切疲劳极限 τ_负1e，MPa。
    [核:p028]
    """
    return float(τ_ae_prime) + float(φ_τe) * float(τ_me_prime)


def eq3_13a(K_τ: float, τ_ae_prime: float, φ_τ: float,
            τ_me_prime: float) -> float:
    """式(3-13a) 零件循环切应力极限应力线方程的另一写法：
    τ_负1 = K_τ·τ'_ae + φ_τ·τ'_me。

    适用条件：与式(3-13) 等价（书中标“或”）；切应力条件。
    K_τ: 剪切疲劳极限综合影响系数（无量纲）；
    τ_ae_prime: 零件极限切应力幅 τ'_ae，MPa；
    φ_τ: 试件受循环切应力时的材料常数（无量纲，φ_τ≈0.5φ_σ）；
    τ_me_prime: 零件极限平均切应力 τ'_me，MPa。
    返回材料对称循环剪切疲劳极限 τ_负1，MPa。
    [核:p028]
    """
    return (float(K_τ) * float(τ_ae_prime)
            + float(φ_τ) * float(τ_me_prime))


def eq3_14(τ_ae_prime: float, τ_me_prime: float) -> float:
    """式(3-14) 零件循环切应力屈服控制段：τ'_ae + τ'_me = τ_S。

    适用条件：切应力条件下零件极限应力线图的 CG 段（书中标“及”，紧接
    3-13a 之后）。
    τ_ae_prime: 零件极限切应力幅 τ'_ae，MPa；
    τ_me_prime: 零件极限平均切应力 τ'_me，MPa。
    返回材料的剪切屈服极限 τ_S，MPa。
    [核:p028]
    """
    return float(τ_ae_prime) + float(τ_me_prime)


def eq3_15(φ_τ: float, K_τ: float) -> float:
    """式(3-15) 零件的切应力材料常数：
    φ_τe = φ_τ/K_τ = (1/K_τ)·(2τ_负1 − τ_0)/τ_0。

    适用条件：切应力条件；仿照式(3-11) 得（第二等号代入 τ 版式3-6）。
    φ_τ: 试件受循环切应力时的材料常数（无量纲，φ_τ≈0.5φ_σ）；
    K_τ: 剪切疲劳极限综合影响系数（无量纲）。
    返回 φ_τe（无量纲）。
    [核:p028]
    """
    if float(K_τ) <= 0:
        raise ValueError("式3-15 的 K_τ 必须为正")
    return float(φ_τ) / float(K_τ)


def eq3_16(k_τ: float, ε_τ: float, β_τ: float, β_q: float) -> float:
    """式(3-16) 剪切综合影响系数：K_τ = (k_τ/ε_τ + 1/β_τ − 1)/β_q。

    适用条件：切应力条件；仿照式(3-12) 得，脚标 τ 表示切应力条件。
    k_τ: 切应力条件下的有效应力集中系数（无量纲）；
    ε_τ: 切应力条件下的尺寸及截面形状系数（无量纲）；
    β_τ: 切应力条件下的表面质量系数（无量纲）；
    β_q: 零件的强化系数（无量纲）。
    返回 K_τ（无量纲）。
    [核:p028]
    """
    if float(ε_τ) <= 0 or float(β_τ) <= 0 or float(β_q) <= 0:
        raise ValueError("式3-16 要求 ε_τ>0、β_τ>0、β_q>0")
    return (float(k_τ) / float(ε_τ) + 1.0 / float(β_τ) - 1.0) / float(β_q)



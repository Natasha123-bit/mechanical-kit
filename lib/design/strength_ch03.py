def _同长(n, N, 名称: str):
    n, N = [float(x) for x in n], [float(x) for x in N]
    if len(n) != len(N) or not n:
        raise ValueError("%s 要求 n、N 等长且非空" % 名称)
    return n, N


def eq3_30(n, N) -> float:
    """式(3-30) 疲劳损伤线性累积假说（Miner 法则）：Σ n_i/N_i = 1。

    适用条件：规律性不稳定变应力；假设应力每循环一次都对材料起相同破坏
    作用，损伤率达 100% 时发生疲劳破坏；σ_i 为对称循环应力幅（或不对称
    循环的等效对称循环应力幅）。小于持久疲劳极限 σ_负1∞ 的工作应力不起
    损伤作用，计算时不计入（由调用方剔除）。
    n: 各级应力实际循环次数 n_i 的序列（次）；
    N: 各级应力单独作用时破坏循环次数 N_i 的序列（次），与 n 等长。
    返回损伤和 Σn_i/N_i（无量纲）；破坏判据为 =1，实际见式(3-31)。
    [核:p032]（00-清单 记 p.33，页图页眉为 32，以页图为准）
    """
    n, N = _同长(n, N, "式3-30")
    if any(x <= 0 for x in N):
        raise ValueError("式3-30 的 N_i 必须为正")
    return sum(a / b for a, b in zip(n, N))


def eq3_31() -> tuple:
    """式(3-31) 修正 Miner 法则：Σ n_i/N_i = 0.7~2.2。

    适用条件：由大量试验得出的式(3-30) 右边实际取值范围。各级应力先作用
    最大的、依次降低时，右边小于 1；先作用最小的、依次升高时，其值大于 1。
    （递增变应力不易破坏——前面较小应力起强化作用；递减变应力因最大应力
    先引起初始裂纹，后续较小应力仍使裂纹扩展。）
    无参数。
    返回 (0.7, 2.2)（无量纲区间）；因不是单值，不实现为可计算的等式。
    设计中仍可用式(3-30) 得较合理结果。
    [核:p033]
    """
    return 式3_31_修正范围


def eq3_32(n, σ, m: float) -> float:
    """式(3-32) 不稳定变应力的极限条件（未破坏判据）：
    Σ n_i σ_i^m < N_0 σ_负1^m。

    适用条件：不稳定变应力，材料尚未破坏；由 N_i=N_0(σ_负1/σ_i)^m 代入
    式(3-30) 得到（同页给出 N_1、N_2、…、N_z 的未编号表达式）。
    n: 各级对称循环变应力的循环次数 n_i 序列（次）；
    σ: 各级对称循环变应力的应力幅 σ_i 序列，MPa；
    m: 材料常数（指数，无量纲）。
    返回左端 Σ n_i σ_i^m（量纲 MPa^m·次）；判据为 < N_0 σ_负1^m，右端由
    调用方用 eq3_1a(σ_负1, m, N_0) 算出比较。
    [核:p033]
    """
    n = [float(x) for x in n]
    σ = [float(x) for x in σ]
    if len(n) != len(σ) or not n:
        raise ValueError("式3-32 要求 n、σ 等长且非空")
    if any(x <= 0 for x in σ) or float(m) <= 0:
        raise ValueError("式3-32 要求 σ_i>0、m>0")
    return sum(a * s ** float(m) for a, s in zip(n, σ))


def eq3_33(n, σ, m: float, N_0: float) -> float:
    """式(3-33) 不稳定变应力的计算应力：
    σ_ca = (1/N_0 · Σ n_i σ_i^m)^(1/m)。

    适用条件：不稳定变应力；由式(3-32) 整理（书中标“令”），把累积损伤折算
    为等效应力幅。
    n: 各级循环次数 n_i 序列（次）；
    σ: 各级对称循环应力幅 σ_i 序列，MPa；
    m: 材料常数（指数，无量纲，与式3-1 的 m 相同）；
    N_0: 循环基数（次）。
    返回 σ_ca，MPa。
    [核:p033]
    """
    if float(N_0) <= 0:
        raise ValueError("式3-33 的 N_0 必须为正")
    return (eq3_32(n, σ, m) / float(N_0)) ** (1.0 / float(m))


def eq3_34(σ_ca: float, σ_负1: float) -> bool:
    """式(3-34) 不稳定变应力下的强度判据：σ_ca < σ_负1。

    适用条件：不稳定变应力；式(3-32) 的计算应力形式（未破坏条件）。
    σ_ca: 不稳定变应力的计算应力，MPa；
    σ_负1: 材料对称循环弯曲疲劳极限，MPa。
    返回 bool（True=未破坏）。
    [核:p033]
    """
    return float(σ_ca) < float(σ_负1)


def eq3_35(σ_负1: float, σ_ca: float) -> float:
    """式(3-35) 不稳定变应力时的计算安全系数：S_ca = σ_负1/σ_ca ≥ S。

    适用条件：不稳定变应力；σ_i 为对称循环应力幅。对零件作疲劳强度计算时
    应计入 K_σ 的影响（即用 K_σ σ_i 代替各式中的 σ_i）；非对称循环的不稳定
    变应力可先按式(3-28) 求各等效对称循环变应力。
    σ_负1: 材料对称循环弯曲疲劳极限，MPa；
    σ_ca: 不稳定变应力的计算应力，MPa。
    返回 S_ca（无量纲）。
    [核:p033]
    """
    if float(σ_ca) <= 0:
        raise ValueError("式3-35 的 σ_ca 必须为正")
    return float(σ_负1) / float(σ_ca)



# 7. 3-2 节 双向稳定变应力：式(3-36) ~ 式(3-37)
# =====================================================================

def eq3_36(τ_a_prime: float, τ_负1e: float,
           σ_a_prime: float, σ_负1e: float) -> float:
    """式(3-36) 双向稳定变应力的极限应力关系：
    (τ'_a/τ_负1e)² + (σ'_a/σ_负1e)² = 1。

    适用条件：零件上同时作用同相位（同频同相）的法向对称循环稳定变应力
    σ_a 与切向对称循环稳定变应力 τ_a；该式为对钢材试验所得；在
    σ_a/σ_负1e — τ_a/τ_负1e 坐标中为四分之一单位圆（图3-11 极限圆 AM'B）。
    τ_a_prime: 同时作用的切应力幅的极限值 τ'_a，MPa；
    τ_负1e: 零件（此处指试件）只受对称循环切应力时的扭转疲劳极限，MPa；
    σ_a_prime: 同时作用的法向应力幅的极限值 σ'_a，MPa；
    σ_负1e: 零件只受对称循环法向应力时的弯曲疲劳极限，MPa。
    返回左端值（无量纲，极限状态 =1，极限圆内 <1）。
    [核:p034]
    """
    return ((float(τ_a_prime) / float(τ_负1e)) ** 2
            + (float(σ_a_prime) / float(σ_负1e)) ** 2)


def eq3_36a(τ_a_prime: float, τ_a: float) -> float:
    """式(3-36a) 双向稳定变应力计算安全系数的相似三角形比值：
    S_ca = OM'/OM = OC'/OC = OD'/OD = τ'_a/τ_a = σ'_a/σ_a。

    适用条件：同式(3-36)；工作应力点 M 在极限圆内（安全），引直线 OM 延长
    与圆弧 AB 交于 M'，按相似三角形取比值。
    τ_a_prime: 切向应力幅的极限值 τ'_a，MPa；
    τ_a: 工作切向应力幅 τ_a，MPa。
    返回 S_ca（无量纲）。书中同时给出 OC'=τ'_a/τ_负1e、OC=τ_a/τ_负1e、
    OD'=σ'_a/σ_负1e、OD=σ_a/σ_负1e，代入后同一比值也可由 σ 侧得到。
    [核:p035]
    """
    if float(τ_a) <= 0:
        raise ValueError("式3-36a 的工作应力幅 τ_a 必须为正")
    return float(τ_a_prime) / float(τ_a)


def eq3_36b(S_ca: float, τ_a: float, σ_a: float) -> tuple:
    """式(3-36b) 极限应力幅与工作应力幅的联立式：
    τ'_a/τ_负1e = S_ca·τ_a/τ_负1e，即 τ'_a = S_ca·τ_a；
    σ'_a/σ_负1e = S_ca·σ_a/σ_负1e，即 σ'_a = S_ca·σ_a。

    适用条件：同式(3-36a)；由式(3-36a) 各线段长度表达式整理，两式在书中以
    右大括号并列成一个编号。
    S_ca: 计算安全系数（无量纲）；
    τ_a: 工作切向应力幅，MPa；
    σ_a: 工作法向应力幅，MPa。
    返回 (τ'_a, σ'_a)，MPa。
    [核:p035]
    """
    return (float(S_ca) * float(τ_a), float(S_ca) * float(σ_a))


def eq3_36c(S_ca: float, τ_a: float, τ_负1e: float,
            σ_a: float, σ_负1e: float) -> float:
    """式(3-36c) 将式(3-36b) 代入式(3-36)：
    (S_ca τ_a/τ_负1e)² + (S_ca σ_a/σ_负1e)² = 1。

    适用条件：同式(3-36)；书页说明“将式(3-36b) 代入式(3-36)，得”本式。
    S_ca: 计算安全系数（无量纲）；
    τ_a: 工作切向应力幅，MPa；
    τ_负1e: 零件对称循环扭转疲劳极限，MPa；
    σ_a: 工作法向应力幅，MPa；
    σ_负1e: 零件对称循环弯曲疲劳极限，MPa。
    返回左端值（无量纲，极限状态 =1）。
    [核:p035]
    """
    return ((float(S_ca) * float(τ_a) / float(τ_负1e)) ** 2
            + (float(S_ca) * float(σ_a) / float(σ_负1e)) ** 2)


def eq3_37(S_σ: float, S_τ: float) -> float:
    """式(3-37) 双向稳定变应力下零件的计算安全系数：
    S_ca = S_σ S_τ/√(S_σ² + S_τ²)。

    适用条件：法向与切向对称循环变应力同时作用。两个变应力均为不对称循环
    时，可先由式(3-19) 分别求出
    S_σ=σ_负1/(K_σ σ_a+φ_σ σ_m)、S_τ=τ_负1/(K_τ τ_a+φ_τ τ_m)，
    再按本式求 S_ca。
    S_σ: 零件只受法向应力 σ_a 时的计算安全系数（无量纲），
         S_σ=σ_负1e/σ_a；
    S_τ: 零件只受切应力 τ_a 时的计算安全系数（无量纲），
         S_τ=τ_负1e/τ_a。
    返回 S_ca（无量纲）。
    [核:p035]
    """
    if float(S_σ) <= 0 or float(S_τ) <= 0:
        raise ValueError("式3-37 的 S_σ、S_τ 必须为正")
    return (float(S_σ) * float(S_τ)
            / math.hypot(float(S_σ), float(S_τ)))


# =====================================================================
# 8. 3-3 节 抗断裂强度与 3-4 节 接触强度：式(3-38)
# =====================================================================

def eq3_38(F: float, B: float, ρ_1: float, ρ_2: float,
           μ_1: float, μ_2: float, E_1: float, E_2: float,
           外接触: bool = True) -> float:
    """式(3-38) 两弹性圆柱体线接触的赫兹接触应力：
    σ_H = √{ (F/B·(1/ρ_1 ± 1/ρ_2))
             / [π((1−μ_1²)/E_1 + (1−μ_2²)/E_2)] }。

    适用条件：两弹性圆柱体线接触（轴线平行的外接触或内接触）；受载后接触
    线变为宽 2b 的矩形接触面，应力沿接触宽度呈半椭圆柱分布，取初始接触线处
    的最大值代表接触应力。本书只在线接触场合作接触应力计算（球轴承、圆弧
    齿轮虽用点接触概念但未作接触应力计算）。接触位置连续改变时接触应力在
    0~σ_H 间变化，属脉动循环变应力。
    F: 作用于接触面上的总压力，N；
    B: 初始接触线长度，mm；
    ρ_1、ρ_2: 零件1、2 初始接触线处的曲率半径，mm（综合曲率 1/ρ_Σ=
        1/ρ_1±1/ρ_2，综合曲率半径 ρ_Σ=ρ_1ρ_2/(ρ_1±ρ_2)）；
    μ_1、μ_2: 两零件材料的泊松比（无量纲）；
    E_1、E_2: 两零件材料的弹性模量，MPa；
    外接触: True=外接触（取正号，默认），False=内接触（取负号）。
    返回接触应力最大值 σ_H，MPa（单位换算：N/mm² = MPa）。
    [核:p038]（符号说明在 p.39）
    """
    if float(B) <= 0 or float(ρ_1) <= 0 or float(ρ_2) <= 0:
        raise ValueError("式3-38 要求 B>0、ρ_1>0、ρ_2>0（mm）")
    曲率 = 1.0 / float(ρ_1) + (1.0 / float(ρ_2) if 外接触
                               else -1.0 / float(ρ_2))
    if 曲率 <= 0:
        raise ValueError("式3-38 的综合曲率必须为正（内接触时 1/ρ_1>1/ρ_2）")
    柔度 = ((1.0 - float(μ_1) ** 2) / float(E_1)
            + (1.0 - float(μ_2) ** 2) / float(E_2))
    if 柔度 <= 0:
        raise ValueError("式3-38 要求 E_1、E_2>0（MPa）")
    return math.sqrt((float(F) / float(B)) * 曲率 / (math.pi * 柔度))



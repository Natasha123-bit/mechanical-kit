    校验("步骤(2)-1 倾覆力矩 M=F_Σh×160+F_Σv×150", M, 1051070.0, 0.005,
         "N·mm", "160/150 为图5-40 力臂")
    校验("步骤(2)-1 M（书值 3677/3085 回代）",
         3677.0 * 160.0 + 3085.0 * 150.0, 1051070.0, 1e-12, "N·mm",
         "588320+462750，精确相等")


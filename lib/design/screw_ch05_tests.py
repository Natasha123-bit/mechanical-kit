    校验("式(5-28) 单螺栓横向工作拉力 3677/4", F_a, 919.0, 0.005, "N",
         "精确 919.25")

    # (2)-3 倾覆力矩分量与最大工作拉力
    F_max = c.eq5_37(M, [140.0, -140.0, 140.0, -140.0])
    校验("式(5-37) 翻转力矩分量 M×140/ΣL²", F_max, 1877.0, 0.005, "N",
         "ΣL²=4×140²=78400")
    校验("式(5-37) 用书值 M=1051070 回代",
         c.eq5_37(1051070.0, [140.0, 140.0, -140.0, -140.0]), 1877.0,
         1e-4, "N", "1876.9")
    F = F_a + F_max
    校验("步骤(2)-3 最大工作拉力 F=F_a+F_max", F, 2796.0, 0.005, "N",
         "2796.25")

    # (2)-4 接合面不滑移条件（f=0.16 表5-7，K_s=1.2，C_b/(C_b+C_m)=0.2）

def 例7_1_焊缝校核():
    print("\n--- 例7-1 工字钢支架焊缝校核（F=150 000 N、l=150、k=8、25a）---")
    F, l力臂, k = 150000.0, 150.0, 8.0
    h, b, t = 250.0, 116.0, 13.0          # 25a 工字钢：高、腿宽、腿平均厚度

    # 步骤(2)：投影面积 A1=2k(h-2t)，剪力分量 τ1=F/(0.7A1)
    A1 = c.焊缝投影面积A1(k, h, t)
    校验("例7-1 式(7-1)前的几何量 A1=2k(h-2t)", A1, 3584.0, 0.0, "mm²",
         "2×8×(250−26)")
    校验("例7-1 A1 手算 2×8×(250−2×13)", A1, 2 * k * (h - 2 * t), 1e-12,
         "mm²")
    τ1 = c.角焊缝计算切应力(F, A1)
    校验("例7-1 τ1=F/(0.7A1)", τ1, 59.79, 0.005, "MPa", "书值 59.79")
    校验("例7-1 τ1 手算 F/(0.7×2k(h−2t))", τ1,
         F / (0.7 * 2.0 * k * (h - 2.0 * t)), 1e-12, "MPa")

    # 步骤(3)：投影惯性矩 J（两个工字形）
    J = c.焊缝投影惯性矩J(b, h, k)
    校验("例7-1 J(x-x)", J, 71451061.0, 1e-8, "mm⁴", "书值 71 451 061")
    校验("例7-1 J 手算 2[bh³−(b−k)(h−2k)³]/12", J,
         2.0 * (b * h ** 3 - (b - k) * (h - 2.0 * k) ** 3) / 12.0, 1e-12,
         "mm⁴")
    校验真("例7-1 脚注条件 k=8<t=13（可设 k≈t）", k < t,
           "p.136 脚注：此时可近似取 A2 的 J 为工字钢 J 的 2 倍")

    # 步骤(4)：抗弯截面模量 W=0.7J/y，弯矩分量 τ2=Fl/W
    y = 112.0
    校验("例7-1 危险点距 y=112（= (h−2t)/2）", y, (h - 2.0 * t) / 2.0, 0.0,
         "mm", "书中直接给出 y=112")
    W = c.焊缝抗弯截面模量(J, y)
    校验("例7-1 W=0.7J/y", W, 446569.0, 1e-5, "mm³", "书值 446 569")
    τ2 = F * l力臂 / W
    校验("例7-1 τ2=Fl/W", τ2, 50.38, 0.005, "MPa", "书值 50.38")
    校验("例7-1 τ2 手算 Fl/(0.7J/y)", τ2, F * l力臂 / (0.7 * J / y), 1e-12,
         "MPa")

    # 步骤(5)：合成切应力
    τ = c.合成切应力(τ1, τ2)
    校验("例7-1 合成切应力 τ=√(τ1²+τ2²)", τ, 78.19, 0.005, "MPa",
         "书值 78.19")
    校验("例7-1 合成切应力手算", τ, (τ1 ** 2 + τ2 ** 2) ** 0.5, 1e-12,
         "MPa")

    # 步骤(6)：查表7-3 得 [τ']=140，比较
    τ许 = c.查表7_3("Q235", "[τ']")
    校验("例7-1 表7-3 查 [τ']（Q235AF→Q235）", τ许, 140.0, 0.0, "MPa")
    校验真("例7-1 强度足够（τ=78.19≤[τ']=140）", τ <= τ许,
           "安全裕度 140/78.19≈1.79")



def 例7_2_过盈连接():
    print("\n--- 例7-2 组合齿轮过盈连接（T=7×10⁶ N·mm、d=480、l=110）---")
    T, d, d1, d2, l = 7.0e6, 480.0, 440.0, 520.0, 110.0
    E1, E2 = 1.3e5, 2.1e5                # 轮芯 HT250、齿圈 45 钢
    μ1, μ2 = 0.25, 0.30
    Ra1, Ra2 = 1.6, 3.2                  # 轴（轮芯）、孔（齿圈）

    # 步骤(1)：表7-5 取 f=0.08，式(7-9) 求 p_min
    校验文本("例7-2 表7-5 钢-铸钢有润滑 f", c.查表7_5("钢-铸钢", 润滑=True),
             (0.08, 0.08))
    校验文本("例7-2 表7-5 钢-优质结构钢有润滑 f",
             c.查表7_5("钢-优质结构钢", 润滑=True), (0.08, 0.08))
    pmin = c.eq7_9(T, d, l, 0.08)
    校验("例7-2 式(7-9) p_min=2T/(πd²lf)", pmin, 2.19, 0.005, "MPa",
         "书值 2.19（未圆整 2.19793）")
    校验("例7-2 p_min 手算", pmin, 2.0 * T / (3.141592653589793 * d * d
                                              * l * 0.08), 1e-12, "MPa")
    说明("圆整：p_min 书值 2.19 由 2.19793 保留 3 位有效数字得到；"
         "下面按课本做法用 2.19 代入式(7-11)。")

    # 步骤(2)1)：刚性系数 C1、C2 与最小过盈量
    C1 = c.C1_刚性系数(d, d1, μ1)
    C2 = c.C2_刚性系数(d2, d, μ2)
    校验("例7-2 式(7-11) C1=(d²+d1²)/(d²−d1²)−μ1", C1, 11.27, 0.005, "—",
         "书值 11.27")
    校验("例7-2 C1 手算", C1,
         (d * d + d1 * d1) / (d * d - d1 * d1) - μ1, 1e-12, "—")
    校验("例7-2 式(7-11) C2=(d2²+d²)/(d2²−d²)+μ2", C2, 12.82, 0.005, "—",
         "书值 12.82")
    校验("例7-2 C2 手算", C2,
         (d2 * d2 + d * d) / (d2 * d2 - d * d) + μ2, 1e-12, "—")
    说明("式7-11 的 C1、C2 已含 μ 与直径比；E1、E2 在 C/E 项中引入，"
         "故 C1、C2 本身无量纲。")

    Δmin = c.eq7_11(2.19, d, C1, E1, C2, E2)
    校验("例7-2 式(7-11) Δ_min=p_min·d(C1/E1+C2/E2)×10³", Δmin, 155.0,
         0.005, "μm", "书值 155（用圆整 p_min=2.19 得 155.32）")
    校验("例7-2 Δ_min 手算", Δmin,
         2.19 * d * (C1 / E1 + C2 / E2) * 1.0e3, 1e-12, "μm")
    未圆整 = c.eq7_11(pmin, d, C1, E1, C2, E2)
    校验("例7-2 未圆整 p_min 链得 Δ=155.88（会圆到 156）", 未圆整, 155.88,
         0.001, "μm", "圆整链单独注明，不当作书值")
    说明("Δ_min=155 是圆整值：书用圆整后的 p_min=2.19，得 155.32→155；"
         "若一路不圆整则 155.88→156。测试主校验走课本的圆整链。")

    # 步骤(2)2)：式(7-12) 加表面峰尖修正，得最小有效过盈量 170
    修正 = 2.0 * (c.压平深度S(Ra1) + c.压平深度S(Ra2))
    校验("例7-2 式(7-12) 修正量 2(S1+S2)", 修正, 15.36, 1e-9, "μm",
         "2×(1.6×1.6+1.6×3.2)")
    δmin = c.eq7_12(155.0, Ra1, Ra2)
    校验("例7-2 式(7-12) δ_min=Δ_min+2(S1+S2)", δmin, 170.0, 0.005, "μm",
         "书值 170（155+15.36=170.36）")
    校验("例7-2 δ_min 手算", δmin,
         155.0 + 2.0 * (1.6 * Ra1 + 1.6 * Ra2), 1e-12, "μm")
    校验("例7-2 式(7-12) 胀缩法 δ_min=Δ_min",
         c.eq7_12(155.0, Ra1, Ra2, 装配="胀缩法"), 155.0, 1e-12, "μm")

    # 步骤(2)2)：选 H7/s6，核最小过盈
    δmax = 292.0 - 0.0
    δmin实 = 252.0 - 63.0
    校验("例7-2 H7/s6 最大过盈 δ_max=292−0", δmax, 292.0, 0.0, "μm",
         "孔 +0.063/0、轴 +0.292/+0.252")
    校验("例7-2 H7/s6 最小过盈 252−63", δmin实, 189.0, 0.0, "μm")
    校验真("例7-2 所选配合最小过盈 189μm>δ_min=170.36μm", δmin实 > δmin,
           "课本结论“合适”")

    # 步骤(3)：式(7-13) 求 p_max，式(7-17) 核齿圈强度
    pmax = c.eq7_13(δmax, d, C1, E1, C2, E2, 擦去量=修正)
    校验("例7-2 式(7-13) p_max（压入法扣 2(S1+S2)）", pmax, 3.90, 0.005,
         "MPa", "书值 3.90（276.64/70.92=3.9006）")
    校验("例7-2 p_max 手算", pmax,
         (292.0 - 15.36) / (d * (C1 / E1 + C2 / E2) * 1.0e3), 1e-12,
         "MPa")
    p许 = c.eq7_17(d2, d, 280.0)
    校验("例7-2 式(7-17) 齿圈许用 p_max", p许, 21.46, 0.005, "MPa",
         "σs2=280 MPa")
    校验("例7-2 式(7-17) 手算", p许,
         (d2 * d2 - d * d) / (3.0 * d2 ** 4 + d ** 4) ** 0.5 * 280.0,
         1e-12, "MPa")
    校验真("例7-2 齿圈强度足够（3.90≪21.46）", pmax < p许,
           "被包容件 HT250 压限很高，无须校核")

    # 步骤(4)：式(7-18) 最大压入力，f=0.10
    校验文本("例7-2 表7-5 钢-铸铁有润滑 f 区间", c.查表7_5("钢-铸铁",
                                                             润滑=True),
             (0.05, 0.10))
    Fi = c.eq7_18(0.10, d, l, 3.90)
    校验("例7-2 式(7-18) F_i=fπdlp_max", Fi, 64692.0, 0.005, "N",
         "书值 64 692")
    校验("例7-2 F_i 手算", Fi, 0.10 * 3.141592653589793 * d * l * 3.90,
         1e-12, "N")
    校验("例7-2 式(7-18) 用未圆整 p_max=3.9006", c.eq7_18(0.10, d, l,
                                                          pmax),
         64692.0, 0.005, "N", "差异属 p_max 圆整")
    说明("例7-2 两处 f 不同：算 p_min 用 0.08（有润滑），算 F_i 用 0.10"
         "（表7-5 钢-铸铁有润滑的上限），课本原文如此。")
    校验真("例7-2 式(7-19) 压出力大于压入力",
           c.eq7_19(Fi) > Fi, "1.3~1.5 倍")



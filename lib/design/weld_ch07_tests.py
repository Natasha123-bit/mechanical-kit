    校验("式7-5 l1+l2=F/(0.7k[τ'])", l1 + l2, F / (0.7 * k * τ许), 1e-12,
         "mm")
    校验异常("式7-5 不适用于 a=b", lambda: c.eq7_5(F, 50.0, 50.0, k, τ许))
    M, h6 = 2.0e6, 40.0

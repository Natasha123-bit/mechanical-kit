"""
clutch_ch14.py 的测试：以课本例14-1（p.369，按电动机轴伸选弹性套柱销联轴器）
的已知条件、中间结果与结论为基准，抽查表14-1 的原始格值（含边界工况），并
校验 14-1↔14-2、14-3 判据、14-4 与 T=FR 的代数关系（容差 1e-9）。

例14-1 书值（B.json）：
  P=10 kW、n=960 r/min、d=42 mm、T=99.48 N·m、K_A=2.3、
  T_ca=228.80 N·m、LT6（T_n=355 N·m）、[n]=3 800 r/min、结论合用。

圆整说明（单独注明，不塞回公式冒充计算值）：
  · T=99.48 N·m：式 T=9.55×10^6P/n 的未圆整值为 99 479.17 N·mm
    =99.479 17 N·m，书保留 4 位有效数字得 99.48 N·m。
  · T_ca=228.80 N·m：书用已圆整的 T=99.48 乘 K_A=2.3，得 228.804→228.80；
    若一路用未圆整 T 则得 228.802，同样圆到 228.80（两条链都记下）。
  · 转速书上写作“3 800 r/min”（千位空格），按 3800 取值。

运行：
    python3 clutch_ch14_tests.py   全部通过则退出码 0，有失败则退出码 1。
    （末行输出“合计：通过 N 项，失败 0 项”。）
"""

from __future__ import annotations

import clutch_ch14 as c

失败 = []
通过 = 0


def 校验(名称: str, 计算值: float, 书上值: float,
        容差: float = 0.005, 单位: str = "", 备注: str = ""):
    """容差为相对误差（默认 0.5%）；书上值只保留 2~4 位有效数字。"""
    global 通过
    if 书上值 == 0:
        ok = abs(计算值) < 1e-9
        rel = 0.0
    else:
        rel = abs(计算值 - 书上值) / abs(书上值)
        ok = rel <= 容差
    if ok:
        通过 += 1
    else:
        失败.append((名称, 计算值, 书上值, rel))
    print("%s %-52s 计算=%14.6f  书上=%14.6f  Δ=%7.4f%% %-5s %s"
          % ("[OK]  " if ok else "[FAIL]", 名称, 计算值, 书上值,
             rel * 100, 单位, 备注))


def 校验文本(名称: str, 计算值, 书上值):
    """字符串/整数/布尔/None/元组等精确相等。"""
    global 通过
    ok = 计算值 == 书上值
    if ok:
        通过 += 1
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
    print("%s %-52s 计算=%s  书上=%s"
          % ("[OK]  " if ok else "[FAIL]", 名称, 计算值, 书上值))


def 校验真(名称: str, 条件: bool, 说明: str = ""):
    """任意布尔断言（结构、范围、判据等）。"""
    global 通过
    if 条件:
        通过 += 1
        print("[OK]   %-52s %s" % (名称, 说明))
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
        print("[FAIL] %-52s %s" % (名称, 说明))


def 校验异常(名称: str, 函数, 异常类=ValueError):
    global 通过
    try:
        函数()
    except 异常类:
        通过 += 1
        print("[OK]   %-52s 按预期抛 %s" % (名称, 异常类.__name__))
    except Exception as e:                       # noqa: BLE001
        失败.append((名称, float("nan"), float("nan"), 1.0))
        print("[FAIL] %-52s 抛了 %r（应为 %s）"
              % (名称, e, 异常类.__name__))
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
        print("[FAIL] %-52s 未抛异常（应为 %s）" % (名称, 异常类.__name__))


def 说明(文字: str):
    print("       · %s" % 文字)



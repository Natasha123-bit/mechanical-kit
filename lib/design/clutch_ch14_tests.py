def 例14_1_选型():
    print("\n--- 例14-1 联轴器选型（P=10 kW、n=960、d=42）---")
    P, n轴, d = 10.0, 960.0, 42.0

    # 步骤(2) 第一式：理论转矩 T=9.55×10^6 P/n
    T计算 = c.理论转矩T(P, n轴)
    校验("例14-1 式(2) T=9.55×10^6P/n", T计算, 99479.0, 0.005, "N·mm",
         "书值 9.55×10^6×10/960=99 479 N·mm")
    校验("例14-1 T 折合 N·m", T计算 / 1000.0, 99.48, 0.005, "N·m",
         "书值 99.48（未圆整 99.479 17）")
    校验("例14-1 T 手算 9.55e6×10/960", T计算, 9.55e6 * P / n轴, 1e-12,
         "N·mm")
    说明("圆整：T=99.48 N·m 由 99.479 17 N·m 保留 4 位有效数字得到；"
         "主校验用书值 99.48 继续。")

    # 步骤(2) 第二句：表14-1 查 K_A=2.3（起重机、电动机）
    KA = c.查表14_1_工作情况系数KA("Ⅴ", "电动机汽轮机")
    校验("例14-1 表14-1 查 K_A（Ⅴ类/电动机）", KA, 2.3, 0.0, "—",
         "书值 2.3")

    # 步骤(2) 第二式：式(14-1) T_ca=K_A T
    Tca = c.eq14_1(99.48, KA)
    校验("例14-1 式(14-1) T_ca=K_A·T", Tca, 228.80, 0.005, "N·m",
         "书值 228.80（2.3×99.48=228.804）")
    校验("例14-1 T_ca 手算 2.3×99.48", Tca, 2.3 * 99.48, 1e-12, "N·m")
    未圆整 = c.eq14_1(T计算 / 1000.0, KA)
    校验("例14-1 未圆整 T 链 T_ca", 未圆整, 228.80, 0.005, "N·m",
         "228.802，与 228.804 同圆到 228.80")
    校验("例14-1 未圆整 T_ca 圆到 228.80", round(未圆整, 2), 228.80, 1e-12,
         "N·m", "圆整链单独核")

    # 步骤(3)：式(14-2) 选 LT6（T_n=355）
    Tn = 355.0
    校验文本("例14-1 LT6 公称转矩 T_n", Tn, 355.0)
    校验真("例14-1 式(14-2) T_ca≤T_n 成立（LT6）", c.eq14_2(Tca, Tn),
           "228.80≤355")
    校验真("例14-1 式(14-2) 边界 T_ca=T_n 含等号", c.eq14_2(355.0, 355.0),
           "判据为“≤”")
    校验真("例14-1 式(14-2) 反例 T_n=200 不满足",
           not c.eq14_2(228.80, 200.0), "判据能拒")

    # 步骤(3)：式(14-3) 校核转速（[n]=3 800）
    n许 = 3800.0
    校验文本("例14-1 LT6 许用转速 [n]", n许, 3800.0)
    校验真("例14-1 式(14-3) n≤[n] 成立", c.eq14_3(n轴, n许), "960≤3800")
    校验真("例14-1 式(14-3) 边界 n=[n] 含等号", c.eq14_3(3800.0, 3800.0),
           "判据为“≤”")
    校验真("例14-1 式(14-3) 反例 n=3801 不满足",
           not c.eq14_3(3801.0, 3800.0), "判据能拒")

    # 步骤(3)：轴孔直径 d=42 在 LT6 范围内（引自标准，书中只给结论）
    校验("例14-1 电动机轴伸直径 d", d, 42.0, 0.0, "mm",
         "只要求电动机侧半联轴器满足")
    校验真("例14-1 三项判据同时满足→LT6 合用",
           c.eq14_2(Tca, Tn) and c.eq14_3(n轴, n许) and d == 42.0,
           "转矩/转速/轴孔直径")



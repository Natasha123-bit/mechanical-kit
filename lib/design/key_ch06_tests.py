def 例6_1_设计():
    print("\n--- 例6-1 平键连接设计（d=70、T=2200 N·m、轮毂宽 100）---")
    d, T, b_毂 = 70.0, 2200.0, 100.0

    # 步骤(1)：查表6-1 选截面
    尺寸 = c.查表6_1(d)
    校验文本("例6-1 表6-1 d=70 所在档", 尺寸["档"], ">65~75")
    校验("例6-1 表6-1 键宽 b", 尺寸["b"], 20.0, 0.0, "mm")
    校验("例6-1 表6-1 键高 h", 尺寸["h"], 12.0, 0.0, "mm")
    校验("例6-1 表6-1 键长范围下限", 尺寸["L_min"], 56.0, 0.0, "mm")
    校验("例6-1 表6-1 键长范围上限", 尺寸["L_max"], 220.0, 0.0, "mm")

    # 键长：由轮毂宽 100 并参考键长系列取 90（比轮毂宽小些）
    取键长 = c.查平键尺寸(d, 90.0)
    校验("例6-1 取标准键长 L=90（在键长系列内）", 取键长["L"], 90.0, 0.0,
         "mm")
    校验真("例6-1 L=90 落在本档键长范围 56~220",
           尺寸["L_min"] <= 90.0 <= 尺寸["L_max"],
           "表6-1 的 L 是范围，90 在系列与档内")
    说明("圆整：L=90 是取标准值（键长系列中有 90），且 90<轮毂宽 100；"
         "不是由公式算出。")
    校验("查表圆整：期望 L=95 → 系列内向下取 90",
         c.查平键尺寸(d, 95.0)["L"], 90.0, 0.0, "mm",
         "只对齐系列，不插值")
    校验("查表圆整：期望 L=100 → 系列内 100（仍为标准值）",
         c.查平键尺寸(d, 100.0)["L"], 100.0, 0.0, "mm",
         "例6-1 另因“比轮毂宽小些”取 90")

    b, h, L = 尺寸["b"], 尺寸["h"], 取键长["L"]

    # 步骤(2)：查表6-2 取 [σbs]
    区间 = c.查表6_2("静连接", "锻钢", "轻微冲击")
    校验文本("例6-1 表6-2 静连接·锻钢·轻微冲击 区间", 区间, (100.0, 120.0))
    许用 = c.查表6_2("静连接", "锻钢", "轻微冲击", 取平均=True)
    校验("例6-1 [σbs] 取区间平均值", 许用, 110.0, 0.0, "MPa",
         "(100+120)/2")

    # 工作长度：A 型圆头 l=L-b
    l = c.平键工作长度(L, b, "A")
    校验("例6-1 键的工作长度 l=L-b", l, 70.0, 0.0, "mm")

    # 单键挤压强度
    σ1 = c.eq6_1(T, d, l, h=h)
    校验("例6-1 式6-1 单键 σbs", σ1, 149.7, 0.005, "MPa",
         "4000T/(hld)")
    校验("例6-1 式6-1 用 k=6 与 h=12 数值相同",
         c.eq6_1(T, d, l, k=h / 2.0), σ1, 1e-9, "MPa", "k≈h/2")
    校验真("例6-1 单键不合格（149.7>110）", σ1 > 许用,
           "课本因此改用双键")

    # 双键：只按 1.5 个键计算
    l2 = c.双键折算工作长度(l)
    校验("例6-1 双键折算工作长度 l=1.5×70", l2, 105.0, 0.0, "mm")
    说明("双键 1.5 是 p.117 的文字规定（两键相隔 180° 布置），"
         "把 1.5 折进工作长度，h 与 d 不变。")
    σ2 = c.eq6_1(T, d, l2, h=h)
    校验("例6-1 式6-1 双键 σbs", σ2, 99.8, 0.005, "MPa", "l 换成 105")
    校验真("例6-1 双键合适（99.8≤110）", σ2 <= 许用, "结论“合适”")

    # 结论：标记 宽×高×长
    校验文本("例6-1 设计结论标记", c.平键标记(b, h, L),
             "GB/T 1096 键 20×12×90")
    说明("结论行只写标记、不含数量；实际按两件、相隔 180° 使用。")



rad = math.radians
deg = math.degrees

失败 = []
通过 = 0


def 校验(名称: str, 计算值: float, 书上值: float, 容差: float = 0.005, 单位: str = ""):
    """容差为相对误差；书上值可能只保留 3~4 位有效数字。"""
    global 通过
    if 书上值 == 0:
        ok = abs(计算值) < 1e-9
        rel = 0.0
    else:
        rel = abs(计算值 - 书上值) / abs(书上值)
        ok = rel <= 容差
    if ok:
        通过 += 1
    else:
        失败.append((名称, 计算值, 书上值, rel))
    print(f"{'✓' if ok else '✗'} {名称:<46s} 计算={计算值:12.5f}  "
          f"书上={书上值:12.5f}  Δ={rel*100:6.3f}% {单位}")



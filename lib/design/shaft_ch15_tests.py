def 例15_1_疲劳():
    print("\n=== 例15-1 步骤(7) 截面 IV 左/右疲劳校核（p.398~p.400）===")
    M1 = 270938.0
    M_IV = M1 * (71.0 - 36.0) / 71.0
    校验("步骤(7) 截面 IV 弯矩 M=270938×(71−36)/71", M_IV, 133561.0, 0.005,
         "N·mm", "按支点位置比例折算，书取整")
    T3 = 9.6e5

    # ---------------- 截面 IV 左侧：d=65（轴承座），过盈配合 + 轴肩
    print("-- 截面 IV 左侧 d=65 --")
    W = c.抗弯截面系数("圆截面", 65.0)
    WT = c.抗扭截面系数("圆截面", 65.0)
    校验("左 表15-4 W=0.1×65³", W, 27462.5, 1e-12, "mm³")
    校验("左 表15-4 WT=0.2×65³", WT, 54925.0, 1e-12, "mm³")
    σb = M_IV / W
    校验("左 σb=M/W=133561/27462.5", σb, 4.86, 0.005, "MPa")
    τT = T3 / WT
    校验("左 τT=T3/WT=9.6×10⁵/54925", τT, 17.48, 0.005, "MPa")

    # 应力集中：r/d=2.0/65=0.031、D/d=70/65=1.08 → ασ=2.0、ατ=1.31
    校验("左 r/d=2.0/65", 2.0 / 65.0, 0.031, 0.01, "",
         "书按两位小数记 0.031（精确 0.030769）")
    校验("左 D/d=70/65", 70.0 / 65.0, 1.08, 0.005)
    kσ = c.有效应力集中系数(2.0, 0.82)
    校验("左 kσ=1+qσ(ασ−1)=1+0.82×1", kσ, 1.82, 1e-12)
    kτ = c.有效应力集中系数(1.31, 0.85)
    校验("左 kτ=1+0.85×(1.31−1)", kτ, 1.26, 0.005, "", "精确 1.2635")
    Kσ = c.综合影响系数(kσ / 0.67, 0.92)
    校验("左 Kσ=1.82/0.67+1/0.92−1", Kσ, 2.80, 0.005, "",
         "精确 2.8034，书取两位")
    Kτ = c.综合影响系数(1.26 / 0.82, 0.92)
    校验("左 Kτ=1.26/0.82+1/0.92−1", Kτ, 1.62, 0.005, "",
         "精确 1.6235，书取两位")
    Sσ = c.eq15_7(275.0, Kσ, σb)
    校验("左 式(15-7) Sσ=275/(2.80×4.86+0.1×0)", Sσ, 20.21, 0.005)
    Sτ = c.eq15_8(155.0, Kτ, τT / 2.0, τT / 2.0)
    校验("左 式(15-8) Sτ=155/(1.62×17.48/2+0.05×17.48/2)", Sτ, 10.62, 0.005)
    Sca = c.eq15_6(Sσ, Sτ)
    校验("左 式(15-6) Sca=SσSτ/√(Sσ²+Sτ²)", Sca, 9.40, 0.005)
    校验真("左 Sca=9.40 > S=1.5 → 安全", Sca > 1.5,
           "%.2f > 1.5" % Sca)
    校验("左 书上 Kσ=2.80、σb=4.86 直接代入的 Sσ",
         275.0 / (2.80 * 4.86), 20.21, 0.005, "", "隔离圆整影响")
    校验("左 书上 Kτ=1.62、τT=17.48 直接代入的 Sτ",
         155.0 / (1.62 * 17.48 / 2.0 + 0.05 * 17.48 / 2.0), 10.62, 0.005, "")
    校验("左 书上 Sσ=20.21、Sτ=10.62 合成的 Sca",
         20.21 * 10.62 / math.hypot(20.21, 10.62), 9.40, 0.005, "")

    # ---------------- 截面 IV 右侧：d=70（齿轮配合处），过盈配合
    print("-- 截面 IV 右侧 d=70 --")
    W2 = c.抗弯截面系数("圆截面", 70.0)
    WT2 = c.抗扭截面系数("圆截面", 70.0)
    校验("右 表15-4 W=0.1×70³", W2, 34300.0, 1e-12, "mm³")
    校验("右 表15-4 WT=0.2×70³", WT2, 68600.0, 1e-12, "mm³")
    σb2 = M_IV / W2
    校验("右 σb=133561/34300", σb2, 3.89, 0.005, "MPa")
    τT2 = T3 / WT2
    校验("右 τT=9.6×10⁵/68600", τT2, 13.99, 0.005, "MPa")
    校验("右 kτ/ετ=0.8×3.16", 0.8 * 3.16, 2.53, 0.005)
    Kσ2 = c.综合影响系数(3.16, 0.92)
    校验("右 Kσ=3.16+1/0.92−1", Kσ2, 3.25, 0.005, "", "精确 3.2470")
    Kτ2 = c.综合影响系数(0.8 * 3.16, 0.92)
    校验("右 Kτ=2.53+1/0.92−1", Kτ2, 2.62, 0.005, "", "精确 2.6170")
    Sσ2 = c.eq15_7(275.0, Kσ2, σb2)
    校验("右 式(15-7) Sσ=275/(3.25×3.89+0.1×0)", Sσ2, 21.75, 0.005)
    Sτ2 = c.eq15_8(155.0, Kτ2, τT2 / 2.0, τT2 / 2.0)
    校验("右 式(15-8) Sτ=155/(2.62×13.99/2+0.05×13.99/2)", Sτ2, 8.30, 0.005)
    Sca2 = c.eq15_6(Sσ2, Sτ2)
    校验("右 式(15-6) Sca=SσSτ/√(Sσ²+Sτ²)", Sca2, 7.75, 0.005)
    校验真("右 Sca=7.75 > S=1.5 → 安全", Sca2 > 1.5, "%.2f > 1.5" % Sca2)
    校验("右 书上 Kσ=3.25、σb=3.89 直接代入的 Sσ",
         275.0 / (3.25 * 3.89), 21.75, 0.005, "")
    校验("右 书上 Kτ=2.62、τT=13.99 直接代入的 Sτ",
         155.0 / (2.62 * 13.99 / 2.0 + 0.05 * 13.99 / 2.0), 8.30, 0.005, "")
    校验("右 书上 Sσ=21.75、Sτ=8.30 合成的 Sca",
         21.75 * 8.30 / math.hypot(21.75, 8.30), 7.75, 0.005, "")

    # ---------------- 静强度（例15-1 未做，只验公式结构）
    print("-- 式(15-9)~(15-11) 静强度（例题略去，仅验算式）--")
    校验("式(15-10) SSσ=355/(133561/34300)", c.eq15_10(355.0, M_IV, W2),
         355.0 / (M_IV / W2), 1e-12)
    校验("式(15-10) 计入轴向力 Fa/A",
         c.eq15_10(355.0, M_IV, W2, 713.0, 3848.0),
         355.0 / (M_IV / W2 + 713.0 / 3848.0), 1e-12)
    校验("式(15-11) SSτ=205/(9.6×10⁵/68600)",
         c.eq15_11(205.0, 9.6e5, WT2), 205.0 / (9.6e5 / WT2), 1e-12)
    Ssσ, Ssτ = c.eq15_10(355.0, M_IV, W2), c.eq15_11(205.0, 9.6e5, WT2)
    校验("式(15-9) SSca 合成", c.eq15_9(Ssσ, Ssτ),
         Ssσ * Ssτ / math.hypot(Ssσ, Ssτ), 1e-12)



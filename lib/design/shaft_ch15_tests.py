def 例15_1_前三步():
    print("\n=== 例15-1 步骤(1)~(3) 运动/动力参数与初估轴径（p.395）===")
    η = 0.97
    P3 = 10.0 * η ** 2
    校验("步骤(1) P3=10×0.97²", P3, 9.41, 0.005, "kW")
    n3 = 1450.0 * (20.0 / 75.0) * (23.0 / 95.0)
    校验("步骤(1) n3=1450×(20/75)×(23/95)", n3, 93.61, 0.005, "r/min")
    T3 = 9.55e6 * P3 / n3
    校验("步骤(1) T3=9.55×10⁶P3/n3", T3, 9.60e5, 0.005, "N·mm",
         "书印 9.60×10⁵")

    # ---- 步骤(2) 齿轮力（低速级大齿轮 mn=4、z=95、β=8°06′34″、αn=20°）
    β = c.角度dms(8, 6, 34)
    校验("步骤(2) β=8°06′34″ 换成弧度", β, math.radians(8 + 6 / 60 + 34 / 3600),
         1e-12, "rad")
    d2 = 4.0 * 95.0 / math.cos(β)
    校验("步骤(2) d2=4×95/cosβ", d2, 383.84, 0.005, "mm")
    Ft = 2.0 * T3 / d2
    校验("步骤(2) Ft=2T3/d2", Ft, 5002.0, 0.005, "N")
    Fr = Ft * math.tan(math.radians(20.0)) / math.cos(β)
    校验("步骤(2) Fr=Ft·tan20°/cosβ", Fr, 1839.0, 0.005, "N")
    Fa = Ft * math.tan(β)
    校验("步骤(2) Fa=Ft·tanβ", Fa, 713.0, 0.005, "N")
    # 书里的 Ft 用四舍五入后的 T3=9.60×10⁵、d2=383.84 复算
    校验("步骤(2) Ft（书取 T3=9.60×10⁵）", 2 * 9.60e5 / 383.84, 5002.0,
         0.005, "N")
    校验("步骤(2) Fr（书取 Ft=5002）",
         5002.0 * math.tan(math.radians(20.0)) / math.cos(β), 1839.0, 0.005, "N")
    校验("步骤(2) Fa（书取 Ft=5002）", 5002.0 * math.tan(β), 713.0, 0.005, "N")

    # ---- 步骤(3) 式(15-2) 初估最小直径，A0=112（45 钢调质）
    dmin = c.eq15_2(P3, n3, A0=112.0)
    校验("步骤(3) 式(15-2) dmin=112∛(9.41/93.61)", dmin, 52.08, 0.005, "mm")
    校验("步骤(3) 式(15-2)（书取 P3=9.41）",
         c.eq15_2(9.41, 93.61, A0=112.0), 52.08, 0.005, "mm")
    校验真("步骤(3) dmin 落在 50~55 mm 之间（50 不够）",
           50.0 < dmin <= 55.0,
           "dmin=%.2f mm → 圆整取 d=55（按 LX4 联轴器孔径，选型非公式）" % dmin)
    校验真("步骤(3) 圆整值 d=55 不小于 dmin", 55.0 >= dmin,
           "圆整为标准直径/联轴器孔径，单独注明")

    # ---- 表15-1 取 45 钢调质的力学性能
    材 = c.查表15_1_材料("45", "调质", 70.0)
    校验("表15-1 45调质 σB", 材["σB"], 640.0, 1e-12, "MPa")
    校验("表15-1 45调质 σs", 材["σs"], 355.0, 1e-12, "MPa")
    校验("表15-1 45调质 σ-1", 材["σ_-1"], 275.0, 1e-12, "MPa")
    校验("表15-1 45调质 τ-1", 材["τ_-1"], 155.0, 1e-12, "MPa")
    校验("表15-1 45调质 [σ-1]", 材["[σ_-1]"], 60.0, 1e-12, "MPa")
    校验文本("表15-1 45调质 毛坯直径档", 材["毛坯直径"], "≤200")
    校验文本("表15-1 45调质 硬度区间", 材["硬度HBW"], (217.0, 255.0))



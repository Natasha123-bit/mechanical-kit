def eq11_1(d_1: float, m: float) -> float:
    """式(11-1) 蜗杆直径系数 q = d_1/m。

    适用：为保证蜗杆与配对蜗轮正确啮合用同尺寸滚刀加工蜗轮，对每一标准模数
    规定若干 d_1，把比值 d_1/m 称为蜗杆直径系数。非标准滚刀/飞刀切制时
    d_1、q 可不受标准限制。
    d_1: 蜗杆分度圆直径 mm；m: 模数 mm；返回 q（无量纲）。
    [核:p258]
    """
    return d_1 / m


def eq11_2(z_1: float, q: float) -> float:
    """式(11-2) 导程角关系 tanγ = p_z/(πd_1) = z_1 p_a/(πd_1) = z_1 m/d_1 = z_1/q。

    适用：由图11-14 几何展开得；p_z 为蜗杆导程，p_z = z_1 p_a，p_a 为轴向齿距。
    z_1: 蜗杆头数；q: 蜗杆直径系数；返回 **tanγ**（无量纲），
    γ = arctan(返回值)。
    [核:p258]
    """
    return z_1 / q


def eq11_3(n_1: float, n_2: float) -> float:
    """式(11-3) 传动比 i = n_1/n_2 = z_2/z_1 = u（蜗杆为主动时）。

    n_1: 蜗杆转速 r/min；n_2: 蜗轮转速 r/min；
    u: 齿数比，u = z_2/z_1。返回 i（无量纲）。
    [核:p260]
    """
    return n_1 / n_2


def eq11_4(d_1: float, d_2: float) -> float:
    """式(11-4) 蜗杆传动的标准中心距 a = ½(d_1+d_2) = ½(d_1+z_2 m)。

    适用：标准传动（不变位，x_2=0）。
    d_1: 蜗杆分度圆直径 mm；d_2: 蜗轮分度圆直径 mm；返回 a/mm。
    [核:p260]
    """
    return (d_1 + d_2) / 2.0


def eq11_5(T_1: float, d_1: float) -> float:
    """式(11-5) 蜗杆圆周力 F_t1 = F_a2 = 2T_1/d_1，N。

    适用：不计摩擦力的影响；各力单位 N。
    T_1: 蜗杆上的公称转矩 N·mm；d_1: 蜗杆分度圆直径 mm。
    返回 F_t1（= 蜗轮轴向力 F_a2 的大小）。
    [核:p265]
    """
    return 2.0 * T_1 / d_1


def eq11_6(T_2: float, d_2: float) -> float:
    """式(11-6) 蜗杆轴向力 F_a1 = F_t2 = 2T_2/d_2，N。

    适用：不计摩擦力的影响；各力单位 N。
    T_2: 蜗轮上的公称转矩 N·mm；d_2: 蜗轮分度圆直径 mm。
    返回 F_a1（= 蜗轮圆周力 F_t2 的大小）。
    [核:p265]
    """
    return 2.0 * T_2 / d_2


def eq11_7(F_t2: float, α: float) -> float:
    """式(11-7) 径向力 F_r1 = F_r2 = F_t2 tanα，N。

    适用：不计摩擦力的影响；各力单位 N。注意课本此处只用 α（轴向压力角），
    不是 α_n。
    F_t2: 蜗轮所受的圆周力 N；α: 压力角，**弧度**。
    返回 F_r1（= F_r2 的大小）。
    [核:p265]
    """
    return F_t2 * math.tan(α)


def eq11_8(T_2: float, d_2: float, α_n: float, γ: float) -> float:
    """式(11-8) 法向载荷 F_n = F_a1/(cosα_n cosγ) = F_t2/(cosα_n cosγ)
    = 2T_2/(d_2 cosα_n cosγ)，N。

    适用：不计摩擦力的影响；各力单位 N。
    T_2: 蜗轮上的公称转矩 N·mm；d_2: 蜗轮分度圆直径 mm；
    α_n: 法向压力角 rad；γ: 导程角 rad。
    [核:p265]
    """
    return 2.0 * T_2 / (d_2 * math.cos(α_n) * math.cos(γ))


def eq11_9(K: float, T_2: float, d_1: float, m: float, z_2: float) -> float:
    """式(11-9) 蜗轮齿面接触疲劳强度校核式，σ_H/MPa。

        σ_H = 480 √( K T_2 / (d_1 m² z_2²) ) ≤ [σ_H]

    适用：闭式蜗杆传动按齿面接触疲劳强度设计（p263）；锡青铜/铸铁蜗轮与钢蜗杆。
    K   : 载荷系数，K = K_A K_β K_v（表11-5 等）
    T_2 : 蜗轮上的公称转矩 N·mm
    d_1 : 蜗杆分度圆直径 mm
    m   : 模数 mm
    z_2 : 蜗轮齿数
    480 是由赫兹式代入 d_2=mz_2、L_0=1.18d_1、1/ρ_Σ=2cos²λ/(m z_2 sinα_n)
    及 Z_E=160 MPa^0.5 后合并成的常数（课本直接印 480）。
    返回 σ_H/MPa。
    [核:p265]
    """
    return 480.0 * math.sqrt(K * T_2 / (d_1 * m ** 2 * z_2 ** 2))


def eq11_10(K: float, T_2: float, z_2: float, σ_H_allow: float) -> float:
    """式(11-10) 按蜗轮接触疲劳强度条件的设计式，m²d_1/mm³。

        m² d_1 ≥ K T_2 ( 480/(z_2 [σ_H]) )²

    适用：由式(11-9) 导出；算出 m²d_1 后按 z_1 从表11-1 选标准 m 与 d_1。
    K          : 载荷系数
    T_2        : 蜗轮上的公称转矩 N·mm
    z_2        : 蜗轮齿数
    σ_H_allow  : 蜗轮齿面许用接触应力 [σ_H]/MPa
    返回 m²d_1 / mm³。
    [核:p267]
    """
    return K * T_2 * (480.0 / (z_2 * σ_H_allow)) ** 2


def eq11_11(K: float, T_2: float, d_1: float, d_2: float, m: float,
            Y_Fa2: float, Y_β: float) -> float:
    """式(11-11) 蜗轮齿根弯曲疲劳强度校核式，σ_F/MPa。

        σ_F = 1.53 K T_2 Y_Fa2 Y_β / (d_1 d_2 m) ≤ [σ_F]

    适用：蜗轮齿根弯曲校核；开式传动以弯曲强度为主要设计准则。
    K   : 载荷系数
    T_2 : 蜗轮上的公称转矩 N·mm
    d_1 : 蜗杆分度圆直径 mm
    d_2 : 蜗轮分度圆直径 mm
    m   : 模数 mm
    Y_Fa2: 蜗轮齿形系数（按 z_v2 查表11-8）
    Y_β : 螺旋角影响系数，Y_β = 1 − γ/140°（γ 以度计）
    1.53 由 b̃_2=πd_1θ/(360°cosγ)（θ 按 100°）、m_n=m cosγ、Y_ε=0.667 合并而来。
    返回 σ_F/MPa。
    [核:p267]
    """
    return 1.53 * K * T_2 * Y_Fa2 * Y_β / (d_1 * d_2 * m)


def eq11_12(K: float, T_2: float, z_2: float, σ_F_allow: float,
            Y_Fa2: float, Y_β: float) -> float:
    """式(11-12) 按蜗轮齿根弯曲疲劳强度的设计式，m²d_1/mm³。

        m² d_1 ≥ 1.53 K T_2 Y_Fa2 Y_β / (z_2 [σ_F])

    适用：由式(11-11) 整理而得；算出 m²d_1 后从表11-1 查蜗杆基本尺寸。
    K          : 载荷系数
    T_2        : 蜗轮上的公称转矩 N·mm
    z_2        : 蜗轮齿数
    σ_F_allow  : 蜗轮许用弯曲应力 [σ_F]/MPa，[σ_F]=[σ'_F]K_FN
    Y_Fa2      : 蜗轮齿形系数
    Y_β        : 螺旋角影响系数
    返回 m²d_1 / mm³。
    [核:p268]
    """
    return 1.53 * K * T_2 * Y_Fa2 * Y_β / (z_2 * σ_F_allow)


def eq11_13(F_t1: float, F_r1: float, E: float, I: float, L_prime: float) -> float:
    """式(11-13) 蜗杆弯曲刚度校核，最大挠度 y/mm。

        y = √(F_t1² + F_r1²) L′³ / (48 E I) ≤ [y]

    适用：把蜗杆螺旋部分看作以齿根圆直径为直径的轴段，校核弯曲刚度。
    F_t1  : 蜗杆所受的圆周力 N（式11-5）
    F_r1  : 蜗杆所受的径向力 N（式11-7）
    E     : 蜗杆材料的弹性模量 MPa
    I     : 蜗杆危险截面惯性矩 mm⁴，I=π d_f1⁴/64（d_f1 为齿根圆直径）
    L_prime: 蜗杆两端支承间的跨距 L′/mm；初步计算可取 L′≈0.9d_2
    许用值 [y] = d_1/1000，mm。
    [核:p268-p269]
    """
    return math.sqrt(F_t1 ** 2 + F_r1 ** 2) * L_prime ** 3 / (48.0 * E * I)


def eq11_14(σ_Hlim: float, σ_H: float) -> float:
    """式(11-14) 圆弧圆柱蜗杆(ZC)接触疲劳强度安全系数 S_H = σ_Hlim/σ_H。

    适用：11-4 节 ZC 传动，先按表11-11/图11-17 初定中心距与几何尺寸，
    再校核安全系数；要求 S_H ≥ S_Hlim（表11-13）。
    σ_Hlim: 蜗轮齿面接触疲劳极限 MPa（式11-16）
    σ_H   : 蜗轮齿面接触应力 MPa（式11-15）
    返回 S_H（无量纲）。
    [核:p273]
    """
    return σ_Hlim / σ_H


def eq11_15(F_t2: float, Z_m: float, Y_z: float, b_m2: float,
            d_2: float, x_2: float, m: float) -> float:
    """式(11-15) ZC 传动蜗轮齿面接触应力 σ_H/MPa。

        σ_H = F_t2 / [ Z_m Y_z b_m2 (d_2 + 2 x_2 m) ]

    适用：圆弧圆柱蜗杆传动强度校核；其余符号意义同前。
    F_t2 : 蜗轮分度圆上的圆周力 N
    Z_m  : 系数，Z_m=√(10m/d_1)
    Y_z  : 蜗杆齿的齿形系数（按 tanγ 查表11-14）
    b_m2 : 蜗轮平均齿宽 mm，b_m2≈0.45(d_1+6m)
    d_2  : 蜗轮分度圆直径 mm
    x_2  : 变位系数
    m    : 模数 mm
    [核:p274]
    """
    return F_t2 / (Z_m * Y_z * b_m2 * (d_2 + 2.0 * x_2 * m))


def eq11_16(K_0: float, f_h: float, f_n: float, f_w: float) -> float:
    """式(11-16) ZC 传动蜗轮齿面接触疲劳极限 σ_Hlim/MPa。

        σ_Hlim = K_0 f_h f_n f_w

    适用：ZC 传动；f_n 按滑动速度 v_s 查表11-16（v_s 见式11-20）。
    K_0 : 蜗轮与蜗杆的配对材料系数 MPa（表11-15）
    f_h : 寿命系数，f_h=∛(12000/L_h)
    f_n : 速度系数（表11-16，转速不变时）
    f_w : 载荷系数，载荷平稳时 f_w=1
    [核:p274]
    """
    return K_0 * f_h * f_n * f_w


def eq11_17(C_Flim: float, C_Fmax: float) -> float:
    """式(11-17) ZC 传动蜗轮齿根弯曲疲劳强度安全系数 S_F = C_Flim/C_Fmax。

    适用：许用值取 1，即要求 S_F ≥ 1。
    C_Flim: 蜗轮齿根应力系数极限值 MPa（表11-17）
    C_Fmax: 蜗轮齿根最大应力系数 MPa（C_Fmax=F_t2max/(m_n π b̃_2)）
    返回 S_F（无量纲）。
    [核:p274]
    """
    return C_Flim / C_Fmax


def eq11_18(η_1: float, η_2: float, η_3: float) -> float:
    """式(11-18) 蜗杆传动总效率 η = η_1 η_2 η_3。

    适用：闭式蜗杆传动；功率损耗分啮合摩擦、轴承摩擦、溅油三部分，
    总效率主要取决于 η_1。
    η_1: 单独考虑啮合摩擦损耗时的效率（式11-19）
    η_2: 单独考虑轴承摩擦损耗时的效率
    η_3: 单独考虑溅油损耗时的效率
    [核:p275]
    """
    return η_1 * η_2 * η_3


def eq11_18a(γ: float, φ_v: float, 系数: float = 0.95) -> float:
    """式(11-18a) 蜗杆传动总效率 η = η_1η_2η_3 = (0.95~0.96)tanγ/tan(γ+φ_v)。

    适用：轴承摩擦与溅油损耗不大，取 η_2η_3 = 0.95~0.96（p277 正文）。
    γ   : 导程角，**弧度**
    φ_v : 当量摩擦角，**弧度**（φ_v = arctan f_v）
    系数: 0.95~0.96，默认 0.95（例11-1 用 0.95 得 η=0.86）
    [核:p278]
    """
    return 系数 * math.tan(γ) / math.tan(γ + φ_v)


def eq11_19(γ: float, φ_v: float) -> float:
    """式(11-19) 计入啮合摩擦损耗时的效率 η_1 = tanγ/tan(γ+φ_v)。

    适用：蜗杆主动时；φ_v = arctan f_v，f_v 按 v_s 查表11-18（普通圆柱蜗杆）
    或表11-19（ZC），表值不符时按表注①插值。
    γ  : 普通圆柱蜗杆分度圆柱上的导程角 rad
    φ_v: 当量摩擦角 rad
    [核:p275]
    """
    return math.tan(γ) / math.tan(γ + φ_v)


def eq11_20(d_1: float, n_1: float, γ: float) -> float:
    """式(11-20) 滑动速度 v_s = v_1/cosγ = πd_1n_1/(60×1000 cosγ)，m/s。

    适用：由图11-18 速度三角形得；单位换算 d_1 取 mm、n_1 取 r/min。
    d_1: 蜗杆分度圆直径 mm；n_1: 蜗杆转速 r/min；γ: 导程角 rad。
    返回 v_s/(m/s)。
    [核:p277]
    """
    return math.pi * d_1 * n_1 / (60.0 * 1000.0 * math.cos(γ))


def eq11_21(t_a: float, P: float, η: float, α_d: float, S: float) -> float:
    """式(11-21) 热平衡时油的工作温度 t_0 = t_a + 1000P(1−η)/(α_d S)，℃。

    适用：由热平衡条件 Φ_1=Φ_2 导出；t_0 一般限制 60~70℃，最高不超过 80℃。
    t_a: 周围空气温度 ℃（常取 20）
    P  : 蜗杆传递的功率 kW
    η  : 总效率
    α_d: 箱体表面传热系数 W/(m²·℃)（8.15~17.45）
    S  : 散热面积 m²
    [核:p279]
    """
    return t_a + 1000.0 * P * (1.0 - η) / (α_d * S)


def eq11_22(P: float, η: float, α_d: float, t_0: float, t_a: float) -> float:
    """式(11-22) 保持正常工作温度所需散热面积 S = 1000P(1−η)/[α_d(t_0−t_a)]，m²。

    适用：既定工作条件下计算所需散热面积；与式(11-21) 互为代数变形。
    P  : 蜗杆传递的功率 kW
    η  : 总效率
    α_d: 箱体表面传热系数 W/(m²·℃)
    t_0: 油的工作温度 ℃（一般 60~70℃，≤80℃）
    t_a: 周围空气温度 ℃（常取 20）
    [核:p279]
    """
    return 1000.0 * P * (1.0 - η) / (α_d * (t_0 - t_a))


def eq11_23(P: float, ΔP_F: float, η: float) -> float:
    """式(11-23) 加装风扇后的总功率损耗 P_f = (P−ΔP_F)(1−η)，kW。

    适用：在蜗杆轴端加装风扇（图11-19）加速空气流通时；风扇功耗先行扣除。
    P    : 蜗杆传递的功率 kW
    ΔP_F : 风扇消耗的功率 kW（式11-24）
    η    : 总效率
    返回 P_f/kW。
    [核:p279]
    """
    return (P - ΔP_F) * (1.0 - η)


def eq11_24(v_F: float) -> float:
    """式(11-24) 风扇消耗的功率 ΔP_F ≈ 1.5 v_F³/10⁵，kW。

    适用：风扇功耗经验式（量纲换算常数为 1.5/10⁵）。
    v_F: 风扇叶轮的圆周速度 m/s。
    返回 ΔP_F/kW。
    [核:p279]
    """
    return 1.5 * v_F ** 3 / 1e5



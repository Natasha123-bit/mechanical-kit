def _查fv_phiv(表, v_s: float, 蜗轮材料: str, 硬度: str) -> tuple:
    """表11-18/11-19 通用查询：返回 (f_v, φ_v/°)，按 v_s 线性内插。"""
    键 = (蜗轮材料, 硬度)
    if 键 not in _列映射_fv:
        raise ValueError("该表无（%s, %s）列；铝青铜只有 ≥45HRC 一档" % (蜗轮材料, 硬度))
    f字段, p字段 = _列映射_fv[键]
    for r in 表:
        if abs(r["v_s"] - v_s) < 1e-12:
            if r[f字段] is None or r[p字段] is None:
                raise ValueError("该格为原表空白（v_s=%s），不得插值" % (v_s,))
            return (r[f字段], _解析度分(r[p字段]))
    lo = None
    hi = None
    for r in 表:
        if r["v_s"] < v_s:
            lo = r
        elif r["v_s"] > v_s and hi is None:
            hi = r
    if lo is None or hi is None:
        raise ValueError("v_s=%s 超出表格范围" % (v_s,))
    if (lo[f字段] is None or hi[f字段] is None
            or lo[p字段] is None or hi[p字段] is None):
        raise ValueError("v_s=%s 相邻档含原表空白格，不得插值" % (v_s,))
    t = (v_s - lo["v_s"]) / (hi["v_s"] - lo["v_s"])
    f_v = lo[f字段] + t * (hi[f字段] - lo[f字段])
    p1 = _解析度分(lo[p字段])
    p2 = _解析度分(hi[p字段])
    return (f_v, p1 + t * (p2 - p1))



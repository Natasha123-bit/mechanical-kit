通过 = 0


def 校验(名称: str, 计算值: float, 书上值: float,
        容差: float = 0.005, 单位: str = "", 备注: str = ""):
    """容差为相对误差（默认 0.5%）；书上值只保留 2~4 位有效数字。"""
    global 通过
    if 书上值 == 0:
        ok = abs(计算值) < 1e-12
        rel = 0.0
    else:
        rel = abs(计算值 - 书上值) / abs(书上值)
        ok = rel <= 容差
    if ok:
        通过 += 1
    else:
        失败.append((名称, 计算值, 书上值, rel))
    print("%s %-56s 计算=%16.8f  书上=%16.8f  Δ=%8.4f%% %-6s %s"
          % ("[OK]  " if ok else "[FAIL]", 名称, 计算值, 书上值,
             rel * 100, 单位, 备注))


def 校验文本(名称: str, 计算值, 书上值):
    """字符串/整数/布尔/None/元组等精确相等。"""
    global 通过
    ok = 计算值 == 书上值
    if ok:
        通过 += 1
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
    print("%s %-56s 计算=%s  书上=%s"
          % ("[OK]  " if ok else "[FAIL]", 名称, 计算值, 书上值))


def 校验真(名称: str, 条件: bool, 说明: str = ""):
    """任意布尔断言（判据、范围、None 格等）。"""
    global 通过
    if 条件:
        通过 += 1
        print("[OK]   %-56s %s" % (名称, 说明))
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
        print("[FAIL] %-56s %s" % (名称, 说明))


def 校验异常(名称: str, 函数, 异常类=ValueError):
    """确认“表外/未知组合/缺参数”按约定抛异常（不猜值、不外推）。"""
    global 通过
    try:
        函数()
    except 异常类:
        通过 += 1
        print("[OK]   %-56s 按预期抛出 %s" % (名称, 异常类.__name__))
    else:
        失败.append((名称, float("nan"), float("nan"), 1.0))
        print("[FAIL] %-56s 未抛出 %s" % (名称, 异常类.__name__))



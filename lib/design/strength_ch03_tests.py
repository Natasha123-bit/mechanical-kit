def 例3_1():
    print("\n=== 例3-1 45 钢试件三级不稳定变应力（p.34）===")
    σ_负1, m, N_0 = 307.0, 9.0, 5.0e6
    σ1, σ2, σ3 = 500.0, 400.0, 350.0
    n = [1.0e4, 1.0e5]
    σ = [σ1, σ2]

    # 步骤(2) 式3-33：两级已作用应力的等效计算应力
    σca = c.eq3_33(n, σ, m, N_0)
    校验("步骤(2) 式3-33 σ_ca=(Σn_iσ_i^m/N_0)^(1/m)", σca, 275.52, 0.005,
         "MPa", "书印两位小数")
    校验("步骤(2) round(σ_ca,2)=275.52", round(σca, 2), 275.52, 1e-12, "MPa",
         "取位项")

    # 步骤(3) 式3-35：计算安全系数
    Sca = c.eq3_35(σ_负1, σca)
    校验("步骤(3) 式3-35 S_ca=σ_-1/σ_ca", Sca, 1.114, 0.005, "—", "")
    校验文本("步骤(3) round(S_ca,3)=1.114", round(Sca, 3), 1.114)

    # 步骤(4)~(6) 式3-1a 逆用：各级应力对应的疲劳寿命
    N1 = c.寿命次数N_i(σ_负1, σ1, N_0, m)
    N2 = c.寿命次数N_i(σ_负1, σ2, N_0, m)
    N3 = c.寿命次数N_i(σ_负1, σ3, N_0, m)
    校验("步骤(4) N_1=N_0(σ_-1/σ_1)^m", N1, 0.062e6, 0.005, "次")
    校验("步骤(5) N_2=N_0(σ_-1/σ_2)^m", N2, 0.462e6, 0.005, "次")
    校验("步骤(6) N_3=N_0(σ_-1/σ_3)^m", N3, 1.537e6, 0.005, "次")
    校验文本("步骤(4) round(N_1/10⁶,3)=0.062", round(N1 / 1e6, 3), 0.062)
    校验文本("步骤(5) round(N_2/10⁶,3)=0.462", round(N2 / 1e6, 3), 0.462)
    校验文本("步骤(6) round(N_3/10⁶,3)=1.537", round(N3 / 1e6, 3), 1.537)

    # 步骤(7)(8) 式3-30 破坏判据解得 n_3
    n3 = N3 * (1.0 - 1.0e4 / N1 - 1.0e5 / N2)
    校验("步骤(8) n_3=N_3(1−n_1/N_1−n_2/N_2)", n3, 9.564e5, 0.005, "次")
    校验文本("步骤(8) round(n_3/10⁵,2)=9.56", round(n3 / 1e5, 2), 9.56)

    损伤 = c.eq3_30([1.0e4, 1.0e5, n3], [N1, N2, N3])
    校验("步骤(7) 式3-30 损伤和 Σn_i/N_i=1", 损伤, 1.0, 1e-9, "—",
         "反解 n_3 后回代")

    # 步骤(10) 式3-31 修正范围 0.7~2.2 对应的 n_3 区间
    已损伤 = 1.0e4 / N1 + 1.0e5 / N2
    校验("步骤(10) 式3-31 取 0.7 时 n_3", N3 * (0.7 - 已损伤), 4.953e5,
         0.005, "次")
    校验("步骤(10) 式3-31 取 2.2 时 n_3", N3 * (2.2 - 已损伤), 2.801e6,
         0.005, "次")
    校验文本("式3-31 只给区间 (0.7, 2.2)", c.eq3_31(), (0.7, 2.2))



def _解例3_3的A(β目标: float, μ_r: float, σ_r: float,
                μ_p: float, σ_p: float) -> float:
    """由式(3-46) 反解面积 A：f(A)=β(A)−β目标 随 A 单调增，二分求根。"""
    def f(A):
        return c.eq3_46(μ_r, σ_r, μ_p / A, σ_p / A) - β目标
    低, 高 = μ_p / μ_r * 1.0001, 1000.0
    if f(低) > 0 or f(高) < 0:
        raise RuntimeError("例3-3 的 A 不在二分区间内")
    for _ in range(200):
        中 = 0.5 * (低 + 高)
        if f(中) < 0:
            低 = 中
        else:
            高 = 中
    return 0.5 * (低 + 高)



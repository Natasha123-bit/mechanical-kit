    校验("12-10 δ=Δ/2 与 δ=R−r 一致", δ, δ2, 1e-12, "mm")
    校验("12-10 δ=0.125", δ, 0.125, 1e-12, "mm")
    校验("12-11 ψ=Δ/d 与 ψ=δ/r 一致", ψ, ψ2, 1e-12, "—")
    校验("12-11 ψ=0.00125", ψ, 0.00125, 1e-12, "—")

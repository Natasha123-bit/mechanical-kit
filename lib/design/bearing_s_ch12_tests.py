    v = c.eq12_3(n, d)
    校验("步骤(3) 式12-3 v=πdn/(60×1000)", v, 5.24, 0.005, "m/s")

    p = c.eq12_1(F, d, B * 1000.0)
    校验("步骤(4) 式12-1 p=F/(dB)", p, 2.5, 0.005, "MPa")

    # 选材：表12-2 中 ZCuSn10P1 行（[p]=15、[v]=10、[pv]=15）
    行 = c.表12_2_金属轴承材料["data"][4]
    校验文本("步骤(5) 表12-2 选 ZCuSn10P1（锡青铜）", 行[1],
             "ZCuSn10P1（10-1 锡青铜）")
    校验文本("表12-2 ZCuSn10P1 [p]", 行[2], "15")
    校验文本("表12-2 ZCuSn10P1 [v]", 行[3], "10")
    校验文本("表12-2 ZCuSn10P1 [pv]", 行[4], "15")
    校验真("步骤(5) p=2.5 ≤ [p]=15", p <= 15.0, "表12-2 许用压力")
    校验真("步骤(5) v=5.236 ≤ [v]=10", v <= 10.0, "表12-2 许用速度")
    pv = c.eq12_2(F, n, B * 1000.0, d=d)
    校验("步骤(5) 式12-2 pv=p·v（未取整 π）", pv, p * v, 1e-9, "MPa·m/s")
    校验真("步骤(5) pv=13.09 ≤ [pv]=15", pv <= 15.0, "表12-2 许用 pv")
    # 书本第二等号把 π/(60×1000) 取整为 1/19100

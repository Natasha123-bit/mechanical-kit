    校验("式12-2 书印常数 19100 的 pv", pv19100, 13.09, 0.005, "MPa·m/s")
    校验真("式12-2 19100 与精确 π 的差 <1×10⁻⁴（取整量）",
           abs(pv19100 / (p * v) - 1.0) < 1e-4,
           "19100 vs 60×1000/π=19098.59，差 7.4×10⁻⁵")



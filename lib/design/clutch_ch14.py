def 理论转矩T(P, n, 系数=9.55e6):
    """
    例14-1 步骤(2) 的理论转矩计算式（**非编号**）：
        T = 9.55×10^6·P/n

    适用条件：由功率 P 与转速 n 求轴上的理论转矩，再乘 K_A 得式(14-1) 的
    计算转矩。例14-1：9.55×10^6×10/960 N·mm=99.48 N·m。
    P: 功率，kW；
    n: 转速，r/min；
    系数: 单位换算系数，课本取 9.55×10^6（P[kW]、n[r/min] → T[N·mm]）。
    返回 T，N·mm（除以 1000 即 N·m）。
    [核:p369]
    """
    _要求正数(P=P, n=n, 系数=系数)
    return 系数 * P / n



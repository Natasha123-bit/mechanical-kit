def _表14_1_分类索引(工作机分类):
    """把 工作机分类 规范成 data 的行号 0~5（内部函数）。"""
    if not isinstance(工作机分类, str):
        raise ValueError("表14-1 的工作机分类须为字符串，收到 %r"
                         % (工作机分类,))
    s = 工作机分类.strip()
    列 = 表14_1_工作情况系数KA["cols"]
    # 1) 完整表头文字
    for i, c in enumerate(列):
        if s == c or s.replace(" ", "") == c.replace(" ", ""):
            return i
    # 2) 罗马数字（可带“类”字，如“Ⅴ类”）
    if s in _表14_1_分类:
        return _表14_1_分类[s]
    if len(s) >= 2 and s[0] in "ⅠⅡⅢⅣⅤⅥ":
        return _表14_1_分类[s[0]]
    if s.endswith("类") and s[:-1] in _表14_1_分类:
        return _表14_1_分类[s[:-1]]
    # 3) 唯一命中的文字片段（如“起重机”“搅拌机”）
    命中 = [i for i, c in enumerate(列) if s and s in c]
    if len(命中) == 1:
        return 命中[0]
    if len(命中) > 1:
        raise ValueError("表14-1 的工作机分类 %r 命中多类（%s），请给罗马数字"
                         "或完整表头文字" % (工作机分类,
                                             [列[i] for i in 命中]))
    raise ValueError("表14-1 无此工作机分类：%r（可选 Ⅰ~Ⅵ 或表头文字）"
                     % (工作机分类,))



def _要求正数(**项):
    """参数为 0 或负时报错（公式只在物理正值的区间有意义）。"""
    for 名, 值 in 项.items():
        if 值 is None or 值 <= 0:
            raise ValueError("%s 必须为正，收到 %r" % (名, 值))


def eq14_1(T, KA):
    """
    式(14-1) 联轴器的计算转矩：
        T_ca = K_A·T

    适用条件：§14-2 第2条按联轴器选型计算计算转矩——应取轴上的最大转矩
    （计入机器启动时的动载荷与运转中可能出现的过载）作为计算转矩 T_ca；
    式本身不区分类别，K_A 由表14-1 按工作机分类与原动机型式查取
    （见“查表14_1_工作情况系数KA”）。
    T: 理论转矩，N·m（A.json 的“式中”只给 T 的量纲 N·m；也可按 N·mm
        代入，此时结果同为 N·mm）；
    K_A: 工作情况系数，无量纲（表14-1）。
    返回 T_ca，**与 T 同单位**：T 用 N·m 得 N·m（例14-1：2.3×99.48
    N·m=228.80 N·m），T 用 N·mm 得 N·mm。
    [核:p367]
    """
    _要求正数(T=T, KA=KA)
    return KA * T


def eq14_2(T_ca, T_n):
    """
    式(14-2) 按公称转矩选定联轴器型号的判据：
        T_ca ≤ T_n

    适用条件：§14-2 第3条按计算转矩 T_ca 及所选联轴器类型，由联轴器标准
    （例14-1 为 GB/T 4323—2017）选定型号时校核该型号的公称转矩；T_ca 由
    式(14-1) 求得。例14-1：LT6 的 T_n=355 N·m ≥ T_ca=228.80 N·m，满足。
    T_ca: 计算转矩，N·m（或 N·mm；必须与 T_n 同单位比较）；
    T_n: 该型号联轴器的公称转矩，N·m（或与 T_ca 相同的 N·mm）。
    返回 bool：True=满足判据（T_ca≤T_n，可选该型号），False=不满足。
    [核:p368]
    """
    _要求正数(T_ca=T_ca, T_n=T_n)
    return T_ca <= T_n


def eq14_3(n, n许):
    """
    式(14-3) 校核最大转速的判据：
        n ≤ [n]

    适用条件：§14-2 第4条校核最大转速——被连接轴的转速不应超过所选联轴器
    的许用转速。例14-1：n=960 r/min ≤ [n]=3 800 r/min，满足。
    n: 被连接轴的转速，r/min；
    n许: 所选联轴器的许用转速 [n]，r/min（方括号表示许用值）。
    返回 bool：True=满足判据（n≤[n]），False=不满足。
    [核:p368]
    """
    _要求正数(n=n, n许=n许)
    return n <= n许


def eq14_4(f, F, R):
    """
    式(14-4) 单盘式摩擦离合器可传递的最大转矩：
        T_max = f·F·R

    适用条件：单盘式摩擦离合器（图14-19）接合时以力 F 将摩擦盘4压在摩擦
    盘3上，主动轴转矩经两摩擦盘接触面间的摩擦力矩传到从动轴；假定摩擦力
    的合力作用在平均半径 R 的圆周上。页文未指明干式或湿式，本式只在该
    假定下成立（多盘式不在本式范围）。
    f: 摩擦系数，无量纲；
    F: 接合时压紧摩擦盘的力（压紧力），N；
    R: 摩擦力合力作用圆的平均半径，mm（若用 m，结果随之为 N·m）。
    返回 T_max，单位 = F 的单位 × R 的单位（f 无量纲）：F[N]×R[mm] 得
    N·mm，F[N]×R[m] 得 N·m。符号顺序照原式 fFR。
    [核:p371]
    """
    _要求正数(f=f, F=F, R=R)
    return f * F * R



def eq15_6(S_σ: float, S_τ: float) -> float:
    """式(15-6) 疲劳强度计算安全系数：S_ca = S_σS_τ/√(S_σ²+S_τ²) ≥ S。

    适用条件：按疲劳强度精确校核——已知轴外形、尺寸与载荷，分析确定一个
    或几个危险截面（既看弯曲/扭转应力大小，也看应力集中与绝对尺寸的影响），
    由式(15-7)、(15-8) 求 S_σ、S_τ 后合成；S_ca 应稍大于或至少等于设计
    安全系数 S。S 取 1.3~1.5（材料均匀、载荷与应力计算精确）、1.5~1.8
    （材料不够均匀、计算精度较低）、1.8~2.5（均匀性与精度很低，或 d>200）。
    S_σ: 仅法向应力时的计算安全系数（式15-7）；S_τ: 仅扭转切应力时的
    计算安全系数（式15-8）；两者均无量纲、均为正。
    返回 S_ca（无量纲）。
    例15-1：S_σ=20.21、S_τ=10.62 → S_ca=9.40 > S=1.5。
    [核:p389]
    """
    S_σ, S_τ = float(S_σ), float(S_τ)
    if S_σ <= 0 or S_τ <= 0:
        raise ValueError("式15-6 的 S_σ、S_τ 必须为正")
    return S_σ * S_τ / math.sqrt(S_σ ** 2 + S_τ ** 2)


def eq15_7(σ_1: float, K_σ: float, σ_a: float, σ_m: float = 0.0,
           φ_σ: float = 0.1) -> float:
    """式(15-7) 仅法向应力时的计算安全系数：
    S_σ = σ-1/(K_σ σ_a + φ_σ σ_m)。

    适用条件：按疲劳强度精确校核，只有法向应力时。式中符号的意义与取值
    见第3章（课本原文明示“已在第3章中说明，此处不再重复”）。
    σ_1: 材料的弯曲疲劳极限 σ-1，MPa（表15-1）；
    K_σ: 法向应力的疲劳极限综合影响系数（k_σ/ε_σ + 1/β_σ − 1）；
    σ_a: 法向应力幅，MPa（对称循环时 σ_a=σ_max，σ_m=0）；
    σ_m: 平均法向应力，MPa（例15-1 取 0：轴向力引起的压应力甚小，予以忽略）；
    φ_σ: 碳钢特性系数 0.1~0.2（例15-1 取 0.1；赋给 σ_m 的加权）。
    返回 S_σ（无量纲）。
    [核:p389]
    """
    if float(K_σ) <= 0:
        raise ValueError("式15-7 的 K_σ 必须为正")
    分母 = float(K_σ) * float(σ_a) + float(φ_σ) * float(σ_m)
    if 分母 <= 0:
        raise ValueError("式15-7 的分母 K_σσa+φ_σσm 必须为正")
    return float(σ_1) / 分母


def eq15_8(τ_1: float, K_τ: float, τ_a: float, τ_m: float,
           φ_τ: float = 0.05) -> float:
    """式(15-8) 仅扭转切应力时的计算安全系数：
    S_τ = τ-1/(K_τ τ_a + φ_τ τ_m)。

    适用条件：按疲劳强度精确校核，只有扭转切应力时。符号意义见第3章
    （课本明示不重复）。
    τ_1: 材料的剪切疲劳极限 τ-1，MPa（表15-1）；
    K_τ: 扭转应力的疲劳极限综合影响系数（k_τ/ε_τ + 1/β_τ − 1）；
    τ_a: 扭转切应力幅，MPa；τ_m: 平均扭转切应力，MPa
      （轴单向旋转、扭转切应力为脉动循环时，τ_a=τ_m=τ_T/2）；
    φ_τ: 碳钢特性系数 0.05~0.1（例15-1 取 0.05）。
    返回 S_τ（无量纲）。
    [核:p389]
    """
    if float(K_τ) <= 0:
        raise ValueError("式15-8 的 K_τ 必须为正")
    分母 = float(K_τ) * float(τ_a) + float(φ_τ) * float(τ_m)
    if 分母 <= 0:
        raise ValueError("式15-8 的分母 K_ττa+φ_ττm 必须为正")
    return float(τ_1) / 分母


def 有效应力集中系数(α: float, q: float) -> float:
    """有效应力集中系数 k = 1 + q(α − 1)。**第3章式(附3-4)**，非本章编号。

    适用条件：由理论应力集中系数 α 与材料敏性系数 q 求 k，再进入
    K=k/ε+1/β−1。本章只引用其值（例15-1 步骤(7) 的 k_σ=1.82、k_τ=1.26）。
    α: 理论应力集中系数（按附表3-2 查取，无量纲）；q: 材料敏性系数
    （附图3-1，无量纲）；两者均无量纲。
    返回 k（无量纲）。例15-1：1+0.82×(2.0−1)=1.82；
    1+0.85×(1.31−1)=1.2635（书取 1.26）。
    [核:p398]（例15-1 步骤(7) 引用第3章式）
    """
    return 1.0 + float(q) * (float(α) - 1.0)


def 综合影响系数(k_ε比: float, β: float) -> float:
    """疲劳极限综合影响系数 K = k/ε + 1/β − 1。**第3章式(3-12)/(3-16)**，
    非本章编号。

    适用条件：把有效应力集中系数 k、尺寸系数 ε、表面质量系数 β 合成为
    式(15-7)/(15-8) 直接使用的 K_σ、K_τ。本章只引用其值。
    k_ε比: k/ε（有效应力集中系数与尺寸系数之比，无量纲，如例15-1 左
           1.82/0.67、右 3.16）；β: 表面质量系数（无量纲，磨削 0.92）。
    返回 K（无量纲）。例15-1 左：1.82/0.67+1/0.92−1=2.8034（书取 2.80）；
    右：3.16+1/0.92−1=3.2470（书取 3.25）。
    [核:p398-p399]（例15-1 步骤(7) 引用第3章式）
    """
    if float(β) <= 0:
        raise ValueError("综合影响系数 的表面质量系数 β 必须为正")
    return float(k_ε比) + 1.0 / float(β) - 1.0


def eq15_9(S_Sσ: float, S_Sτ: float) -> float:
    """式(15-9) 静强度计算安全系数：S_Sca = S_SσS_Sτ/√(S_Sσ²+S_Sτ²) ≥ S_S。

    适用条件：按静强度校核——评定轴对塑性变形的抵抗能力，对瞬时过载很大
    或应力循环不对称性较严重的轴很有必要；按轴上作用的**最大瞬时载荷**校核。
    S_S: 设计安全系数，1.2~1.4（高塑性材料 σs/σB≤0.6 的钢轴）、
    1.4~1.8（中等塑性 σs/σB=0.6~0.8）、1.8~2（低塑性）、2~3（铸造轴）。
    S_Sσ: 只考虑弯矩和轴向力时的计算安全系数（式15-10）；
    S_Sτ: 只考虑扭矩时的计算安全系数（式15-11）。
    返回 S_Sca（无量纲）。与式15-6 同构（判据换成 S_S）。
    [核:p391]
    """
    S_Sσ, S_Sτ = float(S_Sσ), float(S_Sτ)
    if S_Sσ <= 0 or S_Sτ <= 0:
        raise ValueError("式15-9 的 S_Sσ、S_Sτ 必须为正")
    return S_Sσ * S_Sτ / math.sqrt(S_Sσ ** 2 + S_Sτ ** 2)


def eq15_10(σ_S: float, M_max: float, W: float, F_a_max: float = 0.0,
            A: float = None) -> float:
    """式(15-10) 只考虑弯矩和轴向力时的静强度安全系数：
    S_Sσ = σ_S/(M_max/W + F_a_max/A)。

    适用条件：静强度校核（瞬时最大载荷），危险截面上弯应力与轴向压应力叠加。
    σ_S: 材料的抗弯屈服极限，MPa（表15-1 的 σs）；
    M_max: 危险截面上最大弯矩，N·mm；W: 抗弯截面系数，mm³（表15-4）；
    F_a_max: 危险截面上最大轴向力，N（可省，默认 0）；
    A: 危险截面面积，mm²（F_a_max≠0 时必需）。
    返回 S_Sσ（无量纲）。
    [核:p391]
    """
    if float(W) <= 0:
        raise ValueError("式15-10 的 W 必须为正")
    分母 = float(M_max) / float(W)
    if F_a_max:
        if A is None:
            raise ValueError("式15-10 给了 F_a_max 就必须给截面面积 A")
        if float(A) <= 0:
            raise ValueError("式15-10 的截面面积 A 必须为正")
        分母 += float(F_a_max) / float(A)
    if 分母 <= 0:
        raise ValueError("式15-10 的 M_max/W+F_amax/A 必须为正")
    return float(σ_S) / 分母


def eq15_11(τ_S: float, T_max: float, W_T: float) -> float:
    """式(15-11) 只考虑扭矩时的静强度安全系数：S_Sτ = τ_S/(T_max/W_T)。

    适用条件：静强度校核，危险截面只计最大瞬时扭矩。
    τ_S: 材料的抗扭屈服极限，MPa，其中 τ_S≈(0.55~0.62)σ_S；
    T_max: 危险截面上最大扭矩，N·mm；W_T: 抗扭截面系数，mm³（表15-4）。
    返回 S_Sτ（无量纲）。
    [核:p391]
    """
    if float(W_T) <= 0:
        raise ValueError("式15-11 的 W_T 必须为正")
    return float(τ_S) / (float(T_max) / float(W_T))



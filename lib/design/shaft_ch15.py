def eq15_1(P: float = None, n: float = None, d: float = None,
           T: float = None, W_T: float = None) -> float:
    """式(15-1) 按扭转强度计算：τ_T = T/W_T ≈ 9 550 000(P/n)/(0.2d³) ≤ [τ_T]。

    适用条件：仅仅（或主要）承受扭矩的轴（传动轴）；若还受不大弯矩，用降低
    许用扭转切应力 [τ_T] 的办法考虑（表15-3 注①）。结构设计时常用本式
    初估轴径；不重要轴也可作最终计算。
    P: 传递功率，kW；n: 转速，r/min；d: 计算截面直径，mm；
    T: 扭矩，N·mm（给了 T 就按 T/W_T 算，否则按 9 550 000P/n）；
    W_T: 抗扭截面系数，mm³（缺省取实心圆轴 0.2d³，与式内写法一致）。
    返回 τ_T，MPa。判据 τ_T≤[τ_T] 见 判据15_1()。
    注意 W_T=0.2d³ 只是实心圆轴的近似值；带键槽/空心截面请显式传 W_T
    （表15-4 的 抗扭截面系数()）。
    [核:p386]
    """
    if T is None:
        if P is None or n is None:
            raise ValueError("式15-1 需要 (P, n) 或 T")
        T = 9_550_000.0 * float(P) / float(n)
    if W_T is None:
        if d is None:
            raise ValueError("式15-1 缺 W_T 时必须给 d（取 W_T≈0.2d³）")
        W_T = 0.2 * float(d) ** 3
    if float(W_T) <= 0:
        raise ValueError("式15-1 的 W_T 必须为正")
    return float(T) / float(W_T)


def 判据15_1(P: float = None, n: float = None, d: float = None,
             T: float = None, W_T: float = None, 许用: float = None) -> bool:
    """式(15-1) 的判据形式：τ_T ≤ [τ_T] 是否成立 [核:p386]。

    适用条件：按扭转强度校核传动轴；[τ_T] 由表15-3 查取（已计入弯矩影响
    而降低）。P、n、d、T、W_T 同 eq15_1()；许用: [τ_T]，MPa。
    返回 bool。
    """
    if 许用 is None:
        raise ValueError("判据15_1 需要许用扭转切应力 [τ_T]（查表15-3）")
    return eq15_1(P=P, n=n, d=d, T=T, W_T=W_T) <= float(许用)


def 系数A0(许用扭转切应力: float) -> float:
    """式(15-2) 中的系数：A_0 = ∛(9 550 000/(0.2[τ_T]))（无量纲）。

    适用条件：把式(15-2) 中与材料有关的常数项单独开三次方，便于查表15-3
    后直接用 P、n 估算轴径。许用扭转切应力: [τ_T]，MPa（表15-3）。
    返回 A_0。式(15-2) 的印刷式与表15-3 的 A_0 栏均由此式得到。
    [核:p386]
    """
    τ = float(许用扭转切应力)
    if τ <= 0:
        raise ValueError("式15-2 的 [τ_T] 必须为正，收到 %.6g" % (τ,))
    return (9_550_000.0 / (0.2 * τ)) ** (1.0 / 3.0)


def eq15_2(P: float, n: float, A0: float = None,
           τ_T许用: float = None) -> float:
    """式(15-2) 实心轴最小直径：d ≥ A_0·∛(P/n)，A_0=∛(9 550 000/(0.2[τ_T]))。

    适用条件：由式(15-1) 反解直径，用于实心轴（空心轴用式15-3）；求出的
    d 只是承受扭矩轴段的**最小直径 d_min**，之后还要按装配方案与定位要求
    逐段确定各轴段直径，并按表15-3 注②选 A_0 的上/下值。
    P: 功率，kW；n: 转速，r/min；A0: 系数（查表15-3，或由 τ_T许用 现算）；
    τ_T许用: [τ_T]，MPa（缺 A0 时用来算 A0）。
    返回 d_min，mm。开键槽时还须增大轴径（p.387：d>100 一个键槽 +3%、
    两个 +7%；d≤100 一个键槽 +5%~7%、两个 +10%~15%），再圆整为标准直径。
    例15-1：A0=112、P3=9.41、n3=93.61 → d_min=52.08 mm。
    [核:p386]
    """
    if A0 is None:
        if τ_T许用 is None:
            raise ValueError("式15-2 需要 A0（查表15-3）或 [τ_T]")
        A0 = 系数A0(τ_T许用)
    if float(n) <= 0:
        raise ValueError("式15-2 的转速 n 必须为正")
    return float(A0) * (float(P) / float(n)) ** (1.0 / 3.0)


def eq15_3(P: float, n: float, A0: float = None, β: float = None,
           τ_T许用: float = None) -> float:
    """式(15-3) 空心轴外径：d ≥ A_0·∛(P/[n(1−β⁴)])，β=d₁/d。

    适用条件：空心轴（实心轴用式15-2）；通常取 β=0.5~0.6（15-1 节 p.377
    所述空心轴内/外径比值）。
    P: 功率，kW；n: 转速，r/min；A0: 系数（表15-3）；
    β: 空心轴内径 d₁ 与外径 d 之比（无量纲，0≤β<1）；
    返回 d（外径），mm。β→0 时退化为式15-2（自洽性见测试）。
    [核:p386]
    """
    if A0 is None:
        if τ_T许用 is None:
            raise ValueError("式15-3 需要 A0（查表15-3）或 [τ_T]")
        A0 = 系数A0(τ_T许用)
    if β is None:
        raise ValueError("式15-3 需要 β=d₁/d（通常取 0.5~0.6）")
    β = float(β)
    if not 0.0 <= β < 1.0:
        raise ValueError("式15-3 要求 0≤β<1，收到 β=%.6g" % (β,))
    if float(n) <= 0:
        raise ValueError("式15-3 的转速 n 必须为正")
    return float(A0) * (float(P) / (float(n) * (1.0 - β ** 4))) ** (1.0 / 3.0)


def eq15_4(σ: float, τ: float, α: float) -> float:
    """式(15-4) 弯扭合成计算应力（第三强度理论 + 折合系数）：
    σ_ca = √(σ² + 4(ατ)²)。

    适用条件：既受弯矩又受扭矩的转轴，针对危险截面（弯矩与扭矩大而轴径
    可能不足处）；结构尺寸、零件位置、外载荷与支反力均已确定，M、T 已求出。
    **α 是折合系数**——把常常不是对称循环的扭转切应力折算为对称循环，
    与角度无关：扭转切应力为静应力时 α≈0.3、脉动循环时 α≈0.6、
    对称循环时 α=1（p.389；15-4 式旁只给到 0.3，其余见式15-5 段）。
    σ: 弯曲应力，MPa（对称循环）；τ: 扭转切应力，MPa；
    α: 折合系数（无量纲，0.3/0.6/1）。
    返回 σ_ca，MPa。α=1 时退化为未编号的 σ_ca=√(σ²+4τ²)（见
    第三强度理论计算应力()）。
    [核:p388]
    """
    if α is None:
        raise ValueError("式15-4 的 α 是折合系数（0.3/0.6/1），必须给出")
    return math.sqrt(float(σ) ** 2 + 4.0 * (float(α) * float(τ)) ** 2)


def eq15_5(M: float, T: float, W: float, α: float, 许用: float = None):
    """式(15-5) 弯扭合成强度条件：
    σ_ca = √((M/W)² + 4(αT/(2W))²) = √(M²+(αT)²)/W ≤ [σ-1]。

    适用条件：直径 d 的圆轴，取 σ=M/W、τ=T/W_T=T/(2W) 代入式(15-4)；
    心轴（只受弯矩）取 T=0。转动心轴的弯矩应力为对称循环；固定心轴考虑
    启停，可视为脉动循环，许用应力应改取 [σ_0]（无实验值时碳钢
    [σ_0]≈1.7[σ-1]）。轴向力引起的压应力一般忽略（过大时须计入并考虑失稳）。
    M: 弯矩，N·mm；T: 扭矩，N·mm；W: 抗弯截面系数，mm³（表15-4）；
    α: **折合系数**（0.3 静应力 / 0.6 脉动 / 1 对称，见式15-4）；
    许用: [σ-1]，MPa（给定时返回 (σ_ca, 是否合格)）。
    返回 σ_ca（MPa）；给了 许用 则返回 (σ_ca, bool)。
    例15-1 步骤(6)：M1=270938、T3=9.6×10⁵、α=0.6、W=0.1×70³ →
    σ_ca=18.56 MPa < [σ-1]=60 MPa。
    [核:p389]
    """
    if float(W) <= 0:
        raise ValueError("式15-5 的 W 必须为正")
    σca = math.sqrt(float(M) ** 2 + (float(α) * float(T)) ** 2) / float(W)
    if 许用 is None:
        return σca
    return σca, σca <= float(许用)


def 合成弯矩(M_H: float, M_V: float) -> float:
    """总弯矩合成：M = √(M_H² + M_V²)。**非编号辅助式，p.387**。

    适用条件：已作出水平面弯矩图 M_H 与垂直面弯矩图 M_V 之后（15-3 节
    第(2)条步骤 2）“作出弯矩图”），按矢量合成同一截面的总弯矩。
    M_H: 水平面上的弯矩，N·mm；M_V: 垂直面上的弯矩，N·mm
    （书内式旁未标单位，按弯矩量纲记）。
    返回 M，N·mm。书内下标为大写 H、V。
    例15-1：M1=√(236217²+132699²)=270938 N·mm。
    [核:p387]
    """
    return math.sqrt(float(M_H) ** 2 + float(M_V) ** 2)


def 第三强度理论计算应力(σ: float, τ: float) -> float:
    """第三强度理论（最大切应力理论）当量应力：σ_ca = √(σ² + 4τ²)。
    **非编号辅助式，p.388**。

    适用条件：位于 p.388“4）校核轴的强度”段内，是式(15-4) 的**未折合
    形式**（尚未引入折合系数 α），仅作引出 α 的过渡式。
    σ: 弯曲应力，MPa；τ: 扭转切应力，MPa。
    返回 σ_ca，MPa。与 eq15_4(σ,τ,α=1) 完全相同；与 eq15_5(M,T,W,α=1)
    也一致（自洽性见测试）。
    [核:p388]
    """
    return math.sqrt(float(σ) ** 2 + 4.0 * float(τ) ** 2)



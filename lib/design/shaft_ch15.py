def eq15_12(L: float, 段列表) -> float:
    """式(15-12) 阶梯轴的当量直径：d_v = [L/Σ(l_i/d_i⁴)]^(1/4)。

    适用条件：把阶梯轴看成当量直径为 d_v 的光轴，再按材料力学公式算挠度
    或偏转角（近似计算）。载荷作用于两支承之间时 L=l（l 为支承跨距）；
    载荷作用于悬臂端时 L=l+K（K 为悬臂长度）。光轴可直接用材料力学公式；
    精度要求高时也可用有限元法。
    L: 阶梯轴的计算长度，mm；段列表: [(l_i, d_i), …]，第 i 段长度 mm 与
      直径 mm；z 为轴段数（列表长度）。
    返回 d_v，mm。单段且 l=L 时退化为该段直径（自洽性见测试）。
    [核:p392]
    """
    段 = list(段列表)
    if not 段:
        raise ValueError("式15-12 的段列表不能为空")
    和 = 0.0
    for i, (l_i, d_i) in enumerate(段):
        if float(d_i) <= 0:
            raise ValueError("式15-12 第 %d 段直径必须为正" % (i + 1,))
        和 += float(l_i) / float(d_i) ** 4
    if 和 <= 0 or float(L) <= 0:
        raise ValueError("式15-12 的 Σ(l_i/d_i⁴) 与 L 必须为正")
    return (float(L) / 和) ** 0.25


def eq15_13(y: float, y许用: float) -> bool:
    """式(15-13) 弯曲刚度条件（挠度）：y ≤ [y]。

    适用条件：轴的弯曲刚度校核；[y] 按表15-5 依轴类选取（一般用途的轴
    (0.0003~0.0005)l、刚度较严 0.0002l、电动机轴 0.1Δ、安装齿轮
    (0.01~0.03)mₙ、安装蜗轮 (0.02~0.05)mₜ）。
    y: 轴的挠度，mm；y许用: [y]，mm。
    返回 bool。
    [核:p392]
    """
    return float(y) <= float(y许用)


def eq15_14(θ: float, θ许用: float) -> bool:
    """式(15-14) 弯曲刚度条件（偏转角）：θ ≤ [θ]。

    适用条件：轴的弯曲刚度校核，偏转角影响轴承与齿轮啮合；[θ] 按表15-5
    依轴承类型/截面选取（滑动 0.001、向心球 0.005、调心球 0.05、
    圆柱滚子 0.0025、圆锥滚子 0.0016、齿轮处截面 0.001~0.002 rad）。
    θ: 轴的偏转角，**rad**；θ许用: [θ]，rad。
    返回 bool。角度统一弧度，表15-5 的 [θ] 本就是 rad。
    [核:p392]
    """
    return float(θ) <= float(θ许用)


def eq15_15(T: float, I_p: float, G: float = 钢的剪切弹性模量) -> float:
    """式(15-15) 光轴每米长扭转角：φ = 5.73×10⁴·T/(G·I_p)。

    适用条件：光轴的扭转刚度计算；扭转变形用每米长扭转角 φ 表示。
    T: 扭矩，N·mm；G: 材料剪切弹性模量，MPa（钢轴 8.1×10⁴）；
    I_p: 截面极惯性矩，mm⁴（圆轴 I_p=πd⁴/32）。
    返回 φ，(°)/m。系数 5.73×10⁴ 已把 rad 换成度、每 mm 换成每 m。
    [核:p392]
    """
    if float(G) <= 0 or float(I_p) <= 0:
        raise ValueError("式15-15 的 G、I_p 必须为正")
    return 5.73e4 * float(T) / (float(G) * float(I_p))


def eq15_16(段列表, L: float, G: float = 钢的剪切弹性模量) -> float:
    """式(15-16) 阶梯轴每米长扭转角：
    φ = (5.73×10⁴/(L·G))·Σ(T_i l_i/I_pi)。

    适用条件：阶梯轴的扭转刚度计算（各段扭矩、长度、极惯性矩不同）。
    G: 材料剪切弹性模量，MPa（钢轴 8.1×10⁴）；
    段列表: [(T_i, l_i, I_pi), …]，第 i 段扭矩 N·mm、长度 mm、极惯性矩 mm⁴；
    L: 阶梯轴受扭矩作用的计算长度，mm。
    返回 φ，(°)/m。单段且 l=L 时与式(15-15) 完全相同（自洽性见测试）。
    [核:p392]
    """
    段 = list(段列表)
    if not 段:
        raise ValueError("式15-16 的段列表不能为空")
    和 = 0.0
    for i, (T_i, l_i, I_pi) in enumerate(段):
        if float(I_pi) <= 0:
            raise ValueError("式15-16 第 %d 段 I_pi 必须为正" % (i + 1,))
        和 += float(T_i) * float(l_i) / float(I_pi)
    if float(L) <= 0 or float(G) <= 0:
        raise ValueError("式15-16 的 L、G 必须为正")
    return 5.73e4 / (float(L) * float(G)) * 和


def eq15_17(φ: float, φ许用: float) -> bool:
    """式(15-17) 扭转刚度条件：φ ≤ [φ]。

    适用条件：轴的扭转刚度校核。一般传动轴 [φ]=0.5~1 (°)/m；
    精密传动轴 [φ]=0.25~0.5 (°)/m；精度要求不高的轴 [φ] 可大于 1 (°)/m。
    φ: 每米长扭转角，(°)/m；φ许用: [φ]，(°)/m。
    返回 bool。
    [核:p393]
    """
    return float(φ) <= float(φ许用)



def _找数(文本: str) -> list:
    """按出现顺序抽出字符串里的数（用于表15-5 的 “0.0003～0.0005” 等）。"""
    结果, buf = [], ""
    for ch in str(文本):
        if ch.isdigit() or ch == ".":
            buf += ch
        else:
            if buf:
                结果.append(buf)
                buf = ""
    if buf:
        结果.append(buf)
    return 结果



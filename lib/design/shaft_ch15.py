def eq15_18(m: float, ω: float, y: float, e: float) -> float:
    """式(15-18) 圆盘旋转时的离心力：F_r = mω²(y+e)。

    适用条件：装有单圆盘的双铰支轴（图15-25），设圆盘质量 m 很大、轴质量
    可略去；圆盘材料不均匀或制造有误差而未“平衡”，质心 c 与轴线偏心距 e；
    无阻尼。挠度 y 与偏心距 e 同向相加，故括号内为 y+e。
    m: 圆盘质量，**kg**；ω: 轴角速度，**rad/s**；
    y: 离心力产生的轴挠度，**m**；e: 质心与轴线间偏心距，**m**。
    返回 F_r，N。**本节单位按课本 SI，不是 mm 制**。
    [核:p393]
    """
    return float(m) * float(ω) ** 2 * (float(y) + float(e))


def eq15_19(k: float, y: float) -> float:
    """式(15-19) 轴弯曲变形后的弹性反力：F′_r = k y（方向与离心力相反）。

    适用条件：同一单圆盘双铰支模型；轴挠度 y 时产生与离心力对抗的弹性反力。
    k: 轴的弯曲刚度，**N/m**；y: 轴的挠度，**m**。
    返回 F′_r，N。
    [核:p393]
    """
    return float(k) * float(y)


def eq15_20(m: float, ω: float, y: float, e: float, k: float) -> dict:
    """式(15-20) 离心力与弹性反力的平衡方程：mω²(y+e) = k y。

    适用条件：由式(15-18)、(15-19) 联立（离心力=弹性反力），用于导出
    挠度式(15-21)。
    m: 圆盘质量，kg；ω: 角速度，rad/s；y: 挠度，m；e: 偏心距，m；
    k: 弯曲刚度，N/m。
    返回 {"左边","右边","残差"}（N）；代入式(15-21) 的 y 时残差应为 0。
    本式是方程而非求解式，故以“左右两边+残差”的形式实现，求解用 eq15_21()。
    [核:p393]
    """
    左 = eq15_18(m, ω, y, e)
    右 = eq15_19(k, y)
    return {"左边": 左, "右边": 右, "残差": 左 - 右}


def eq15_21(e: float, k: float, m: float, ω: float) -> float:
    """式(15-21) 轴在圆盘处的挠度：y = e/(k/(mω²) − 1)。

    适用条件：无阻尼单圆盘双铰支轴。ω 由零增大时分母随之减小、y 增大；
    当 k/(mω²)→1 时 y→∞，轴产生极大变形而破坏（即临界状态）。
    e: 质心与轴线间偏心距，m；k: 弯曲刚度，N/m；m: 圆盘质量，kg；
    ω: 角速度，rad/s。
    返回 y，m。ω=0 或分母为 0（恰好共振）时抛 ValueError。
    [核:p394]
    """
    m, ω = float(m), float(ω)
    if m <= 0:
        raise ValueError("式15-21 的圆盘质量 m 必须为正")
    if abs(ω) < 1e-15:
        raise ValueError("式15-21 在 ω=0 时无意义")
    分母 = float(k) / (m * ω ** 2) - 1.0
    if abs(分母) < 1e-15:
        raise ValueError("式15-21 分母为 0（k/(mω²)=1，恰好临界，y→∞）")
    return float(e) / 分母


def eq15_22(k: float, m: float) -> float:
    """式(15-22) 轴的临界角速度：ω_c = √(k/m)。

    适用条件：无阻尼单圆盘双铰支轴，k/(mω²)→1 时挠度趋于无穷所对应的
    角速度。书中说明：右边恰为轴的固有角频率，即临界角速度等于固有角频率；
    ω_c 只与刚度 k、圆盘质量 m 有关，与偏心距 e 无关。
    k: 弯曲刚度，N/m；m: 圆盘质量，kg。
    返回 ω_c，rad/s。
    [核:p394]
    """
    if float(m) <= 0:
        raise ValueError("式15-22 的圆盘质量 m 必须为正")
    if float(k) <= 0:
        raise ValueError("式15-22 的弯曲刚度 k 必须为正")
    return math.sqrt(float(k) / float(m))


def eq15_23(k: float = None, m: float = None, g: float = None,
            y0: float = None) -> float:
    """式(15-23) 用静挠度表示临界角速度：ω_c = √(k/m) = √(g/y₀)。

    适用条件：同式(15-22) 模型；以 k=mg/y₀ 代入（m 圆盘质量、g 重力加速度、
    y₀ 轴在圆盘处的静挠度）。
    k: 弯曲刚度，N/m；m: 圆盘质量，kg；——给 (k, m) 走 √(k/m)；
    g: 重力加速度，m/s²；y0: 静挠度，**m**（课本本式按 m；下一页未编号的
    一阶临界转速式改用 mm）——给 (g, y0) 走 √(g/y₀)。
    返回 ω_c，rad/s。例：g=9.81、y₀=0.001 m → ω_c=99.05 rad/s。
    [核:p394]
    """
    if k is not None and m is not None:
        return eq15_22(k, m)
    if y0 is None:
        raise ValueError("式15-23 需要 (k, m) 或 (g, y0)")
    if float(y0) <= 0:
        raise ValueError("式15-23 的静挠度 y₀ 必须为正")
    if g is None:
        if m is None:
            g = 重力加速度
        else:
            raise ValueError("式15-23 给 y₀ 时请同时给 g（或改给 k、m）")
    return math.sqrt(float(g) / float(y0))


def 一阶临界转速(y0: float, g: float = 重力加速度) -> float:
    """一阶临界转速：n_c1 = (60/2π)ω_c = (30/π)√(g/y₀) ≈ 946√(1/y₀)。
    **非编号辅助式，p.394**（位于式15-23 与“刚性轴/挠性轴”一段之间）。

    适用条件：装有单圆盘的双铰支轴、**不计轴的质量**时；用于工作转速判定：
    刚性轴（亚临界）n<0.85n_c1；挠性轴（超临界）1.15n_c1<n<0.85n_c2
    （n_c1、n_c2 为一阶、二阶临界转速）；转速很高时还须避开高阶临界转速。
    y0: 轴在圆盘处的静挠度，**mm**（注意与式15-23 的 m 不同）；
    g: 重力加速度，m/s²（书取 9.810）。
    返回 n_c1，r/min。系数 946 = (30/π)√9810 是 y₀ 用 mm 时的结果
    （自洽性见测试：946 ≈ (30/π)√(9.81×1000) = 945.9）。
    [核:p394]
    """
    if float(y0) <= 0:
        raise ValueError("一阶临界转速的静挠度 y₀ 必须为正（mm）")
    return 30.0 / math.pi * math.sqrt(float(g) * 1000.0 / float(y0))



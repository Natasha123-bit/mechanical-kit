def _解析区间文本(文本) -> tuple:
    """把“15~25”“0.000 3～0.000 5”解析为 (低, 高)；只读数、不插值。"""
    s = str(文本).replace(" ", "").replace("～", "~")
    if "~" not in s:
        raise ValueError("表值“%s”不是 a~b 形式的区间" % (文本,))
    左, 右 = s.split("~", 1)
    return float(左), float(右)


def _数值(文本):
    """把表内格子转成数值：单值→float，区间→(低, 高)，None→None，其余→原串。

    只做类型转换，不改写原表文字（如“≥241”“渗碳 56~62HRC”“400~420”）。
    """
    if 文本 is None:
        return None
    s = str(文本).replace(" ", "")
    if "～" in s or "~" in s:
        try:
            return _解析区间文本(s)
        except ValueError:
            return 文本
    try:
        return float(s)
    except ValueError:
        return 文本


def _直径在档内(档: str, d: float) -> bool:
    """判断直径 d 是否落在表15-1/15-2 的印刷档（“≤200”“>100~300”“>6~10”）。

    印刷档左开右闭：">100~300" 表示 100<d≤300，"≤100" 表示 d≤100。
    不做外推：d 落在所有档之外返回 False。
    """
    s = str(档).replace(" ", "").replace("～", "~")
    if s.startswith("≤"):
        return d <= float(s[1:])
    if s.startswith("≥"):
        return d >= float(s[1:])
    if s.startswith("<"):
        return d < float(s.lstrip("<"))
    if s.startswith(">"):
        s = s[1:]

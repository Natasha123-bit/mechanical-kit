def _区间(文本):
    """把表里的 "a~b" / "a～b" / "a" 解析成 (a, b) 浮点二元组。"""
    if 文本 is None:
        return None
    s = str(文本).strip().replace("～", "~")
    if "~" in s:
        lo, hi = s.split("~")
        return float(lo), float(hi)
    v = float(s)
    return v, v



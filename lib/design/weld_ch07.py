def 焊缝投影面积A1(k, h, t):
    """
    例7-1 步骤(2)：两条竖直角焊缝在连接面上的投影面积（**非编号**）：
        A1 = 2k(h-2t)

    适用条件：工字钢支架的角焊缝校核，简化计算——设在 F 作用下（l=0 时）
    的剪力仅由两条竖直焊缝承担（偏于安全），投影面积只计腹板段高度
    h-2t、每侧焊缝宽 k。
    k: 焊脚尺寸，mm；
    h: 工字钢高，mm；
    t: 工字钢腿平均厚度，mm。
    返回 A1，mm²。例7-1：2×8×(250−26)=3584 mm²。
    [核:p135]
    """
    _要求正数(k=k, h=h)
    if h - 2.0 * t <= 0:
        raise ValueError("h-2t 必须为正，收到 h=%r、t=%r" % (h, t))
    return 2.0 * k * (h - 2.0 * t)


def 焊缝投影惯性矩J(b, h, k):
    """
    例7-1 步骤(3)：焊缝投影面积对形心轴 x-x 的转动惯量（**非编号**）：
        J(x-x) ≈ 2[bh³-(b-k)(h-2k)³]/12

    适用条件：略去上、下腿两端很短的焊缝，把焊缝投影面积（图7-15c）简化
    成腰、腿厚度均为 8 mm 的两个工字形；k=8 mm<t=13 mm 时课本假设 k≈t，
    可近似取 A2 的 J 为工字钢横截面 J 的 2 倍（p.136 脚注）。
    b: 工字钢腿宽，mm；
    h: 工字钢高，mm；
    k: 焊脚尺寸，mm（b-k=108、h-2k=234）。
    返回 J，mm⁴。例7-1：71 451 061 mm⁴。
    [核:p136]
    """
    _要求正数(b=b, h=h, k=k)
    if b - k <= 0 or h - 2.0 * k <= 0:
        raise ValueError("b-k 与 h-2k 必须为正，收到 b=%r、h=%r、k=%r"
                         % (b, h, k))
    return 2.0 * (b * h ** 3 - (b - k) * (h - 2.0 * k) ** 3) / 12.0


def 焊缝抗弯截面模量(J, y):
    """
    例7-1 步骤(4)：角焊缝危险截面的抗弯截面模量（**非编号**）：
        W = 0.7J/y

    适用条件：在力矩 Fl 作用下，按 0.7J/y 作为焊缝截面的抗弯截面模量
    计算危险截面切应力；0.7 为角焊缝计算厚度与焊脚之比。
    J: 焊缝投影面积对 x-x 轴的转动惯量，mm⁴；
    y: 危险点至 x-x 轴的距离，mm（例7-1 取 112 mm）。
    返回 W，mm³。
    [核:p136]
    """
    _要求正数(J=J, y=y)
    return 0.7 * J / y


def 角焊缝计算切应力(F, A投影):
    """
    例7-1 步骤(2)：按投影面积计的危险截面切应力（**非编号**）：
        τ = F/(0.7A)

    适用条件：角焊缝按 0.7k 作为计算厚度、以连接面上的投影面积 A 折算；
    0.7 为角焊缝计算厚度与焊脚之比。
    F: 作用在该组焊缝上的力，N；
    A投影: 焊缝在连接面上的投影面积，mm²。
    返回 τ，MPa。
    [核:p135]
    """
    _要求正数(A投影=A投影)
    return F / (0.7 * A投影)


def 合成切应力(τ1, τ2):
    """
    例7-1 步骤(5)：两个相互垂直的切应力分量的合成（**非编号**）：
        τ = √(τ1²+τ2²)

    适用条件：剪力分量与弯矩分量在同一危险点上产生的切应力方向相互
    垂直，按平方和开方合成。
    τ1: 剪力分量切应力，MPa；
    τ2: 弯矩分量切应力，MPa。
    返回 τ，MPa。
    [核:p136]
    """
    return math.hypot(τ1, τ2)



def eq7_1(t, d, δ, σ许):
    """
    式(7-1) 单排搭接铆缝按被铆件拉伸强度条件的允许静载荷：
        F1 = (t-d)δ[σ]

    适用条件：单排搭接铆缝静强度分析（图7-6）；取图中宽度等于节距 t 的
    阴影部分计算；设边距 e 合乎规范要求（不出现图7-5b 板边剪坏）；静载荷；
    危险截面取被铆件因钉孔削弱的净截面 (t-d)δ。计算假定：一组铆钉受力
    均等、危险截面应力均匀分布、接合面无摩擦、铆缝不受弯矩。
    t: 节距（垂直于受载方向的铆钉间距），mm；
    d: 铆钉直径，mm；
    δ: 被铆件板厚，mm；
    σ许: 被铆件的许用拉应力 [σ]，MPa（一般强固铆缝按表7-1，见“查表7_1”）。
    返回 F1，N。F1、F2、F3 中的最小者即该段铆缝允许承受的静载荷 F。
    [核:p129]
    """
    _要求正数(t=t, d=d, δ=δ, σ许=σ许)
    if t - d <= 0:
        raise ValueError("式7-1 的净截面宽 (t-d) 必须为正，收到 t=%r、d=%r"
                         % (t, d))
    return (t - d) * δ * σ许


def eq7_2(d, δ, σbs许):
    """
    式(7-2) 单排搭接铆缝按被铆件孔壁挤压强度条件的允许压力：
        F2 = dδ[σbs]

    适用条件：单排搭接铆缝静强度分析（图7-6）；取宽度等于节距 t 的阴影
    部分计算；静载荷；挤压面积取 dδ。
    d: 铆钉直径，mm；
    δ: 被铆件板厚，mm；
    σbs许: 被铆件的许用挤压应力 [σbs]，MPa（表7-1）。
    返回 F2，N。与式(7-1)、(7-3) 联立取三者最小值作为铆缝承载能力。
    [核:p129]
    """
    _要求正数(d=d, δ=δ, σbs许=σbs许)
    return d * δ * σbs许


def eq7_3(d, τ许):
    """
    式(7-3) 单排搭接铆缝按铆钉剪切强度条件的允许横向载荷：
        F3 = πd²[τ]/4

    适用条件：单排搭接铆缝静强度分析（图7-6）；静载荷；单个剪切面
    （单剪）——式中只有一个 πd²/4 项，课本未写多剪面系数。
    d: 铆钉直径，mm；
    τ许: 铆钉的许用切应力 [τ]，MPa（表7-1）。
    返回 F3，N。
    [核:p129]
    """
    _要求正数(d=d, τ许=τ许)
    return math.pi * d * d * τ许 / 4.0


def eq7_4(t, d):
    """
    式(7-4) 铆缝的强度系数（以图7-6 单排搭接铆缝为例）：
        φ = (t-d)δ[σ] / (tδ[σ]) = (t-d)/t < 1

    适用条件：静载荷；被铆件遭到钉孔削弱后的强度与完整时的强度之比，
    约去 δ[σ] 后只由 t/d 决定。铆钉排数一定时 φ 由 t 与 d 的比值决定；
    排数增多时 t 可取大些、φ 可提高，但材料及工时增多、结构质量增大。
    t: 节距，mm；
    d: 铆钉直径，mm。
    返回 φ（无量纲，0<φ<1）。
    [核:p130]
    """
    _要求正数(t=t, d=d)
    if t - d <= 0:
        raise ValueError("式7-4 要求 t>d，收到 t=%r、d=%r" % (t, d))
    return (t - d) / t


def eq7_5(F, a, b, k, τ许):
    """
    式(7-5) 角钢与钢板焊接时两侧不对称侧面角焊缝所需的焊缝长度：
        l1 = F1/(0.7k[τ']) = F·a/(0.7k[τ'](a+b))
        l2 = F2/(0.7k[τ']) = F·b/(0.7k[τ'](a+b))

    适用条件：焊接结构中有角钢等构件（图7-12）；外力 F 的作用线通过角钢
    截面的形心 c，因 a≠b 两侧焊缝受力不等，设计成不对称侧面角焊缝；
    静载荷（[τ'] 用表7-3 静载荷许用应力）。受力分配 F=F1+F2、
    F1/F2=a/b，即 F1=Fa/(a+b)、F2=Fb/(a+b)；再由侧面角焊缝强度条件
    τ=F/(0.7kl)≤[τ'] 反解所需长度。
    F: 外载荷，N；a、b: 作用线在焊接平面上的投影线与两侧焊缝间的距离
    （a≠b），mm；k: 焊脚尺寸，mm；τ许: 焊缝许用切应力 [τ']，MPa（表7-3）。
    返回 (l1, l2)，单位 mm（与课本式(7-5) 两式一一对应；两侧分担
    F1/F2=a/b，长度 l1/l2 同此比例）。
    注：表7-3 表注——单边焊接的角钢，各许用应力降低 25%。
    [核:p133]
    """
    _要求正数(F=F, a=a, b=b, k=k, τ许=τ许)
    if a == b:
        raise ValueError("式7-5 用于 a≠b 的不对称侧面角焊缝，收到 a=b=%r"
                         % (a,))
    分母 = 0.7 * k * τ许 * (a + b)
    return F * a / 分母, F * b / 分母


def eq7_6(M, k, l, h):
    """
    式(7-6) 混合角焊缝受弯矩时危险截面上的切应力：
        τ = 6M / (0.7k[6l(h+k)+h²]) ≤ [τ']

    适用条件：混合角焊缝受弯矩（图7-11c）；按力矩独立作用原理计算，
    对称侧面角焊缝与正面角焊缝共同承载；静载荷。力矩平衡 M=M1+M2，
    其中对称侧面角焊缝 M1=0.7kl(h+k)τ，正面角焊缝 M2=Wτ、
    W=0.7kh²/6。设计时取 k=δ 即可由上式求所需焊缝长度 l。
    M: 作用在混合角焊缝上的弯矩，N·mm；
    k: 焊脚尺寸，mm；
    l: 侧面角焊缝的长度，mm；
    h: 图7-11c 中正面角焊缝的尺寸（焊缝高度），mm。
    返回 τ，MPa。其余常用焊缝的承载情况及强度条件式见表7-2。
    [核:p134]
    """
    _要求正数(M=M, k=k, l=l, h=h)
    分母 = 0.7 * k * (6.0 * l * (h + k) + h * h)
    if 分母 <= 0:
        raise ValueError("式7-6 分母必须为正，收到 %r" % (分母,))
    return 6.0 * M / 分母


def eq7_7(a, b, Fmin, Fmax):
    """
    式(7-7) 变载荷下焊缝及被焊件许用应力的降低系数：
        γ = 1/(a - b·Fmin/Fmax) ≤ 1

    适用条件：被焊件承受变载荷时，焊缝及被焊件的许用应力均应乘以 γ；
    a、b 按焊缝形式与材料（低碳钢/低碳合金钢）由表7-4 查取（见
    “查表7_4”）。
    a、b: 系数（无量纲，表7-4）；
    Fmin、Fmax: 按绝对值计算的最小及最大载荷，N；代入时必须带本身的正
        （拉力）、负（压力）号。
    返回 γ（无量纲）。按课本“当 γ 计算值大于 1 时应取为 1”的说明，
    本函数对结果做上限截断为 1（不另设下限）。
    [核:p134]
    """
    _要求正数(a=a, b=b)
    if Fmax == 0:
        raise ValueError("式7-7 的 Fmax 不能为 0")
    r = float(Fmin) / float(Fmax)
    分母 = a - b * r
    if 分母 <= 0:
        raise ValueError("式7-7 分母 a-b·Fmin/Fmax 必须为正，收到 %r"
                         % (分母,))
    return min(1.0, 1.0 / 分母)


def eq7_8(F, d, l, f):
    """
    式(7-8) 过盈连接传递轴向力时所需的最小径向压力：
        F_f = πdlpf ≥ F  →  p ≥ F/(πdlf)，p_min = F/(πdlf)

    适用条件：连接传递轴向力 F（图7-20），应保证不产生轴向滑动；
    全节共同前提：连接零件应力处于平面应力状态（σz=0）、应变在弹性范围、
    弹性模量为常量、连接部分为两个等长的厚壁圆筒、配合面压力均匀分布。
    F: 传递的轴向力，N；
    d: 配合的公称直径，mm；
    l: 配合长度，mm；
    f: 配合面间的摩擦因数（无量纲，表7-5）。
    返回 p_min，MPa。摩擦阻力 F_f=πdlpf 见“摩擦阻力Ff”。
    [核:p141]
    """
    _要求正数(d=d, l=l, f=f)
    return F / (math.pi * d * l * f)


def eq7_9(T, d, l, f):
    """
    式(7-9) 过盈连接传递转矩时所需的最小径向压力：
        M_f = πdlpf·(d/2) ≥ T  →  p ≥ 2T/(πd²lf)，p_min = 2T/(πd²lf)

    适用条件：连接传递转矩 T（图7-21），应保证不产生周向滑动；前提同
    式(7-8)（厚壁圆筒、弹性范围、压力均匀分布）。
    T: 连接传递的转矩，N·mm；
    d: 配合的公称直径，mm；
    l: 配合长度，mm；
    f: 配合面上的摩擦因数（无量纲，表7-5）。课本脚注：周向与轴向摩擦
       因数略有差异，现为简化取两者近似相等，均以 f 表示。
    返回 p_min，MPa。摩擦阻力矩 M_f=πdlpf·d/2 见“摩擦阻力矩Mf”。
    [核:p141]
    """
    _要求正数(T=T, d=d, l=l, f=f)
    return 2.0 * T / (math.pi * d * d * l * f)


def eq7_10(F, T, d, l, f):
    """
    式(7-10) 过盈连接同时承受轴向力 F 与转矩 T 时所需的最小径向压力：
        p_min = √(F²+(2T/d)²) / (πdlf)

    适用条件：连接同时承受轴向力与转矩的联合作用；把轴向力与圆周摩擦力
    （等效为 2T/d）按矢量合成，再除以摩擦面积与摩擦因数 πdlf。
    F: 传递的轴向力，N；
    T: 传递的转矩，N·mm；
    d: 配合的公称直径，mm；
    l: 配合长度，mm；
    f: 配合面间的摩擦因数（无量纲，表7-5）。
    返回 p_min，MPa。T=0 时退化为式(7-8)，F=0 时退化为式(7-9)。
    [核:p141]
    """
    _要求正数(d=d, l=l, f=f)
    if F < 0 or T < 0:
        raise ValueError("式7-10 的 F、T 取载荷大小，须非负；收到 F=%r、"
                         "T=%r" % (F, T))
    return math.hypot(F, 2.0 * T / d) / (math.pi * d * l * f)


# ------------------------------------------------ 非编号：摩擦阻力/力矩
def 摩擦阻力Ff(p, d, l, f):
    """
    式(7-8) 的摩擦阻力式（**式7-8 的同一公式的左半式**）：
        F_f = πdlpf

    适用条件：同式(7-8)（过盈连接传递轴向力、厚壁圆筒前提）；不发生轴向
    滑动的条件是 F_f ≥ F。
    p: 配合面间的径向压力，MPa；
    d: 配合的公称直径，mm；
    l: 配合长度，mm；
    f: 配合面间的摩擦因数（无量纲）。
    返回 F_f，N。
    [核:p141]
    """
    _要求正数(d=d, l=l, f=f)
    return math.pi * d * l * p * f


def 摩擦阻力矩Mf(p, d, l, f):
    """
    式(7-9) 的摩擦阻力矩式（**式7-9 的同一公式的左半式**）：
        M_f = πdlpf·(d/2)

    适用条件：同式(7-9)（过盈连接传递转矩、厚壁圆筒前提）；不发生周向
    滑动的条件是 M_f ≥ T。
    p: 配合面间的径向压力，MPa；
    d: 配合的公称直径，mm；
    l: 配合长度，mm；
    f: 配合面间的摩擦因数（无量纲）。
    返回 M_f，N·mm。
    [核:p141]
    """
    _要求正数(d=d, l=l, f=f)
    return math.pi * d * l * p * f * d / 2.0


# ------------------------------------------------ 式7-11 的刚性系数
def C1_刚性系数(d, d1, μ1):
    """
    式(7-11) 符号说明中的被包容件刚性系数（**式7-11 的符号式**）：
        C1 = (d²+d1²)/(d²-d1²) - μ1

    适用条件：厚壁圆筒过盈连接（图7-20/7-21 前提）；被包容件内径 d1，
    当 d1=0（实心轴）时 C1=1-μ1。
    d: 配合的公称直径，mm；
    d1: 被包容件的内径，mm；
    μ1: 被包容件材料的泊松比（钢 0.3，铸铁 0.25）。
    返回 C1（无量纲）。d≤d1 时抛 ValueError。
    此式含 E、μ、直径比中的 μ 与直径比两项；E 在式(7-11) 的 C/E 中引入。
    [核:p142]
    """
    _要求正数(d=d, μ1=μ1)
    if d1 < 0:
        raise ValueError("d1 不能为负，收到 %r" % (d1,))
    if d * d - d1 * d1 <= 0:
        raise ValueError("式7-11 要求 d>d1，收到 d=%r、d1=%r" % (d, d1))
    return (d * d + d1 * d1) / (d * d - d1 * d1) - μ1


def C2_刚性系数(d2, d, μ2):
    """
    式(7-11) 符号说明中的包容件刚性系数（**式7-11 的符号式**）：
        C2 = (d2²+d²)/(d2²-d²) + μ2

    适用条件：厚壁圆筒过盈连接；包容件外径 d2。
    d2: 包容件的外径，mm；
    d: 配合的公称直径，mm；
    μ2: 包容件材料的泊松比（钢 0.3，铸铁 0.25）。
    返回 C2（无量纲）。d2≤d 时抛 ValueError。
    [核:p142]
    """
    _要求正数(d2=d2, d=d)
    if μ2 < 0:
        raise ValueError("μ2 不能为负，收到 %r" % (μ2,))
    if d2 * d2 - d * d <= 0:
        raise ValueError("式7-11 要求 d2>d，收到 d2=%r、d=%r" % (d2, d))
    return (d2 * d2 + d * d) / (d2 * d2 - d * d) + μ2


def eq7_11(p, d, C1, E1, C2, E2):
    """
    式(7-11) 过盈连接的过盈量（p 为 p_min 时即最小过盈量）：
        Δ = p·d·(C1/E1 + C2/E2)×10³
        Δ_min = p_min·d·(C1/E1 + C2/E2)×10³

    适用条件：根据材料力学厚壁圆筒计算理论，在径向压力 p 时的过盈量；
    Δ_min 由式(7-8)~(7-10) 求得 p_min 后代入。课本同段指出：传递载荷一定
    时配合长度 l 越短所需 p_min 越大、所需过盈量随之增大，故 l 不宜过短，
    一般推荐 l≈0.9d；当 l>0.8d 时应考虑两端应力集中影响。
    p: 配合面间的径向压力（求最小过盈量时传 p_min），MPa；
    d: 配合的公称直径，mm；
    C1: 被包容件的刚性系数（见“C1_刚性系数”），无量纲；
    E1: 被包容件材料的弹性模量，MPa；
    C2: 包容件的刚性系数（见“C2_刚性系数”），无量纲；
    E2: 包容件材料的弹性模量，MPa。
    返回 Δ（或 Δ_min），**μm**；式中的 ×10³ 是把 mm 换算成 μm。
    注：课本小标题写“最小有效过盈量 δ_min”，而公式与符号说明一律用 Δ、
    Δ_min；胀缩法装配时 δ_min=Δ_min（式7-12）。
    [核:p142]
    """
    _要求正数(d=d, E1=E1, E2=E2)
    if p < 0:
        raise ValueError("p 不能为负，收到 %r" % (p,))
    return p * d * (C1 / E1 + C2 / E2) * 1.0e3


def 压平深度S(Ra):
    """
    式(7-12) 的子式 S_i = 1.6Ra_i（**式7-12 的同一公式的子式**）：

    适用条件：压入法装配时，配合表面微观峰尖被擦去部分的高度或压平深度
    （图7-25），按经验式 S_i=1.6Ra_i 取；胀缩法装配时峰尖被擦去或压平得
    很少，可忽略不计。
    Ra: 配合表面评定轮廓的算术平均偏差，μm（表7-6）。
    返回 S，μm。
    [核:p143]
    """
    if Ra < 0:
        raise ValueError("Ra 不能为负，收到 %r" % (Ra,))
    return 1.6 * Ra


def eq7_12(Δmin, Ra1, Ra2, 装配="压入法"):
    """
    式(7-12) 过盈连接的最小有效过盈量（含表面微观峰尖修正）：
        δ_min = Δ_min + 2(S1+S2)，S_i = 1.6Ra_i  (i=1,2)

    适用条件：压入法装配时（配合表面微观峰尖将被擦去或压平一部分，
    图7-25），式(7-11) 求出的 Δ_min 只是理论值，应再增加被擦去部分
    2(S1+S2)；胀缩法装配时峰尖被擦去或压平得很少、可忽略，δ_min=Δ_min，
    不必加此项。
    Δmin: 按式(7-11) 求出的理论最小过盈量，μm；
    Ra1: 被包容件（轴）配合表面的 Ra，μm（表7-6）；
    Ra2: 包容件（孔）配合表面的 Ra，μm（表7-6）；
    装配: "压入法"（默认，加 2(S1+S2)）/ "胀缩法"（不加）。
    返回 δ_min，μm。选标准过盈配合时其最小过盈量应略大于或等于 δ_min
    （压入法），或按 Δ_min=δ_min 选（胀缩法）。
    [核:p143]
    """
    if Δmin < 0:
        raise ValueError("Δmin 不能为负，收到 %r" % (Δmin,))
    修正 = 2.0 * (压平深度S(Ra1) + 压平深度S(Ra2))
    if 装配 == "压入法":
        return Δmin + 修正
    if 装配 == "胀缩法":
        return float(Δmin)
    raise ValueError("装配方式只有“压入法”“胀缩法”，收到 %r" % (装配,))


def eq7_13(δmax, d, C1, E1, C2, E2, 擦去量=0.0):
    """
    式(7-13) 由最大过盈量求最大径向压力：
        p_max = δ_max / [d(C1/E1 + C2/E2)×10³]

    适用条件：先按所选标准过盈配合算出最大过盈量 δ_max，再由该式求
    p_max，然后据 p_max 校核连接零件本身强度（式7-14~7-17）。采用压入法
    装配时 δ_max 应减掉被擦去部分 2(S1+S2)（例7-2 即如此，用“擦去量”）。
    δmax: 最大过盈量，μm；
    d: 配合的公称直径，mm；
    C1、C2: 被包容件、包容件的刚性系数（同式7-11），无量纲；
    E1、E2: 被包容件、包容件材料的弹性模量，MPa；
    擦去量: 压入法装配时被擦去的 2(S1+S2)，μm（默认 0，即不扣减）。
    返回 p_max，MPa；分母的 ×10³ 是 μm→mm 的换算（与式7-11 的 mm→μm
    互逆）。
    [核:p144]
    """
    _要求正数(d=d, E1=E1, E2=E2)
    if δmax < 0:
        raise ValueError("δmax 不能为负，收到 %r" % (δmax,))
    有效 = δmax - 擦去量
    if 有效 < 0:
        raise ValueError("δmax 减去擦去量后为负（%r），检查输入"
                         % (有效,))
    return 有效 / (d * (C1 / E1 + C2 / E2) * 1.0e3)


def eq7_14(d, d1, σB1, n=2.0):
    """
    式(7-14) 脆性材料被包容件的 p_max 上限（第一强度理论）：
        p_max ≤ (d²-d1²)/(2d²) · σB1/(2~3)

    适用条件：零件材料为脆性材料时，按图7-26 的最大周向应力（拉或压）
    用第一强度理论校核；主要破坏形式是包容件内表层断裂，本式对应被包容件
    的压缩强度极限。
    d: 配合的公称直径，mm；
    d1: 被包容件的内径，mm；
    σB1: 被包容件材料的压缩强度极限，MPa；
    n: 安全系数，课本取 2~3（默认 2.0，即下限；n 越大上限越低）。
    返回 p_max 的许用上限，MPa。使用时须满足 实际 p_max ≤ 返回值。
    [核:p144]
    """
    _要求正数(d=d, σB1=σB1, n=n)
    if d * d - d1 * d1 <= 0:
        raise ValueError("式7-14 要求 d>d1，收到 d=%r、d1=%r" % (d, d1))
    return (d * d - d1 * d1) / (2.0 * d * d) * σB1 / n


def eq7_15(d2, d, σB2, n=2.0):
    """
    式(7-15) 脆性材料包容件的 p_max 上限（第一强度理论）：
        p_max ≤ (d2²-d²)/(d2²+d²) · σB2/(2~3)

    适用条件：零件材料为脆性材料时按第一强度理论校核；本式对应包容件
    （内表层周向拉应力为危险应力）。
    d2: 包容件的外径，mm；
    d: 配合的公称直径，mm；
    σB2: 包容件材料的拉伸强度极限，MPa；
    n: 安全系数，课本取 2~3（默认 2.0）。
    返回 p_max 的许用上限，MPa。
    [核:p144]
    """
    _要求正数(d2=d2, d=d, σB2=σB2, n=n)
    if d2 * d2 - d * d <= 0:
        raise ValueError("式7-15 要求 d2>d，收到 d2=%r、d=%r" % (d2, d))
    return (d2 * d2 - d * d) / (d2 * d2 + d * d) * σB2 / n


def eq7_16(d, d1, σS1):
    """
    式(7-16) 塑性材料被包容件的 p_max 上限（第四强度理论）：
        p_max ≤ (d²-d1²)/(2d²) · σS1

    适用条件：零件材料为塑性材料时，按第四强度理论检验承受最大应力的
    表层是否处于弹性变形范围内；本式对应被包容件内表层（不出现塑性变形
    的检验公式）。
    d: 配合的公称直径，mm；
    d1: 被包容件的内径，mm；
    σS1: 被包容件材料的屈服极限，MPa。
    返回 p_max 的许用上限，MPa。
    [核:p144]
    """
    _要求正数(d=d, σS1=σS1)
    if d * d - d1 * d1 <= 0:
        raise ValueError("式7-16 要求 d>d1，收到 d=%r、d1=%r" % (d, d1))
    return (d * d - d1 * d1) / (2.0 * d * d) * σS1


def eq7_17(d2, d, σS2):
    """
    式(7-17) 塑性材料包容件的 p_max 上限（第四强度理论）：
        p_max ≤ (d2²-d²)/√(3d2⁴+d⁴) · σS2

    适用条件：零件材料为塑性材料时，按第四强度理论检验包容件内表层是否
    处于弹性变形范围；本式对应包容件内表层（σ1 周向拉应力与 σ3 径向压
    应力叠加）。例7-2 用本式校核 45 钢齿圈，得许用 p_max=21.46 MPa。
    d2: 包容件的外径，mm；
    d: 配合的公称直径，mm；
    σS2: 包容件材料的屈服极限，MPa。
    返回 p_max 的许用上限，MPa。分母的根号覆盖 3d2⁴+d⁴（已放大核对）。
    [核:p144]
    """
    _要求正数(d2=d2, d=d, σS2=σS2)
    if d2 * d2 - d * d <= 0:
        raise ValueError("式7-17 要求 d2>d，收到 d2=%r、d=%r" % (d2, d))
    return ((d2 * d2 - d * d) / math.sqrt(3.0 * d2 ** 4 + d ** 4)
            * σS2)


def eq7_18(f, d, l, pmax):
    """
    式(7-18) 采用压入法装配时的最大压入力：
        F_i = f·π·d·l·p_max

    适用条件：采用压入法装配、准备拆开时，为选择所需压力机容量而计算
    最大压入力；把式(7-8) 中的 F 换成压入时的摩擦阻力，并以 p_max 取代 p。
    f: 配合面间的摩擦因数（表7-5；例7-2 此处取 0.10，与计算 p_min 用的
       0.08 不同）；
    d: 配合的公称直径，mm；
    l: 配合长度，mm；
    pmax: 最大径向压力，MPa。
    返回 F_i，N。配套见式(7-19)。
    [核:p144]
    """
    _要求正数(d=d, l=l, f=f)
    if pmax < 0:
        raise ValueError("p_max 不能为负，收到 %r" % (pmax,))
    return f * math.pi * d * l * pmax


def eq7_19(Fi, 系数=1.5):
    """
    式(7-19) 采用压入法装配后的最大压出力：
        F_o = (1.3~1.5)F_i = (1.3~1.5)f·π·d·l·p_max

    适用条件：采用压入法装配后准备拆开时，为选择压力机容量计算最大压
    出力；在最大压入力基础上乘经验系数 1.3~1.5（长期存放后拆开阻力增大）。
    Fi: 最大压入力 F_i，N（式7-18）；
    系数: 经验放大系数，课本取 1.3~1.5（默认 1.5，即按最不利的拆开阻力）。
    返回 F_o，N。
    [核:p144]
    """
    _要求正数(Fi=Fi)
    if not (1.3 - 1e-12 <= 系数 <= 1.5 + 1e-12):
        raise ValueError("式7-19 的经验系数取 1.3~1.5，收到 %r" % (系数,))
    return 系数 * Fi


def eq7_20(t0, δmax, Δ0, α1, d):
    """
    式(7-20) 胀缩法装配时被包容件（冷缩）的冷却温度：
        t1 = t0 - (δmax+Δ0)/(α1·d×10³)

    适用条件：采用胀缩法装配时，计算被包容件的冷却温度；δmax、Δ0 按 μm
    代入，分母 ×10³ 把 μm 换算为 mm，故 α1·d×10³ 的单位为 mm/℃。
    t0: 装配环境的温度，℃；
    δmax: 所选标准配合在装配前的最大过盈量，μm；
    Δ0: 装配时为避免配合面互相擦伤所需的最小间隙，μm（通常取同公称直径
        的间隙配合 H7/g6 的最小间隙，或从手册查取）；
    α1: 被包容件材料的线膨胀系数，**1/℃**（查有关手册）；
    d: 配合的公称直径，mm。
    返回 t1（低于环境温度），℃。×10³ 的来源：α1[1/℃]·d[mm] 得 mm/℃，
    而 (δmax+Δ0) 以 μm 计，须除以 10³ 化为 mm。
    [核:p145]
    """
    _要求正数(α1=α1, d=d)
    if δmax < 0 or Δ0 < 0:
        raise ValueError("δmax、Δ0 不能为负，收到 %r、%r" % (δmax, Δ0))
    return t0 - (δmax + Δ0) / (α1 * d * 1.0e3)


def eq7_21(t0, δmax, Δ0, α2, d):
    """
    式(7-21) 胀缩法装配时包容件（加热）的加热温度：
        t2 = t0 + (δmax+Δ0)/(α2·d×10³)

    适用条件：采用胀缩法（加热包容件）装配时；δmax、Δ0 按 μm 代入，
    ×10³ 换算为 mm。
    t0: 装配环境的温度，℃；
    δmax: 所选标准配合在装配前的最大过盈量，μm；
    Δ0: 装配时所需的最小间隙，μm（同上，通常取 H7/g6 的最小间隙）；
    α2: 包容件材料的线膨胀系数，**1/℃**（查有关手册）；
    d: 配合的公称直径，mm。
    返回 t2（高于环境温度），℃。×10³ 的来源同式(7-20)。
    [核:p145]
    """
    _要求正数(α2=α2, d=d)
    if δmax < 0 or Δ0 < 0:
        raise ValueError("δmax、Δ0 不能为负，收到 %r、%r" % (δmax, Δ0))
    return t0 + (δmax + Δ0) / (α2 * d * 1.0e3)


def eq7_22(pmax, d, d1, E1):
    """
    式(7-22) 过盈连接装配后被包容件内径的最大缩小量：
        Δd1max = 2·p_max·d1·d² / [E1(d²-d1²)]

    适用条件：当有必要计算过盈连接装配后变形量时使用，一般只需计算其
    最大绝对值（按厚壁圆筒在 p_max 作用下的径向位移，取 d1 处内表面）。
    pmax: 装配后可能产生的最大径向压力，MPa；
    d: 配合的公称直径，mm；
    d1: 被包容件的内径，mm；
    E1: 被包容件材料的弹性模量，MPa。
    返回 Δd1max，**mm**（本式不含 ×10³，结果即 mm）。
    [核:p145]
    """
    _要求正数(d=d, E1=E1)
    if pmax < 0:
        raise ValueError("p_max 不能为负，收到 %r" % (pmax,))
    if d1 < 0:
        raise ValueError("d1 不能为负，收到 %r" % (d1,))
    if d * d - d1 * d1 <= 0:
        raise ValueError("式7-22 要求 d>d1，收到 d=%r、d1=%r" % (d, d1))
    return 2.0 * pmax * d1 * d * d / (E1 * (d * d - d1 * d1))


def eq7_23(pmax, d, d2, E2):
    """
    式(7-23) 过盈连接装配后包容件外径的最大胀大量：
        Δd2max = 2·p_max·d2·d² / [E2(d2²-d²)]

    适用条件：计算过盈连接装配后包容件外径胀大量，一般只需计算其最大
    绝对值（按厚壁圆筒在 p_max 作用下的径向位移，取 d2 处外表面）。
    pmax: 装配后可能产生的最大径向压力，MPa；
    d: 配合的公称直径，mm；
    d2: 包容件的外径，mm；
    E2: 包容件材料的弹性模量，MPa。
    返回 Δd2max，**mm**。分母 E2(d2²-d²) 与式(7-22) 的符号相反，已放大
    核对。
    [核:p145]
    """
    _要求正数(d=d, E2=E2)
    if pmax < 0:
        raise ValueError("p_max 不能为负，收到 %r" % (pmax,))
    if d2 * d2 - d * d <= 0:
        raise ValueError("式7-23 要求 d2>d，收到 d2=%r、d=%r" % (d2, d))
    return 2.0 * pmax * d2 * d * d / (E2 * (d2 * d2 - d * d))



失败 = []
通过 = 0


def 校验(名称: str, 计算值: float, 书上值: float, 容差: float = 0.005, 单位: str = ""):
    """容差为相对误差；书上值可能只保留 3~4 位有效数字。"""
    global 通过
    if 书上值 == 0:
        ok = abs(计算值) < 1e-9
        rel = 0.0
    else:
        rel = abs(计算值 - 书上值) / abs(书上值)
        ok = rel <= 容差
    if ok:
        通过 += 1
    else:
        失败.append((名称, 计算值, 书上值, rel))
    print("%s %-46s 计算=%12.5f  书上=%12.5f  Δ=%6.3f%% %s"
          % ("✓" if ok else "✗", 名称, 计算值, 书上值, rel * 100, 单位))


def 校验异常(名称: str, 函数, 异常类=ValueError):
    """确认在"原表空白/表外"输入下按约定抛异常（不猜值）。"""
    global 通过
    try:
        函数()
    except 异常类:
        通过 += 1
        print("✓ %-46s 按预期抛出 %s" % (名称, 异常类.__name__))
    else:
        失败.append((名称, float("nan"), 0.0, 1.0))
        print("✗ %-46s 未抛出 %s" % (名称, 异常类.__name__))



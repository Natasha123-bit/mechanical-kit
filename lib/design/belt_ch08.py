def _线性插值(点, x: float, 表名: str) -> float:
    """在 [(x_i, y_i)] 上做线性内插，供表8-4/8-5/8-6 使用。

    点: 由 (横坐标, 纵坐标) 组成的序列；y_i 可为 None（原表“—”）。
    x : 待查横坐标。
    规则：x 精确命中表列值时直接返回（该格为 None 则抛 ValueError）；
    x 落在两表列之间时线性内插（任一端为 None 则抛 ValueError，不外推）；
    x 超出表列范围抛 ValueError。**不做任何纵向/区间外插值。**
    [核:p163-p166]
    """
    序列 = sorted([(float(a), b) for a, b in 点], key=lambda p: p[0])
    if not 序列:
        raise ValueError("%s 无可用数据" % (表名,))
    最小, 最大 = 序列[0][0], 序列[-1][0]
    if x < 最小 - 1e-9 or x > 最大 + 1e-9:
        raise ValueError("%s 表外输入：%s 不在 %s~%s 内，不插值"
                         % (表名, x, 最小, 最大))
    for 横, 纵 in 序列:
        if abs(横 - x) < 1e-9:
            if 纵 is None:
                raise ValueError("%s 中 %s 对应格为原表“—”，不猜值" % (表名, x))
            return float(纵)
    for (x0, y0), (x1, y1) in zip(序列, 序列[1:]):
        if x0 < x < x1:
            if y0 is None or y1 is None:
                raise ValueError("%s 中 %s~%s 区间含原表“—”，不插值" % (表名, x0, x1))
            return float(y0) + (x - x0) / (x1 - x0) * (float(y1) - float(y0))
    raise ValueError("%s 无法定位 %s" % (表名, x))



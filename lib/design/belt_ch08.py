def eq8_7(F_0: float, f: float, α: float) -> 式8_7结果:
    """式(8-7) 临界状态三式：
    F_1c = F_ec e^{fα}/(e^{fα}−1)，F_2c = F_ec/(e^{fα}−1)，
    F_ec = 2F_0 (e^{fα}−1)/(e^{fα}+1) = 2F_0 (1−1/e^{fα})/(1+1/e^{fα})。

    适用条件：由式(8-5)、(8-2)、(8-3)导出，处于最大（临界）有效拉力状态；
    α 取 α_1、α_2 中的较小者；V 带用 f_v 代替 f。
    F_0: 初拉力 N；f: 摩擦因数（V 带为 f_v）；α: 包角 **弧度**。
    返回 NamedTuple(F_1c, F_2c, F_ec)，单位 N。
    [核:p160]
    """
    e = math.exp(f * α)
    F_ec = 2.0 * F_0 * (e - 1.0) / (e + 1.0)
    return 式8_7结果(F_ec * e / (e - 1.0), F_ec / (e - 1.0), F_ec)


def eq8_8(F_1: float, F_2: float, A: float) -> 式8_8结果:
    """式(8-8) 拉应力：σ_1 = F_1/A，σ_2 = F_2/A，MPa。

    适用条件：带传动工作时紧边、松边的拉应力；A 见表8-1。
    F_1: 紧边拉力 N；F_2: 松边拉力 N；A: 带的横截面积 mm²。
    返回 NamedTuple(σ_1, σ_2)，单位 MPa。
    [核:p160]
    """
    return 式8_8结果(F_1 / A, F_2 / A)


def eq8_9(E: float, h: float, d_d1: float, d_d2: float) -> 式8_9结果:
    """式(8-9) 弯曲应力：σ_b1 ≈ E h/d_d1，σ_b2 ≈ E h/d_d2，MPa。

    适用条件：带绕上带轮时产生弯曲应力，与带轮基准直径成反比，故 σ_b1>σ_b2。
    E: 带的弹性模量 MPa；h: 带的高度 mm（表8-1）；
    d_d1/d_d2: 小/大带轮基准直径 mm。
    返回 NamedTuple(σ_b1, σ_b2)，单位 MPa。
    [核:p160]
    """
    return 式8_9结果(E * h / d_d1, E * h / d_d2)


def eq8_10(q: float, v: float, A: float) -> float:
    """式(8-10) 离心拉应力：σ_c = q v²/A，MPa。

    适用条件：带随带轮作圆周运动，自身质量引起离心力，离心拉力存在于全长。
    q: 带单位长度质量 kg/m（表8-3）；v: 带速 m/s；A: 横截面积 mm²。
    返回 σ_c，MPa（按课本单位制代入即得 MPa）。
    [核:p161]
    """
    return q * v ** 2 / A


def eq8_11(σ_1: float = None, σ_b1: float = None, σ_c: float = None,
           σ_max: float = None, 解: str = "σ_max") -> float:
    """式(8-11) 带中最大应力（近似）：σ_max ≈ σ_1 + σ_b1 + σ_c，MPa。

    适用条件：最大应力发生在紧边开始绕上小带轮处；等式型，默认解 σ_max。
    σ_1: 紧边拉应力 MPa；σ_b1: 小带轮上弯曲应力 MPa；σ_c: 离心拉应力 MPa；
    σ_max: 最大应力 MPa。
    解: "σ_max" → 三者之和；"σ_1"/"σ_b1"/"σ_c" → 由 σ_max 减去另两项。
    返回所求解，MPa。
    [核:p161]
    """
    if 解 == "σ_max":
        return σ_1 + σ_b1 + σ_c
    if 解 == "σ_1":
        return σ_max - σ_b1 - σ_c
    if 解 == "σ_b1":
        return σ_max - σ_1 - σ_c
    if 解 == "σ_c":
        return σ_max - σ_1 - σ_b1
    raise ValueError("式8-11 只能解 σ_max/σ_1/σ_b1/σ_c，收到 %s" % (解,))


def eq8_12(v_1: float, v_2: float) -> float:
    """式(8-12) 滑动率：ε = (v_1−v_2)/v_1 × 100%。

    适用条件：带传动弹性滑动时，主动轮线速度 v_1 与从动轮线速度 v_2 的相对变化。
    v_1: 主动带轮线速度 m/s；v_2: 从动带轮线速度 m/s。
    返回 ε 的**百分数**（如 1.5 表示 1.5%）；若要用式8-12a/8-14/8-15 的 (1−ε)，
    请先经 ``滑动率小数()`` 换成小数。v_1 不能为 0。
    [核:p162]
    """
    return (v_1 - v_2) / v_1 * 100.0


def eq8_12a(v_1: float, ε: float = 0.0) -> float:
    """式(8-12a) 由式(8-12)改写：v_2 = (1−ε) v_1。

    适用条件：带传动正常工作时弹性滑动总是存在。等式型，默认解 v_2。
    v_1: 主动带轮线速度 m/s；ε: 滑动率，**小数**（0.015 表示 1.5%，不是 1.5）。
    返回 v_2，m/s。
    [核:p162]
    """
    return (1.0 - ε) * v_1


def eq8_13(d_d1: float, d_d2: float, n_1: float, n_2: float) -> 式8_13结果:
    """式(8-13) 带轮线速度：v_1 = π d_d1 n_1/(60×1000)，
    v_2 = π d_d2 n_2/(60×1000)。

    适用条件：由转速换算线速度（分母 60×1000 使 mm、r/min 得 m/s）。
    d_d1/d_d2: 小/大带轮基准直径 mm；n_1/n_2: 小/大带轮转速 r/min。
    返回 NamedTuple(v_1, v_2)，单位 m/s。
    [核:p162]
    """
    return 式8_13结果(math.pi * d_d1 * n_1 / (60.0 * 1000.0),
                      math.pi * d_d2 * n_2 / (60.0 * 1000.0))


def eq8_14(d_d1: float = None, d_d2: float = None, n_1: float = None,
           n_2: float = None, ε: float = 0.0, 解: str = "d_d2") -> float:
    """式(8-14) 将式8-13代入式8-12a：d_d2 n_2 = (1−ε) d_d1 n_1。

    适用条件：弹性滑动存在时两带轮基准直径与转速的关系；等式型，默认解 d_d2。
    d_d1/d_d2: 小/大带轮基准直径 mm；n_1/n_2: 小/大带轮转速 r/min；
    ε: 滑动率 **小数**（0.015 表示 1.5%）。
    解: "d_d2"、"d_d1"、"n_1"、"n_2" 之一。
    返回所求解（mm 或 r/min）。
    [核:p162]
    """
    if 解 == "d_d2":
        return (1.0 - ε) * d_d1 * n_1 / n_2
    if 解 == "d_d1":
        return d_d2 * n_2 / ((1.0 - ε) * n_1)
    if 解 == "n_1":
        return d_d2 * n_2 / ((1.0 - ε) * d_d1)
    if 解 == "n_2":
        return (1.0 - ε) * d_d1 * n_1 / d_d2
    raise ValueError("式8-14 只能解 d_d2/d_d1/n_1/n_2，收到 %s" % (解,))


def eq8_15(d_d1: float, d_d2: float, ε: float = 0.0) -> float:
    """式(8-15) 平均传动比：i = n_1/n_2 = d_d2/[(1−ε) d_d1]。

    适用条件：带传动平均传动比（考虑弹性滑动）。
    d_d1/d_d2: 小/大带轮基准直径 mm；ε: 滑动率 **小数**。
    返回 i（无量纲）。
    [核:p162]
    """
    return d_d2 / ((1.0 - ε) * d_d1)


def eq8_15a(i: float = None, n_1: float = None, n_2: float = None,
            d_d1: float = None, d_d2: float = None,
            解: str = "i") -> float:
    """式(8-15a) 忽略滑动率：i = n_1/n_2 ≈ d_d2/d_d1。

    适用条件：一般带传动 ε≈1%~2%，可不予考虑。等式型，默认解 i。
    i: 传动比；n_1/n_2: 小/大带轮转速 r/min；d_d1/d_d2: 基准直径 mm。
    解: "i"（优先用 d_d2/d_d1，缺直径时用 n_1/n_2）、"d_d2"、"d_d1"、
        "n_1"、"n_2"。
    返回所求解（无量纲、mm 或 r/min）。
    [核:p162]
    """
    if 解 == "i":
        if d_d1 is not None and d_d2 is not None:
            return d_d2 / d_d1
        if n_1 is not None and n_2 is not None:
            return n_1 / n_2
        raise ValueError("式8-15a 解 i 需要 d_d1、d_d2 或 n_1、n_2")
    if 解 == "d_d2":
        比值 = i if i is not None else n_1 / n_2
        return 比值 * d_d1
    if 解 == "d_d1":
        比值 = i if i is not None else n_1 / n_2
        return d_d2 / 比值
    if 解 == "n_1":
        比值 = i if i is not None else d_d2 / d_d1
        return 比值 * n_2
    if 解 == "n_2":
        比值 = i if i is not None else d_d2 / d_d1
        return n_1 / 比值
    raise ValueError("式8-15a 只能解 i/d_d2/d_d1/n_1/n_2，收到 %s" % (解,))


def eq8_16(σ_1: float, σ_b1: float, σ_c: float,
           σ_allow: float = None) -> float:
    """式(8-16) V 带疲劳强度条件：σ_max ≈ σ_1 + σ_b1 + σ_c ≤ [σ]。

    适用条件：带传动在保证不打滑的同时，应使带具有所需疲劳强度与寿命；
    即 8-3 节的设计准则之一。本函数返回 σ_max（MPa），是否满足需与 [σ] 比较
    （传 σ_allow 时仅用于 docstring 说明，不抛异常）。
    σ_1: 紧边拉应力 MPa；σ_b1: 小带轮弯曲应力 MPa；σ_c: 离心拉应力 MPa；
    σ_allow: 许用应力 [σ] MPa，可省略。
    返回 σ_max，MPa。
    [核:p163]
    """
    return σ_1 + σ_b1 + σ_c


def eq8_16a(σ_allow: float, σ_b1: float, σ_c: float) -> float:
    """式(8-16a) 由式(8-16)改写：σ_1 ≤ [σ] − σ_b1 − σ_c。

    适用条件：V 带疲劳强度条件；本函数返回右边上限值，
    实际 σ_1 应不超过该值。
    σ_allow: 许用应力 [σ] MPa；σ_b1: 小带轮弯曲应力 MPa；σ_c: 离心拉应力 MPa。
    返回 σ_1 的上限，MPa。
    [核:p163]
    """
    return σ_allow - σ_b1 - σ_c


def eq8_17(F_1c: float = None, σ_1max: float = None, A: float = None,
           *, f_v: float, α: float) -> float:
    """式(8-17) 满足疲劳强度时允许的最大有效拉力：
    F_ec = F_1c (1 − 1/e^{f_v α}) = σ_1max A (1 − 1/e^{f_v α})。

    适用条件：由式(8-7)、(8-8)导出；满足带传动具有一定疲劳强度和寿命；V 带用
    当量摩擦因数 f_v。
    F_1c: 紧边拉力临界值 N（给了就优先用）；σ_1max: 紧边拉应力最大值 MPa
    （= [σ]−σ_b1−σ_c），与 A 同用时替代 F_1c；A: 横截面积 mm²；
    f_v: 当量摩擦因数；α: 包角 **弧度**（取 α_1、α_2 较小者）。
    返回 F_ec，N。
    [核:p163]
    """
    强度项 = 1.0 - 1.0 / math.exp(f_v * α)
    if F_1c is not None:
        return F_1c * 强度项
    if σ_1max is not None and A is not None:
        return σ_1max * A * 强度项
    raise ValueError("式8-17 需要 F_1c，或 σ_1max 与 A 同时给出")


def eq8_18(σ_allow: float, σ_b1: float, σ_c: float, f_v: float,
           α: float, A: float, v: float) -> float:
    """式(8-18) 单根 V 带基本额定功率：
    P_0 = ([σ]−σ_b1−σ_c)(1−1/e^{f_v α}) A v / 1000，kW。

    适用条件：由式(8-4)、(8-16)、(8-17)得到；试验条件为 α_1=α_2=180°（i=1）、
    特定带长、平稳工作（P_0 见表8-4）。
    σ_allow: 许用应力 [σ] MPa；σ_b1: 小带轮弯曲应力 MPa；σ_c: 离心拉应力 MPa；
    f_v: 当量摩擦因数；α: 包角 **弧度**；A: 横截面积 mm²；v: 带速 m/s。
    返回 P_0，kW。
    [核:p163]
    """
    强度项 = 1.0 - 1.0 / math.exp(f_v * α)
    return (σ_allow - σ_b1 - σ_c) * 强度项 * A * v / 1000.0


def eq8_19(P_0: float, ΔP_0: float, K_α: float, K_L: float) -> float:
    """式(8-19) 单根 V 带的额定功率：P_r = (P_0 + ΔP_0) K_α K_L，kW。

    适用条件：实际传动比、带长、包角与试验条件不同，对基本额定功率 P_0 修正。
    P_0: 单根 V 带基本额定功率 kW（表8-4）；
    ΔP_0: i≠1 时的功率增量 kW（表8-5）；
    K_α: 包角修正系数（表8-6）；K_L: 带长修正系数（表8-2）。
    返回 P_r，kW。
    [核:p165]
    """
    return (P_0 + ΔP_0) * K_α * K_L


def eq8_20(d_d1: float, d_d2: float) -> 式8_20结果:
    """式(8-20) 初选中心距范围：0.7(d_d1+d_d2) ≤ a_0 ≤ 2(d_d1+d_d2)。

    适用条件：设计步骤“初选带传动的中心距 a_0”；中心距大有利于包角与寿命，
    但过大会加剧带的波动、降低平稳性并增大尺寸；过小则相反。
    d_d1/d_d2: 小/大带轮基准直径 mm。
    返回 NamedTuple(a_0_min, a_0_max)，单位 mm。
    [核:p167]
    """
    和 = d_d1 + d_d2
    return 式8_20结果(0.7 * 和, 2.0 * 和)


def eq8_21(K_A: float, P: float) -> float:
    """式(8-21) 计算功率：P_ca = K_A P，kW。

    适用条件：按额定功率 P 与带的工作条件（表8-8）确定计算功率。
    K_A: 工作情况系数（表8-8）；P: 所需传递的额定功率 kW
    （如电动机额定功率或名义负载功率）。
    返回 P_ca，kW。
    [核:p167-p168]
    """
    return K_A * P


def eq8_22(a_0: float, d_d1: float, d_d2: float) -> float:
    """式(8-22) 带的初定基准长度：
    L_d0 ≈ 2a_0 + (π/2)(d_d1+d_d2) + (d_d2−d_d1)²/(4a_0)。

    适用条件：初定中心距 a_0 后计算所需带长；为**近似式**（≈）。
    a_0: 初定中心距 mm；d_d1/d_d2: 小/大带轮基准直径 mm。
    返回 L_d0，mm。
    [核:p169]
    """
    return (2.0 * a_0 + math.pi / 2.0 * (d_d1 + d_d2)
            + (d_d2 - d_d1) ** 2 / (4.0 * a_0))


def eq8_23(a_0: float, L_d: float, L_d0: float) -> float:
    """式(8-23) 实际中心距近似值：a ≈ a_0 + (L_d − L_d0)/2，mm。

    适用条件：由表8-2选定标准基准长度 L_d 之后计算实际中心距。
    a_0: 初定中心距 mm；L_d: 选定基准长度 mm；L_d0: 式8-22 算出的所需长度 mm。
    返回 a，mm。
    [核:p170]
    """
    return a_0 + (L_d - L_d0) / 2.0


def eq8_24(a: float, L_d: float) -> 式8_24结果:
    """式(8-24) 中心距变动范围：a_min = a − 0.015L_d，a_max = a + 0.02L_d，mm。

    适用条件：考虑带轮制造误差、带长误差、带弹性及松弛后补充张紧的需要。
    a: 式8-23 求得的实际中心距 mm；L_d: 带的基准长度 mm。
    返回 NamedTuple(a_min, a_max)，单位 mm。
    [核:p170]
    """
    return 式8_24结果(a - 0.015 * L_d, a + 0.02 * L_d)


def eq8_25(d_d1: float, d_d2: float, a: float) -> float:
    """式(8-25) 小带轮包角验算：
    α_1 ≈ 180° − (d_d2−d_d1)·57.3°/a ≥ 120°。

    适用条件：打滑通常发生在小带轮上，为保证工作能力应使 α_1≥120°；
    57.3° 按课本原样、按**度**计算。
    d_d1/d_d2: 小/大带轮基准直径 mm；a: 中心距 mm。
    返回 α_1，度（是否 ≥120° 需调用方判断）。
    [核:p170]
    """
    return 180.0 - (d_d2 - d_d1) * 57.3 / a


def eq8_26(P_ca: float, P_r: float) -> float:
    """式(8-26) 带的根数：z = P_ca/P_r = K_A P/[(P_0+ΔP_0)K_α K_L]。

    适用条件：确定根数；为使各根受力均匀，根数不宜过多，一般应少于 10 根，
    否则应换横截面积较大的带型。
    P_ca: 计算功率 kW（式8-21）；P_r: 单根 V 带额定功率 kW（式8-19）。
    返回 z（未圆整值；圆整用 ``根数圆整``）。
    [核:p170]
    """
    return P_ca / P_r


def eq8_27(K_α: float, P_ca: float, z: float, v: float,
           q: float) -> float:
    """式(8-27) 单根 V 带初拉力：
    F_0 = 500 (2.5−K_α) P_ca/(K_α z v) + q v²，N。

    适用条件：确定初拉力；F_0 过小易打滑，过大则带寿命短、轴与轴承压力大。
    K_α: 包角系数（表8-6）；P_ca: 计算功率 kW；z: 根数；v: 带速 m/s；
    q: 单位长度质量 kg/m（表8-3）。
    返回 F_0，N。式中 500 为课本原印换算系数。
    [核:p170]
    """
    return 500.0 * (2.5 - K_α) * P_ca / (K_α * z * v) + q * v ** 2


def eq8_28(F_0: float, ΔF_0: float) -> float:
    """式(8-28) 新安装 V 带的测试力：G = (1.5F_0 + ΔF_0)/16，N。

    适用条件：新安装的 V 带；在带与两带轮切点跨度中点 M 施加与带边垂直的
    测试力 G，使每 100 mm 产生 y=1.6 mm 挠度（图8-12）。
    F_0: 单根 V 带初拉力 N；ΔF_0: 初拉力增量 N（表8-10）。
    返回 G，N。
    [核:p170]
    """
    return (1.5 * F_0 + ΔF_0) / 16.0


def eq8_29(F_0: float, ΔF_0: float) -> float:
    """式(8-29) 运转后 V 带的测试力：G = (1.3F_0 + ΔF_0)/16，N。

    适用条件：运转后的 V 带（与式8-28 仅首项系数由 1.5 改为 1.3）。
    F_0: 单根 V 带初拉力 N；ΔF_0: 初拉力增量 N（表8-10）。
    返回 G，N。
    [核:p171]
    """
    return (1.3 * F_0 + ΔF_0) / 16.0


def eq8_30(F_0: float, ΔF_0: float) -> float:
    """式(8-30) 最小极限值的测试力：G = (F_0 + ΔF_0)/16，N。

    适用条件：初拉力的最小极限值（与式8-28、8-29 构成新装/运转后/极限三档）。
    F_0: 单根 V 带初拉力 N；ΔF_0: 初拉力增量 N（表8-10）。
    返回 G，N。
    [核:p171]
    """
    return (F_0 + ΔF_0) / 16.0


def eq8_31(z: float, F_0: float, α_1: float) -> float:
    """式(8-31) 压轴力：F_p = 2 z F_0 sin(α_1/2)，N。

    适用条件：为设计带轮轴和轴承，按两边初拉力的合力近似计算（不计两边拉力差，
    图8-13）。
    z: 带的根数；F_0: 单根 V 带初拉力 N；α_1: 小带轮包角 **弧度**。
    返回 F_p，N。注意 α_1 必须先 ``弧度()``，本式不吃度。
    [核:p171]
    """
    return 2.0 * z * F_0 * math.sin(α_1 / 2.0)



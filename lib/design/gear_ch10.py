def _线值(线, 硬度):
    """取一条线的 σ 值。线可以是 (k, b)，也可以是分段 [[k, b, 该段上端硬度], ...]。

    分段形式用于折线（如图10-20(e) 氮碳共渗钢 ME=MQ 在 ≈449 HV 处拐弯）：
    取**第一个** 硬度 ≤ 段上端 的段；超出末段按末段外推（调用方已先验硬度范围）。
    """
    if isinstance(线[0], (list, tuple)):
        for 段 in 线:
            if 硬度 <= 段[2]:
                return 段[0] * 硬度 + 段[1]
        段 = 线[-1]
        return 段[0] * 硬度 + 段[1]
    return 线[0] * 硬度 + 线[1]



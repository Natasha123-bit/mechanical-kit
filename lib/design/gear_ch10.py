def _网纹区取值(取值线, L):
    """在 (log10N, K) 折线上插值；L 超出末端按末端值平延（即网纹区下限 0.85）。"""
    if L <= 取值线[0][0]:
        return 取值线[0][1]
    for (l0, k0), (l1, k1) in zip(取值线, 取值线[1:]):
        if L <= l1:
            return k0 + (k1 - k0) * (L - l0) / (l1 - l0)
    return 取值线[-1][1]


def _下降段插值(段, L):
    """在 '段' 点集 (log10N, K) 上做线性插值（L 已保证落在首末点之间）。"""
    for (l0, k0), (l1, k1) in zip(段, 段[1:]):
        if L <= l1:
            return k0 + (k1 - k0) * (L - l0) / (l1 - l0)
    return 段[-1][1]



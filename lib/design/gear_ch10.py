def 图10_21_插值(点集, 硬度):
    """点集按硬度升序，线性内插；硬度越界返回 None（由调用方抛 ValueError）。"""
    if 硬度 < 点集[0][0] or 硬度 > 点集[-1][0]:
        return None
    for (x1, y1), (x2, y2) in zip(点集, 点集[1:]):
        if x1 <= 硬度 <= x2:
            if x2 == x1:
                return y1
            return y1 + (y2 - y1) * (硬度 - x1) / (x2 - x1)
    return None



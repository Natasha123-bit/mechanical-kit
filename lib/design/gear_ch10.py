def 传动比(z_1: float, z_2: float) -> float:
    """齿数比 u = z_2 / z_1。"""
    return z_2 / z_1


def 转矩(T: float = None, P: float = None, n: float = None) -> float:
    """T = 9.549e6 P/n，N·mm（P/kW，n/r·min⁻¹）。"""
    if T is not None:
        return T
    return 9.549e6 * P / n


def 端面压力角(α_n: float, β: float) -> float:
    """斜齿端面压力角 α_t = arctan(tanα_n / cosβ)。返回弧度。"""
    return math.atan(math.tan(α_n) / math.cos(β))


def 基圆螺旋角(β: float, α_t: float) -> float:
    """基圆柱螺旋角 β_b = arctan(tanβ · cosα_t)。返回弧度。"""
    return math.atan(math.tan(β) * math.cos(α_t))


def 区域系数直齿(α: float) -> float:
    """直齿区域系数 Z_H = sqrt(2 / (cosα sinα))。"""
    return math.sqrt(2.0 / (math.cos(α) * math.sin(α)))


def 区域系数斜齿(β: float, α_t: float) -> float:
    """斜齿区域系数 Z_H = sqrt(2 cosβ_b / (cosα_t sinα_t))。"""
    β_b = 基圆螺旋角(β, α_t)
    return math.sqrt(2.0 * math.cos(β_b) / (math.cos(α_t) * math.sin(α_t)))


def 齿顶圆压力角(d_a: float, d: float, α: float) -> float:
    """α_a = arccos(d cosα / d_a)。返回弧度。"""
    return math.acos(d * math.cos(α) / d_a)


def 端面重合度(z_1: float, z_2: float, α: float,
               α_a1: float, α_a2: float) -> float:
    """直齿端面重合度 ε_α = [z_1(tanα_a1 - tanα) + z_2(tanα_a2 - tanα)] / (2π)。"""
    return (z_1 * (math.tan(α_a1) - math.tan(α))
            + z_2 * (math.tan(α_a2) - math.tan(α))) / (2 * math.pi)


def 轴向重合度(φ_d: float, z_1: float, β: float) -> float:
    """斜齿轴向重合度 ε_β = φ_d z_1 tanβ / π。"""
    return φ_d * z_1 * math.tan(β) / math.pi


def 当量齿数(z: float, β: float) -> float:
    """斜齿当量齿数 z_v = z / cos³β。"""
    return z / math.cos(β) ** 3


def 当量齿数锥(z: float, δ: float) -> float:
    """锥齿轮当量齿数 z_v = z / cosδ。"""
    return z / math.cos(δ)


def 分锥角(z_1: float, z_2: float) -> tuple:
    """直齿锥齿轮分锥角 δ_1 = arctan(z_1/z_2)，δ_2 = 90° - δ_1。返回弧度。"""
    δ_1 = math.atan(z_1 / z_2)
    return δ_1, math.pi / 2 - δ_1


def 齿宽中点直径(d: float, φ_R: float) -> float:
    """锥齿轮齿宽中点分度圆直径 d_m = d(1 - 0.5 φ_R)。"""
    return d * (1 - 0.5 * φ_R)


def 齿根高(h_a_star: float, c_star: float, m: float) -> float:
    """齿根高 h_f = (h_a* + c*)m；全齿高 h = (2h_a* + c*)m。"""
    return (h_a_star + c_star) * m


def 全齿高(h_a_star: float, c_star: float, m: float) -> float:
    """全齿高 h = (2h_a* + c*)m（例题用于 b/h）。"""
    return (2 * h_a_star + c_star) * m


def 圆整标准模数(m: float) -> float:
    """就近取标准模数（第一系列）。"""
    return min(标准模数_第一系列, key=lambda x: abs(x - m))


def 齿顶圆压力角_直齿(z: float, α: float, h_a_star: float = 1.0) -> float:
    """α_a = arccos[ z cosα / (z + 2h_a*) ]，与模数无关。返回弧度。"""
    return math.acos(z * math.cos(α) / (z + 2 * h_a_star))


def 齿顶圆压力角_斜齿(z: float, α_t: float, β: float, h_a_star: float = 1.0) -> float:
    """α_a = arccos[ z cosα_t / (z + 2h_a* cosβ) ]。返回弧度。"""
    return math.acos(z * math.cos(α_t) / (z + 2 * h_a_star * math.cos(β)))


def 当量重合度(ε_α: float, β: float, α_t: float) -> float:
    """ε_αv = ε_α / cos²β_b（式10-18 说明中的当量齿轮重合度）。"""
    β_b = 基圆螺旋角(β, α_t)
    return ε_α / math.cos(β_b) ** 2



def eq10_1(K: float, F_n: float) -> float:
    """式(10-1) 计算载荷 F_ca = K F_n / N。

    适用：名义载荷换算为计算载荷，用于齿轮强度计算。
    K  : 载荷系数，K = K_A K_v K_α K_β
    F_n: 名义载荷（法向力），N
    """
    return K * F_n


def eq10_2(K_A: float, K_v: float, K_α: float, K_β: float) -> float:
    """式(10-2) 载荷系数 K = K_A K_v K_α K_β。

    K_A : 使用系数（表10-2）
    K_v : 动载系数（图10-8）
    K_α : 齿间载荷分配系数（表10-3），接触用 K_Hα、弯曲用 K_Fα
    K_β : 齿向载荷分布系数（表10-4 / 图10-13），接触用 K_Hβ、弯曲用 K_Fβ
    """
    return K_A * K_v * K_α * K_β


class 直齿受力(NamedTuple):
    """式(10-3) 的三个分力，N。"""
    F_t: float   # 圆周力
    F_r: float   # 径向力
    F_n: float   # 法向力


def eq10_3(T_1: float, d_1: float, α: float) -> 直齿受力:
    """式(10-3) 标准直齿圆柱齿轮轮齿受力。

    F_t = 2T_1/d_1,  F_r = F_t tanα,  F_n = F_t / cosα
    T_1: 小齿轮转矩 N·mm；d_1: 分度圆直径 mm；α: 压力角 rad（标准 20°）
    """
    F_t = 2 * T_1 / d_1
    return 直齿受力(F_t=F_t,
                  F_r=F_t * math.tan(α),
                  F_n=F_t / math.cos(α))


def eq10_4(K_F: float, F_t: float, Y_Fa: float, Y_Sa: float, Y_ε: float,
           b: float, m: float) -> float:
    """式(10-4) 直齿圆柱齿轮齿根弯曲疲劳强度条件式（基本式），σ_F/MPa。

    σ_F = K_F F_t Y_Fa Y_Sa Y_ε / (b m) ≤ [σ_F]
    K_F : 弯曲载荷系数 K_A K_v K_Fα K_Fβ
    b   : 齿宽 mm；m: 模数 mm
    Y_Fa/Y_Sa: 表10-5；Y_ε: 式(10-5)
    """
    return K_F * F_t * Y_Fa * Y_Sa * Y_ε / (b * m)


def eq10_5(ε_α: float) -> float:
    """式(10-5) 直齿圆柱齿轮弯曲疲劳强度用重合度系数 Y_ε = 0.25 + 0.75/ε_α。"""
    return 0.25 + 0.75 / ε_α


def eq10_6(K_F: float, T_1: float, Y_Fa: float, Y_Sa: float, Y_ε: float,
           φ_d: float, m: float, z_1: float) -> float:
    """式(10-6) 直齿圆柱齿轮齿根弯曲疲劳强度校核式，σ_F/MPa。

    σ_F = 2 K_F T_1 Y_Fa Y_Sa Y_ε / (φ_d m³ z_1²) ≤ [σ_F]
    由式(10-4) 代入 φ_d = b/d_1、F_t = 2T_1/d_1、m = d_1/z_1 整理而得。
    """
    return 2 * K_F * T_1 * Y_Fa * Y_Sa * Y_ε / (φ_d * m ** 3 * z_1 ** 2)


def eq10_7(K_F: float, T_1: float, Y_ε: float, φ_d: float, z_1: float,
           Y_Fa: float, Y_Sa: float, σ_F_allow: float) -> float:
    """式(10-7) 直齿圆柱齿轮齿根弯曲疲劳强度设计式，求 m/mm。

    m ≥ ∛[ 2 K_F T_1 Y_ε /(φ_d z_1²) · Y_Fa Y_Sa/[σ_F] ]
    设计时取 Y_Fa Y_Sa/[σ_F] 较大的一轮（通常大齿轮）。
    """
    return (2 * K_F * T_1 * Y_ε / (φ_d * z_1 ** 2)
            * Y_Fa * Y_Sa / σ_F_allow) ** (1 / 3)


def eq10_8(Z_E: float, F_n: float, ρ_Σ: float, L: float) -> float:
    """式(10-8) 齿面接触应力（赫兹公式），σ_H/MPa。

    σ_H = Z_E sqrt( F_n / (ρ_Σ L) )
    Z_E  : 弹性影响系数 MPa^0.5（表10-6）
    ρ_Σ  : 综合曲率半径 mm
    L    : 接触线长度 mm
 
    注：本式仅用于推导；工程计算直接用式(10-10)/式(10-22)/式(10-28)。
    """
    return Z_E * math.sqrt(F_n / (ρ_Σ * L))


def eq10_9(ε_α: float) -> float:
    """式(10-9) 直齿圆柱齿轮接触疲劳强度用重合度系数 Z_ε = sqrt((4-ε_α)/3)。"""
    return math.sqrt((4 - ε_α) / 3)


def eq10_10(Z_H: float, Z_E: float, Z_ε: float, K_H: float, T_1: float,
            φ_d: float, d_1: float, u: float) -> float:
    """式(10-10) 直齿圆柱齿轮齿面接触疲劳强度校核式，σ_H/MPa。

    σ_H = Z_H Z_E Z_ε sqrt( 2K_H T_1/(φ_d d_1³) · (u+1)/u ) ≤ [σ_H]
    """
    return Z_H * Z_E * Z_ε * math.sqrt(2 * K_H * T_1 / (φ_d * d_1 ** 3)
                                       * (u + 1) / u)


def eq10_11(K_H: float, T_1: float, φ_d: float, u: float,
            Z_H: float, Z_E: float, Z_ε: float, σ_H_allow: float) -> float:
    """式(10-11) 直齿圆柱齿轮接触疲劳强度设计式，求 d_1/mm。

    d_1 ≥ ∛[ 2K_H T_1/φ_d · (u+1)/u · (Z_H Z_E Z_ε/[σ_H])² ]
    """
    return (2 * K_H * T_1 / φ_d * (u + 1) / u
            * (Z_H * Z_E * Z_ε / σ_H_allow) ** 2) ** (1 / 3)


def eq10_12(d_t: float, K_H: float, K_Ht: float) -> float:
    """式(10-12) 按实际载荷系数修正试算分度圆直径 d = d_t ∛(K_H/K_Ht)。"""
    return d_t * (K_H / K_Ht) ** (1 / 3)


def eq10_13(m_t: float, K_F: float, K_Ft: float) -> float:
    """式(10-13) 按实际载荷系数修正试算模数 m = m_t ∛(K_F/K_Ft)。"""
    return m_t * (K_F / K_Ft) ** (1 / 3)


def eq10_14(K_N: float, σ_lim: float, S: float) -> float:
    """式(10-14) 许用应力 [σ] = K_N σ_lim / S，MPa。

    K_N  : 寿命系数（接触查图10-19，弯曲查图10-18）
    σ_lim: 疲劳极限（接触查图10-21，弯曲查图10-20）
    S    : 安全系数（接触取 1；弯曲取 1.4，重要场合 1.5）
    """
    return K_N * σ_lim / S


def eq10_15(n: float, j: float, L_h: float) -> float:
    """式(10-15) 应力循环次数 N = 60 n j L_h。

    n  : 转速 r/min；j: 齿轮每转一周同侧齿面啮合次数；L_h: 工作寿命 h
    """
    return 60 * n * j * L_h


class 斜齿受力(NamedTuple):
    """式(10-16) 的四个分力，N。"""
    F_t: float
    F_r: float
    F_a: float
    F_n: float


def eq10_16(T_1: float, d_1: float, α_n: float, β: float) -> 斜齿受力:
    """式(10-16) 标准斜齿圆柱齿轮轮齿受力。

    F_t = 2T_1/d_1,  F_r = F_t tanα_n / cosβ,  F_a = F_t tanβ,
    F_n = F_t /(cosα_n cosβ)
    """
    F_t = 2 * T_1 / d_1
    return 斜齿受力(F_t=F_t,
                  F_r=F_t * math.tan(α_n) / math.cos(β),
                  F_a=F_t * math.tan(β),
                  F_n=F_t / (math.cos(α_n) * math.cos(β)))


def eq10_17(K_F: float, T_1: float, Y_Fa: float, Y_Sa: float, Y_ε: float,
            Y_β: float, β: float, φ_d: float, m_n: float, z_1: float) -> float:
    """式(10-17) 标准斜齿圆柱齿轮齿根弯曲疲劳强度条件式，σ_F/MPa。

    σ_F = 2 K_F T_1 Y_Fa Y_Sa Y_ε Y_β cos²β / (φ_d m_n³ z_1²) ≤ [σ_F]
    Y_Fa、Y_Sa 按当量齿数 z_v 查表10-5；cos²β 来自 d_1 = m_n z_1/cosβ 的代入。
    """
    return (2 * K_F * T_1 * Y_Fa * Y_Sa * Y_ε * Y_β * math.cos(β) ** 2
            / (φ_d * m_n ** 3 * z_1 ** 2))


def eq10_18(ε_αv: float) -> float:
    """式(10-18) 斜齿弯曲疲劳强度用重合度系数 Y_ε = 0.25 + 0.75/ε_αv。

    ε_αv = ε_α / cos²β_b（当量齿轮重合度）。
    """
    return 0.25 + 0.75 / ε_αv


def eq10_19(ε_β: float, β: float, 限制: bool = False) -> float:
    """式(10-19) 螺旋角系数 Y_β = (1 - ε_β β/120°) / cos³β。

    ε_β : 轴向重合度（式：ε_β = φ_d z_1 tanβ/π）
    β   : 螺旋角，**度**
    限制: 课本正文注明"当 ε_β>1.0 时取 ε_β=1；当 β>30° 时取 β=30°"，
          但例10-2 实际代入 ε_β=1.905 未作限制（结果 0.851 与此一致）。
          默认 False（照例题）；置 True 按正文注释封顶。
    """
    if 限制:
        ε_β = min(ε_β, 1.0)
        β = min(β, 30.0)
    return (1 - ε_β * β / 120.0) / math.cos(math.radians(β)) ** 3


def eq10_20(K_F: float, T_1: float, Y_ε: float, Y_β: float, β: float,
            φ_d: float, z_1: float, Y_Fa: float, Y_Sa: float,
            σ_F_allow: float) -> float:
    """式(10-20) 斜齿圆柱齿轮齿根弯曲疲劳强度设计式，求 m_n/mm。

    m_n ≥ ∛[ 2K_F T_1 Y_ε Y_β cos²β /(φ_d z_1²) · Y_Fa Y_Sa/[σ_F] ]
    """
    return (2 * K_F * T_1 * Y_ε * Y_β * math.cos(β) ** 2 / (φ_d * z_1 ** 2)
            * Y_Fa * Y_Sa / σ_F_allow) ** (1 / 3)


def eq10_21(ε_α: float, ε_β: float) -> float:
    """式(10-21) 斜齿接触疲劳强度用重合度系数 Z_ε（分段）。

    ε_β < 1 : Z_ε = sqrt[ (4-ε_α)/3 ·(1-ε_β) + ε_β/ε_α ]
    ε_β ≥ 1 : Z_ε = sqrt(1/ε_α)
    """
    if ε_β < 1:
        return math.sqrt((4 - ε_α) / 3 * (1 - ε_β) + ε_β / ε_α)
    return math.sqrt(1 / ε_α)


def eq10_22(Z_H: float, Z_E: float, Z_ε: float, Z_β: float, K_H: float,
            T_1: float, φ_d: float, d_1: float, u: float) -> float:
    """式(10-22) 斜齿圆柱齿轮齿面接触疲劳强度校核式，σ_H/MPa。

    σ_H = Z_H Z_E Z_ε Z_β sqrt( 2K_H T_1/(φ_d d_1³) · (u+1)/u ) ≤ [σ_H]
    """
    return Z_H * Z_E * Z_ε * Z_β * math.sqrt(
        2 * K_H * T_1 / (φ_d * d_1 ** 3) * (u + 1) / u)


def eq10_23(β: float) -> float:
    """式(10-23) 斜齿接触疲劳强度用螺旋角系数 Z_β = sqrt(1/cosβ)。

    课本印刷为根号内取倒数（例10-2：β=14°，Z_β=√(1/cos14°)=1.015）。
    """
    return math.sqrt(1 / math.cos(β))


def eq10_24(K_H: float, T_1: float, φ_d: float, u: float, Z_H: float,
            Z_E: float, Z_ε: float, Z_β: float, σ_H_allow: float) -> float:
    """式(10-24) 斜齿圆柱齿轮接触疲劳强度设计式，求 d_1/mm。

    d_1 ≥ ∛[ 2K_H T_1/φ_d · (u+1)/u · (Z_H Z_E Z_ε Z_β/[σ_H])² ]
    """
    return (2 * K_H * T_1 / φ_d * (u + 1) / u
            * (Z_H * Z_E * Z_ε * Z_β / σ_H_allow) ** 2) ** (1 / 3)


class 锥齿受力(NamedTuple):
    """式(10-25) 的四个分力，N。"""
    F_t: float
    F_r: float
    F_a: float
    F_n: float


def eq10_25(T_1: float, d_m1: float, α: float, δ_1: float) -> 锥齿受力:
    """式(10-25) 直齿锥齿轮轮齿受力（按齿宽中点）。

    F_t = 2T_1/d_m1,  F_r = F_t tanα cosδ_1,  F_a = F_t tanα sinδ_1,
    F_n = F_t / cosα
    d_m1: 齿宽中点分度圆直径 mm；δ_1: 小齿轮分锥角 rad
    """
    F_t = 2 * T_1 / d_m1
    return 锥齿受力(F_t=F_t,
                  F_r=F_t * math.tan(α) * math.cos(δ_1),
                  F_a=F_t * math.tan(α) * math.sin(δ_1),
                  F_n=F_t / math.cos(α))


def eq10_26(K_F: float, T_1: float, Y_Fa: float, Y_Sa: float, Y_ε: float,
            φ_R: float, m: float, z_1: float, u: float) -> float:
    """式(10-26) 直齿锥齿轮齿根弯曲疲劳强度条件式，σ_F/MPa。

    σ_F = 4 K_F T_1 Y_Fa Y_Sa Y_ε /
          [ φ_R (1-0.5φ_R)² m³ z_1² sqrt(u²+1) ] ≤ [σ_F]
    """
    return (4 * K_F * T_1 * Y_Fa * Y_Sa * Y_ε
            / (φ_R * (1 - 0.5 * φ_R) ** 2 * m ** 3 * z_1 ** 2
               * math.sqrt(u ** 2 + 1)))


def eq10_27(K_F: float, T_1: float, Y_ε: float, φ_R: float, z_1: float,
            u: float, Y_Fa: float, Y_Sa: float, σ_F_allow: float) -> float:
    """式(10-27) 直齿锥齿轮齿根弯曲疲劳强度设计式，求 m/mm（大端模数）。

    m ≥ ∛[ 4K_F T_1 Y_ε /(φ_R (1-0.5φ_R)² z_1² sqrt(u²+1)) · Y_Fa Y_Sa/[σ_F] ]
    """
    return (4 * K_F * T_1 * Y_ε
            / (φ_R * (1 - 0.5 * φ_R) ** 2 * z_1 ** 2 * math.sqrt(u ** 2 + 1))
            * Y_Fa * Y_Sa / σ_F_allow) ** (1 / 3)


def eq10_28(Z_H: float, Z_E: float, Z_ε: float, K_H: float, T_1: float,
            φ_R: float, d_1: float, u: float) -> float:
    """式(10-28) 直齿锥齿轮齿面接触疲劳强度条件式，σ_H/MPa。

    σ_H = Z_H Z_E Z_ε sqrt( 4K_H T_1 /[φ_R (1-0.5φ_R)² d_1³ u] ) ≤ [σ_H]
    """
    return Z_H * Z_E * Z_ε * math.sqrt(
        4 * K_H * T_1 / (φ_R * (1 - 0.5 * φ_R) ** 2 * d_1 ** 3 * u))


def eq10_29(K_H: float, T_1: float, φ_R: float, u: float, Z_H: float,
            Z_E: float, Z_ε: float, σ_H_allow: float) -> float:
    """式(10-29) 直齿锥齿轮接触疲劳强度设计式，求 d_1/mm。

    d_1 ≥ ∛[ 4K_H T_1/(φ_R (1-0.5φ_R)² u) · (Z_H Z_E Z_ε/[σ_H])² ]
    """
    return (4 * K_H * T_1 / (φ_R * (1 - 0.5 * φ_R) ** 2 * u)
            * (Z_H * Z_E * Z_ε / σ_H_allow) ** 2) ** (1 / 3)



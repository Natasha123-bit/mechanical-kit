def 查表10_5_YFa_YSa(z: float, z_无穷等效: float = 350.0) -> tuple:
    """表10-5 齿形系数 Y_Fa 与应力修正系数 Y_Sa（z 为齿数或当量齿数 z_v，线性插值）。

    表的最后一列为 z=∞（2.06 / 1.97）。例10-3 中 z_v=258.76 书上取 2.097 / 1.906，
    相当于在 z=200 与 ∞ 之间按 z_无穷等效=350 线性内插即可复现；此为读表内插的等效处理，
    非课本明文规定，改动时请留意。
    """
    ks = sorted(k for k in 表10_5_YFa_YSa)
    zmax = ks[-2]                      # 200
    if z <= ks[0]:
        return 表10_5_YFa_YSa[ks[0]]
    if z >= z_无穷等效:
        return 表10_5_YFa_YSa[math.inf]
    for a, b in zip(ks, ks[1:]):
        b_eff = z_无穷等效 if b == math.inf else b
        if a <= z <= b_eff:
            t = (z - a) / (b_eff - a)
            ya, sa = 表10_5_YFa_YSa[a]
            yb, sb = 表10_5_YFa_YSa[b]
            return (ya + t * (yb - ya), sa + t * (sb - sa))
    raise ValueError(z)



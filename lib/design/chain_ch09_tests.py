    z_1 = 21
    z_2_算 = c.eq9_14(z_1=z_1, i=i_给定, 解="z_2")
    校验("式(9-14) z2 = i z1（圆整前）", z_2_算, 67.2, 1e-12, "齿",
         "67.2 为未圆整值")
    z_2 = c.齿数圆整(z_2_算)
    校验文本("齿数圆整 67.2 → 67（圆整规则单独注明）", z_2, 67)
    校验("式(9-14) 反算 i（z2=67）", c.eq9_14(z_1=z_1, z_2=z_2), 67.0 / 21.0,
         1e-12)

    # (2) 确定计算功率：K_A=1.0（表9-6），K_z=(19/21)^1.08=0.9，单排 K_p=1
    K_A = c.查表9_6_工作情况系数KA("平稳运转", "平稳运转")
    校验("表9-6 K_A（从动平稳/主动平稳）", K_A, 1.0, 0.0)
    K_z = c.齿数系数K_z(z_1)
    校验("式(9-15) K_z=(19/21)^1.08", K_z, 0.9, 0.005, "", "书中圆整写 0.9")
    K_p = c.多排链系数K_p(1)
    校验("多排链系数 K_p（单排）", K_p, 1.0, 0.0)
    P_ca = c.eq9_15(K_A, K_z, K_p, P)
    校验("式(9-15) P_ca（用计算 K_z）", P_ca, 3.6, 0.005, "kW")
    校验("式(9-15) P_ca（用书上 K_z=0.9）", c.eq9_15(1.0, 0.9, 1.0, 4.0),
         3.6, 1e-12, "kW")
    校验真("式(9-16) P_ca≤P_c 判据（3.6≤3.6）", c.eq9_16(3.6, 3.6))
    校验真("式(9-16) P_ca=3.7>P_c=3.6 判据不成立", not c.eq9_16(3.7, 3.6))

    # (3) 选链号 16A，查表9-1 得 p=25.40
    p = c.查表9_1_节距("16A")
    校验("表9-1 16A 节距 p", p, 25.40, 0.0, "mm")

    # (4) 初选中心距 a0=(30~50)p=762~1270，取 a0=1000
    校验("初选中心距下限 30p", 30.0 * p, 762.0, 0.0, "mm")
    校验("初选中心距上限 50p", 50.0 * p, 1270.0, 0.0, "mm")
    校验真("a0=1000 落在 (30~50)p 内", 30.0 * p <= 1000.0 <= 50.0 * p)
    a_0 = 1000.0

    L_p0 = c.eq9_17(a_0, p, z_1, z_2)
    校验("式(9-17) L_p0=124.1", L_p0, 124.1, 0.005, "节", "124.1016 未圆整")
    L_p = c.链节数圆整(L_p0)
    校验文本("链节数圆整 124.1 → 126（取不小于计算值的最小偶数）", L_p, 126)
    校验文本("链节数圆整：已为偶数的 126 保持 126", c.链节数圆整(126.0), 126)
    校验文本("链节数圆整：124.0 保持 124", c.链节数圆整(124.0), 124)

    比值 = (L_p - z_1) / (z_2 - z_1)
    校验("表9-7 横坐标 x=(126−21)/(67−21)=105/46", 比值, 2.2826087, 1e-6,
         "", "≈2.283")
    f_1 = c.查表9_7_中心距计算系数f1(比值)
    校验("表9-7 f1（x≈2.283 在 2.0~2.4 间内插）", f_1, 0.24576, 0.005,
         "", "五位小数 0.245 76")
    校验("表9-7 内插手算 0.24421+(x−2)/0.4×0.00222",
         f_1, 0.24421 + (105.0 / 46.0 - 2.0) / 0.4 * (0.24643 - 0.24421),
         1e-12)
    a_max = c.eq9_18(f_1, p, L_p, z_1, z_2)
    校验("式(9-18) a_max=1024", a_max, 1024.0, 0.005, "mm")
    校验("式(9-18) a_max（用书上 f1=0.24576）",
         c.eq9_18(0.24576, 25.40, 126, 21, 67), 1024.0, 0.005, "mm",
         "1023.86 圆整为 1024")

    # (5) 链速 v=0.8 m/s（式9-1）
    v = c.eq9_1(z_1=z_1, n_1=n_1, p=p)
    校验("式(9-1) v=z1 n1 p/(60×1000)", v, 0.8, 0.005, "m/s")
    校验("式(9-1) v（书值 0.8 直接代回）", 21 * 90 * 25.4 / 60000.0, 0.8,
         0.005, "m/s")

    # (6) 有效圆周力 Fe=5000 N，压轴力 Fp=5750 N
    F_e = c.eq9_11(P=P, v=v)
    校验("式(9-11) F_e=1000P/v", F_e, 5000.0, 0.005, "N")
    K_Fp = c.压轴力系数K_Fp("水平")
    校验("压轴力系数 K_Fp（水平传动）", K_Fp, 1.15, 0.0)
    校验("压轴力系数 K_Fp（垂直传动）", c.压轴力系数K_Fp("垂直"), 1.05, 0.0)
    F_p = c.eq9_20(K_Fp, F_e)
    校验("式(9-20) F_p≈K_Fp F_e", F_p, 5750.0, 0.005, "N")

    # (7) 设计结论
    print("[INFO] 例9-1 结论：16A，z1=21/z2=67，L_p=126，a=1024 mm，"
          "滴油润滑，F_p=5750 N")
    校验真("图9-11 只给说明、不造查图函数",
           hasattr(c, "图9_11_选型说明")
           and "不造查图函数" in c.图9_11_选型说明
           and not hasattr(c, "查图9_11"))



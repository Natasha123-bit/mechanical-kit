"""_lookup_tests.py —— `_区间()` 行标签形态的回归测试（2026-10-22 验收时发现并修复）

背景：全书 901 条行标签里有 17 条是区间但解析不了，`区间取` 直接 KeyError：
  表4-1 '自 6~8'（d=6~8 全查不到）、表11-4 'a≤150'、表6-16/6-17 '—~18'、'50~120（推力球轴承）'
修复后本文件锁死行为：脏写法要能解析，非区间标签（f7 / N7 / M8 / 文字）必须仍是 None。
"""
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import _lookup as L

通过 = 0
失败 = []


def 断言(cond, msg):
    global 通过
    if cond:
        通过 += 1
    else:
        失败.append(msg)


def 相等(a, b, msg):
    断言(a == b, f"{msg}：期望 {b!r}，实际 {a!r}")


# ---- 1. 脏写法解析 ----
相等(L._区间("6~8"), (6.0, 8.0, True, True), "普通区间")
相等(L._区间("自 6~8"), (6.0, 8.0, True, True), "「自」前缀")
相等(L._区间(">8~10"), (8.0, 10.0, False, True), "下界开")
相等(L._区间("≥10~12"), (10.0, 12.0, True, True), "下界闭")
相等(L._区间("≤6"), (float("-inf"), 6.0, False, True), "单侧上界")
相等(L._区间("a≤150"), (float("-inf"), 150.0, False, True), "带变量名的单侧上界")
相等(L._区间("—~18"), (float("-inf"), 18.0, False, True), "下界开口破折号")
相等(L._区间("50~120（推力球轴承）"), (50.0, 120.0, True, True), "尾随括注")
相等(L._区间("１８～２０"), (18.0, 20.0, True, True), "全角数字：\\d 与 float 都吃，解析出 18~20")

# ---- 2. 非区间标签不许误判 ----
for 标签 in ("f7", "g7", "N7", "M8", "h6", "6×6", "备注", "尽量靠近，一般取s≈D₂"):
    断言(L._区间(标签) is None, f"非区间标签被误解析：{标签!r} → {L._区间(标签)!r}")

# ---- 3. 落到真实表上：查值 ----
import key_ch04 as K4
import reducer_ch11 as R11

表 = K4.表4_1_平键
相等(L.区间取(表, 6, "公称尺寸 b×h"), "2×2", "表4-1 d=6")
相等(L.区间取(表, 7.5, "公称尺寸 b×h"), "2×2", "表4-1 d=7.5")
相等(L.区间取(表, 8, "公称尺寸 b×h"), "2×2", "表4-1 d=8 属「自 6~8」档（>8~10 下界开）")
相等(L.区间取(表, 8.1, "公称尺寸 b×h"), "3×3", "表4-1 d=8.1 进「>8~10」档")
相等(L.区间取(表, 9, "公称尺寸 b×h"), "3×3", "表4-1 d=9")
相等(L.区间取(表, 11, "公称尺寸 b×h"), "4×4", "表4-1 d=11")

表11_4 = None
for n in dir(R11):
    o = getattr(R11, n)
    if isinstance(o, dict) and str(o.get("表号")) == "表11-4":
        表11_4 = o
        break
断言(表11_4 is not None, "表11-4 必须在 reducer_ch11 里存在")
if 表11_4 is not None:
    值 = L.区间取(表11_4, 200, 表11_4["cols"][1])
    断言(值 is not None, f"表11-4 a=200 应能查到值，实际 {值!r}")
    值2 = L.区间取(表11_4, 480, 表11_4["cols"][1])
    断言(值2 is not None, f"表11-4 a=480 应能查到值，实际 {值2!r}")

# ---- 4. 越界仍是 KeyError（不许猜相邻档）----
try:
    L.区间取(表, 200, "公称尺寸 b×h")
    失败.append("越界 d=200 应当 KeyError，实际返回了值")
except KeyError:
    通过 += 1

# ---- 5. 双参数表（2026-10-25 新增 区间取2 / 区间行列取）----
import gear_tol_ch10 as G10

T10_6 = G10.T05            # 表10-6(1) 单个齿距偏差 ±f_pt，行是「d档 / m档」，列是 4~9 级
T10_15 = G10.T22           # 表10-15 中心距极限偏差，行是精度等级档，列是中心距档
T10_16 = G10.T23           # 表10-16 Ra 推荐极限值，行是精度等级，列是模数档

相等(L._段("20<d≤50"), (20.0, 50.0, False, True), "「下限<参数≤上限」下界开")
相等(L._段("5≤d≤20"), (5.0, 20.0, True, True), "「下限≤参数≤上限」两边闭")
相等(L._段("2<m≤3.5"), (2.0, 3.5, False, True), "模数档")
相等(L._段("m>25"), (25.0, float("inf"), False, False), "带变量名的单边下界")

相等(L.双参行号(T10_6, 30, 4), 4, "表10-6 d=30 m=4 落「20<d≤50 / 3.5<m≤6」")
相等(L.双参行号(T10_6, 10, 1), 0, "表10-6 d=10 m=1 落首行")
断言(L.双参行号(T10_6, 20, 4) is None, "d=20 m=4 书上没有这一档，必须返回 None 而不是猜邻行")
断言(L.双参行号(T10_6, 600, 4) is None, "d=600 越界必须 None")

相等(L.数值(L.区间取2(T10_6, 30, 4, "7级")), 12, "表10-6 页图 p.135 核对：20<d≤50/3.5<m≤6 的 7 级 = 12")
相等(L.数值(L.区间取2(T10_6, 10, 1, "6级")), 6.5, "表10-6 页图核对：5≤d≤20/0.5≤m≤2 的 6 级 = 6.5")
行 = L.区间取2(T10_6, 30, 4) or {}
相等(L.数值(行.get("9级")), 24, "省略列键返回整行，9 级 = 24")
try:
    L.区间取2(T10_6, 600, 4, "7级")
    失败.append("d=600 越界应当 KeyError")
except KeyError:
    通过 += 1

相等(L.数值(L.区间行列取(T10_15, 6, 40)), 12.5, "表10-15 6 级、中心距 40 → 12.5")
相等(L.数值(L.区间行列取(T10_16, 6, 4)), 0.8, "表10-16 6 级、m=4 → Ra 0.8")
try:
    L.区间行列取(T10_15, 6, 9999)
    失败.append("中心距 9999 越界应当 KeyError")
except KeyError:
    通过 += 1

print(f"合计：通过 {通过} 项，失败 {len(失败)} 项")
for m in 失败:
    print("  FAIL", m)
sys.exit(0 if not 失败 else 1)

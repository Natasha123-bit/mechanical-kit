def 载荷区分(径向当量动载荷, 径向额定动载荷):
    """向心轴承载荷区分（表6-9，p.85）：P/C ≤0.06 轻；>0.06~0.12 正常；>0.12 重。

    [核:p.85] 依据：表6-9
    """
    C = float(径向额定动载荷)
    if C <= 0:
        raise ValueError("径向额定动载荷必须 >0")
    ratio = float(径向当量动载荷) / C
    if ratio <= 0.06:
        级 = "轻载荷"
    elif ratio <= 0.12:
        级 = "正常载荷"
    else:
        级 = "重载荷"
    return {"P/C": round(ratio, 6), "载荷状态": 级, "页": 85}



def _数(v):
    x = 数值(v)
    if x is None:
        return None
    return int(x) if float(x).is_integer() else x


def _列名(表, *候选):
    """返回第一个列名里含任一候选词的列；没有返回 None。"""
    for c in 表["cols"]:
        s = str(c)
        if any(k in s for k in 候选):
            return c
    return None


def _取列(表, 行键, *候选):
    c = _列名(表, *候选)
    if c is None:
        return None
    return 取(表, 行键, c)


def _范围含(label, v):
    """表里的尺寸档位 → 是否含 v。

    支持 '≤18'、'>18~100'、'6~10'、'—~18'、'所有尺寸'、'—'（无档）。
    """
    s = str(label).strip().replace(" ", "").split("（")[0]
    if s in ("", "—", "-", "None"):
        return False
    if "所有" in s:
        return True
    s = s.replace("—", "0").replace("–", "0")
    if "~" in s:
        a, b = s.split("~", 1)
        a = a.lstrip("≥>≤<")
        return float(a) <= float(v) <= float(b)
    if s.startswith("≤") or s.startswith("<="):
        return float(v) <= float(s.lstrip("≤<= "))
    if s.startswith("≥") or s.startswith(">="):
        return float(v) >= float(s.lstrip("≥>= "))
    if s.startswith("<"):
        return float(v) < float(s[1:])
    if s.startswith(">"):
        return float(v) > float(s[1:])
    return abs(float(v) - float(s)) < 1e-9


def _行按范围(表, v, 行子集=None):
    """按数值找档位行；区间下行开、上行闭（第一行除外）。

    '6~10' 表示 >6 且 ≤10；第一行 '≤6'/'—~30' 表示 ≤ 上限。
    行子集用于表6-16 的两块（角接触/圆锥 与 推力球）。
    """
    rows = 表["rows"] if 行子集 is None else 行子集
    for i, r in enumerate(rows):
        s = str(r).strip().split("（")[0]
        if "~" in s:
            a, b = s.split("~", 1)
            a = a.replace("—", "0").lstrip("≥>≤<")
            lo, hi = float(a), float(b)
            ok = (float(v) <= hi) if i == 0 else (lo < float(v) <= hi)
            if ok:
                return r
        elif s.startswith(("≤", "<")):
            if float(v) <= float(s.lstrip("≤< ")):
                return r
        elif s.startswith(("≥", ">")):
            if float(v) >= float(s.lstrip("≥> ")):
                return r
        elif s not in ("", "—", "-"):
            if abs(float(v) - float(s)) < 1e-9:
                return r
    raise ValueError(f"{表['表号']}（p.{表['页']}）没有能容纳 {v} 的档位")



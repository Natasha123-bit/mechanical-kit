def _标准号(表):
    """从表名里取标准号：'表8-7 弹性柱销联轴器（GB/T 5014—2017）' → 'GB/T 5014—2017'。"""
    s = str(表.get('表名') or '')
    if '（' in s and '）' in s:
        return s[s.index('（') + 1:s.rindex('）')].strip()
    return None


def _轴孔行(表, 行s, d):
    """型号组的数据行里，找「轴孔直径格含 d」的那一行 → (行号, 格原样, 是否括号备用值)。

    一个型号可能占多行（轴孔长随 d 变），所以要逐行试；括号备用值（表8-9 '16,(17),18'）
    单独标出，书注「尽量不用」。
    """
    try:
        jd = _列(表, '轴孔直径')
    except KeyError:
        return None
    for i in 行s:
        格 = _格(表, i, jd)
        if 格 is None:
            continue
        for v, 括号 in _直径值(格):
            if v == d:
                return i, 格, 括号
    return None



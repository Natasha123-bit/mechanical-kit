def 离合器(类型, d=None):
    """类型（'简易传动用矩形牙嵌式' / '矩形、梯形牙嵌式'）→ 该类型全部档。
    [核:表8-10/8-11]

    d 给定时：表8-10 按轴孔直径档过滤（d 格为逗号并列如 '35,40'）；表8-11 书上无 d 列，
    给 d 报 ValueError。类型不存在 → ValueError。Tn 过滤不做（书上无转矩数据，零猜测）。
    """
    表号 = _离合器表.get(str(类型).strip())
    if 表号 is None:
        raise ValueError(f"离合器类型只有 {list(_离合器表)}（按实有表）")
    t = _表(表号)
    rows = []
    for i in range(len(t['rows'])):
        明细 = {str(t['cols'][j]): _格(t, i, j) for j in range(len(t['cols']))}
        if d is not None:
            if 表号 == '表8-11':
                raise ValueError('表8-11 矩形、梯形牙嵌式离合器无轴孔直径 d 列，不能按 d 过滤')
            jd = _列(t, 'd')
            格 = _格(t, i, jd)
            if 格 is None or dv_ok(格, d) is False:
                continue
        rows.append({'行标签': t['rows'][i], '明细': 明细})
    if d is not None and not rows:
        raise ValueError(f"表8-10 轴孔直径档没有 {d}")
    return rows


def dv_ok(格, d):
    """表8-10 d 格（'35,40' 逗号并列）是否含 d"""

def 按轴径选联轴器(d):
    """轴径 → 全章 8 张联轴器规格表（8-2~8-9）中轴孔直径装得下 d 的所有型号档（跨表汇总）。
    [核:表8-2~8-9 轴孔直径列]

    返回 [{表号, 页, 品名, 型号, 轴孔直径(格原样), 括号备用, 轴孔长度明细}, ...]，
    按表号顺序；括号备用值（表8-9 '16,(17),18'）命中时 括号备用=True（书注「尽量不用」）。
    一档多值格只要含 d 即命中整档。查不到 → ValueError。
    """
    dv = _d(d)
    out = []
    for 表号, 品名 in _联轴器表.items():
        t = _表(表号)
        jd = _列(t, '轴孔直径')
        for 型号, 行s in _型号组(t).items():
            for i in 行s:
                格 = _格(t, i, jd)
                if 格 is None:
                    continue
                vals = _直径值(格)
                hit = [v for v, kg in vals if v == dv]
                if not hit:
                    continue
                out.append({'表号': 表号, '页': t['页'], '品名': 品名, '型号': 型号,
                            '轴孔直径': 格, '括号备用': any(kg for v, kg in vals if v == dv),
                            '轴孔长度明细': _规格dict(t, i)})
    if not out:
        raise ValueError(f"8 张联轴器规格表的轴孔直径档都没有 {dv:g} mm")
    return out


def 校核转速(型号, n):
    """型号 + 工作转速 → 与书上许用转速比对。超限 ValueError，未超返回比对结果。
    [核:表8-2~8-9 许用转速列]

    型号在全章 8 张联轴器规格表中精确匹配（去空格、大小写不敏感）；表8-2 型号格为
    「GY1\\nGYS1\\nGYH1」三元组合并格，逐行匹配，命中返回格原样 + 命中行。
    许用转速多列（表8-4 不装/装罩壳）按最严（最小）值比对，全列值在返回中保留。
    """
    nn = _d(n)
    want = _型号norm(型号)
    hits = []
    for 表号, 品名 in _联轴器表.items():
        t = _表(表号)
        for 型号2, (tor, spd, 行s, 全列) in _转矩组(t).items():
            命中行 = [ln for ln in str(型号2).split('\n') if _型号norm(ln) == want]
            if 命中行:
                hits.append({'型号': 型号2, '命中行': 命中行[0], '品名': 品名,
                             '许用转速/(r/min)': spd, '许用转速全列': 全列,
                             '表号': 表号, '页': t['页']})
    if not hits:
        raise ValueError(f"8 张联轴器规格表都没有型号 {型号!r}")
    for h in hits:
        if nn > h['许用转速/(r/min)']:
            raise ValueError(f"{h['命中行']} 许用转速 {h['许用转速/(r/min)']:g} r/min，"
                             f"工作转速 {nn:g} r/min 超限（{h['表号']}，p.{h['页']}）")
    return {'工作转速/(r/min)': nn, '比对': hits}



def _格(表, i, j):
    """merge 感知的取格：落点在合并区则回落首格；首格 None（书上「—」/空白区）返回 None 不抛异常"""
    for m in 表.get('merges') or []:
        r0, r1, c0, c1 = (m[0], m[1], m[2], m[2]) if len(m) < 4 else (m[0], m[1], m[2], m[3])
        if r0 <= i <= r1 and c0 <= j <= c1:
            return 表['data'][r0][c0]
    return 表['data'][i][j]


def _表(表号):
    for _name in _表变量:
        t = globals()[_name]
        if t['表号'] == 表号:
            return t
    raise KeyError(f'本章没有 {表号}')


def _列(表, 关键词):
    """按列名包含关键词找列（列名照书原样）；唯一才给，重码/缺失报错"""
    hits = [j for j, c in enumerate(表['cols']) if 关键词 in str(c)]
    if len(hits) == 1:
        return hits[0]
    raise KeyError(f"{表['表号']} 列名含 {关键词!r} 命中 {hits} 列（cols={表['cols']}）")


def _d(x):
    v = 数值(x)
    if v is None:
        raise ValueError(f"{x!r} 不是可识别的数值")
    return v


def _型号norm(x):
    return str(x).strip().replace(' ', '').upper()


def _型号组(表):
    """型号列（第0列）按 merge 回落分组：型号原样 → 该型号各数据行号（保持书上顺序）"""
    out = {}
    for i in range(len(表['rows'])):
        m = _格(表, i, 0)
        if m is None:
            continue
        out.setdefault(str(m), []).append(i)
    return out


def _直径值(格):
    """轴孔直径格 → [(直径, 是否括号备用值)]。'12,14'→[(12,False),...]；'16,(17),18'→17 带括号标"""
    out = []
    for tok in str(格).replace(' ', '').split(','):
        if not tok:
            continue
        括号 = tok.startswith('(') and tok.endswith(')')
        v = 数值(tok.strip('()'))
        if v is not None:
            out.append((v, 括号))
    return out


def _规格dict(表, i, 额外=()):
    """数据行 i 的选型明细：轴孔直径 + 全部轴孔长度列（merge 回落），外加指定列"""
    js = [j for j, c in enumerate(表['cols'])
          if '轴孔直径' in str(c) or '轴孔长度' in str(c)]
    for kw in 额外:
        try:
            js.append(_列(表, kw))
        except KeyError:
            pass
    seen, js2 = set(), []
    for j in js:
        if j not in seen:
            seen.add(j)
            js2.append(j)
    return {str(表['cols'][j]): _格(表, i, j) for j in js2}


def _转矩组(表):
    """型号 → (公称转矩, 许用转速, [各行号], 转速全列dict)。转矩/转速取组内 merge 回落值。
    许用转速多列时（表8-4 不装/装罩壳）取最严（最小）值比对，全列原值随第四元返回。"""
    jtor = _列(表, '公称转矩')
    jspds = [j for j, c in enumerate(表['cols']) if '许用转速' in str(c)]
    out = {}
    for 型号, 行s in _型号组(表).items():
        全列 = {str(表['cols'][j]): _d(_格(表, 行s[0], j)) for j in jspds}
        out[型号] = (_d(_格(表, 行s[0], jtor)), min(全列.values()), 行s, 全列)
    return out


def _选型(表号, Tn):
    """给定需求转矩 → 该表内公称转矩 ≥ Tn 的最小档型号（零猜测不插值、不外推）。"""
    t = _表(表号)
    需求 = _d(Tn)
    组 = _转矩组(t)
    候选 = {型号: v for 型号, v in 组.items() if v[0] >= 需求}
    if not 候选:
        mx = max(v[0] for v in 组.values())
        raise ValueError(f"需求转矩 {需求:g} N·m 超过 {t['表名']} 最大档 {mx:g} N·m")
    best = min(v[0] for v in 候选.values())
    并列 = sorted(型号 for 型号, v in 候选.items() if v[0] == best)
    型号 = 并列[0]
    tor, spd, 行s, 转速全列 = 候选[型号]
    各档 = [_规格dict(t, i) for i in 行s]
    return {'品名': _联轴器表[表号], '型号': 型号, '公称转矩/(N·m)': tor,
            '许用转速/(r/min)': spd, '许用转速全列': 转速全列,
            '各档明细': 各档, '并列同转矩型号': 并列,
            '表号': 表号, '页': t['页'], '表名': t['表名']}



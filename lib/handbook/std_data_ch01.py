def _数(v):
    x = 数值(v)
    if x is None:
        return None
    x = round(x, 10)
    return int(x) if float(x).is_integer() else x


def _回落(t, i, j):
    """被合并格 → 合并区内的值（merges 4 元矩形，0-based）。

    书上合并格只有一个值，录库时可能落在区内任一格（居中/靠边都可能），
    故扫全区取首个非 None 值；全区皆 None 才返回 None。
    """
    for m in t.get("merges") or []:
        r0, r1, c0, c1 = int(m[0]), int(m[1]), int(m[2]), int(m[3] if len(m) >= 4 else m[2])
        if r0 <= i <= r1 and c0 <= j <= c1:
            for ii in range(r0, r1 + 1):
                for jj in range(c0, c1 + 1):
                    if t["data"][ii][jj] is not None:
                        return t["data"][ii][jj]
            return None
    return t["data"][i][j]


def _档(标签):
    """'>10~18' '~3' '≤5' '>100' '6~30' '25' → 判定闭包；解析不出返回 None"""
    s = str(标签).strip().replace('～', '~').replace(' ', '')
    m = re.match(r'^~(-?\d+(?:\.\d+)?)$', s)
    if m:
        a = float(m.group(1))
        return lambda v: v <= a
    m = re.match(r'^(≥|≤|>|<)(-?\d+(?:\.\d+)?)$', s)
    if m:
        a = float(m.group(2))
        return {'≥': lambda v: v >= a, '≤': lambda v: v <= a,
                '>': lambda v: v > a, '<': lambda v: v < a}[m.group(1)]
    m = re.match(r'^(>?)((-?\d+(?:\.\d+)?)~(-?\d+(?:\.\d+)?))$', s)
    if m:
        a, b = float(m.group(3)), float(m.group(4))
        if m.group(1):
            return lambda v: a < v <= b
        return lambda v: a <= v <= b
    m = re.match(r'^(-?\d+(?:\.\d+)?)$', s)
    if m:
        a = float(m.group(1))
        return lambda v: v == a
    return None



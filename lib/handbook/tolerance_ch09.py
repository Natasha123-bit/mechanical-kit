def 配合偏差(基本尺寸, 孔公差带, 轴公差带):
    """孔轴配合：上下偏差、最大间隙/过盈、配合性质。

    例：配合偏差(40, "H7", "k6") → 孔 +25/0、轴 +18/+2、过渡配合。
    最大间隙 = 孔上 − 轴下；最大过盈 = 轴上 − 孔下（取正值）。
    [核:p.116-119、p.111-115] 依据：表9-6 + 表9-5
    """
    h = 孔偏差(孔公差带, 基本尺寸)
    s = 轴偏差(轴公差带, 基本尺寸)
    ES, EI = h["上偏差/μm"], h["下偏差/μm"]
    es, ei = s["上偏差/μm"], s["下偏差/μm"]
    if EI >= es:
        性质 = "间隙配合"
    elif ES <= ei:
        性质 = "过盈配合"
    else:
        性质 = "过渡配合"
    return {
        "基本尺寸": _数(基本尺寸), "孔公差带": h["公差带"], "轴公差带": s["公差带"],
        "孔上偏差/μm": ES, "孔下偏差/μm": EI, "轴上偏差/μm": es, "轴下偏差/μm": ei,
        "最大间隙/μm": max(0, ES - ei), "最大过盈/μm": max(0, es - EI),
        "配合性质": 性质, "孔页": h["页"], "轴页": s["页"],
    }



def _数(v):
    x = 数值(v)
    if x is None:
        return None
    return int(x) if float(x).is_integer() else x


def _范围含(s, v):
    s = str(s).strip()
    if "~" in s:
        a, b = s.split("~", 1)
        lo = a.replace("—", "0").lstrip("≥>≤<")
        hi = b.replace("—", "0")
        return float(lo) < float(v) <= float(hi)
    if s.startswith("≤") or s.startswith("<="):
        return float(v) <= float(s.lstrip("≤<= "))
    if s.startswith("<"):
        return float(v) < float(s[1:])
    if s.startswith("≥") or s.startswith(">="):
        return float(v) >= float(s.lstrip("≥>= "))
    if s.startswith(">"):
        return float(v) > float(s[1:])
    try:
        return abs(float(v) - float(s)) < 1e-9
    except ValueError:
        return False


def _行按范围(表, v):
    rows = 表["rows"]
    for i, r in enumerate(rows):
        s = str(r).strip()
        if "~" in s:
            a, b = s.split("~", 1)
            lo = a.replace("—", "0").lstrip("≥>≤<")
            hi = b.replace("—", "0")
            if i == 0:
                if float(v) <= float(hi):
                    return r
            elif float(lo) < float(v) <= float(hi):
                return r
        elif s.startswith(("≤", "<")):
            if float(v) <= float(s.lstrip("≤< ")):
                return r
        elif s.startswith(("≥", ">")):
            if float(v) >= float(s.lstrip("≥> ")):
                return r
        else:
            try:
                if abs(float(v) - float(s)) < 1e-9:
                    return r
            except ValueError:
                pass
    raise ValueError(f"{表['表号']}（p.{表['页']}）没有能容纳 {v} 的档位")


def _列按范围(表, v):
    for c in 表["cols"]:
        if _范围含(c, v):
            return c
    raise ValueError(f"{表['表号']}（p.{表['页']}）没有能容纳 {v} 的尺寸列")


def _拆上下(s):
    s = str(s)
    if "/" in s:
        a, b = s.split("/", 1)
        return a, b
    return s, None



# ================================================================ L3 标注

def _偏差两段(偏差串):
    """"+0.009/-0.004" → ("+0.009", "-0.004")；None/无偏差 → (None, None)"""
    if not 偏差串:
        return None, None
    parts = str(偏差串).split("/")
    if len(parts) == 2:
        return parts[0].strip(), parts[1].strip()
    return str(偏差串).strip(), "0"


def 轴伸标注(D, 偏差=None, 长度E=None):
    """电机轴伸在配套件（联轴器/带轮/齿轮）孔上的标注串（调 _anno.尺寸）。

    轴伸标注("38", "+0.009/-0.004", "80") -> {"直径": "φ38+0.009/-0.004", "长度": "80"}
    偏差取自安装尺寸表的 D（极限偏差）列（表12-2~12-6/12-9~12-14/12-21~12-23）。
    """
    上, 下 = _偏差两段(偏差)
    出 = {"直径": _anno.尺寸(D, 上, 下, "φ") if 上 else _anno.尺寸(D, 前缀="φ")}
    if 长度E is not None:
        出["长度"] = _anno.尺寸(长度E)
    return 出


def 凸缘止口标注(N):
    """凸缘止口直径 N 的标注串（照书原样代号，如 "180j6"）→ "φ180j6"。

    表12-10（YZR IM3001/3003）N 列带 j6 公差照书；表12-14（YZ IM3001/3003）不带 j6——
    两表差异照书保留，本函数不添加也不剥离公差代号。
    """
    return _anno.尺寸(str(N).strip(), 前缀="φ")


def 电机明细表行(选型结果):
    """把 L2 选型结果变成装配图明细表的一行文字（机座号+功率+转速+安装形式）。

    电机明细表行({"型号": "132S-4", "功率/kW": 5.5, "同步转速/(r/min)": 1500, "极数": 4})
        -> "电机 YE3-132S-4 5.5kW 1500r/min IMB3"
    型号缺系列前缀时按书上命名规则补「Y-」（系列号由调用方给，缺省 YE3）。
    """
    型号 = str(选型结果["型号"]).strip()
    if not re.match(r"^(YX3|YE2|YE3|Y)[-\s]", 型号):
        型号 = f"{选型结果.get('系列', 'YE3')}-{型号}"
    段 = [型号, f"{_数键(选型结果['功率/kW'])}kW"]
    if 选型结果.get("同步转速/(r/min)") is not None:
        段.append(f"{int(选型结果['同步转速/(r/min)'])}r/min")
    段.append(str(选型结果.get("安装形式", "IMB3")).strip())
    return "电机 " + " ".join(段)



def _数键(x):
    """入参数值 → 串：5.5 → '5.5'；5.0 → '5'；'132S' → '132S'"""
    if isinstance(x, (int, float)) and not isinstance(x, bool):
        return str(int(x)) if float(x) == int(x) else str(x)
    return str(x).strip()


def _格回落(表, i, j):
    """读 data[i][j]，被合并的格回落到合并区首格（与 _lookup 内部同规）"""
    for m in 表.get("merges") or []:
        if len(m) >= 4:
            r0, r1, c0, c1 = int(m[0]), int(m[1]), int(m[2]), int(m[3])
        else:
            r0, r1, c0, c1 = int(m[0]), int(m[1]), int(m[2]), int(m[2])
        if r0 <= i <= r1 and c0 <= j <= c1:
            return 表["data"][r0][c0]
    return 表["data"][i][j]


def _整行(表, i):
    """第 i 行 → {列名: 值}（合并格已回落；None = 原表空白/破折号，照书不补）"""
    return {str(c): _格回落(表, i, j) for j, c in enumerate(表["cols"])}


def _规整机座号(x):
    """机座号入参规整：'Y132S-4'/'YE3-132S-4'→'132S'；'Y80'/'80'→'80'；'160M1'→'160M1'"""
    s = str(x).strip().upper()
    s = re.sub(r"^(?:YX3|YE2|YE3)[-\s]", "", s)
    s = re.sub(r"^Y(?=\d)", "", s)
    s = s.split("-")[0].strip()
    if not s:
        raise ValueError(f"机座号入参无法规整：{x!r}")
    return s


def _极数由转速(转速rpm):
    """同步转速 → 极数（照书：2极3000、4极1500、6极1000、8极750 r/min）。

    额定转速（如 1440）不是同步转速，书上未给 满载转速→极数 判据，抛 ValueError。
    """
    映 = {3000: 2, 1500: 4, 1000: 6, 750: 8}
    v = 数值(转速rpm)
    if v is None or int(v) not in 映:
        raise ValueError(f"转速 {转速rpm} r/min 不是同步转速（2极3000/4极1500/6极1000/8极750），"
                         "满载转速→极数书上未给判据，请直接提供 极数")
    return 映[int(v)]


def _查行唯一(表, 行键):
    """行标签必须唯一命中（不许子串猜、不许重复取首行）→ 行号；否则 ValueError"""
    键 = str(行键).strip()
    rows = [str(r).strip() for r in 表["rows"]]

    if D is not None:
        D键 = str(D).strip()
        目标 = None
        for i in 候选行:
            for tok in str(表["data"][i][1]).split(","):
                if tok.strip("() ") == D键:
                    目标 = i
                    break
            if 目标 is not None:
                break
        if 目标 is None:
            可选 = "/".join(str(表["data"][i][1]) for i in 候选行)
            raise ValueError(f"表7-14 d₁={键} 无 D={D}（可选：{可选}）")
    else:
        目标 = 候选行[0]
    b = _格回落(表, 目标, 2)
    # D 可选清单（聚合所有同名 d₁ 行）
    D可选 = []
    for i in 候选行:
        for tok in str(表["data"][i][1]).split(","):
            项 = {"D": tok.strip("() "), "国内补充规格": "(" in tok}
            if 项 not in D可选:
                D可选.append(项)
    型式说明 = None
    if m形:
        mm = re.search(型式 + r"型（([^）]+)）", m形.group(1))
        if mm:
            型式说明 = f"{型式}型（{mm.group(1)}）"
    D选定 = str(D).strip() if D is not None else None
    return {"d₁": 键, "D可选": D可选, "D选定": D选定, "b": b,
            "型式": 型式, "型式说明": 型式说明,
            "标注串": (唇形密封圈标记(型式, 键, D选定) if D选定 else None),
            "安装要求": 唇形密封圈安装要求(轴径d1=float(键), 基本宽度b=数值(b))}



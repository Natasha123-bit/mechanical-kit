def _温度范围(用途文本):
    """从表7-2 用途列原文解析印刷的温度范围 → (lo, hi, 原文片段)；未印温度 → None。

    钙基原文「工作温度低于55~60℃」为区间表述，函数保守取下端 55 作上限（选用时以原文为准）。
    """
    if not 用途文本:
        return None
    t = str(用途文本)
    m = re.search(r"低于(-?\d+)~(\d+)℃", t)
    if m:
        return (-float("inf"), float(m.group(1)), m.group(0))     # 保守取下端
    m = re.search(r"在(-?\d+)~(\d+)℃", t)
    if m:
        return (float(m.group(1)), float(m.group(2)), m.group(0))
    m = re.search(r"使用温度≤(-?\d+)℃", t)
    if m:
        return (-float("inf"), float(m.group(1)), m.group(0))
    m = re.search(r"使用温度为(-?\d+)~(\d+)℃", t)
    if m:
        return (float(m.group(1)), float(m.group(2)), m.group(0))
    return None



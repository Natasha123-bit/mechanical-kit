def _数键(x):
    """入参数值 → 行标字符串：40 / 40.0 → '40'；32.5 → '32.5'；'M10×1' → 原样"""
    if isinstance(x, (int, float)) and not isinstance(x, bool):
        return str(int(x)) if float(x) == int(x) else str(x)
    return str(x).strip()


def _格回落(表, i, j):
    """读 data[i][j]，被合并的格回落到合并区首格（与 _lookup 内部同规）"""
    for m in 表.get("merges") or []:
        if len(m) >= 4:
            r0, r1, c0, c1 = int(m[0]), int(m[1]), int(m[2]), int(m[3])
        else:
            r0, r1, c0, c1 = int(m[0]), int(m[1]), int(m[2]), int(m[2])
        if r0 <= i <= r1 and c0 <= j <= c1:
            return 表["data"][r0][c0]
    return 表["data"][i][j]



def 箱座壁厚验算(低速轴转矩T):
    """箱座壁厚经验式：δ = 2·⁴√(0.1T) mm，且 ≥8 mm（T 为低速轴转矩，N·m）。

    只有这一条经验式，不给取整规则；返回值是计算值，取整/圆整由设计者定。

    依据：第17章 五.1(1)1)，p.233。
    [核:p.233]
    """
    if 低速轴转矩T is None or float(低速轴转矩T) <= 0:
        raise ValueError("低速轴转矩 T 必须为正数")
    T = float(低速轴转矩T)
    δ = 2 * (0.1 * T) ** 0.25
    return {'δ计算': round(δ, 3), 'δ下限': 8.0, '采用下限': round(max(δ, 8.0), 3),
            '注': 'δ=2·⁴√(0.1T) ≥8；圆整规则书上未给', '页': 233}


def 轴承孔轴向尺寸(箱座壁厚δ, C1, C2):
    """箱体轴承孔处的轴向尺寸 L ≥ δ + C₁ + C₂ + (5~10) mm。

    C₁、C₂ 为扳手空间所决定的尺寸（表11-2、图11-1、图11-2）。
    书上给 5~10 的范围，本库返回区间，不拍数。

    依据：第17章 三.5(2)3)，p.222。
    [核:p.222]
    """
    if 箱座壁厚δ is None or C1 is None or C2 is None:
        raise ValueError("δ、C₁、C₂ 都必须给")
    base = float(箱座壁厚δ) + float(C1) + float(C2)
    return {'下限': round(base + 5, 3), '上限': round(base + 10, 3), '关系': '≥',
            '注': '书上给 L≥δ+C₁+C₂+(5~10) mm，末项取 5~10 由设计者定', '页': 222}



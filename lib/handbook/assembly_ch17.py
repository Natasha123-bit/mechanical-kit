def _速度上限(s):
    """'<3~5' -> 5.0；'<8' -> 8.0；'<30' -> 30.0。书上给范围时取范围上限，并在调用处注明。"""
    s = str(s).replace("<", "").replace("≤", "").strip()
    parts = [p for p in s.replace("~", "-").split("-") if p.strip()]
    try:
        return float(parts[-1])
    except (ValueError, IndexError):
        return None


def _温度上限(s):
    """'<90' -> 90；'<-40~100' -> 100（书上印 <-40~100，取其上端作适用上限）"""
    if s is None:
        return None
    s = str(s).replace("<", "").replace("≤", "").replace("℃", "").strip()
    if "~" in s:
        return float(s.split("~")[-1])
    try:
        return float(s)
    except ValueError:
        return None


def 密封方式选用(轴表面速度, 工作温度=None, 润滑剂=None):
    """按轴表面圆周速度与工作温度查表17-1，返回适用/不适用的密封方式。

    轴表面速度 m/s；工作温度 ℃（可不给）。表17-1 只给适用上限，且速度是范围写法
    （毡圈 <3~5 表示 3~5 之间由设计者定），所以返回的是**上限比较**结果，
    不是「一定合适」。径向迷宫密封原表未给工作温度，温度一栏返回 None。

    依据：表17-1，p.231。
    [核:p.231]
    """
    out = {'轴表面速度': 轴表面速度, '工作温度': 工作温度,
           '适用': [], '不适用': [], '温度待判': [], '说明': '表17-1 给的是适用上限；'
           '毡圈"<3~5"、迷宫"<5"为书上原样范围/上限，取值需设计者定。“温度待判”= 速度已过、'
           '但原表温度一栏是定性文字或空白，不能直接比大小'}
    for 方式 in 表17_1_密封速度温度['cols'][1:]:
        v_txt = 取(表17_1_密封速度温度, '适用的轴表面圆周速度/(m/s)', 方式)
        t_txt = 取(表17_1_密封速度温度, '适用的工作温度/℃', 方式)
        v_max = _速度上限(v_txt)
        item = {'密封方式': 方式, '速度限值': v_txt, '温度限值': t_txt}
        ok_v = v_max is not None and float(轴表面速度) <= v_max
        ok_t = True
        if 工作温度 is not None:
            t_max = _温度上限(t_txt)
            ok_t = None if t_max is None else (float(工作温度) <= t_max)
        if not ok_v:
            out['不适用'].append(item)
        elif ok_t is True:
            out['适用'].append(item)
        elif ok_t is None:
            out['温度待判'].append(item)
        else:
            out['不适用'].append(item)
    return out



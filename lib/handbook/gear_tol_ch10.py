def _段含(段, v, 变量):
    """'5≤d≤20' / '50<d≤125' / '2<m≤3.5' → 是否含 v。"""
    s = str(段).replace(" ", "").replace("m_n", "m")
    import re
    m = re.match(r"^(\d+(?:\.\d+)?)\s*(≤|<)\s*" + 变量 + r"\s*(≤|<)\s*(\d+(?:\.\d+)?)$", s)
    if not m:
        return False
    lo, op1, op2, hi = float(m.group(1)), m.group(2), m.group(3), float(m.group(4))
    return (lo <= v if op1 == "≤" else lo < v) and (v <= hi if op2 == "≤" else v < hi)



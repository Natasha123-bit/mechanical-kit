def _数(v):
    """表值 → int/float；破折号/空白（已存 None）返回 None。"""
    x = 数值(v)
    if x is None:
        return None
    return int(x) if float(x).is_integer() else x


def _区间(s):
    """'12~60' -> (12.0, 60.0)；'200' -> (200.0, 200.0)。"""
    s = str(s).strip()
    if "~" in s:
        a, b = s.split("~", 1)
        return float(a), float(b)
    return float(s), float(s)


def _系列集合(s):
    """长度系列串 → 数值集合。

    支持 '6, 8, 10'、'40~75(5 进位),85,100'、'6~32(2 进位),35~100(5 进位)'。
    只用于校验“设计者给的 L 是否在书上系列内”，不用于插值。
    """
    out = set()
    for part in str(s).replace("，", ",").split(","):
        p = part.strip()
        if not p:
            continue
        m = re.match(r"^(\d+(?:\.\d+)?)\s*~\s*(\d+(?:\.\d+)?)\s*\(\s*(\d+(?:\.\d+)?)\s*进位\s*\)$", p)
        if m:
            a, b, step = float(m.group(1)), float(m.group(2)), float(m.group(3))
            x = a
            while x <= b + 1e-9:
                out.add(round(x, 6))
                x += step
        else:
            out.add(float(p))
    return out


def _校长度(L, 范围串, 系列串, 名称):
    """L 必须在表给的 [l_min, l_max] 内且落在长度系列上；缺省返回 None。"""
    if L is None:
        return None
    L = float(L)
    lo, hi = _区间(范围串)
    if not (lo <= L <= hi):
        raise ValueError(f"{名称} 的 l 范围为 {范围串}，收到 l={L:g}")
    if 系列串 and L not in _系列集合(系列串):
        raise ValueError(f"{名称} 的 l={L:g} 不在书上长度系列内（{系列串}）")
    return _数(L)


def _列(表, d):
    """按数值找列名（销表的列头是 d 的数值）；找不到抛 ValueError。"""
    for c in 表["cols"]:
        try:
            if abs(float(c) - float(d)) < 1e-9:
                return c
        except (TypeError, ValueError):
            continue
    raise ValueError(f"{表['表号']}（p.{表['页']}）没有 d={d:g} 这一档")


def _直(表, i, j):
    """直接读第 i 行第 j 列。

    仅用于书上同一行标签重复出现（如两个 'd h10' 的 min/max 行）且该格
    本身不是合并续格的情形；这些行由核读时确认值都印在本行。
    """
    v = 表["data"][i][j]
    if v is None:
        raise KeyError(f"{表['表号']} 第{i}行第{j}列是空值（核读时该格应已印值）")
    return v


def _偏差对(s):
    """'+0.2/0' -> ('+0.2', '0')；'±0.018' -> ('±0.018', None)。"""
    s = str(s).strip()
    if "/" in s:
        a, b = s.split("/", 1)
        return a, b
    return s, None



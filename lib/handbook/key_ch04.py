def 矩形花键选型(d, 系列="中", 装配形式="固定", 精度="一般", 内d公差带=None):
    """矩形花键选型（表4-3，p.58）。

    d 只有 18,21,23,26,28,32,36,42,46,52,56,62,72,82,92,102；轻系列没有
    d=18、21（书上该两行轻系列为空）。返回 N×d×D×B、C、r、d1min、amin
    与内/外花键公差带。

    公差带：一般用取 3 行（f7/g7/h7），精密传动用取 6 行（f5/g5/h5/f6/g6/h6）；
    按装配形式（滑动/紧滑动/固定）选行。精密块内同一装配形式有两行
    （内花键 d=H5 或 H6），用 内d公差带 消歧，未给时取前一行 H5/H7。
    注2 的两条例外（H7/H9、H6/H7 允许提高一级配合）写在返回的 注 里。

    [核:p.58] 依据：表4-3（GB/T 1144—2001 摘录）
    """
    if 系列 not in ("轻", "中"):
        raise ValueError("系列只支持 轻/中")
    if 精度 not in ("一般", "精密"):
        raise ValueError("精度只支持 一般/精密")
    d = float(d)
    row = None
    for r in 表4_3_矩形花键["rows"]:
        if abs(float(r) - d) < 1e-9:
            row = r
            break
    if row is None:
        raise ValueError("表4-3（p.58）小径 d 只有 18,21,23,26,28,32,36,42,46,52,56,62,72,82,92,102，"
                         f"收到 d={d:g}")
    if 系列 == "轻" and d in (18, 21):
        raise ValueError("表4-3（p.58）轻系列没有 d=18、21（书上该两行轻系列为空）")
    pre = 系列 + "系列/"
    规格 = 取(表4_3_矩形花键, row, pre + "规格 N×d×D×B")
    N, dd, D, B = (int(x) for x in str(规格).split("×"))
    C = _数(取(表4_3_矩形花键, row, pre + "C"))
    r = _数(取(表4_3_矩形花键, row, pre + "r"))
    d1min = _数(取(表4_3_矩形花键, row, pre + "参考 d₁ₘᵢₙ"))
    amin = _数(取(表4_3_矩形花键, row, pre + "参考 aₘᵢₙ"))

    tab = 表4_3_花键公差带
    block = tab["rows"][:3] if 精度 == "一般" else tab["rows"][3:]
    cands = [x for x in block if 取(tab, x, "装配形式") == 装配形式]
    if not cands:
        raise ValueError(f"表4-3 精度={精度} 没有装配形式={装配形式}")
    if 内d公差带 is not None:
        cands = [x for x in cands if 取(tab, x, "内花键/d") == 内d公差带]
        if not cands:
            raise ValueError(f"表4-3 精度={精度}、装配形式={装配形式} 没有内花键 d={内d公差带}")
    trow = cands[0]
    内B1 = 取(tab, trow, "内花键/B/拉削后不热处理")
    if 精度 == "一般":
        内B = f"{内B1}(拉削后不热处理)/{取(tab, trow, '内花键/B/拉削后热处理')}(拉削后热处理)"
    else:
        内B = f"{内B1}（控制键侧间隙取 H7，一般取 H9）"
    return {
        "N": N, "d": _数(dd), "D": D, "B": B, "C": C, "r": r,
        "d1min": d1min, "amin": amin, "规格串": str(规格),
        "内花键d": 取(tab, trow, "内花键/d"),
        "内花键D": 取(tab, trow, "内花键/D"),
        "内花键B": 内B,
        "外花键d": 取(tab, trow, "外花键/d"),
        "外花键D": 取(tab, trow, "外花键/D"),
        "外花键B": 取(tab, trow, "外花键/B"),
        "注": "表4-3 注1：精密传动内花键需控制键侧间隙时槽宽取 H7，一般取 H9；"
              "注2：d 为 H6/H7 的内花键允许与提高一级的外花键配合。",
    }



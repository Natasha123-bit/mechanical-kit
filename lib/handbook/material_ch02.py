def 按用途选材料(用途关键词):
    """用途关键词（如 '齿轮'、'轴'、'阀壳'）→ 命中「应用举例/应用/用途」列的候选牌号列表。
    [核:各表应用列]

    关键词对应用列原文做包含匹配（大小写不敏感）；同一 (表号, 牌号) 多行命中去重留首条。
    表2-1 是热处理方法词条（行标签=方法名），牌号原样返回方法名。查不到 → ValueError。
    """
    kw = str(用途关键词).strip().lower()
    if not kw:
        raise ValueError('用途关键词不能为空')
    out = []
    seen = set()
    for 表号, 列关键词 in _用途列.items():
        t = _表(表号)
        j = _列(t, 列关键词)
        模型 = _性能表.get(表号, 'row')  # 表2-1 热处理方法词条不在 _性能表，按 'row' 取行标签
        for i in range(len(t['rows'])):
            cell = _格(t, i, j)
            if cell is None or kw not in str(cell).lower():
                continue
            if 模型 == '17' and str(t['rows'][i]).startswith(_17分块):
                continue
            牌列 = 0 if 模型 != 'col1' else 1
            牌 = _格(t, i, 牌列)
            key = (表号, _牌号norm(牌))
            if key in seen:
                continue
            seen.add(key)
            out.append({'表号': 表号, '页': t['页'], '牌号': 牌, '应用原文': str(cell)})
    if not out:
        raise ValueError(f"全章应用列没有含 {用途关键词!r} 的材料（覆盖表：{list(_用途列)}）")
    return out


# 「按强度选钢」允许的表（同一口径内比较，不跨表混）——铸铁/铸造合金/有色/塑料不参与
_钢表Rm = {'表2-5': '抗拉强度 R_m', '表2-6': '抗拉强度 R_m', '表2-7': '抗拉强度 R_m',
          '表2-8': '抗拉强度 R_m', '表2-9': '抗拉强度 R_m', '表2-10': '抗拉强度'}


def 按强度选钢(Rm下限, 表号=None):
    """Rm 下限（MPa）→ 满足「抗拉强度 ≥ 下限」的牌号，按表分组返回、不跨表混口径。
    [核:表2-5~2-10]

    表号给 None 则逐钢表各报一组（dict 键=表号）；给具体表号则只比该表
    （合法档：list(_钢表Rm)）。Rm 取数规则（照书口径）：数值格直取；'375~460' 范围
    取下限；'≥590' 取 590——这些列本身即「不小于/最小值」类书载下限。书上空白/「—」
    格不参与（零猜测）。返回 {表号: [{'牌号':.., 'Rm/MPa（书载下限）': v}, ...]}。
    """
    thr = 数值(Rm下限)
    if thr is None:
        raise ValueError(f"Rm下限 {Rm下限!r} 不是数值")
    if 表号 is not None and 表号 not in _钢表Rm:
        raise ValueError(f"{表号!r} 不是本章钢的性能表（合法档：{list(_钢表Rm)}）")
    out = {}
    for 表号2, 列关键词 in _钢表Rm.items():
        if 表号 is not None and 表号2 != 表号:
            continue
        t = _表(表号2)
        j = _列(t, 列关键词)
        rows = []
        for i in range(len(t['rows'])):
            v = 数值(_格(t, i, j))
            if v is None or v < thr:
                continue
            项 = {'牌号': _格(t, i, 0) if 表号2 != '表2-10' else _格(t, i, 1),
                  'Rm/MPa（书载下限）': v}
            if 表号2 == '表2-6':
                项['等级'] = _格(t, i, 1)
            rows.append(项)
        if rows:
            out[表号2] = rows
    if not out:
        raise ValueError(f"没有钢的抗拉强度下限 ≥ {thr:g} MPa（范围：{list(_钢表Rm)}）")
    return out



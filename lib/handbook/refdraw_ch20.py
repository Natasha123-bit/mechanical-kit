def 零件图标注(图号, 含未核=False):
    """某张零件工作图的逐条标注。默认只返回 confidence=='verified' 的条目。

    依据：第20章 p.268–271 页图。
    [核:p.268–271]
    """
    g = _图(图号)
    items = g['标注']
    if 含未核:
        return list(items)
    return [x for x in items if x['confidence'] == 'verified']


def 全部条目():
    """五张图全部条目（含未核），按 图号/条目 顺序。"""
    out = []
    for g in 零件工作图:
        for x in g['标注']:
            out.append({'图号': g['图号'], **x})
    return out


def 图上条目数(图号=None):
    """条目计数：{'总数':…, 'verified':…, 'partial':…}"""
    pool = 全部条目() if 图号 is None else [x for x in 全部条目() if x['图号'] == 图号]
    return {'总数': len(pool),
            'verified': sum(1 for x in pool if x['confidence'] == 'verified'),
            'partial': sum(1 for x in pool if x['confidence'] != 'verified')}


def 未核项(图号=None):
    """未核/图-表不一致的条目清单（含图号）。"""
    return [x for x in 全部条目()
            if x['confidence'] != 'verified' or str(x['复核']).startswith('图-表不一致')]


def 取标注(图号, 位置关键词):
    """按位置关键词取一条标注；命中未核项直接 raise（零猜测红线）。"""
    cand = [x for x in _图(图号)['标注'] if 位置关键词 in x['位置']]
    if not cand:
        raise KeyError(f"{图号} 没有位置含 {位置关键词!r} 的条目")
    if len(cand) > 1:
        raise KeyError(f"{图号} 位置含 {位置关键词!r} 的条目有 {len(cand)} 条，请写细一点")
    x = cand[0]
    if x['confidence'] != 'verified':
        raise NotImplementedError(f"待核：{图号}「{x['位置']}」— {x['注'] or x['复核']}")
    return x



def 复核配合(公称尺寸, 孔公差带, 轴公差带):
    """用 ch09 的极限偏差表反算图上配合，返回标注串 + 上下偏差。

    例：复核配合(100, 'H7', 'h6') / 复核配合(60, 'H7', 'r6')
    [核:p.243]
    """
    import tolerance_ch09 as _t
    孔 = _t.孔偏差(孔公差带, 公称尺寸)
    轴 = _t.轴偏差(轴公差带, 公称尺寸)
    return {'标注': _anno.配合标注(公称尺寸, 孔公差带, 轴公差带),
            '孔': f"+{孔['上偏差/μm']}/{孔['下偏差/μm']}",
            '轴': f"+{轴['上偏差/μm']}/{轴['下偏差/μm']}",
            '孔页': 孔['页'], '轴页': 轴['页']}


def 复核键槽(公称直径, 键长=None, 配合='正常'):
    """用 ch04 的表4-1 反算键与键槽（b×h、t/t₁、轴槽/毂槽组合尺寸、公差带）。

    图20-5 的 18±0.0215 / 64.4+0.2/0、图20-6 的 18 0/-0.043、12 0/-0.043 /
    53、37 都由这里出。
    [核:p.56]
    """

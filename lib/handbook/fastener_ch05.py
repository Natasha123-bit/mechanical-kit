def _表(表号):
    """按表号取本章 L1 表 dict"""
    for _name in _表变量:
        t = globals()[_name]
        if t['表号'] == 表号:
            return t
    raise KeyError(f'本章没有 {表号}')


def _格(表, i, j):
    """merge 感知的取格：落点在合并区则回落首格；首格本身为 None（书上「—」/空白区）返回 None 不抛异常"""
    for m in 表.get('merges') or []:
        r0, r1, c0, c1 = (m[0], m[1], m[2], m[2]) if len(m) < 4 else (m[0], m[1], m[2], m[3])
        if r0 <= i <= r1 and c0 <= j <= c1:
            return 表['data'][r0][c0]
    return 表['data'][i][j]


def _d(x):
    v = 数值(x)
    if v is None:
        raise ValueError(f"规格 {x!r} 不是可识别的数值规格")
    return v


def _规格行(表, x):
    """按数值匹配行标签（'25*'、'(17)'、20、'120' 均可）；唯一才给，查不到/重码都列合法档"""
    v = _d(x)
    hits = [i for i, r in enumerate(表['rows']) if 数值(r) == v]
    if len(hits) == 1:
        return hits[0]
    if not hits:
        raise ValueError(f"{表['表号']} 没有规格 {x}（合法档：{表['rows']}）")
    raise ValueError(f"{表['表号']} 规格 {x} 命中多行 {hits}（合法档：{表['rows']}）")


def _行dict(表, i, 列集=None):
    """整行 → {列名: 值}（合并格回落首格）；列集给 (起,止) 半开区间则只取该段"""
    lo, hi = 列集 or (0, len(表['cols']))
    return {表['cols'][j]: _格(表, i, j) for j in range(lo, hi)}


def _规格列(表, x, 起列=1):
    """转置表：按数值匹配列标签（表5-8 的规格沿列向排）；唯一才给"""
    v = _d(x)
    hits = [j for j in range(起列, len(表['cols'])) if 数值(表['cols'][j]) == v]
    if len(hits) == 1:
        return hits[0]
    legal = 表['cols'][起列:]
    if not hits:
        raise ValueError(f"{表['表号']} 没有规格列 {x}（合法档：{legal}）")
    raise ValueError(f"{表['表号']} 规格 {x} 命中多列 {hits}（合法档：{legal}）")


def _圆螺母规格(s):
    """归一化螺纹规格写法：'m10x1*' 与 'M10×1' 同判；尾部 *（仅滚动轴承锁紧装置标记）不参与匹配"""
    s = str(s).strip().upper().replace('X', '×')
    return s.rstrip('*').strip()



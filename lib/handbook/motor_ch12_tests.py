    for 名称, fn in CASES:
        try:
            fn()
            通过 += 1
        except Exception:  # noqa: BLE001
            失败.append((名称, traceback.format_exc()))
    for 名称, tb in 失败:
        print(f"[失败] {名称}\n{tb}")
    print(f"合计：通过 {通过} 项，失败 {len(失败)} 项")
    sys.exit(1 if 失败 else 0)



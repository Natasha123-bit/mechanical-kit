def _数(v):
    """表里的数值字符串 → int/float；带≈、M、×、~ 的原样返回字符串。float 统一 round 到 6 位。"""
    if isinstance(v, (int, float)):
        f = round(float(v), 6)
        return int(f) if f.is_integer() else f
    if v is None:
        return None
    s = str(v).strip()
    if s.startswith("≈") or "~" in s or "×" in s or s.startswith("M"):
        return s
    try:
        f = round(float(s), 6)
    except ValueError:
        return s
    return int(f) if f.is_integer() else f


def _范围(v):
    """'12~16' -> (12, 16)；'5' -> (5, 5)；已是 tuple 原样。"""
    if isinstance(v, tuple):
        return v
    if isinstance(v, (int, float)):
        return (v, v)
    s = str(v).strip()
    if "~" in s:
        a, b = s.split("~", 1)
        return (_数(a), _数(b))
    x = _数(s)
    return (x, x)


def _元组(v):
    return tuple(_数(x) for x in v)


def _加(v, k):
    lo, hi = _范围(v)
    return (_数(lo + k), _数(hi + k))


def _乘(v, k):
    lo, hi = _范围(v)
    return (_数(lo * k), _数(hi * k))


def _区间行(表, 值, 行子集=None):
    """按 '45~65' 这类纯数字区间行取 row 标签；返回 (行标签, 行dict)。"""
    v = float(值)
    rows = 表["rows"] if 行子集 is None else 行子集
    for r in rows:
        s = str(r)
        if "~" not in s:
            continue
        a, b = s.split("~", 1)
        if float(a) <= v <= float(b):
            return r, 行(表, r)
    raise ValueError(f"{表.get('表号')} 没有能容纳 {值} 的区间行（{rows}）")


def _格式(v):
    if isinstance(v, tuple) and len(v) == 2:
        if v[0] == v[1]:
            return _格式(v[0])
        return f"{_格式(v[0])}~{_格式(v[1])}"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)



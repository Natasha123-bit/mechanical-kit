def 蜗杆长度(d, d1, da2, d2, m, z2, 变位=False):
    """蜗杆结构尺寸（表11-8，p.170）：L≥2m√(z₂+1)（不变位）或 L≥√(d_a2²+d₂²)（变位）。

    返回最小长度 L_min；d1 只用于判断车制/铣制条件（d₁-d≥2~4 mm 为车制）。
    [核:p.170] 依据：表11-8
    """
    if 变位:
        L = math.sqrt(float(da2) ** 2 + float(d2) ** 2)
        式 = "L≥√(d_a2²+d_2²)（变位）"
    else:
        L = 2 * float(m) * math.sqrt(float(z2) + 1)
        式 = "L≥2m√(z₂+1)（不变位）"
    return {
        "L_min": _数(L), "式": 式,
        "车制条件": f"d₁-d={float(d1) - float(d):g} mm（车制要求 2~4 mm）",
        "注": "d_a2—蜗轮顶圆直径；m—模数；d₂—蜗轮分度圆直径",
    }


def 蜗轮结构尺寸(d, d1, d2, m, d5=None, b=None, da1=None, z1=1):
    """蜗轮结构尺寸（表11-9，p.171）。z1=1/2~3/4 决定 D_w、B 的上限。

    返回范围；D₀ 需 d₅、b 才给，d₆ 由强度计算（返回 None）。
    [核:p.171] 依据：表11-9
    """
    d = float(d); d1 = float(d1); d2 = float(d2); m = float(m)
    d3 = (_数(1.6 * d), _数(1.8 * d))
    l = (_数(1.2 * d), _数(1.8 * d))
    d4 = (_数(max(1.2 * m, 6)), _数(max(1.5 * m, 6)))
    l1 = (3 * d4[0], 3 * d4[1])
    a = b2 = max(2 * m, 10)
    C = max(1.5 * m, 10)
    da2 = d2 + 2 * m
    if z1 == 1:
        Dw = da2 + 2 * m
    elif z1 in (2, 3):
        Dw = da2 + 1.5 * m
    elif z1 == 4:
        Dw = da2 + m
    else:
        raise ValueError("z1 只支持 1、2~3、4")
    Bmax = None
    if da1 is not None:
        Bmax = 0.75 * float(da1) if z1 in (1, 2, 3) else 0.67 * float(da1)
    D0 = None
    if d5 is not None and b is not None:
        D0 = 0.5 * (float(d5) - 2 * float(b) + d3[0])
    return {
        "d3": d3, "l": l, "d4": d4, "l1": _元组(l1),
        "a": _数(a), "b": _数(b2), "C": _数(C), "x": (1, 3), "e": 10,
        "n": (2, 3), "R1": _数(0.5 * (d1 + 2.4 * m)), "R2": _数(0.5 * (d1 - 2 * m)),
        "da2": _数(da2), "2γ": (90, 110), "D0": _数(D0) if D0 is not None else None,
        "d6": None, "f": _数(1.7 * m), "R": (4, 5),
        "Dw_max": _数(Dw), "B_max": _数(Bmax) if Bmax is not None else None,
        "注": "d₆按强度计算确定；d₅、d₇、d₀、n₁、r由结构确定；D₀=0.5(d₅-2b+d₃)",
    }



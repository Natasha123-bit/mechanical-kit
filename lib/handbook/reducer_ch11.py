def 内壁间距(b大1, b大2, δ2=12.0, Δ=10.0):
    """箱体内壁间距 Lw = δ2 + b大1 + Δ + b大2 + δ2（展开式两级，p.164 表11-1 布置口径）。

    b大1、b大2 是**两个大齿轮**的齿宽（mm）：小齿轮比大齿轮宽 5 mm，别拿 b₁ 代 b₂。
    本例：12 + 61 + 10 + 92 + 12 = 187。

    [核:本例实测] 187.0 mm（设计测试/calc/s3_shaft.json 的 布置.Lw）
    """
    b大1, b大2, δ2, Δ = float(b大1), float(b大2), float(δ2), float(Δ)
    for 名, v in (("b大1", b大1), ("b大2", b大2), ("δ2", δ2), ("Δ", Δ)):
        if v <= 0:
            raise ValueError(f"{名} 必须为正，收到 {v!r}")
    return _数(δ2 + b大1 + Δ + b大2 + δ2)


def 齿轮位置(级, b大1, b大2, δ2=12.0, Δ=10.0):
    """齿轮中心到**左内壁**的距离 c（mm）。级：1=高速级，2=低速级（展开式）。

    c₁ = δ2 + b大1/2
    c₂ = δ2 + b大1 + Δ + b大2/2
    本例：c₁ = 42.5、c₂ = 129。

    [核:本例实测] 42.5 / 129.0（s3_shaft.json 的 布置.c_高速级 / c_低速级）
    """
    if 级 not in (1, 2):
        raise ValueError("级只支持 1（高速级）或 2（低速级）")
    内壁 = 内壁间距(b大1, b大2, δ2, Δ)   # 顺带做 b/δ2/Δ 为正的校验
    if 级 == 1:
        c = float(δ2) + float(b大1) / 2
    else:
        c = float(δ2) + float(b大1) + float(Δ) + float(b大2) / 2
    assert 0 < c < 内壁, f"齿轮中心 {c} 应在内壁间距 {内壁} 之内（构造上恒成立，走到这里说明公式被改坏）"
    return _数(c)


def 轴承跨距(内壁Lw, T轴承, Δ1=5.0):
    """轴承中心跨距 L = Lw + 2(Δ1 + T/2)，mm。

    T 取**轴承装配高**（表6-7 的 T 列，不是宽度 B）：30207 T=18.25、30212 T=23.75，
    换来 L = 215.25 / 220.75。
    Δ1 是轴承内端面到箱体内壁的间隙（本例 5，表11-1 只给 Δ1 > 1.2δ 的下限）。

    [核:本例实测] 215.25 / 220.75（s3_shaft.json 的 跨度）
    """
    内壁Lw, T轴承, Δ1 = float(内壁Lw), float(T轴承), float(Δ1)
    if 内壁Lw <= 0 or T轴承 <= 0:
        raise ValueError("内壁间距与轴承装配高都必须为正")
    if Δ1 < 0:
        raise ValueError("Δ1 不能为负")
    return _数(内壁Lw + 2 * (Δ1 + T轴承 / 2))


def 力学臂(跨距L, 齿轮中心c, T轴承, Δ1=5.0):
    """简化力学模型的两段臂长 (a, b)，mm。

    a = Δ1 + T/2 + c（支点A到齿轮中心）   b = L − a
    本例：a = 5 + 11.875 + 129 = 145.875、b = 74.875（L = 220.75）。

    [核:本例实测] (145.875, 74.875)（s3_shaft.json 的 低速轴受力.a / .b）
    """
    跨距L, 齿轮中心c, T轴承, Δ1 = float(跨距L), float(齿轮中心c), float(T轴承), float(Δ1)
    if 跨距L <= 0 or T轴承 <= 0:
        raise ValueError("跨距与轴承装配高都必须为正")
    a = Δ1 + T轴承 / 2 + 齿轮中心c
    b = 跨距L - a
    if not (0 < a < 跨距L) or b <= 0:
        raise ValueError(f"力学臂不合理：a={a}、b={b}、跨距={跨距L}（齿轮中心或跨距给错）")
    return (_数(a), _数(b))


def 布置(b大1, b大2, T轴承, 级=2, δ2=12.0, Δ=10.0, Δ1=5.0):
    """一次算全：内壁间距 / 齿轮中心 / 跨距 / 力学臂 a、b。

    参数
    ----
    b大1, b大2 : 高速级、低速级大齿轮齿宽 mm
    T轴承      : 该轴轴承的装配高 mm（表6-7）
    级         : 1=高速级轴，2=低速级轴
    δ2, Δ      : 齿轮端面到内壁、两级大齿轮端面间距（经验值，本例 12/10）
    Δ1         : 轴承内端面到内壁（本例 5）

    返回 dict：内壁间距、齿轮中心、跨距、a、b、以及回代用的入参。

    [核:本例实测] 低速级 30212：187 / 129 / 220.75 / 145.875 / 74.875
    """
    Lw = 内壁间距(b大1, b大2, δ2, Δ)
    c = 齿轮位置(级, b大1, b大2, δ2, Δ)
    L = 轴承跨距(Lw, T轴承, Δ1)
    a, b = 力学臂(L, c, T轴承, Δ1)
    return {
        "内壁间距": Lw, "齿轮中心": c, "跨距": L, "a": a, "b": b,
        "级": 级, "b大1": _数(float(b大1)), "b大2": _数(float(b大2)),
        "T轴承": _数(float(T轴承)), "δ2": _数(float(δ2)), "Δ": _数(float(Δ)), "Δ1": _数(float(Δ1)),
        "注": "δ2/Δ/Δ1 为结构布置经验取值，表11-1 只给下限；小齿轮比大齿轮宽 5 mm，b 别取错。",
    }

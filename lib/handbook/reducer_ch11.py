def 地脚螺钉数目(a=None, 形式="齿轮", 底凸缘周长=None):
    """地脚螺钉数目 n（表11-1，p.164）。

    齿轮减速器：a≤250→4；a>250~500→6；a>500→8。
    蜗杆减速器：4。
    锥齿轮减速器：n=底凸缘周长之半/(200~300)≥4；未给周长返回 None，给了返回整数范围。
    [核:p.164] 依据：表11-1「地脚螺钉数目」行
    """
    if 形式 == "蜗杆":
        return 4
    if 形式 == "锥齿轮":
        if 底凸缘周长 is None:
            return None
        lo = max(4, math.ceil(float(底凸缘周长) / 2 / 300))
        hi = max(4, math.ceil(float(底凸缘周长) / 2 / 200))
        return (lo, hi)
    if a is None:
        raise ValueError("齿轮减速器要给定中心距 a")
    a = float(a)
    if a <= 250:
        return 4
    if a <= 500:
        return 6
    return 8



"""_demo_l3.py —— L1→L2→L3 三层闭环的最小演示（不是章库，只是接口样板）

数据只用 p.56 页图上核过的表4-1 前三档（vision 复核过）：
    6~8    → b×h 2×2,  t 1.2, t1 1.0, r 0.08~0.16
    >8~10  → b×h 3×3,  t 1.8, t1 1.4, r 0.08~0.16
    >10~12 → b×h 4×4,  t 2.5, t1 1.8
跑法：python3 _demo_l3.py
ZCode 的 ch04 章库应当长成这个样子，只是把表补全到 d=500。
"""
import sys
from collections import namedtuple
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lookup import 区间取, 取, 校验  # noqa: E402
from _anno import 尺寸, 配合标注, 键槽标注, 圆角    # noqa: E402

表4_1_平键 = {
    "表号": "表4-1",
    "表名": "平键连接的剖面和键槽尺寸、普通平键的形式和尺寸",
    "页": 56,
    "单位": "mm",
    "rows": ["6~8", ">8~10", ">10~12"],
    "cols": ["轴d", "键b×h", "键b", "宽度b/轴H9", "宽度b/毂D10", "深度t", "深度t1", "半径r/最小"],
    "data": [
        ["6~8", "2×2", 2, "+0.025/0", "+0.060/+0.020", 1.2, 1.0, 0.08],
        [">8~10", "3×3", 3, None, None, 1.8, 1.4, 0.08],
        [">10~12", "4×4", 4, None, None, 2.5, 1.8, 0.08],
    ],
    "merges": [[0, 2, 3], [0, 2, 4], [0, 2, 7]],   # 公差带与 r 三档合并（页图上就是合并格）
    "注": "演示用子表：只抄 p.56 前三档；宽度公差与 r 为纵向合并格，已登记 merges",
}

键规格 = namedtuple("键规格", "b h t t1 r 轴槽 毂槽 键标记")


def 平键选型(d, 键长=None, 配合="正常"):
    """轴径 d → 键 b×h、槽深及偏差、键标记。依据：表4-1 [核:p.56]

    配合：松/正常/紧密 → 轴槽与毂槽的宽度公差带（H9 / N9+JS9 / P9），本演示只回公差带代号。
    """
    if d <= 0:
        raise ValueError("轴径必须为正")
    try:
        bh = 区间取(表4_1_平键, d, "键b×h")
        b = float(区间取(表4_1_平键, d, "键b"))
        t = float(区间取(表4_1_平键, d, "深度t"))
        t1 = float(区间取(表4_1_平键, d, "深度t1"))
        r = 区间取(表4_1_平键, d, "半径r/最小")
    except KeyError:
        raise ValueError(f"表4-1 只抄到 d=12，d={d} 需补全表值后再选型")
    h = float(bh.split("×")[1])
    return 键规格(
        b=int(b), h=int(h), t=t, t1=t1, r=r,
        轴槽=尺寸(t, "+0.1", "0"),
        毂槽=尺寸(t1, "+0.1", "0"),
        键标记=键槽标注(int(b), int(h), 键长 or "L"),
    )


if __name__ == "__main__":
    print("表结构体检：", 校验(表4_1_平键) or "通过")
    print("合并格回落（>10~12 行的宽度公差取自首行）：", 取(表4_1_平键, ">10~12", "宽度b/轴H9"))

    s = 平键选型(8, 键长=25)
    print(f"\nd=8 选型：键 {s.b}×{s.h}，轴槽深 {s.轴槽}，毂槽深 {s.毂槽}，"
          f"圆角 {圆角(s.r)}，标记「{s.键标记}」")

    # 图上要写的三处标注，全部由 L3 生成（偏差值由 ch09 查表给出，这里不编）
    print("轴上键槽标注：", f"{配合标注(8, 'H7', 'k6')}（偏差待 ch09 填） 槽宽 {s.b}N9，槽深 {s.轴槽}")
    print("轮毂键槽标注：", f"槽宽 {s.b}JS9，槽深 {s.毂槽}")
    print("技术要求条目：", "未注圆角 R0.08~0.16（表4-1 半径 r）")

    for bad in (35, 150):
        try:
            平键选型(bad)
        except ValueError as e:
            print(f"\nd={bad} 被拒绝：{e}")

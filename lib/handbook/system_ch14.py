def 设计功率(P_w, η):
    """式14-1（p.199）：P_d = P_w / η。

    P_w：工作机所需（输入）功率，kW；η：电动机至工作机之间传动装置的总效率
    （概略值用 总效率() 连乘，或查 ch01 表1-5）；返回 P_d：所需电动机（动力机）
    功率，kW。单位不做自动换算。
    P_w ≤ 0 或 η 不在 (0, 1]（含 η≤0、η>1）→ ValueError，不静默返回 0。
    """
    P_w = float(P_w)
    η = float(η)
    if P_w <= 0.0:
        raise ValueError(f'式14-1 工作机功率 P_w={P_w!r} 非法（应 >0），不静默返回 0')
    if not (0.0 < η <= 1.0):
        raise ValueError(f'式14-1 总效率 η={η!r} 非法（应 0<η≤1），不静默返回 0')
    return P_w / η


def 工作机功率_力(F, v, η_w=1.0):
    """式14-2（p.199）：P_w = F·v / (1000·η_w)。

    F：工作机阻力，N；v：工作机线速度，m/s；η_w：工作机自身的效率
    （默认 1.0）；返回 P_w：工作机所需输入功率，kW。单位不做自动换算。
    F < 0、v < 0 或 η_w ≤ 0 → ValueError；F=0 或 v=0 属正常边界（算式得 0）。
    """
    F = float(F)
    v = float(v)
    η_w = float(η_w)
    if F < 0.0:
        raise ValueError(f'式14-2 阻力 F={F!r} N 非法（应 ≥0）')
    if v < 0.0:
        raise ValueError(f'式14-2 线速度 v={v!r} m/s 非法（应 ≥0）')
    if η_w <= 0.0:
        raise ValueError(f'式14-2 效率 η_w={η_w!r} 非法（应 >0）')
    return (F * v) / (1000.0 * η_w)


def 工作机功率_扭矩(T, n_w, η_w=1.0):
    """式14-3（p.199）：P_w = T·n_w / (9550·η_w)。

    T：工作机扭矩，N·m；n_w：工作机转速，r/min；η_w：工作机自身的效率
    （默认 1.0）；返回 P_w：工作机所需输入功率，kW（9550 为手册口径的
    功率-扭矩-转速换算常数）。单位不做自动换算。
    T < 0、n_w ≤ 0 或 η_w ≤ 0 → ValueError，不静默返回 0。
    """
    T = float(T)
    n_w = float(n_w)
    η_w = float(η_w)
    if T < 0.0:
        raise ValueError(f'式14-3 扭矩 T={T!r} N·m 非法（应 ≥0）')
    if n_w <= 0.0:
        raise ValueError(f'式14-3 转速 n_w={n_w!r} r/min 非法（应 >0），不静默返回 0')
    if η_w <= 0.0:
        raise ValueError(f'式14-3 效率 η_w={η_w!r} 非法（应 >0）')
    return (T * n_w) / (9550.0 * η_w)


def 总效率(η列表):
    """式14-4（p.199）：η = η_0·η_1·η_2·…·η_n。

    η列表：传动系统中每个传动副、每对轴承、每个联轴器的效率，按顺序传
    list 或 tuple（概略值查 ch01 表1-5；每传动副/轴承对/联轴器都乘进去）；
    返回总效率，round 到 4 位小数。
    空（非 list/tuple 或长度 0）、任一因子 ≤0 或 >1 → ValueError，
    不静默返回 0。
    """
    if not isinstance(η列表, (list, tuple)) or len(η列表) == 0:
        raise ValueError(f'式14-4 η列表={η列表!r} 非法（应传非空 list/tuple），不静默返回 0')
    η = 1.0
    for k, x in enumerate(η列表, 1):
        x = float(x)
        if not (0.0 < x <= 1.0):
            raise ValueError(f'式14-4 第 {k} 个效率因子 {x!r} 非法（应 0<x≤1），不静默返回 0')
        η *= x
    return round(η, 4)


def 电动机转速范围(i范围列表, n_w):
    """式14-5（p.200）：n_d = i′·n_w = (i′_1·i′_2·…·i′_n)·n_w。

    i范围列表：各级传动的合理传动比范围 [(下限, 上限), …]，逐级列出
    （概略值查 ch01 表1-6 或本章表14-2，可用 单级传动比范围() 取）；n_w：
    工作机转速，r/min；返回 (下限, 上限)：各取下限连乘 ×n_w、各取上限
    连乘 ×n_w，即同步转速可取区间的两端（电机极对数选择用，倾向同步
    1500/1000 r/min，见 p.200–201）。单位不做自动换算。
    空列表、n_w ≤ 0、某级不是二元、某级传动比 ≤0 或下限>上限 → ValueError。
    """
    if not isinstance(i范围列表, (list, tuple)) or len(i范围列表) == 0:
        raise ValueError(f'式14-5 i范围列表={i范围列表!r} 非法（应传非空 list/tuple）')
    n_w = float(n_w)
    if n_w <= 0.0:
        raise ValueError(f'式14-5 工作机转速 n_w={n_w!r} r/min 非法（应 >0）')
    下 = 1.0
    上 = 1.0
    for k, it in enumerate(i范围列表, 1):
        if not isinstance(it, (list, tuple)) or len(it) != 2:
            raise ValueError(f'式14-5 第 {k} 级传动比范围 {it!r} 应为 (下限, 上限) 二元')
        a = float(it[0])
        b = float(it[1])
        if a <= 0.0 or b < a:
            raise ValueError(f'式14-5 第 {k} 级传动比范围 ({a!r}, {b!r}) 非法（应 0<下限≤上限）')
        下 *= a
        上 *= b
    return (下 * n_w, 上 * n_w)

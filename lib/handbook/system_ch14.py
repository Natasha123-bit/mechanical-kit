def _格(表, i, j):
    """merge 感知取格：落点在合并区（3 元纵/4 元矩形）则回落首格"""
    for m in 表.get('merges') or []:
        r0, r1, c0, c1 = (m[0], m[1], m[2], m[2]) if len(m) < 4 else (m[0], m[1], m[2], m[3])
        if r0 <= i <= r1 and c0 <= j <= c1:
            return 表['data'][r0][c0]
    return 表['data'][i][j]


def _行号(表, 行键):
    """行查找：'/' 与 '／' 双向归一（'单级传动比/常用值' 与书上 '／' 等价；
    '功率/kW' 两侧同归一不受影响）"""
    rows = [str(r).strip().replace('/', '／') for r in 表['rows']]
    key = str(行键).strip().replace('/', '／')
    if key in rows:
        return rows.index(key)
    cand = [i for i, r in enumerate(rows) if key in r]
    if len(cand) == 1:
        return cand[0]
    raise ValueError(f"{表['表号']} 找不到行 {行键!r}（合法档：{表['rows']}）")



def 单级传动比范围(传动机构, 档='常用值', 齿式=None):
    """传动机构单级传动比 → {'原文','最小','最大'}（表14-2「单级传动比」两行）。
    [核:表14-2 p.200]

    档：'常用值' 或 '最大值'。齿轮传动仍须给 齿式（常用值 圆柱 3~5 / 锥 2~3；
    最大值 圆柱 8 / 锥 5）。范围照书是「阶梯推荐」，不是插值基点。
    """
    if 档 not in ('常用值', '最大值'):
        raise ValueError(f"档 只能是 '常用值'/'最大值'（实收 {档!r}）")
    原文 = 传动机构性能(传动机构, f'单级传动比／{档}', 齿式=齿式)
    s = str(原文).replace(' ', '')
    for 前缀 in ('圆柱', '锥'):
        if s.startswith(前缀):
            if 传动机构 == '齿轮传动' and 齿式 != 前缀:
                raise ValueError(f'齿轮传动 常用值格印着 {原文!r}，与齿式 {齿式!r} 不符')
            s = s[len(前缀):]
    m = re.match(r'^(\d+(?:\.\d+)?)~(\d+(?:\.\d+)?)$', s)
    if m:
        lo, hi = float(m.group(1)), float(m.group(2))
    else:
        m1 = re.match(r'^\d+(?:\.\d+)?$', s)   # 「最大值」行书上就是单值（5、7、8、80…）
        if not m1:
            raise ValueError(f'{传动机构} {档} 传动比 {原文!r} 不是「a~b」或单值，无法给范围')
        lo = hi = float(s)
    return {'传动机构': 传动机构, '齿式': 齿式, '档': 档, '原文': 原文,
            '最小': lo, '最大': hi}



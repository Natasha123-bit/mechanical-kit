def 退刀槽与收尾(螺距):
    """螺距 → 普通螺纹收尾、肩距、退刀槽、倒角关键值。[核:表3-25，p.53]

    返回外螺纹（收尾 X、肩距 a、退刀槽 g₂/g₁/r≈/d_g）与内螺纹（G₁、R≈、D_g）主用档（「一般」档）。
    """
    t = _表('表3-25')
    v = _d(螺距)
    hits = [i for i in range(len(t['rows'])) if 数值(t['rows'][i]) == v]
    if len(hits) != 1:
        raise ValueError(f"表3-25 螺距 {螺距} 命中 {len(hits)} 行")
    i = hits[0]
    def c(后缀):
        for j, name in enumerate(t['cols']):
            if name.endswith(后缀):
                return j
        raise KeyError(后缀)
    r = {'螺距P': v}
    for 键, 后缀 in [('外螺纹收尾 X max（一般）', '收尾 X max / 一般'),
                    ('外螺纹肩距 a max（一般）', '肩距 a max / 一般'),
                    ('外螺纹退刀槽 g₂ max', '退刀槽 g_2 max'),
                    ('外螺纹退刀槽 g₁ min', '退刀槽 g_1 min'),
                    ('外螺纹退刀槽 r≈', '退刀槽 r ≈'),
                    ('外螺纹退刀槽 d_g', '退刀槽 d_g'),
                    ('内螺纹收尾 X max（一般）', '内螺纹 收尾 X max / 一般'),
                    ('内螺纹退刀槽 G₁（一般）', '内螺纹 退刀槽 G_1 / 一般'),
                    ('内螺纹退刀槽 R≈', '内螺纹 退刀槽 R ≈'),
                    ('内螺纹退刀槽 D_g', '内螺纹 退刀槽 D_g')]:
        r[键] = _格(t, i, c(后缀))
    r['出处'] = f'表3-25，p.{t["页"]}（GB/T 3—1997 摘录）'
    return r




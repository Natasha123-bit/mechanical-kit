def _表(表号):
    """按表号取本章 L1 表 dict"""
    for _name in _表变量:
        t = globals()[_name]
        if t['表号'] == 表号:
            return t
    raise KeyError(f'本章没有 {表号}')


def _格(表, i, j):
    """merge 感知的取格：落点在合并区则回落首格；首格本身为 None（书上「—」区）返回 None 不抛异常"""
    for m in 表.get('merges') or []:
        r0, r1, c0, c1 = (m[0], m[1], m[2], m[2]) if len(m) < 4 else (m[0], m[1], m[2], m[3])
        if r0 <= i <= r1 and c0 <= j <= c1:
            return 表['data'][r0][c0]
    return 表['data'][i][j]


def _d(x):
    v = 数值(x)
    if v is None:
        raise ValueError(f"规格 {x!r} 不是可识别的数值规格")
    return v


def _规格列(表, 规格):
    """按规格数值定位规格列（兼容 'M12'/'(M14)'/'12'/'(14)' 写法）；唯一才给，重码报错"""
    v = _d(规格)
    hits = [j for j, c in enumerate(表['cols']) if j >= 1 and 数值(c) == v]
    if len(hits) == 1:
        return hits[0]
    raise ValueError(f"{表['表号']} 找不到唯一规格列 {规格!r}（命中 {hits}，列名 {表['cols']}）")


def _行标格(表, i, j):
    return _格(表, i, j)


def _区间含(s, x):
    """'16~22' / '130' / '40~120' 数值区间含 x；解析不出返回 False"""
    s = str(s).strip()
    m = re.match(r'^(-?\d+(?:\.\d+)?)\s*~\s*(-?\d+(?:\.\d+)?)$', s.replace('～', '~'))
    if m:
        return float(m.group(1)) <= x <= float(m.group(2))
    v = 数值(s)
    return v is not None and v == x


def _系列含(系列串, x):
    """'6,8,10,12,16,20~70(5进位),80~160(10进位),180~360(20进位)' 类系列串是否含整数 x"""
    x = int(x)
    for seg in re.split(r'[，,、]', str(系列串)):
        seg = seg.strip()
        if not seg:
            continue
        step_note = re.search(r'[（(](\d+)进位[）)]', seg)
        seg = re.sub(r'[（(][^）)]*[）)]', '', seg).strip()
        if '~' in seg or '～' in seg:
            lo_s, hi_s = re.split(r'[~～]', seg)
            lo, hi = 数值(lo_s), 数值(hi_s)
            if lo is None or hi is None:
                continue
            if not (lo <= x <= hi):
                continue
            if step_note:
                step = int(step_note.group(1))
                if (x - int(lo)) % step != 0:
                    continue
            return True
        else:
            v = 数值(seg)
            if v is not None and v == x:
                return True
    return False



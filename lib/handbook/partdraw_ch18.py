def 轴表面Ra(加工表面, 圆周速度=None):
    """轴加工表面的 Ra 推荐值（表18-2）。

    加工表面取表内整串或唯一子串（'轮毂'、'轴承'、'平键键槽'、'密封'）。
    「密封处的表面」必须给圆周速度，按 表18-2b 的档取值；速度超出 >5~10 档抛 ValueError
    （原表只到 >5~10）。
    表内写「见表 6-14」的，返回 依据='表6-14'、值=None，不代查。
    书上给「3.2，1.6 或 0.8，0.4」这类并列候选，原样返回，不替设计者挑一个。

    依据：表18-2 / 表18-2b，p.250–251。
    [核:p.250]
    """
    r = 行(表18_2_轴加工表面Ra, 加工表面)
    名 = r['加工表面']
    if 名 == '密封处的表面':
        if 圆周速度 is None:
            raise ValueError("表18-2「密封处的表面」要按与轴接触处的圆周速度分档，请给 圆周速度")
        v = float(圆周速度)
        if v <= 3:
            档 = '≤3'
        elif v <= 5:
            档 = '>3~5'
        elif v <= 10:
            档 = '>5~10'
        else:
            raise ValueError("表18-2b 速度档只到 >5~10 m/s，超出请另选密封型式")
        return {'加工表面': 名, '圆周速度档': 档,
                'Ra': 取(表18_2_密封处, '密封处的表面', 档), '页': 251,
                '注': '≤3 档属毡封油圈列；>3~5、>5~10 属橡胶油封列；末列「间隙及迷宫」不按速度分'}
    v = r['表面粗糙度 Ra/μm']
    out = {'加工表面': 名, 'Ra': v, '页': 250 if 名 in (
        '与传动件及联轴器等轮毂相配合的表面', '与 G、E 级滚动轴承相配合的表面') else 251}
    if v and v.startswith('见表'):
        out['依据'] = '表6-14'
        out['注'] = '原表指向表6-14（滚动轴承配合面粗糙度），本库不代查'
    elif v and '  ' in v:
        out['注'] = '原表一格两段（工作面/非工作面），照原样返回'
    else:
        out['注'] = '书上给并列候选值，原样返回，取值需设计者定'
    return out



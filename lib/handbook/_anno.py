# -*- coding: utf-8 -*-
"""_anno.py — 图样标注层：把查表结果变成能直接画到零件图上的东西

《机械设计课程设计手册》的用法不是「查个数」，是**画图时每一处标注都要有出处**。
所以 handbook 各章库除了保真的表字典，还要给出「标注对象」：

    尺寸       → (60, "+0.030", "0")            -> "φ60+0.030/0"
    配合       → 由 ch09 查表得偏差，交给 配合标注
    形位       → ["◎", "φ0.015", "A-B"]        -> gbdraw.TOL_FRAME(cells=[...])
    粗糙度     → "Ra1.6"                        -> gbdraw.ROUGH(x, y, "Ra1.6")
    技术要求   → ["1. 调质…", "2. 未注圆角 R3…"] -> 直接画进图右下角
    未注公差   → "未注尺寸公差按 GB/T 1804-m"

接口约定：**返回字符串或字符串列表**，字段与 `mdkit/draw/gbdraw.py` 的参数对齐
（`TOL_FRAME(cells=[...])`、`ROUGH(x, y, "Ra…")`、`T(x, y, s)`）。不要在这里画图，
也不要引入 SVG；画图是 gbdraw 的事。

偏差写法沿用书上的「上/下」两段，用 `/` 连接，缺省一侧写 0 或省略：
    "+0.030/0"、"+0.1/0"、"+0.0215/-0.0215"、"-0.004/-0.029"
**不要**把 `±0.0125` 拆成两段——书上就这么印的，照抄。

来源：标注规则见手册第9章（极限与配合、几何公差、表面粗糙度）、第10章（齿轮精度）、
第18章（零件工作图要求）；图例见第20章（图20-5 齿轮、20-6 轴、20-8 箱盖、20-9 箱座）。
"""
from __future__ import annotations

__all__ = [
    "尺寸", "配合标注", "形位", "基准", "粗糙度", "技术要求", "未注公差",
    "倒角", "圆角", "退刀槽", "中心孔", "键槽标注", "齿轮检验表头",
]

# 手册表9-8 的几何特征符号（只收零件图常用的，全部出自该表）
形位符号 = {
    "直线度": "—", "平面度": "▱", "圆度": "○", "圆柱度": "⌭",
    "线轮廓度": "⌒", "面轮廓度": "⌓", "平行度": "∥", "垂直度": "⊥",
    "倾斜度": "∠", "位置度": "⌖", "同轴度": "◎", "对称度": "⌯",
    "圆跳动": "↗", "全跳动": "⌅",
}


def _sgn(v):
    """偏差数值 → 带正负号的字符串；'0' 原样保留，'—' 原样保留"""
    if v is None:
        return None
    if isinstance(v, str):
        return v
    return f"{v:+.3f}".rstrip("0").rstrip(".").replace("-0", "-0") if v else "0"


def 尺寸(公称, 上偏差=None, 下偏差=None, 前缀="", 单位=""):
    """基本尺寸 + 上下偏差 → 图样标注串。

    尺寸(60, "+0.030", "0", "φ")  -> "φ60+0.030/0"
    尺寸(60)                     -> "60"              （无偏差，只给基本尺寸）
    尺寸(40, "±0.0125", None, "φ")-> "φ40±0.0125"     （对称偏差原样写，不拆两段）
    """
    head = f"{前缀}{公称}"
    if 上偏差 is None and 下偏差 is None:
        return head + 单位
    if 下偏差 is None or str(上偏差).startswith(("±", "±")):
        return f"{head}{上偏差}{单位}"
    return f"{head}{上偏差}/{下偏差}{单位}"


def 配合标注(公称, 孔代号, 轴代号, 前缀="φ"):
    """配合代号 → "φ40H7/k6"（偏差值由 ch09 查表给出，这里只管写法）"""
    return f"{前缀}{公称}{孔代号}/{轴代号}"


def 形位(项目, 公差值, *基准, 直径=True):
    """几何公差框格 → ["◎", "φ0.015", "A-B"]

    形位("同轴度", 0.015, "A-B")        -> ["◎", "φ0.015", "A-B"]
    形位("平行度", 0.02, "A", 直径=False) -> ["∥", "0.02", "A"]
    """
    if 项目 not in 形位符号:
        raise KeyError(f"表9-8 里没有几何特征 {项目!r}；常用：{list(形位符号)}")
    cells = [形位符号[项目]]
    v = f"{公差值:g}" if isinstance(公差值, (int, float)) else str(公差值)
    cells.append(("φ" if 直径 else "") + v)
    cells.extend(str(b) for b in 基准)
    return cells


def 基准(字母):
    """基准字母 → "A"（gbdraw.DATUM(x, y, label="A") 直接吃）"""
    return str(字母).upper()


def 粗糙度(ra):
    """Ra 值 → "Ra1.6"；值必须来自表9-13/9-14 的系列，或表9-15 的加工方法对应值"""
    v = f"{ra:g}" if isinstance(ra, (int, float)) else str(ra).replace("Ra", "")
    return f"Ra{v}"


def 技术要求(*条目, 起始号=1):
    """技术要求条目 → 自动编号的列表（图上顺序照抄，不要自己加条目）

    技术要求("调质处理后硬度 220~250HBW", "未注圆角半径为 R3") ->
        ["1. 调质处理后硬度 220~250HBW", "2. 未注圆角半径为 R3"]
    """
    out = []
    for i, s in enumerate(条目, 起始号):
        s = str(s).strip().rstrip("；;。")
        out.append(f"{i}. {s}；")
    return out


def 未注公差(等级="m", 类别="尺寸"):
    """GB/T 1804 未注公差 → "未注尺寸公差按 GB/T 1804-m"（等级 f/m/c/v 见表9-7）"""
    if 等级 not in {"f", "m", "c", "v"}:
        raise KeyError(f"表9-7 只有 f/m/c/v 四级，收到 {等级!r}")
    return f"未注{类别}公差按 GB/T 1804-{等级}"


def 倒角(c):
    """倒角 → "C1.5"（表1-25 零件倒圆与倒角）"""
    return f"C{c:g}" if isinstance(c, (int, float)) else f"C{c}"


def 圆角(r):
    """圆角 → "R3"（表1-25 / 表1-26）"""
    return f"R{r:g}" if isinstance(r, (int, float)) else f"R{r}"


def 退刀槽(宽, 深=None, 型式=""):
    """退刀槽 → "3×0.5" 或 "3×0.5（表1-20 插齿空刀槽 型式A）"；尺寸必须来自表1-20/1-23"""
    s = f"{宽:g}" if isinstance(宽, (int, float)) else str(宽)
    if 深 is not None:
        s += f"×{深:g}" if isinstance(深, (int, float)) else f"×{深}"
    return s + (f"（{型式}）" if 型式 else "")


def 中心孔(型号="B", d="4", 标准="GB/T 4459.5"):
    """中心孔标记 → "2×GB/T 4459.5-B4/12.5"（表1-17/1-18；图上按需加数量前缀）"""
    return f"{标准}-{型号}{d}"


def 键槽标注(b, h, L, 标准="GB/T 1096", 圆头=True):
    """平键标记 → "键 8×7×40 GB/T 1096"（表4-1；A型圆头省略，B型平头写 "B 8×7×40"）"""
    head = "键" if 圆头 else "键 B"
    return f"{head} {b}×{h}×{L} {标准}"


def 齿轮检验表头(精度等级, 标准="GB/T 10095.1"):
    """齿轮检验项目表的表头行 → "精度等级 7 GB/T 10095.1"（图20-5/20-7 右上角那块表）"""
    return f"精度等级 {精度等级} {标准}"


if __name__ == "__main__":
    assert 尺寸(60, "+0.030", "0", "φ") == "φ60+0.030/0"
    assert 尺寸(60) == "60"
    assert 尺寸(40, "±0.0125", None, "φ") == "φ40±0.0125"
    assert 配合标注(40, "H7", "k6") == "φ40H7/k6"
    assert 形位("同轴度", 0.015, "A-B") == ["◎", "φ0.015", "A-B"]
    assert 形位("平行度", 0.02, "A", 直径=False) == ["∥", "0.02", "A"]
    assert 粗糙度(1.6) == "Ra1.6" and 粗糙度("Ra3.2") == "Ra3.2"
    assert 技术要求("调质处理后硬度 220~250HBW", "未注圆角半径为 R3") == [
        "1. 调质处理后硬度 220~250HBW；", "2. 未注圆角半径为 R3；"]
    assert 未注公差("m") == "未注尺寸公差按 GB/T 1804-m"
    assert 倒角(1.5) == "C1.5" and 圆角(3) == "R3"
    assert 退刀槽(3, 0.5) == "3×0.5"
    assert 中心孔("B", "4") == "GB/T 4459.5-B4"
    assert 键槽标注(8, 7, 40) == "键 8×7×40 GB/T 1096"
    assert 齿轮检验表头(7) == "精度等级 7 GB/T 10095.1"
    try:
        形位("不存在的项目", 0.01, "A")
    except KeyError:
        pass
    else:
        raise AssertionError("未收录的形位项目应抛 KeyError")
    print("_anno.py 自检通过")

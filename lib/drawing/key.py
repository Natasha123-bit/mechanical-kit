# ------------------------------------------------------------------ 内部工具
def _弧点(cx, cy, r, a1, a2, n=36):
    """沿圆弧采样成点列（度，a1→a2 线性，可为负角）。"""
    step = (a2 - a1) / n
    return [(cx + r * math.cos(math.radians(a1 + step * i)),
             cy + r * math.sin(math.radians(a1 + step * i))) for i in range(n + 1)]


def _轴剖矩形槽(r, 槽半宽, 槽底, n=64):
    """轴断面（圆）扣掉顶部矩形键槽后的剖面区顶点表。"""
    if 槽底 >= math.sqrt(r * r - 槽半宽 ** 2):
        raise ValueError("槽底必须低于槽壁与圆面的交点，否则键槽不成形")
    y交 = math.sqrt(r * r - 槽半宽 ** 2)
    a1 = math.degrees(math.atan2(y交, 槽半宽))
    a2 = 180.0 - a1 - 360.0
    return ([(槽半宽, 槽底), (槽半宽, y交)] + _弧点(0, 0, r, a1, a2, n)
            + [(-槽半宽, y交), (-槽半宽, 槽底)])


def _轴剖圆槽(r, 槽心y, 槽r, n=64):
    """轴断面扣掉顶部半圆键槽后的剖面区顶点表（月牙槽）。"""
    y交 = (r * r + 槽心y ** 2 - 槽r ** 2) / (2.0 * 槽心y)
    if not (-r < y交 < r):
        raise ValueError("半圆槽与轴断面不相交：检查 h 与 t1")
    x交 = math.sqrt(max(r * r - y交 ** 2, 0.0))
    # 轴外圆：自左交点逆时针绕底部到右交点（a2 取 +360 保证 a2>a1、弧长 <180°）
    a1 = math.degrees(math.atan2(y交, -x交))
    a2 = math.degrees(math.atan2(y交, x交)) + 360.0
    # 槽弧：自右交点顺时针经槽底回到左交点（角度递减，扫角 121.8°）
    b1 = math.degrees(math.atan2(y交 - 槽心y, x交))
    b2 = math.degrees(math.atan2(y交 - 槽心y, -x交))
    pts = _弧点(0, 0, r, a1, a2, n)              # 轴外圆
    pts += _弧点(0, 槽心y, 槽r, b1, b2, n)       # 槽弧（经槽底）
    return pts


def _环剖(右, R, r内, 槽半宽, 槽顶, n=64):
    """轮毂断面剖面区的一半（右半或左半），避开顶部矩形槽。"""
    if 槽顶 >= math.sqrt(R * R - 槽半宽 ** 2):
        raise ValueError("槽顶过高：轮毂壁容不下键槽")
    s = 1.0 if 右 else -1.0
    y外 = math.sqrt(R * R - 槽半宽 ** 2)
    a1 = math.degrees(math.atan2(y外, s * 槽半宽))
    a2, i1 = (-90.0, -90.0) if 右 else (270.0, 270.0)
    return ([(0.0, 槽顶), (s * 槽半宽, 槽顶), (s * 槽半宽, y外)]
            + _弧点(0, 0, R, a1, a2, n)
            + [(0.0, -R), (0.0, -r内)]
            + _弧点(0, 0, r内, i1, 90.0, n)
            + [(0.0, r内)])


def _断面骨架(R轮, r, 槽半宽, 槽底, 键顶, 槽顶, 键半宽, cx):
    """A—A 断面的公共画法：轴圆、槽、键、轮毂圆 + 剖面线 + 十字中心线。

    键顶 < 槽顶 时画两条线（顶部有间隙）；键顶 == 槽顶 时只画一条（楔键顶面贴合）。
    """
    g = 图形()
    有间隙 = 槽顶 - 键顶 > 1e-9
    y上 = 槽顶 if 有间隙 else 键顶
    # 轴断面 + 键槽
    g.加(圆(cx, 0, r), 线(cx - 槽半宽, 槽底, cx - 槽半宽, r),
         线(cx + 槽半宽, 槽底, cx + 槽半宽, r), 线(cx - 槽半宽, 槽底, cx + 槽半宽, 槽底))
    # 键（不剖）：两侧面与槽壁重合 → 只画一条线；顶面一条线
    g.加(线(cx - 键半宽, 槽底, cx - 键半宽, 键顶), 线(cx + 键半宽, 槽底, cx + 键半宽, 键顶),
         线(cx - 键半宽, 键顶, cx + 键半宽, 键顶))
    # 轮毂 + 轮毂键槽（间隙存在时才有第二条顶线）
    y轮 = math.sqrt(R轮 ** 2 - 槽半宽 ** 2)
    g.加(圆(cx, 0, R轮),
         线(cx - 槽半宽, y上, cx - 槽半宽, y轮), 线(cx + 槽半宽, y上, cx + 槽半宽, y轮))
    if 有间隙:
        g.加(线(cx - 槽半宽, 槽顶, cx + 槽半宽, 槽顶))
    # 剖面线：轴 45°、轮毂 -45°（两零件方向相反）；键不画剖面线
    轴区 = [(x + cx, y) for x, y in _轴剖矩形槽(r, 槽半宽, 槽底)]
    g.加(剖面线(轴区, 剖面间距, 45.0),
         剖面线([(x + cx, y) for x, y in _环剖(右=True, R=R轮, r内=r, 槽半宽=槽半宽, 槽顶=y上)],
                剖面间距, -45.0),
         剖面线([(x + cx, y) for x, y in _环剖(右=False, R=R轮, r内=r, 槽半宽=槽半宽, 槽顶=y上)],
                剖面间距, -45.0))
    g.加(线(cx - R轮 - 4, 0, cx + R轮 + 4, 0, "center"),
         线(cx, -R轮 - 4, cx, R轮 + 4, "center"))
    return g


# ------------------------------------------------------------------ 9 平键
def 平键连接画法(d=30.0, b=8.0, h=7.0, L=25.0, t1=None):
    """普通平键连接（主视 + A—A 断面）。

    依据：图8-38 p.238 [核]（普通平键连接画法；键槽尺寸见图8-37 p.238 [核]）
      键不剖（键内无剖面线），轴为实心件按不剖；键顶面与轮毂键槽顶面之间有间隙
      → **两条线**；键两侧面是工作面，配合后只画一条线。
    t1（轴槽深）默认 0.6h ——**示例值，实际查附表19**；键长 L、键宽 b、键高 h 亦按附表19。
    """
    t1 = 0.6 * h if t1 is None else t1
    r = d / 2.0
    R轮 = 轮毂半径系数 * d
    间隙 = max(0.4, 间隙系数 * d)
    if not (0 < t1 < h):
        raise ValueError("t1 必须落在 (0, h) 内")
    槽底 = r - t1
    键顶 = 槽底 + h
    槽顶 = 键顶 + 间隙
    槽半宽 = b / 2.0
    L轴 = L + 2 * b
    x键 = b
    cx = L轴 + 1.4 * R轮

    g = 图形()
    # 主视：轴（上母线在键槽处断开）、轴线
    g.加(线(0, r, x键, r), 线(x键 + L, r, L轴, r),
         线(0, -r, L轴, -r),
         线(0, -r, 0, r), 线(L轴, -r, L轴, r))
    # 键槽底 + 轮毂
    g.加(线(x键, 槽底, x键 + L, 槽底),
         线(0, R轮, L轴, R轮), 线(0, -R轮, L轴, -R轮),
         线(0, r, 0, R轮), 线(0, -R轮, 0, -r),
         线(L轴, r, L轴, R轮), 线(L轴, -R轮, L轴, -r))
    # 键（矩形，不剖）
    g.加(矩形(x键, 槽底, L, h))
    # 键顶面 与 轮毂槽顶面：两条线（顶部间隙）
    g.加(线(x键, 槽顶, x键 + L, 槽顶))
    g.加(线(0, 0, L轴 + 4, 0, "center"))
    # A—A 断面
    g.加(_断面骨架(R轮, r, 槽半宽, 槽底, 键顶, 槽顶, 槽半宽, cx))

    g.注(f"平键 b×h×L = {b:g}×{h:g}×{L:g}（GB/T 1096，查附表19）",
         f"轴槽深 t1={t1:g}（默认 0.6h，示例值，实际查附表19）；d−t1={d - t1:g}",
         "键不剖、轴不剖；键顶面与轮毂槽顶面画两条线（顶部有间隙）",
         "键两侧面为工作面，配合后只画一条线；键无剖面线")
    g.范围(0, -R轮, cx + R轮 + 4, R轮)
    return g


# ------------------------------------------------------------------ 10 半圆键
def 半圆键连接画法(d=30.0, b=8.0, h=7.0):
    """半圆键（月牙键）连接（主视 + A—A 断面）。

    依据：图8-39 p.238 [核]（半圆键连接图）
      键为月牙形、不剖；顶部同样有间隙 → 两条线；轴上半圆槽轮廓粗实线。
    t1（槽深）页图未给数值，此处取 0.7h（示意值，实际按半圆键标准查表）。
    """
    r = d / 2.0
    t1 = 0.7 * h
    R轮 = 轮毂半径系数 * d
    间隙 = max(0.4, 间隙系数 * d)
    if not (0 < t1 < h):
        raise ValueError("h 过小，半圆槽不成形")
    槽心y = r - t1 + h            # 键的平顶 = 圆心高度（半圆半径 = h）
    键顶 = 槽心y
    槽顶 = 键顶 + 间隙
    槽半宽 = b / 2.0
    槽底 = r - t1
    x槽 = b + 0.5 * (d + b)
    L轴 = x槽 + 2.0 * b
    cx = L轴 + 1.4 * R轮
    # 槽弧与轴圆交点
    y交 = (r * r + 槽心y ** 2 - h * h) / (2.0 * 槽心y)
    x交 = math.sqrt(max(r * r - y交 ** 2, 0.0))
    a槽1 = math.degrees(math.atan2(y交 - 槽心y, -x交)) + 360.0   # 209.1°（左交点）
    a槽2 = math.degrees(math.atan2(y交 - 槽心y, x交)) + 360.0    # 330.9°（右交点），扫角 121.8°

    g = 图形()
    # 主视：轴（上母线在槽口断开）
    g.加(线(0, r, x槽 - x交, r), 线(x槽 + x交, r, L轴, r),
         线(0, -r, L轴, -r), 线(0, -r, 0, r), 线(L轴, -r, L轴, r))
    # 半圆槽（月牙下弧，粗实线）
    g.加(弧(x槽, 槽心y, h, a槽1, a槽2))
    # 键：槽弧即键的下表面（配合面，一条线）+ 平顶
    g.加(线(x槽 - x交, 键顶, x槽 + x交, 键顶))
    # 轮毂 + 轮毂槽顶面（两条线 = 顶部间隙）
    g.加(线(x槽 - x交, 槽顶, x槽 + x交, 槽顶),
         线(0, R轮, L轴, R轮), 线(0, -R轮, L轴, -R轮),
         线(0, r, 0, R轮), 线(0, -R轮, 0, -r),
         线(L轴, r, L轴, R轮), 线(L轴, -R轮, L轴, -r))
    g.加(线(0, 0, L轴 + 4, 0, "center"))
    # A—A 断面（键截面按矩形槽处理，月牙形已在主视图表达）
    g.加(_断面骨架(R轮, r, 槽半宽, 槽底, 键顶, 槽顶, 槽半宽, cx))

    g.注(f"半圆键 b×h = {b:g}×{h:g}（GB/T 1099）",
         f"槽深 t1={t1:g}（取 0.7h，示意值；页图未给数值，实际查表）",
         "键按不剖绘制；键顶面与轮毂槽顶面画两条线（顶部间隙）")
    g.范围(0, -R轮, cx + R轮 + 4, R轮)
    return g


# ------------------------------------------------------------------ 11 钩头楔键
def 钩头楔键连接画法(d=30.0, b=8.0, h=8.0, L=30.0):
    """钩头楔键连接（主视 + A—A 断面）。

    依据：图8-40 p.239 [核]（钩头楔键连接图）
      楔键靠**上表面楔紧** → 顶面贴合（与轮毂槽顶面画成**一条线**）；
      **两侧面各留间隙 → 每侧画两条线**（引出标注原文：“两侧面有间隙，画两条线”）；
      左端带钩头，伸出轮毂端面。A—A 断面里键两侧因此比槽壁各窄一点。
    斜度：页图未标数值，按楔键（GB/T 1564）常用 1:100 画，跨 L 的落差仅 L/100，图面上近于直线。
    钩头长取 0.2L、钩头高取 1.2h（示意值，实际按标准查表）。
    """
    r = d / 2.0
    t1 = 0.6 * h
    R轮 = 轮毂半径系数 * d
    隙 = max(0.4, 间隙系数 * d)
    if not (0 < t1 < h):
        raise ValueError("t1 必须落在 (0, h) 内")
    槽底 = r - t1
    键顶左 = 槽底 + h
    键顶右 = 键顶左 - L / 100.0          # 1:100 斜度（楔紧面，近于水平）
    槽半宽 = b / 2.0
    键半宽 = 槽半宽 - 隙                 # 两侧面留间隙 → 每侧两条线
    钩长, 钩高 = 0.2 * L, 1.2 * h
    L轴 = L + 2 * b
    cx = L轴 + 1.4 * R轮

    g = 图形()
    # 主视：轴（上母线在键槽处断开）
    g.加(线(-钩长 - b, r, 0, r), 线(L, r, L轴, r),
         线(-钩长 - b, -r, L轴, -r),
         线(-钩长 - b, -r, -钩长 - b, r), 线(L轴, -r, L轴, r))
    # 轴槽底 + 轮毂
    g.加(线(0, 槽底, L, 槽底),
         线(-钩长 - b, R轮, L轴, R轮), 线(-钩长 - b, -R轮, L轴, -R轮),
         线(-钩长 - b, r, -钩长 - b, R轮), 线(-钩长 - b, -R轮, -钩长 - b, -r),
         线(L轴, r, L轴, R轮), 线(L轴, -R轮, L轴, -r))
    # 键（顶面斜、与轮毂槽顶面贴合 → 只有一条线）
    g.加(线(0, 槽底, 0, 键顶左), 线(L, 槽底, L, 键顶右),
         线(0, 键顶左, L, 键顶右))
    # 钩头（伸出轮毂左端面）
    g.加(矩形(-钩长, 键顶左 - 钩高, 钩长, 钩高))
    g.加(线(-钩长 - b, 0, L轴 + 4, 0, "center"))
    # A—A 断面：键两侧面与槽壁各画一条 → 每侧两条线；顶面贴合 → 顶线只有一条
    键顶断 = (键顶左 + 键顶右) / 2.0
    g.加(_断面骨架(R轮, r, 槽半宽, 槽底, 键顶断, 键顶断, 键半宽, cx))

    g.注(f"钩头楔键 b×h×L = {b:g}×{h:g}×{L:g}（GB/T 1564）",
         "楔键靠上表面楔紧：顶面贴合，与轮毂槽顶面画一条线",
         "两侧面有间隙：每侧画两条线（键宽比槽宽各小 %.2f）" % 隙,
         "上表面斜度按 1:100 绘制（页图未标数值）；左端钩头用于拆卸")
    g.范围(-钩长 - b, -R轮, cx + R轮 + 4, R轮)
    return g


# ------------------------------------------------------------------ 12 花键
def 花键画法(D=40.0, d=32.0, B=6.0, N=8, 长=40.0, 类型="外"):
    """矩形花键（外花键为轴向视图 + A—A；内花键为剖视 + A—A）。

    依据：图8-42 p.239 [核]（外花键的画法）/ 图8-43 p.239 [核]（内花键的画法）
      外花键：大径 thick、小径 thin、工作长度终止线 thin、尾部 30° 斜线 thin；
      内花键：大径 D、小径 d **均为 thick**，齿区（D 与 d 之间）不画剖面线。
      A—A 画 N 个齿，矩形花键齿侧为直线。
    """
    if 类型 not in ("外", "内"):
        raise ValueError('类型 只能是 "外" 或 "内"')
    if not (d < D):
        raise ValueError("小径 d 必须小于大径 D")
    if B <= 0 or N < 3:
        raise ValueError("键宽 B 应为正、齿数 N ≥ 3")
    R, rr = D / 2.0, d / 2.0
    尾长 = (R - rr) / math.tan(math.radians(30.0))   # 尾部斜线与轴线成 30°
    光轴 = 2.0 * B
    cx = 长 + 尾长 + 光轴 + 1.4 * R
    g = 图形()

    if 类型 == "外":
        # 大径 thick / 小径 thin，均自工作长度起点到尾部末端
        g.加(线(0, R, 长 + 尾长, R), 线(0, -R, 长 + 尾长, -R))
        g.加(线(0, rr, 长 + 尾长, rr, "thin"), 线(0, -rr, 长 + 尾长, -rr, "thin"))
        # 工作长度终止线（细实线）
        g.加(线(长, -R, 长, R, "thin"))
        # 尾部 30° 斜线 + 尾部末端线
        g.加(线(长, R, 长 + 尾长, rr, "thin"), 线(长, -R, 长 + 尾长, -rr, "thin"))
        g.加(线(长 + 尾长, -rr, 长 + 尾长, rr, "thin"))
        # 光轴
        g.加(线(长 + 尾长, rr, 长 + 尾长 + 光轴, rr),
             线(长 + 尾长, -rr, 长 + 尾长 + 光轴, -rr),
             线(长 + 尾长 + 光轴, -rr, 长 + 尾长 + 光轴, rr))
        g.加(线(-4, 0, 长 + 尾长 + 光轴 + 4, 0, "center"))
        # A—A：大径粗圆、小径细圆、N 个齿（直线齿侧）
        g.加(圆(cx, 0, R), 圆(cx, 0, rr, "thin"))
        齿线 = []
        for i in range(N):
            θ = 360.0 * i / N
            Δ = math.degrees(math.asin(B / (2.0 * R)))
            for s in (-1, 1):
                a = math.radians(θ + s * Δ)
                齿线.append(线(cx + rr * math.cos(a), rr * math.sin(a),
                               cx + R * math.cos(a), R * math.sin(a)))
        g.加(*齿线)
        g.加(线(cx - R - 4, 0, cx + R + 4, 0, "center"),
             线(cx, -R - 4, cx, R + 4, "center"))
        标记 = f"{N}×{d:g}×{D:g}×{B:g} GB/T 1144"
        范围 = (0, -R, cx + R + 4, R)
    else:
        R轮 = R + 0.5 * d
        齿区半 = R
        g.加(线(0, R, 长, R), 线(0, -R, 长, -R))            # 大径 D（thick）
        g.加(线(0, rr, 长, rr), 线(0, -rr, 长, -rr))          # 小径 d（thick）
        g.加(线(0, -R轮, 0, R轮), 线(长, -R轮, 长, R轮),
             线(0, R轮, 长, R轮), 线(0, -R轮, 长, -R轮))
        # 剖面线只填轮毂实体（D 以外），齿区 D~d 留白
        上 = [(0, R), (长, R), (长, R轮), (0, R轮)]
        下 = [(x, -y) for x, y in 上]
        g.加(剖面线(上, 剖面间距, 45.0), 剖面线(下, 剖面间距, 45.0))
        g.加(线(-4, 0, 长 + 4, 0, "center"))
        # A—A：大、小径均粗圆 + N 个齿
        g.加(圆(cx, 0, R), 圆(cx, 0, rr))
        齿线 = []
        for i in range(N):
            θ = 360.0 * i / N
            Δ = math.degrees(math.asin(B / (2.0 * R)))
            for s in (-1, 1):
                a = math.radians(θ + s * Δ)
                齿线.append(线(cx + rr * math.cos(a), rr * math.sin(a),
                               cx + R * math.cos(a), R * math.sin(a)))
        g.加(*齿线)
        g.加(线(cx - R - 4, 0, cx + R + 4, 0, "center"),
             线(cx, -R - 4, cx, R + 4, "center"))
        标记 = f"{N}×{d:g}×{D:g}×{B:g} GB/T 1144"
        范围 = (0, -R轮, cx + R + 4, R轮)

    g.注(f"花键标记 {标记}",
         f"尾部长 {尾长:.2f} = (D−d)/2 / tan30°，尾部斜线与轴线成 30°",
         "外花键：大径粗、小径细，终止线与尾部线均细实线；内花键：大、小径均粗实线")
    g.范围(*范围)
    return g



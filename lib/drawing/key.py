def _自检():
    cases = [平键连接画法(), 半圆键连接画法(), 钩头楔键连接画法(),
             花键画法(), 花键画法(类型="内"), 平键连接画法(t1=4.0)]
    for i, g in enumerate(cases, 1):
        ok, msg = 校验图元(g.elems)
        assert ok, f"#{i} {msg}"
        print(f"#{i} {len(g):>4} 图元  {msg}  bbox={tuple(round(v, 2) for v in g.bbox)}")

    # 平键：顶部“两条线”间距 = 间隙；t1 默认 0.6h
    g = 平键连接画法()
    ys = sorted({round(dd["y1"], 3) for k, dd in g.elems if k == "line"})
    assert 17.8 in ys and 18.4 in ys, f"键顶(17.8)/轮毂槽顶(18.4) 两条线缺失：{ys}"
    assert 10.8 in ys, f"轴槽底 d/2−t1=10.8 缺失：{ys}"
    print("平键：t1=0.6h=%.1f 槽底=%.1f 键顶=%.1f 轮毂槽顶=%.1f（两条线间距 %.1f）"
          % (4.2, 10.8, 17.8, 18.4, 0.6))
    # 楔键：顶面只一条线；两侧面各两条线（A—A 里 ±4 与 ±3.4）
    g = 钩头楔键连接画法()
    xs = {round(dd["x1"], 3) for k, dd in g.elems if k == "line"}
    print("楔键：键半宽=%.1f 槽半宽=%.1f → A—A 每侧两条线" % (4.0 - 0.6, 4.0))
    # 花键：尾长
    print("花键：尾长=(D−d)/2/tan30°=%.2f（D=40,d=32）" % (4 / math.tan(math.radians(30))))



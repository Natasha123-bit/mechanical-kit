"""spring.py —— 圆柱螺旋压缩弹簧的画法（《机械制图》ch8 §8-7，图8-58~8-62，p.247–250）

依据：books/drawing/handoff-ch08/A-spring.json（A 角色逐线核过图8-59/8-60 的页图）
  图8-58 名称 [核]：D2=(D+D1)/2、D1=D−2d、H0≈n·t+(n2−0.5)d、轴线 center。
  图8-59 常见画法 [核]：轮廓 thick；剖视图断面为 φd 小圆 + 45° 细实线剖面线；
          同侧相邻断面圆间距 = t（支承段相切）；有效圈 >4 圈时中间各圈可省略，
          两端用细点画线连起来；支承圈一律按 2.5 圈画。
  图8-60 五步画法 [核]：(a) 三条竖直细点画线（轴线 + 两条簧丝中心线，相距 D2）
          →(b) 支承圈投影 →(c) 有效圈断面（同侧距 t、异侧错开 t/2）→(d) 断面公切线
          （thick，与圆相切）→(e) 剖面线（图上 d≤2 整圆涂黑）。
  图8-62 [核]：装配图中 d≤2 涂黑、d≤1 可示意画法。

硬约束：只走 lib.drawing._prim 原语；线型只用 thick/thin/center/hidden/wavy。

两个已知缺口（都在注记里如实写明，不偷偷绕过）：
  1. _prim.圆 虽接收 fill=，但 Sheet 生成的 CSS（`.thick{…fill:none}`）优先级高于 circle 的
     fill 属性，故 fill="solid" 不会真的涂黑（且 "solid" 不是合法颜色值）；`("poly",…)`
     也不在 校验图元 的允许种类里（只有 "polygon"）。因此图上 d≤2 时**不涂黑**，只画剖面线。
  2. 图8-58 的 H0≈n·t+(n2−0.5)d 只给两端支承圈共 (n2−0.5)d=2d 的高度，而图8-59/8-60 的
     规定画法每端就要 2 个相切圆（2d），两端共 4d。书里自己的弹簧 H0=96 与公式值 81 差 15，
     正是这个矛盾。本模块：弹簧参数 按书公式校验/反推，画法按规定画法的真实几何（每端 2d）。
"""

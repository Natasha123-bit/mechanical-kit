涂黑阈值 = 2.0          # 图上 d ≤ 2mm：整圆涂黑（图8-60(e)、图8-62b）
示意阈值 = 1.0          # 装配图中 d ≤ 1mm 可用折线示意（图8-62c）——本模块只记录，不实现示意图
支承圈默认 = 2.5        # 图8-59 规定(4)：不论实际支承圈数多少都按 2.5 圈画


# ============================================================ 参数校验 / 推导
def 弹簧参数(d, D2, H0, t, 支承圈=支承圈默认, n=None):
    """弹簧基本参数与校验，返回 dict。

    依据：图8-58 p.247 [核] D2=(D+D1)/2、D1=D−d、H0≈n·t+(n2−0.5)d；图8-59 [核] 支承圈 2.5 圈。
    n=None 时按 n = round((H0 − (支承圈−0.5)d)/t) 反推；给出 n 时校验 H0 ≥ n·t + (支承圈−0.5)d。
    """
    for 名, v in (("d", d), ("D2", D2), ("H0", H0), ("t", t)):
        if v <= 0:
            raise ValueError(f"{名} 必须 > 0，收到 {v}")
    if D2 <= d:
        raise ValueError(f"弹簧中径 D2={D2} 必须大于簧丝直径 d={d}（否则内径 D1=D2−d≤0）")
    if 支承圈 <= 0:
        raise ValueError(f"支承圈 必须 > 0，收到 {支承圈}")
    最小高 = lambda nn: nn * t + (支承圈 - 0.5) * d
    if n is None:
        n = int(round((H0 - (支承圈 - 0.5) * d) / t))
        if n < 1:
            raise ValueError(f"由 H0={H0}、t={t} 反推不出有效圈数（算出 n={n}）")
    elif H0 < 最小高(n) - 1e-9:
        raise ValueError(f"自由高度不足：H0={H0} < n·t+(支承圈−0.5)d={最小高(n):g}（n={n}）")
    return dict(d=float(d), D2=float(D2), D=D2 + d, D1=D2 - d, H0=float(H0), t=float(t),
                支承圈=支承圈, n=n, 总圈数=n + 支承圈, 旋绕比=D2 / d,
                有效段高=n * t, 端部可用高=(H0 - n * t) / 2, 书公式最小高=最小高(n))


def _断面圆内接八边形(x, y, r):
    """剖面线用的多边形：圆内接正八边形（顶点在圆周上，剖面线不越出圆轮廓）。"""
    return [(x + r * math.cos(math.radians(22.5 + 45 * k)),
             y + r * math.sin(math.radians(22.5 + 45 * k))) for k in range(8)]


def _双切线(c1, c2, r):
    """两等半径圆的**两条**外公切线（上、下各一条，图8-60(d) 的带形轮廓）。

    圆心连线方向 (dx,dy)，法向 n=(−dy,dx)/|·|；切点 = 圆心 ± r·n。
    每条切线的两个切点同侧偏移，故到两圆心距离都等于 r。只画一条会变成锯齿折线，
    书上每一段是两条平行细带（簧丝的正、背两侧），此处按书补成两条。
    """
    (x1, y1), (x2, y2) = c1, c2
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1.0
    nx, ny = -dy / L, dx / L
    up = ((x1 + r * nx, y1 + r * ny), (x2 + r * nx, y2 + r * ny))
    dn = ((x1 - r * nx, y1 - r * ny), (x2 - r * nx, y2 - r * ny))
    return up, dn


# ============================================================ 画法
def 弹簧画法(d=8.0, D2=48.0, H0=96.0, t=13.0, n=5, 支承圈=支承圈默认, 剖视=True,
          cx=80.0, y0=40.0, 省略中间圈=False):
    """圆柱螺旋压缩弹簧（轴线竖直，下端面 y0，上端面 y0+H0）。返回 图形。

    依据：图8-60 五步画法 p.248 [核]；图8-59 常见画法 p.247 [核]。
      第1步 基准线：轴线 + 两条簧丝中心线（x=cx±D2/2）三条细点画线；上下端面细实线相距 H0；
      第2步 支承圈：每端 2 个相切断面圆（'8'形）+ 对侧 1 个圆（2.5 圈规定画法）；
      第3步 有效圈：左右交替断面圆，同侧相邻圆心距 = t、异侧错开 t/2（n 圈 → 2n 个断面）；
      第4步 公切线：相邻断面圆之间的斜直线（与圆相切，thick）构成螺旋轮廓（不是波浪线）；
      第5步 剖面线：剖视=True 时每个断面圆内 45° 细实线（内接正八边形做裁剪域）。
    n=None 时先按 弹簧参数 的书公式反推；若规定画法的支承段（每端 2d）挤不下，按绘图几何
    n = round((H0 − 4d)/t) 复算并在注记里写明改用了哪个。
    """
    p = 弹簧参数(d, D2, H0, t, 支承圈, n)
    r = d / 2
    端共 = 2 * d                                   # 每端 2 个相切圆占高
    可用 = H0 - 2 * 端共                           # 留给有效圈的总高
    提示 = []
    if n is None:
        n = p["n"]
        需要 = (2 * n - 1) * t / 2
        if 需要 > 可用:
            n2 = int((可用 + t / 2) // t)
            if n2 < 1:
                raise ValueError(f"H0={H0} 放不下有效圈（可用 {可用:g}，t={t}）")
            提示.append(f"n 由 H0 反推：书公式 H0=n·t+(支承圈−0.5)d 给 n={p['n']}，"
                      f"但规定画法每端并紧段占 2d（合计 {2 * 端共:g}），改用 n={n2}")
            n = n2
            p.update(弹簧参数(d, D2, H0, t, 支承圈, n))
    需要 = (2 * n - 1) * t / 2
    if 需要 > 可用 + 1e-9:
        raise ValueError(f"H0={H0} 容不下 {n} 圈有效圈：可用 {可用:g} < 需要 {需要:g}"
                         f"（每端支承圈并紧段 2d={端共:g}）")

    y_top = y0 + H0
    xL, xR = cx - D2 / 2, cx + D2 / 2
    节距半 = t / 2
    y_首 = y0 + 端共 + (可用 - 需要) / 2           # 有效圈首断面：居中留白
    y_末 = y_首 + 需要

    # ---------- 断面圆清单（自下而上） ----------
    底 = [dict(侧="L", y=y0 + r, 组="底"), dict(侧="R", y=y0 + d, 组="底"),
          dict(侧="L", y=y0 + 1.5 * d, 组="底")]
    效 = [dict(侧=("R" if k % 2 == 0 else "L"), y=y_首 + k * 节距半, 组="效")
          for k in range(2 * n)]
    顶 = [dict(侧="R", y=y_top - 1.5 * d, 组="顶"), dict(侧="L", y=y_top - d, 组="顶"),
          dict(侧="R", y=y_top - r, 组="顶")]
    断面 = 底 + 效 + 顶
    省略 = bool(省略中间圈 and n > 4)
    保 = 底 + ([效[0], 效[-1]] if 省略 else 效) + 顶

    g = 图形()

    # ---------- 第1步 作图基准线 ----------
    g.加(线(cx, y0 - 4, cx, y_top + 4, "center"),
         线(xL, y0 - 4, xL, y_top + 4, "center"),
         线(xR, y0 - 4, xR, y_top + 4, "center"))
    g.加(线(xL - r, y0, xR + r, y0, "thin"),         # 下端面（相距 H0）
         线(xL - r, y_top, xR + r, y_top, "thin"))    # 上端面

    坐标 = lambda s: ((xL if s["侧"] == "L" else xR), s["y"])

    # ---------- 第2/3/5步 断面圆 + 剖面线 ----------
    间距 = max(1.0, min(2.0, d / 4))
    for s in 保:
        x, y = 坐标(s)
        g.加(圆(x, y, r))                            # 断面圆 thick
        if 剖视:
            g.加(剖面线(_断面圆内接八边形(x, y, r), spacing=间距, angle=45.0))

    # ---------- 第4步 公切线 ----------
    for a_, b_ in zip(保, 保[1:]):
        if 省略 and a_["组"] == "效" and b_["组"] == "效":
            continue                                 # 省略段不画公切线，改画细点画线
        for p1, p2 in _双切线(坐标(a_), 坐标(b_), r):
            g.加(线(p1[0], p1[1], p2[0], p2[1]))

    # ---------- 省略中间圈：三条细点画线贯通 ----------
    if 省略:
        g.加(线(xL, 效[0]["y"], xL, 效[-1]["y"], "center"),
             线(xR, 效[0]["y"], xR, 效[-1]["y"], "center"),
             线(cx, 效[0]["y"], cx, 效[-1]["y"], "center"))

    # ---------- 注记 ----------
    g.注(f"簧丝 d={d:g}，中径 D2={D2:g}，外径 D=D2+d={p['D']:g}，内径 D1=D2−d={p['D1']:g}，"
         f"旋绕比 D2/d={p['旋绕比']:.2f}",
         f"有效圈 n={n}，总圈数 n1={p['总圈数']:g}，节距 t={t:g}，自由高度 H0={H0:g}",
         "支承圈不论实际圈数多少一律按 2.5 圈画：每端 2 个相切断面圆（'8'形）+ 对侧 1 个圆",
         "同侧相邻断面圆间距 = t，异侧错开 t/2；每对断面圆画两条相切斜直线（粗实线）连成簧丝带")
    if 剖视:
        g.注("剖面线 45° 细实线只画在簧丝断面内，弹簧本体不画剖面线（图8-62 注）")
        if d <= 涂黑阈值:
            g.注(f"图上 d={d:g} ≤ {涂黑阈值:g} 应整圆涂黑；_prim.圆 的 fill 被 Sheet 的 CSS 覆盖，"
                 f"本库暂以剖面线代替，未涂黑")
    if 省略:
        g.注("有效圈 >4，中间各圈省略不画，两端用细点画线连起来（图8-59 规定(3)）")
    if abs(端共 - p["端部可用高"]) > 0.5:
        g.注(f"端部并紧段实绘 {端共:g}（2d），(H0−n·t)/2={p['端部可用高']:g}；"
             f"书公式 H0=n·t+(支承圈−0.5)d 只给两端共 2d，与规定画法 4d 不符，H0 仍按图示值")
    for t_ in 提示:
        g.注(t_)

    g.参数 = dict(p, n=n, 端部实绘高=端共, 有效圈可用高=可用, 有效圈需要高=需要,
                  断面圆数=len(断面), 实绘断面圆数=len(保),
                  有效圈首=y_首, 有效圈末=y_末, 剖视=剖视, 省略中间圈=省略)
    g.范围(xL - r - 6, y0 - 6, xR + r + 6, y_top + 6)
    return g


# ============================================================ 自检
def _自检():
    out = []
    for 剖 in (True, False):
        g = 弹簧画法(剖视=剖)
        ok, msg = 校验图元(g.elems)
        assert ok, msg
        q = g.参数
        out.append((f"弹簧画法(剖视={剖})", f"{msg}；图元 {len(g)}"))
        out.append(("  几何", f"H0={q['H0']:g} D2={q['D2']:g} D={q['D']:g} D1={q['D1']:g} "
                              f"t={q['t']:g} n={q['n']} n1={q['总圈数']:g} "
                              f"断面圆 {q['断面圆数']} 个（实绘 {q['实绘断面圆数']}）"
                              f" 同侧间距 t={q['t']:g}"))
    g = 弹簧画法(省略中间圈=True)
    ok, msg = 校验图元(g.elems)
    assert ok, msg
    out.append(("弹簧画法(省略中间圈)", f"{msg}；图元 {len(g)}，实绘断面 {g.参数['实绘断面圆数']}"))
    g = 弹簧画法(n=None)
    out.append(("n=None", f"n={g.参数['n']}（书公式反推 6，规定画法挤不下，改按 (96−32)/13≈4.9→5）"))
    for bad in (dict(H0=60.0), dict(D2=6.0), dict(d=0.0)):
        try:
            弹簧画法(**bad)
        except ValueError as e:
            out.append((f"应报错 {bad}", str(e)[:56]))
    return out


if __name__ == "__main__":
    for k, v in _自检():
        print(f"{k}: {v}")

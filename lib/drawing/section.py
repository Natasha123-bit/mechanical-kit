# ============================================================ 9. 剖面符号（表6-1）
def 剖面符号(多边形, 材料="金属", 间距=2.0):
    """按材料返回剖面线图元（HATCH 或 HATCH 组合）。

    依据：表6-1 p.148 [核]（剖面符号只表示材料类别，材料名称/代号另行注明）。
      金属   → 45° 平行细实线（图6-10 p.149 [核]）；
      非金属 → 45° 与 −45° 交叉（菱形网格），间距 = 间距×1.5（默认 3）；
      线圈   → 表6-1 为“正交网格线”，用 45° 与 −45° 交叉近似，间距 = 间距×0.75（默认 1.5）；
      其它   → NotImplementedError（表6-1 其余 9 种材料：木材/玻璃/液体/迭钢片/格网等未实现，不臆造）。
    返回：金属为单个 ("group", HATCH)；非金属/线圈为 分组(两条 HATCH) 的组合。
    """
    点 = [(float(x), float(y)) for x, y in 多边形]
    if len(点) < 3:
        raise ValueError(f"多边形至少 3 个顶点，收到 {len(点)}")
    if 间距 <= 0:
        raise ValueError(f"间距 必须 > 0，收到 {间距}")

    if 材料 == "金属":
        return 剖面线(点, spacing=间距, angle=45.0)
    if 材料 == "非金属":
        return 分组(剖面线(点, spacing=间距 * 非金属间距系数, angle=45.0),
                    剖面线(点, spacing=间距 * 非金属间距系数, angle=-45.0))
    if 材料 == "线圈":
        return 分组(剖面线(点, spacing=间距 * 线圈间距系数, angle=45.0),
                    剖面线(点, spacing=间距 * 线圈间距系数, angle=-45.0))
    raise NotImplementedError(
        f"材料 {材料!r} 的剖面符号待补（表6-1 p.148 共 11 种，本模块只做 金属/非金属/线圈）")


# ============================================================ 5. 剖视
def 剖视(宽=80, 高=50, 孔半径=12, 类型="全剖", 材料="金属", cx=80, cy=110):
    """剖视图：外框 thick + 内孔（竖直通孔，两壁 thick）+ 剖面线 + 上方“A—A”。

    依据：图6-13 p.151 [核]（全剖）、图6-14/6-15 p.152 [核]（半剖）、
          图6-16/6-17 p.153 [核]（局部剖）。
      全剖  ：孔壁两条竖线（cx±r）贯通；剖面线填**孔外**（孔左/孔右两条贯通条带 = 契约的
              “四块”左/右 × 上/下，合为两条以免 HATCH 在接缝处相位错位），孔内留白；
      半剖  ：中间竖直分界线用 **center**（细点画线，不是 thick）；左半画孔左壁 cx−r 并填剖面线，
              右半既不画剖面线、也不画孔（视图半边不画细虚线，图6-14 [核]）；
      局部剖：孔壁两条竖线贯通；在 cx+r+10 处竖直画波浪线作断裂边界，两端各超出外框 3；
              剖面线只填波浪线左侧（且避开孔洞，图6-20 [核]：“不能画在孔洞处”）。
    参数 cx,cy 为外框中心；宽、高为外框尺寸；孔半径 r 须 0 < 2r < 宽。
    “A—A”标在视图上方 6（示意）。
    """
    if 类型 not in 剖视类型:
        raise ValueError(f"类型 只能是 {剖视类型}，收到 {类型!r}")
    if 宽 <= 0 or 高 <= 0:
        raise ValueError("宽、高 必须 > 0")
    if not (0 < 孔半径 < 宽 / 2.0):
        raise ValueError(f"孔半径 须在 (0, 宽/2) 内，收到 {孔半径}（宽 {宽}）")
    if 材料 not in 剖面材料:
        raise NotImplementedError(f"材料 {材料!r} 待补（表6-1 p.148，见 剖面符号()）")

    x0, y0 = cx - 宽 / 2.0, cy - 高 / 2.0
    x1, y1 = cx + 宽 / 2.0, cy + 高 / 2.0
    r = float(孔半径)

    g = 图形().加(矩形(x0, y0, 宽, 高, "thick"))

    if 类型 == "全剖":
        g.加(线(cx - r, y0, cx - r, y1, "thick"), 线(cx + r, y0, cx + r, y1, "thick"))
        # 剖面线按“孔左/孔右”两条贯通条带填充（孔内留白）。若再按上/下切成四块，
        # gbdraw.HATCH 每块各自从自身包围盒起算相位，接缝处剖面线会错位半格（试渲染可见），
        # 故四块合为两条——覆盖的区域与四块完全相同。
        for bx0, bx1 in ((x0, cx - r), (cx + r, x1)):
            g.加(剖面符号(_矩形面(bx0, y0, bx1, y1), 材料))
        g.注("全剖视图：孔内不画剖面线（图6-13 p.151）")

    elif 类型 == "半剖":
        g.加(线(cx, y0, cx, y1, "center"))                 # 分界线：细点画线，不能画成粗实线
        g.加(线(cx - r, y0, cx - r, y1, "thick"))          # 只在剖开的左半画孔左壁
        g.加(剖面符号(_矩形面(x0, y0, cx - r, y1), 材料))
        g.注("半剖视图：分界线为细点画线；外形半边不画细虚线（图6-14 p.152）")

    else:  # 局部剖
        g.加(线(cx - r, y0, cx - r, y1, "thick"), 线(cx + r, y0, cx + r, y1, "thick"))
        断x = cx + r + 局部剖孔壁外距
        if 断x >= x1:
            raise ValueError(f"局部剖波浪线 x={断x:.1f} 已越出外框右边界 {x1:.1f}（孔半径过大或宽过小）")
        g.加(波浪线(断x, y0 - 3, 断x, y1 + 3, style="thin"))   # 两端略超出外框（图6-21 同理）
        g.加(剖面符号(_矩形面(x0, y0, cx - r, y1), 材料))       # 孔洞左侧
        g.加(剖面符号(_矩形面(cx + r, y0, 断x, y1), 材料))      # 孔壁与波浪线之间
        g.注("局部剖视图：波浪线只表示剖切范围，不超出轮廓线、不画在孔洞处（图6-16/6-20）")

    g.加(文(cx, y1 + 6, "A—A", TEXT_H))
    g.范围(x0 - 3, y0 - 4, x1 + 3, y1 + 10)
    return g


# ============================================================ 6. 剖切符号
def 剖切符号(方向="竖", 长度=60, 字母="A", x=80, y=110, 间隔=8):
    """剖切符号：两端粗短画 + 与短画垂直的投射方向箭头 + 两侧同名字母。

    依据：§6-2 p.149 [核]——“在剖切面的起、止处画粗短画（1.5 倍粗实线线宽），
    在表示起、止处的粗短画上垂直画出箭头表示投射方向；同样字母分注在剖切符号的两侧”。
      “竖”：剖切面竖直（在俯视图上表现为一条竖直迹线），两短画沿**竖直方向**分居两端，
            间距 = 长度，箭头水平指向**右侧**（即从左向右看）；
      “横”：剖切面水平，两短画沿**水平方向**分居两端，箭头竖直指向**上方**，字母同上。
    书中未给 mm：**短画长取 6、箭头长取 4、字高 3.5 示意**（§6-2 只规定“1.5 倍粗实线线宽”与
    “字母注在剖切符号两侧”）。本函数把箭头长做成参数 `间隔`（默认 8，传 4 即与上述示意值一致），
    字母再让位 2。
    箭头按 §6-2 的画法为**细直线箭杆 + 实心箭头**（gbdraw.ARROW 只生成箭头本身，故另加 线() 作箭杆）。
    参数 x,y 为剖切符号的中心；长度 = 两条短画之间的距离。
    """
    if 方向 not in ("竖", "横"):
        raise ValueError(f"方向 只能是 ('竖', '横')，收到 {方向!r}")
    if 长度 <= 0:
        raise ValueError(f"长度 必须 > 0，收到 {长度}")
    if 间隔 <= 0:
        raise ValueError(f"间隔 必须 > 0，收到 {间隔}")

    g = 图形()
    半 = 长度 / 2.0
    箭头长 = float(间隔)

    if 方向 == "竖":
        for s in (1, -1):
            ys = y + s * 半
            g.加(线(x, ys - 短画长 / 2, x, ys + 短画长 / 2, "thick"))   # 竖直粗短画
            yt = ys + s * 短画长 / 2                                     # 短画外端
            g.加(线(x, yt, x + 箭头长, yt, "thin"),                       # 水平箭杆（细实线）
                 箭头(x, yt, x + 箭头长, yt))                            # 箭头指向右
            g.加(文(x + 箭头长 + 2, yt, 字母, TEXT_H, anchor="start"))
    else:
        for s in (1, -1):
            xs = x + s * 半
            g.加(线(xs - 短画长 / 2, y, xs + 短画长 / 2, y, "thick"))   # 水平粗短画
            xt = xs + s * 短画长 / 2
            g.加(线(xt, y, xt, y + 箭头长, "thin"),                       # 竖直箭杆
                 箭头(xt, y, xt, y + 箭头长))                            # 箭头指向上
            g.加(文(xt + 2, y + 箭头长 + 2, 字母, TEXT_H, anchor="start"))

    g.注(f"剖切符号 {字母}—{字母}：粗短画 (1.5 倍粗实线) + 垂直箭头 + 两侧同名字母（§6-2 p.149）")
    if 方向 == "竖":
        g.范围(x - 4, y - 半 - 6, x + 箭头长 + 8, y + 半 + 6)
    else:
        g.范围(x - 半 - 6, y - 4, x + 半 + 6, y + 箭头长 + 8)
    return g


# ============================================================ 7. 断面
def 断面(宽=40, 高=20, 类型="移出", 材料="金属", x=80, y=110):
    """断面图：闭合轮廓 + 剖面线；移出用 thick、重合用 thin。

    依据：图6-38 p.161 [核]（移出断面轮廓粗实线、配置在剖切线的延长线上，与主视图分开）
          + 图6-44 p.163 [核]（重合断面轮廓细实线、画在视图之内，被重合处的视图轮廓线
          仍连续画出、不断开；对称的重合断面不必标注）。
      移出：thick 闭合矩形 + 剖面线 + 上方“A—A”，单独摆放（不与主视图画在一起）；
      重合：thin 闭合矩形 + 剖面线，叠在一个水平视图矩形内——视图的上下轮廓 thick 且连续不间断，
            不画字母。视图带宽 高/2、长 宽×2（示意，书未给）。
    参数 x,y 为断面矩形左下角。
    """
    if 类型 not in 断面类型:
        raise ValueError(f"类型 只能是 {断面类型}，收到 {类型!r}")
    if 宽 <= 0 or 高 <= 0:
        raise ValueError("宽、高 必须 > 0")
    if 材料 not in 剖面材料:
        raise NotImplementedError(f"材料 {材料!r} 待补（表6-1 p.148，见 剖面符号()）")

    面 = _矩形面(x, y, x + 宽, y + 高)
    g = 图形()

    if 类型 == "移出":
        g.加(矩形(x, y, 宽, 高, "thick"))
        g.加(剖面符号(面, 材料))
        g.加(文(x + 宽 / 2, y + 高 + 6, "A—A", TEXT_H))
        g.注("移出断面：轮廓粗实线，配置在剖切线延长线上，与视图分开（图6-38 p.161）")
        g.范围(x - 3, y - 3, x + 宽 + 3, y + 高 + 10)
    else:  # 重合
        带高 = 高 / 2.0
        视x, 视y = x - 宽 / 2.0, y + 高 / 4.0        # 带 2宽×(高/2)，与断面同心
        g.加(矩形(视x, 视y, 宽 * 2, 带高, "thick"))  # 视图上下轮廓：thick、连续（不被断面切断）
        g.加(矩形(x, y, 宽, 高, "thin"))              # 重合断面轮廓：细实线
        g.加(剖面符号(面, 材料))
        g.注("重合断面：轮廓细实线，视图轮廓线连续不断，不标注（图6-44 p.163）")
        g.范围(视x - 3, y - 3, 视x + 宽 * 2 + 3, y + 高 + 3)
    return g


# ============================================================ 8. 局部放大
def 局部放大(半径=12, 比例=2.0, 罗马数字="I", x=80, y=110):
    """局部放大图：左侧细实线圈示被放大部位，右侧 thick 放大图，细引出线 + 上方“罗马数字  比例”。

    依据：图6-45 p.164 [核]——用细实线圈出被放大部位；细引出线接水平托线写罗马数字；
    放大图线性尺寸 = 实长 × 比例；罗马数字与比例分两行注在放大图上方（此处排成一行，见存疑）。
    参数：半径 = 被放大结构的外圆半径（细实线圈示，半径=半径）；比例 = 放大倍数；
    x,y 为左侧小结构圆心。
    几何：小结构 = 外圆 R + 内孔 R/3（均 thin）；放大图 = 外圆 R×比例 + 内孔 R×比例/3（均 thick），
          故两外圆半径比、两内孔半径比都等于 比例。内孔系数 1/3 为示意（书只给“圆+内孔”）。
    存疑：书上是罗马数字在上、比例在下两行；本函数按契约排成一行「I  2:1」。
    """
    if 半径 <= 0:
        raise ValueError(f"半径 必须 > 0，收到 {半径}")
    if 比例 <= 0:
        raise ValueError(f"比例 必须 > 0，收到 {比例}")
    if not 罗马数字:
        raise ValueError("罗马数字 不能为空")

    内孔系数 = 1.0 / 3.0
    小外, 小内 = float(半径), float(半径) * 内孔系数
    大外, 大内 = 小外 * 比例, 小内 * 比例
    距 = 小外 + 大外 + 24.0                     # 两图间距（示意）
    xm, ym = x + 距, y

    g = 图形()
    # 左：被放大部位（细实线圈示，不分粗实线）
    g.加(圆(x, y, 小外, "thin"), 圆(x, y, 小内, "thin"))
    # 右：放大图（thick）
    g.加(圆(xm, ym, 大外, "thick"), 圆(xm, ym, 大内, "thick"))
    # 引出线：自小圆右上缘斜出，接水平托线
    引x, 引y = x + 小外 * math.cos(math.radians(45)), y + 小外 * math.sin(math.radians(45))
    拐x, 拐y = 引x + 14, 引y + 14
    g.加(线(引x, 引y, 拐x, 拐y, "thin"), 线(拐x, 拐y, 拐x + 10, 拐y, "thin"))
    g.加(文(xm, ym + 大外 + 8, f"{罗马数字}  {比例:g}:1", TEXT_H))
    g.注(f"局部放大图 {罗马数字}：{比例:g}:1，细实线圈示被放大部位（图6-45 p.164）")

    g.半径 = dict(小外=小外, 小内=小内, 大外=大外, 大内=大内, 比例=比例)
    g.范围(x - 小外 - 3, y - max(小外, 大外) - 3,
           xm + max(小外, 大外) + 3, ym + max(小外, 大外) + 12)
    return g


# ============================================================ 小工具
def _矩形面(x0, y0, x1, y1):
    """矩形 → 剖面线用的闭合多边形（逆时针）。"""
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]



"""fastener.py —— 螺纹紧固件连接画法（ch8 §8-2，p.232–235）

坐标约定：**轴线竖直**，x=0 为轴线；y=0 取两被连接件的结合面（螺栓/螺柱）或上件底面（螺钉），
+ y 向上。全部几何只经 lib.drawing._prim 原语表达，线型只用 STYLES 的 thick/thin/center。

比例值全部取自页图上直接标注的公式（A-fastener.json）：
    螺栓连接 a=0.3d  m=0.8d  h=0.15d  k=0.7d  e=2d  垫圈外径 2.2d  光孔 1.1d  b=2d
    螺柱连接 a=0.3d  m=0.8d  弹簧垫圈 s=0.2d 厚、外径 1.35d  螺孔深=bm+0.5d  孔深=bm+d
被连接件的板宽（图中未标）取 1.6d 半宽，属示意值。
"""
import math
import sys
from pathlib import Path

MDKIT = Path(__file__).resolve().parents[2]
if str(MDKIT) not in sys.path: sys.path.insert(0, str(MDKIT))
from lib.drawing._prim import 图形, 校验图元, 线, 圆, 弧, 矩形, 文, 剖面线, 尺寸H, 尺寸V, 拼  # noqa: E402,F401

小径 = 0.85          # d1 = 0.85d
光孔 = 1.1           # 1.1d
钻头锥角 = 120.0
板半宽系数 = 1.6     # 示意值（页图未标被连接件外宽）


def _锥深(r1):
    return r1 / math.tan(math.radians(钻头锥角 / 2.0))


def _双片剖面(零件半宽, 孔半径, y0, y1, 间距, 角):
    """左右两条剖面线带（通孔贯穿时用），返回两个 polygon 顶点表。"""
    左 = [(-零件半宽, y0), (-孔半径, y0), (-孔半径, y1), (-零件半宽, y1)]
    右 = [(孔半径, y0), (零件半宽, y0), (零件半宽, y1), (孔半径, y1)]
    return 左, 右


def _环剖面(零件半宽, 孔半径, y0, 底y, 孔底y, 尖y):
    """盲孔件的 C 形剖面区（一块连通区，含孔底以下的实体）。"""
    return [(-零件半宽, y0), (-孔半径, y0), (-孔半径, 孔底y), (0.0, 尖y),
            (孔半径, 孔底y), (孔半径, y0), (零件半宽, y0), (零件半宽, 底y), (-零件半宽, 底y)]


# ------------------------------------------------------------------ 6 螺栓连接
def 螺栓连接画法(d=20.0, t1=20.0, t2=25.0, 垫圈=True):
    """螺栓连接（简化画法，主视全剖 + 轴线竖直）。

    依据：图8-27 p.233 [核]（螺栓连接的简化画法）
      k=0.7d（头高）、e=2d（头/螺母对边宽）、m=0.8d（螺母高）、h=0.15d（垫圈厚）、
      垫圈外径 2.2d、光孔 1.1d、伸出长度 a=0.3d、螺纹终止线距自由端 b=2d；
      被连接件剖面线两件方向相反；螺栓/螺母/垫圈为实心标准件，按不剖绘制（无剖面线）。
    接触面（结合面）只画一条线；非接触面（杆与光孔）画两条线，单边间隙 0.05d。
    """
    k, e, m, h, a, b = 0.7 * d, 2.0 * d, 0.8 * d, 0.15 * d, 0.3 * d, 2.0 * d
    r, r1 = d / 2.0, 小径 * d / 2.0
    r光 = 光孔 * d / 2.0
    半宽 = 板半宽系数 * d
    y下顶 = t2
    y上顶 = t2 + t1
    y垫 = y上顶 + (h if 垫圈 else 0.0)
    y母顶 = y垫 + m
    y顶 = y母顶 + a
    y终 = y顶 - b
    if y终 <= 0:
        raise ValueError("螺纹终止线落到了螺栓头以内：增大 t1/t2 或减小 d")

    g = 图形()
    # 被连接件轮廓
    g.加(线(-半宽, 0, -半宽, t2), 线(半宽, 0, 半宽, t2),          # 下件两侧
         线(-半宽, 0, -r光, 0), 线(r光, 0, 半宽, 0),              # 下件底（让开光孔）
         线(-半宽, y下顶, -半宽, y上顶), 线(半宽, y下顶, 半宽, y上顶),  # 上件两侧
         线(-半宽, y上顶, 半宽, y上顶),                            # 上件顶
         线(-半宽, y下顶, -r光, y下顶), 线(r光, y下顶, 半宽, y下顶))  # 结合面（一条线）
    # 光孔（非接触面画两条线）
    g.加(线(-r光, 0, -r光, y上顶), 线(r光, 0, r光, y上顶))
    # 螺栓头（六角头侧视，不剖）
    g.加(矩形(-e / 2.0, -k, e, k))
    # 螺栓杆（大径粗实线）
    g.加(线(-r, 0, -r, y顶), 线(r, 0, r, y顶))
    # 螺纹小径（细实线，自自由端到终止线）
    g.加(线(-r1, y终, -r1, y顶, "thin"), 线(r1, y终, r1, y顶, "thin"))
    # 螺纹终止线：两小段，自大径画到小径
    g.加(线(-r, y终, -r1, y终), 线(r1, y终, r, y终))
    # 垫圈 + 螺母（不剖）
    if 垫圈:
        g.加(矩形(-1.1 * d, y上顶, 2.2 * d, h))
    g.加(矩形(-e / 2.0, y垫, e, m))
    # 剖面线：上件 45°/2.0，下件 -45°/2.0（方向相反，便于区分）
    上左, 上右 = _双片剖面(半宽, r光, y下顶, y上顶, 2.0, 45.0)
    下左, 下右 = _双片剖面(半宽, r光, 0.0, t2, 2.0, -45.0)
    g.加(剖面线(上左, 2.0, 45.0), 剖面线(上右, 2.0, 45.0),
         剖面线(下左, 2.0, -45.0), 剖面线(下右, 2.0, -45.0))
    # 轴线
    g.加(线(0, -k - 4, 0, y顶 + 4, "center"))

    g.注(f"螺栓 M{d:g}，a=0.3d={a:g}，m=0.8d={m:g}，k=0.7d={k:g}，e=2d={e:g}",
         f"垫圈 h=0.15d={h:g}、外径 2.2d={2.2 * d:g}；光孔 1.1d={光孔 * d:g}，单边间隙 0.05d",
         f"螺纹终止线距自由端 b=2d={b:g}；两被连接件剖面线方向相反",
         "螺栓、螺母、垫圈为实心标准件，按不剖绘制")
    g.范围(-半宽, -k - 4, 半宽, y顶 + 4)
    return g


# ------------------------------------------------------------------ 7 螺柱连接
def 螺柱连接画法(d=20.0, t=25.0, bm=None):
    """双头螺柱连接（主视全剖 + 轴线竖直）。

    依据：图8-29 p.234 [核]（螺柱连接的画法）
      bm 默认取 d（钢/青铜，GB/T 897）；旋入端螺纹终止线与结合面重合（画成一条线）；
      螺孔深 = bm + 0.5d、孔深 = bm + d、孔底 120° 钻头角；
      弹簧垫圈 s=0.2d、外径 1.35d；螺母 m=0.8d、e=2d；伸出 a=0.3d。
    """
    bm = d if bm is None else bm
    s, m, a, e = 0.2 * d, 0.8 * d, 0.3 * d, 2.0 * d
    r, r1 = d / 2.0, 小径 * d / 2.0
    r光 = 光孔 * d / 2.0
    半宽 = 板半宽系数 * d
    螺孔深 = bm + 0.5 * d
    孔深 = bm + d
    h锥 = _锥深(r1)
    y尖 = -(孔深) - h锥
    y下底 = y尖 - 0.5 * d
    y顶 = t + s + m + a
    倒角 = 0.1 * d
    if r光 >= 半宽:
        raise ValueError("板宽不足")

    g = 图形()
    # 上件（薄板）轮廓 + 下件（机座）轮廓
    g.加(线(-半宽, 0, -半宽, t), 线(半宽, 0, 半宽, t), 线(-半宽, t, 半宽, t),
         线(-半宽, 0, -r光, 0), 线(r光, 0, 半宽, 0),          # 结合面（一条线，兼作旋入端终止线）
         线(-半宽, y下底, -半宽, 0), 线(半宽, y下底, 半宽, 0),
         线(-半宽, y下底, 半宽, y下底))
    # 上件光孔
    g.加(线(-r光, 0, -r光, t), 线(r光, 0, r光, t))
    # 螺柱：大径粗实线（-bm 到顶端倒角）
    g.加(线(-r, -bm, -r, y顶 - 倒角), 线(r, -bm, r, y顶 - 倒角),
         线(-r, y顶 - 倒角, -r + 倒角, y顶), 线(r, y顶 - 倒角, r - 倒角, y顶),
         线(-r + 倒角, y顶, r - 倒角, y顶))
    # 螺柱小径细实线：自顶端到旋入端（旋合段按外螺纹，与螺孔小径粗线共线）
    g.加(线(-r1, -bm, -r1, y顶 - 倒角, "thin"), 线(r1, -bm, r1, y顶 - 倒角, "thin"))
    # 螺孔：大径细实线（未旋合段，-bm 到 -(bm+0.5d)）
    g.加(线(-r, -bm, -r, -螺孔深, "thin"), 线(r, -bm, r, -螺孔深, "thin"))
    # 螺孔小径粗实线：自 -bm 到孔深末端，再接 120° 锥尖（底孔≈D1）
    g.加(线(-r1, -bm, -r1, -孔深), 线(r1, -bm, r1, -孔深),
         线(-r1, -孔深, 0.0, y尖), 线(r1, -孔深, 0.0, y尖))
    # 螺孔螺纹终止线：两小段，自大径细线到小径粗线
    g.加(线(-r, -螺孔深, -r1, -螺孔深), 线(r1, -螺孔深, r, -螺孔深))
    # 弹簧垫圈（薄矩形 + 切口斜线）与螺母
    g.加(矩形(-1.35 * d / 2.0, t, 1.35 * d, s))
    g.加(线(-1.35 * d / 2.0, t + s * 0.85, 1.35 * d / 2.0, t + s * 0.15, "thin"))
    g.加(矩形(-e / 2.0, t + s, e, m))
    # 剖面线：上件 45°/2.5，下件 -45°/2.5
    上左, 上右 = _双片剖面(半宽, r光, 0.0, t, 2.5, 45.0)
    下块 = _环剖面(半宽, r1, 0.0, y下底, -孔深, y尖)
    g.加(剖面线(上左, 2.5, 45.0), 剖面线(上右, 2.5, 45.0), 剖面线(下块, 2.5, -45.0))
    # 轴线
    g.加(线(0, y下底 - 4, 0, y顶 + 4, "center"))

    g.注(f"螺柱 M{d:g}，bm={bm:g}（默认 d）；螺孔深=bm+0.5d={螺孔深:g}，孔深=bm+d={孔深:g}",
         f"弹簧垫圈 s=0.2d={s:g}、外径 1.35d={1.35 * d:g}；螺母 m=0.8d={m:g}，伸出 a=0.3d={a:g}",
         "旋入端螺纹终止线与结合面重合，画成一条线",
         "螺柱、弹簧垫圈、螺母按不剖绘制")
    g.范围(-半宽, y下底 - 4, 半宽, y顶 + 4)
    return g


# ------------------------------------------------------------------ 8 螺钉连接
def 螺钉连接画法(d=10.0, t=20.0, bm=None):
    """开槽圆柱头螺钉连接（主视全剖 + 俯视，轴线竖直）。

    依据：图8-31 p.235 [核]（螺钉连接的画法）
      上件光孔 1.1d；下件螺孔（螺孔深 bm+0.5d、孔深 bm+d、120° 钻头角）；
      螺钉头坐落上件顶面；一字槽：主视画与轴线重合的一小段加粗线，俯视画 45° 粗线；
      bm 默认 d。螺钉头径/头高页图未标（“按标准查表”），此处取 1.8d / 0.7d 为示意值。
    """
    bm = d if bm is None else bm
    头径, 头高 = 1.8 * d, 0.7 * d
    r, r1 = d / 2.0, 小径 * d / 2.0
    r光 = 光孔 * d / 2.0
    半宽 = 板半宽系数 * d
    螺孔深 = bm + 0.5 * d
    孔深 = bm + d
    h锥 = _锥深(r1)
    y尖 = -孔深 - h锥
    y下底 = y尖 - 0.5 * d
    y头顶 = t + 头高
    if r光 >= 半宽:
        raise ValueError("板宽不足")

    g = 图形()
    # 上件（薄板）与下件轮廓
    g.加(线(-半宽, 0, -半宽, t), 线(半宽, 0, 半宽, t), 线(-半宽, t, 半宽, t),
         线(-半宽, 0, -r光, 0), 线(r光, 0, 半宽, 0),
         线(-半宽, y下底, -半宽, 0), 线(半宽, y下底, 半宽, 0),
         线(-半宽, y下底, 半宽, y下底))
    # 上件光孔 1.1d
    g.加(线(-r光, 0, -r光, t), 线(r光, 0, r光, t))
    # 螺钉头（坐落上件顶面，不剖）
    g.加(矩形(-头径 / 2.0, t, 头径, 头高))
    # 一字槽（主视）：与轴线重合的一小段加粗线
    g.加(线(0, y头顶 - 0.3 * 头高, 0, y头顶))
    # 螺钉杆（大径粗实线），杆端平头；（螺纹段在 bm 以内）
    g.加(线(-r, -bm, -r, t), 线(r, -bm, r, t), 线(-r, -bm, r, -bm))
    # 螺纹小径细实线：自结合面到杆端
    g.加(线(-r1, -bm, -r1, 0.0, "thin"), 线(r1, -bm, r1, 0.0, "thin"))
    # 螺孔：未旋合段大径细实线 + 小径粗实线 + 终止线两小段 + 120° 锥尖
    g.加(线(-r, -bm, -r, -螺孔深, "thin"), 线(r, -bm, r, -螺孔深, "thin"))
    g.加(线(-r1, -bm, -r1, -孔深), 线(r1, -bm, r1, -孔深),
         线(-r1, -孔深, 0.0, y尖), 线(r1, -孔深, 0.0, y尖))
    g.加(线(-r, -螺孔深, -r1, -螺孔深), 线(r1, -螺孔深, r, -螺孔深))
    # 剖面线：上件 45°/2.0，下件 -45°/2.0
    上左, 上右 = _双片剖面(半宽, r光, 0.0, t, 2.0, 45.0)
    下块 = _环剖面(半宽, r1, 0.0, y下底, -孔深, y尖)
    g.加(剖面线(上左, 2.0, 45.0), 剖面线(上右, 2.0, 45.0), 剖面线(下块, 2.0, -45.0))
    # 俯视图（头部圆 + 45° 一字槽 + 十字中心线）
    cx = 半宽 + 1.5 * 头径
    g.加(圆(cx, 0, 头径 / 2.0),
         线(cx - 0.35 * 头径, -0.35 * 头径, cx + 0.35 * 头径, 0.35 * 头径),
         线(cx - 0.75 * 头径, 0, cx + 0.75 * 头径, 0, "center"),
         线(cx, -0.75 * 头径, cx, 0.75 * 头径, "center"))
    # 主视轴线
    g.加(线(0, y下底 - 4, 0, y头顶 + 4, "center"))

    g.注(f"螺钉 M{d:g}，bm={bm:g}（默认 d）；螺孔深=bm+0.5d={螺孔深:g}，孔深=bm+d={孔深:g}",
         f"上件光孔 1.1d={光孔 * d:g}；头径 1.8d、头高 0.7d 为示意值（页图未标，实际查表）",
         "一字槽：主视为轴线上的一小段加粗线，俯视为 45° 粗线（即双倍粗实线）")
    g.范围(-半宽, min(y下底 - 4, -0.75 * 头径 - 2), cx + 0.75 * 头径 + 2, max(y头顶 + 4, 0.75 * 头径 + 2))
    return g


# ------------------------------------------------------------------ 自检
def _自检():
    cases = [螺栓连接画法(), 螺栓连接画法(垫圈=False), 螺柱连接画法(),
             螺钉连接画法(), 螺柱连接画法(bm=25.0)]
    for i, g in enumerate(cases, 1):
        ok, msg = 校验图元(g.elems)
        assert ok, f"#{i} {msg}"
        print(f"#{i} {len(g):>3} 图元  {msg}  bbox={tuple(round(v, 2) for v in g.bbox)}")

    d = 20.0
    g = 螺栓连接画法()
    xs = {round(dd["x1"], 3) for k, dd in g.elems if k == "line"}
    assert 11.0 in xs, "光孔 1.1d/2=11 缺失"
    assert 10.0 in xs and 8.5 in xs, "大径 10 / 小径 8.5 缺失"
    矩形s = [(dd["x"], dd["w"], dd["h"]) for k, dd in g.elems if k == "rect"]
    assert (-22.0, 44.0, 3.0) in [(round(a, 3), round(b, 3), round(c, 3)) for a, b, c in 矩形s], \
        f"垫圈 2.2d × 0.15d 缺失：{矩形s}"
    print("螺栓连接：头高 k=%.1f（矩形 -k..0）、螺母 m=%.1f、垫圈 h=%.1f、光孔半 %.1f、垫圈半 %.1f"
          % (0.7 * d, 0.8 * d, 0.15 * d, 0.55 * d, 1.1 * d))
    g2 = 螺柱连接画法()
    print("螺柱连接：bm=%.1f 螺孔深=%.1f 孔深=%.1f 弹簧垫圈 s=%.1f 外径=%.1f"
          % (d, 1.5 * d, 2.0 * d, 0.2 * d, 1.35 * d))
    g3 = 螺钉连接画法()
    print("螺钉连接：bm=%.1f 螺孔深=%.1f 孔深=%.1f 光孔=%.1f 头径=%.1f（示意）"
          % (10, 15, 20, 11, 18))


if __name__ == "__main__":
    _自检()

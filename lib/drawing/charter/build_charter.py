APPENDIX_A = """## 附录 A　常见错误对照

| 表现 | 根因 | 修正与复查 |
|---|---|---|
| 主视与断面尺寸不同 | 多份参数分别硬编码 | 改为同一特征模型驱动，比较还原后的真实量 |
| 槽口方向不对应 | 未定义视图坐标和观察轴 | 从特征方向向量重新投影，核对剖切箭头 |
| 槽口被完整圆穿过 | 先画整圆后忘记扣除缺口 | 直接生成开口轮廓，检查槽口角区及拓扑 |
| 圆弧多出一条弦线 | 使用自动闭合多边形 | 改用开放圆弧或开放折线，核对端点连接 |
| 名义轮廓可画，公差极限不能成形 | 只检查公称尺寸 | 核查最大圆角和最小台阶、实际净距 |
| 倒角看起来有，但尖角仍在 | 旧端面和旧母线未截短 | 删除不再存在的边段，按真实切点重建 |
| 引线穿字、穿基准框 | 只检查实体外形，没有检查标注包络 | 为文字和框留区，移动整组标注并重检 |
| 偏差数字压尺寸线 | 只给主值计算留白 | 将主值与上下偏差合组计算尺寸 |
| 标题栏横线穿过名称 | 合并格仍输出完整网格 | 按实际单元格边界重建格线 |
| 字体突然变宽或换形 | 静默字体回退或子集字宽损坏 | 核查字体加载、字符映射及实际文字包围盒 |
| 辅助功能带变成实体台阶 | 精度要求混入几何模型 | 将功能区移到精度层，用适用范围表示 |
| 自检零报错，实际仍有圆弧穿字 | 检查器未处理路径 | 补足路径覆盖，未补足前记为未自动检查 |
| 所有线位同时误报 | 坐标重复翻转或截图偏移错误 | 标定根坐标到像素映射后再判断图是否需要修改 |
| 改完后预览仍像旧图 | 渲染失败、缓存或交付版本混用 | 检查执行结果与哈希，重建当前版本预览 |
"""


def build(doc):
    rules = doc["rules"]
    by_ch = collections.OrderedDict()
    for r in rules:
        by_ch.setdefault(r["id"].split("-")[0], []).append(r)
    c = collections.Counter(r["st"] for r in rules)
    n = len(rules)
    L = []
    A = L.append
    A("# 机械零件矢量制图章程（drawing 模块）")
    A("")
    A("版本 %s　·　%s　·　条款 %d 条" % (doc["version"], doc["date"], n))
    A("")
    A("> 本文件是 `lib/drawing` 的章程，对模块内的生成器、校验器与交付物有约束力。")
    A("> 条款的机器可读形式是 `charter/rules.json`；本文件由 `charter/build_charter.py` 生成，")
    A("> 不要直接改本文件——改 `rules.json` 后重跑生成器，再用 `charter/check_charter.py` 校验一致性。")
    A("")
    A("## 0　条款状态与约束力")
    A("")
    A("每条条款有一个状态，标在条款 id 之后：")
    A("")
    A("| 标记 | 含义 | 交付时的处理 |")
    A("|---|---|---|")
    A("| `[A]` | 有自动检查 | 检查不通过即不得交付 |")
    A("| `[M]` | 本质上需要人工判断 | 必须有人签字，并在自检记录里写明依据 |")
    A("| `[X]` | 已规定，但当前没有自动检查 | **不得声称已符合**；必须人工核，并在自检记录中标“未自动检查” |")
    A("")
    A("当前覆盖率：**A %d 条（%.1f%%）／ M %d 条 ／ X %d 条**。" % (
        c["A"], 100 * c["A"] / n, c["M"], c["X"]))
    A("")
    A("这个比例是事实，不是目标。任何“本章程已全部落实”的说法，都必须先把 X 清零；")
    A("在此之前，交付物只能声明“按本章程人工核对，自动检查覆盖 %.1f%%”。" % (100 * c["A"] / n))
    A("")
    A("条款等级：**必**（不通过不得交付）／**应**（偏离须在自检记录中说明）。")
    A("")
    for pre, title in [(k, v[0]) for k, v in INTRO.items()]:
        if pre not in by_ch:
            continue
        A("## %s　%s" % (rules_by_prefix(by_ch, pre), title))
        A("")
        A(INTRO[pre][1])
        A("")
        for r in by_ch[pre]:
            A("- **%s** `%s` %s　%s" % (r["id"], r["st"], r["sev"], r["req"]))
        A("")
    A(APPENDIX_A)
    A("")
    A("## 附录 B　与原始规程的对应")
    A("")
    A("| 原始章节 | 去处 |")
    A("|---|---|")
    A("| §1 执行规则 | 第 1 章 GEN |")
    A("| §2 输入清单 | 第 2 章 IN |")
    A("| §3 标准依据 | 第 3 章 STD |")
    A("| §4 六层模型 | 第 4 章 MDL |")
    A("| §5 视图与剖切 | 第 5 章 VIEW |")
    A("| §6 几何成立性 | 第 6 章 GEO |")
    A("| §7 幅面线型字体 | 第 7 章 SHT |")
    A("| §8 尺寸公差 | 第 8 章 DIM |")
    A("| §9 工作库用法 | 第 9 章 LIB；接口签名见 `charter/api.md`（由代码反射生成） |")
    A("| §10 字体落地 | 第 10 章 FONT |")
    A("| §11 排版 | 第 11 章 LAY |")
    A("| §12 图元身份 | 第 12 章 ID |")
    A("| §13 四层自检 | 第 13 章 CHK |")
    A("| §14 可复现渲染 | 第 14 章 RUN |")
    A("| §15 检查器自检 | 第 15 章 MUT |")
    A("| §16 常见错误 | 附录 A（原样保留） |")
    A("| §17 交付门禁 | 第 17 章 GATE |")
    A("| §18 执行指令 | `charter/PROMPT.md`（给外部 AI 的入口） |")
    A("")
    return "\n".join(L)


def rules_by_prefix(by_ch, pre):
    return {"GEN": "1", "IN": "2", "STD": "3", "MDL": "4", "VIEW": "5", "GEO": "6",
            "SHT": "7", "DIM": "8", "LIB": "9", "FONT": "10", "LAY": "11", "ID": "12",
            "CHK": "13", "RUN": "14", "MUT": "15", "GATE": "17"}.get(pre, pre)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true")
    a = ap.parse_args()
    doc = json.loads((HERE / "rules.json").read_text(encoding="utf-8"))
    md = build(doc)
    if a.stdout:
        print(md)
    else:
        OUT.write_text(md, encoding="utf-8")
        print("wrote %s（%d 行，%d 字符）" % (OUT, md.count("\n") + 1, len(md)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
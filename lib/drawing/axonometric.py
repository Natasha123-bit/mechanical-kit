from lib.drawing._prim import 图形, 线, 圆, 文, 箭头, TEXT_H  # noqa: E402

COS30 = math.cos(math.radians(30))
SIN30 = 0.5


def 轴测变换(x, y, z, 类型="正等测"):
    """三维点 → 轴测图二维点。

    依据：图5-2 p.135 [核]（正等测三轴 120°、OX/OY 与水平成 30°）；
          图5-12 p.141 [核]（斜二测 ∠XOZ=90°、∠XOY=∠YOZ=135°、p=r=1、q=0.5）。
    正等测：X=(x−y)cos30°，Y=(x+y)sin30°+z（简化系数 p=q=r=1）。
    斜二测：X=x+0.5y·cos45°，Y=z+0.5y·sin45°（X-Z 面反映实形，y 向 45° 减半）。
    """
    if 类型 == "正等测":
        return ((x - y) * COS30, (x + y) * SIN30 + z)
    if 类型 == "斜二测":
        return (x + 0.5 * y * math.cos(math.radians(45)),
                z + 0.5 * y * math.sin(math.radians(45)))
    raise ValueError(f"类型 只能是 正等测/斜二测，收到 {类型!r}")


def 轴测轴(类型="正等测", 长=40, x=0, y=0):
    """画 OX/OY/OZ 三根轴测轴 + 箭头 + 轴间角注记。

    依据：图5-2 p.135 [核]（正等测三轴 120°）、图5-12 p.141 [核]（斜二测轴间角）。
    轴长 为示意；O 为原点；箭头在轴端。
    """
    if 长 <= 0:
        raise ValueError("长 必须 > 0")
    O = (x, y)
    dirs = {}
    for 名, p in (("X", (1, 0, 0)), ("Y", (0, 1, 0)), ("Z", (0, 0, 1))):
        dx, dy = 轴测变换(*p, 类型=类型)
        dirs[名] = (dx, dy)
    g = 图形()
    for 名, (dx, dy) in dirs.items():
        ex, ey = O[0] + dx * 长, O[1] + dy * 长
        g.加(线(O[0], O[1], ex, ey, "thin"), 箭头(O[0], O[1], ex, ey, size=2.5),
             文(ex + 2 * (1 if dx >= 0 else -1), ey + 2, 名, TEXT_H,
                anchor="start" if dx >= 0 else "end"))
    g.加(圆(O[0], O[1], 0.8, "thick"))
    if 类型 == "正等测":
        g.注("正等测：轴间角 120°，OX/OY 与水平成 30°，p=q=r=1（图5-2 p.135）")
        角 = 120
    else:
        g.注("斜二测：∠XOZ=90°，∠XOY=∠YOZ=135°，p=r=1、q=0.5（图5-12 p.141）")
        角 = 135
    g.范围(x - 3, y - 3, x + 长 + 8, y + 长 + 8)
    g.参数 = dict(O=O, 方向=dirs, 轴间角=角)
    return g


def _立方体顶点(长, 宽, 高, 类型, x, y):
    pts = {}
    for i, (a, b, c) in enumerate(((0, 0, 0), (长, 0, 0), (长, 宽, 0), (0, 宽, 0),
                                   (0, 0, 高), (长, 0, 高), (长, 宽, 高), (0, 宽, 高))):
        X, Y = 轴测变换(a, b, c, 类型=类型)
        pts[i] = (x + X, y + Y)
    return pts


def 正等轴测(长=60, 宽=40, 高=30, x=0, y=0):
    """长方体正等轴测：可见的三个面用粗实线，不可见的三条棱用细虚线。

    依据：图5-2 p.135 [核]（轴间角与轴向系数）、图5-4 p.136 [核]（坐标法：先定原点，
          沿轴量取，只画可见轮廓）。简化系数 p=q=r=1；实际长度放大 1.22 倍由 轴测变换 体现。
    顶点编号：0 前下左、1 前下右、2 后下右、3 后下左、4~7 为对应上顶点。
    """
    if 长 <= 0 or 宽 <= 0 or 高 <= 0:
        raise ValueError("长、宽、高 必须 > 0")
    p = _立方体顶点(长, 宽, 高, "正等测", x, y)
    g = 图形()
    # 可见：前面 0-1-5-4、右面 1-2-6-5、顶面 4-5-6-7
    for a, b in ((0, 1), (1, 2), (2, 6), (6, 7), (7, 4), (4, 0),
                 (1, 5), (5, 6), (4, 5), (0, 4)):
        g.加(线(*p[a], *p[b], "thick"))
    # 不可见：3-0、3-2、3-7
    for a, b in ((3, 0), (3, 2), (3, 7)):
        g.加(线(*p[a], *p[b], "hidden"))
    g.注("正等轴测：p=q=r=1，轴间角 120°；不可见棱用细虚线（图5-2/5-4 p.135–136）")
    xs = [q[0] for q in p.values()]; ys = [q[1] for q in p.values()]
    g.范围(min(xs) - 3, min(ys) - 3, max(xs) + 3, max(ys) + 3)
    g.参数 = dict(顶点=p, 长=长, 宽=宽, 高=高)
    return g


def 斜二测(长=60, 宽=40, 高=30, x=0, y=0):
    """长方体斜二轴测：X-Z 面（前面）反映实形，Y 向 45°、长度减半。

    依据：图5-12 p.141 [核]（∠XOZ=90°、∠XOY=∠YOZ=135°、p=r=1、q=0.5）、
          图5-13 p.142 [核]（平行 XOZ 面的形状反映实形）。
    可见/不可见棱的取舍同 正等轴测。
    """
    if 长 <= 0 or 宽 <= 0 or 高 <= 0:
        raise ValueError("长、宽、高 必须 > 0")
    p = _立方体顶点(长, 宽, 高, "斜二测", x, y)
    g = 图形()
    for a, b in ((0, 1), (1, 2), (2, 6), (6, 7), (7, 4), (4, 0),
                 (1, 5), (5, 6), (4, 5), (0, 4)):
        g.加(线(*p[a], *p[b], "thick"))
    for a, b in ((3, 0), (3, 2), (3, 7)):
        g.加(线(*p[a], *p[b], "hidden"))
    g.注("斜二测：前面（XOZ）反映实形，Y 向 45° 且 q=0.5（图5-12/5-13 p.141–142）")
    xs = [q[0] for q in p.values()]; ys = [q[1] for q in p.values()]
    g.范围(min(xs) - 3, min(ys) - 3, max(xs) + 3, max(ys) + 3)
    g.参数 = dict(顶点=p, 长=长, 宽=宽, 高=高)
    return g


def _椭圆折线(g, cx, cy, a, b, style, n=72):
    pts = [(cx + a * math.cos(2 * math.pi * i / n), cy + b * math.sin(2 * math.pi * i / n))
           for i in range(n + 1)]
    for p, q in zip(pts, pts[1:]):
        g.加(线(p[0], p[1], q[0], q[1], style))
    return pts


def 圆柱正等轴测(直径=30, 高=40, x=0, y=0):
    """圆柱正等轴测：顶/底圆为椭圆（长短轴 1.22d / 0.70d），两侧为竖向转向线。

    依据：图5-7 p.138 [核]（圆柱正等轴测的椭圆四段圆弧近似：菱形、四个圆心、移心法）、
          图5-8 p.138 [核]（轴线垂直 H 面时，圆所在平面内的轴测轴）。
    本函数用参数椭圆折线绘制（与四段圆弧同为近似椭圆），长轴 1.22d 沿水平、短轴 0.70d 沿竖向；
    顶椭圆粗实线、底椭圆细实线（被遮挡部分不另分可见段），两条竖向转向线粗实线。
    """
    if 直径 <= 0 or 高 <= 0:
        raise ValueError("直径、高 必须 > 0")
    d = float(直径)
    长轴, 短轴 = 1.22 * d, 0.70 * d
    bx, by = 轴测变换(0, 0, 0, 类型="正等测")
    tx, ty = 轴测变换(0, 0, 高, 类型="正等测")
    cb = (x + bx, y + by)
    ct = (x + tx, y + ty)

    g = 图形()
    _椭圆折线(g, ct[0], ct[1], 长轴 / 2, 短轴 / 2, "thick")
    _椭圆折线(g, cb[0], cb[1], 长轴 / 2, 短轴 / 2, "thin")
    for s in (-1, 1):
        g.加(线(ct[0] + s * 长轴 / 2, ct[1], cb[0] + s * 长轴 / 2, cb[1], "thick"))
    g.加(线(ct[0], ct[1] - 短轴 / 2 - 3, cb[0], cb[1] + 短轴 / 2 + 3, "center"))
    g.注("圆柱正等轴测：顶/底椭圆 1.22d×0.70d，四段圆弧近似（图5-7 p.138）")
    g.范围(ct[0] - 长轴 / 2 - 3, cb[1] - 短轴 / 2 - 3,
           ct[0] + 长轴 / 2 + 3, ct[1] + 短轴 / 2 + 3)
    g.参数 = dict(顶=ct, 底=cb, 长轴=长轴, 短轴=短轴)
    return g

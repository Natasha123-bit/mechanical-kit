def _交叠(a, b, 容差=0.0):
    """两个包围盒 (x0,y0,x1,y1) 是否相交（容差 >0 时允许贴边）。"""
    return not (a[2] <= b[0] + 容差 or b[2] <= a[0] + 容差
                or a[3] <= b[1] + 容差 or b[3] <= a[1] + 容差)


def 装配图一页(视图=None, 件表=None, 序号表=None, 件名="装配图", 图号="", 比例="1:1",
               幅面="A3", 装订边="左", 横放=True, 单位名称="", 设计="", 审核="", 日期="",
               完整明细=True, 间距=5.0):
    """一页完整装配图 = 图框 + 视图 + 序号 + 明细栏 + 标题栏。

    依据：图1-15 p.9（标题栏 180×56）、图1-17 p.9 与图9-19 p.270（明细栏 180 宽、
    行高 7、序号自下而上）、图9-15/9-16 p.265（序号引线）。

    参数
    ----
    视图   : 图形()（原点随意，函数会平移到空白区居中）；None → 只出框和栏
    件表   : [{序号,代号,名称,数量,材料,单件,总计,备注}]，序号 1 落在明细栏最下一行
    序号表 : [(编号, 起点xy, 终点xy) 或 (编号, 起点, 终点, 形式)]，坐标用**视图局部坐标**，
             函数跟着视图一起平移；不给形式按 "短线"
    间距   : 视图与图框/标题栏之间的最小空隙

    版面检查（任一不过直接 ValueError，不出半张图）：
      1. 视图平移后必须落在「图框 − 标题栏 − 明细栏」的空白区里
      2. 件表的序号集合 == 序号表的编号集合（不漏标，也不标明细里没有的零件）
      3. 编号不重复
      4. 每条序号引线都在图框内，且不压标题栏/明细栏
    """
    框 = _sheet.图框(幅面=幅面, 比例=比例, 装订边=装订边, 横放=横放)
    标题 = _sheet.标题栏(件名=件名, 比例=比例, 图号=图号, 设计=设计, 审核=审核,
                        日期=日期, 单位名称=单位名称, 幅面=幅面, 装订边=装订边, 横放=横放)
    tx, ty = 标题.参数["原点"]
    tw, th = 标题.参数["尺寸"]
    明细 = 明细栏(件表, x=tx, y=ty + th, 完整=完整明细, 幅面=幅面, 装订边=装订边)

    W, H = 框.参数["W"], 框.参数["H"]
    左, 三边 = 框.参数["框"]
    框内 = (左, 三边, W - 三边, H - 三边)
    栏块 = (tx, ty, tx + tw, ty + th + 明细.参数["高"])
    # 空白区是个 L 形：左带（栏块左侧、全高）与上带（栏块上沿以上、全宽）。
    # 哪个装得下且面积大就用哪个——明细行少时上带更宽，行多时左带更合适。
    候选区 = [(框内[0] + 间距, 框内[1] + 间距, 栏块[0] - 间距, 框内[3] - 间距),
              (框内[0] + 间距, 栏块[3] + 间距, 框内[2] - 间距, 框内[3] - 间距)]
    视图区 = max(候选区, key=lambda r: max(0, r[2] - r[0]) * max(0, r[3] - r[1]))

    g = 图形().加(框)
    dx = dy = 0.0
    if 视图 is not None:
        vb = 视图.bbox
        vw, vh = vb[2] - vb[0], vb[3] - vb[1]
        aw, ah = 视图区[2] - 视图区[0], 视图区[3] - 视图区[1]
        能放 = [r for r in 候选区 if r[2] - r[0] >= vw - 1e-9 and r[3] - r[1] >= vh - 1e-9]
        if not 能放:
            raise ValueError(
                "视图 %.1f×%.1f 放不进任何空白区（左带/上带最大 %.1f×%.1f；%s 横放=%s，"
                "标题栏+明细栏占右下角 %d 行）——要么缩小比例，要么减少明细行数"
                % (vw, vh, max(r[2] - r[0] for r in 候选区), max(r[3] - r[1] for r in 候选区),
                   幅面, 横放, len(件表 or [])))
        视图区 = max(能放, key=lambda r: (r[2] - r[0]) * (r[3] - r[1]))
        aw, ah = 视图区[2] - 视图区[0], 视图区[3] - 视图区[1]
        dx = (视图区[0] + 视图区[2]) / 2 - (vb[0] + vb[2]) / 2
        dy = (视图区[1] + 视图区[3]) / 2 - (vb[1] + vb[3]) / 2
        g.加(平移(视图, dx, dy))

    mx, my = 明细.参数["左下"]
    mw, mh = 明细.参数["宽"], 明细.参数["高"]
    号s = []
    for item in (序号表 or []):
        编号, p1, p2 = item[0], item[1], item[2]
        形式 = item[3] if len(item) > 3 else "短线"
        one = 序号(编号, (p1[0] + dx, p1[1] + dy), (p2[0] + dx, p2[1] + dy), 形式)
        bb = one.bbox
        if not (框内[0] <= bb[0] and bb[2] <= 框内[2] and 框内[1] <= bb[1] and bb[3] <= 框内[3]):
            raise ValueError("序号 %r 的引线超出图框：bbox=%r" % (编号, bb))
        if _交叠(bb, (tx, ty, tx + tw, ty + th)) or _交叠(bb, (mx, my, mx + mw, my + mh)):
            raise ValueError("序号 %r 的引线压到标题栏/明细栏：bbox=%r" % (编号, bb))
        号s.append(one)

    if 序号表:
        编号们 = [it[0] for it in 序号表]
        if len(set(编号们)) != len(编号们):
            raise ValueError("序号编号重复：%r" % (编号们,))
    if 件表 is not None and 序号表 is not None:
        表号 = [x for x in (r.get("序号") for r in 件表) if x not in (None, "")]
        if sorted(map(int, 表号)) != sorted(map(int, [it[0] for it in 序号表])):
            raise ValueError("件表序号 %r 与图上序号 %r 不一致（漏标或多标）"
                             % (sorted(map(int, 表号)), sorted([it[0] for it in 序号表])))

    g.加(*号s)
    g.加(明细, 标题)
    g.参数 = dict(幅面=幅面, 比例=比例, 装订边=装订边, 横放=横放, W=W, H=H,
                视图区=视图区, 平移=(dx, dy), 标题栏=(tx, ty, tw, th),
                明细栏=明细.参数, 件数=len(件表 or []), 序号数=len(号s))
    g.范围(0, 0, W, H)
    校验图元(g.elems)
    return g



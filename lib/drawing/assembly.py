def 序号(编号=1, 起点=(0.0, 0.0), 终点=(30.0, 20.0), 形式="短线"):
    """零件序号：引线 + 起点标记 + 终端（短线/圆/直接）。依据：图9-15/9-16 p.265 [核]。

    编号字高 5（比尺寸数字大 1~2 号）；起点用实心小箭头指向零件（薄件允许箭头）。
    """
    if 形式 not in ("短线", "圆", "直接"):
        raise ValueError('形式 只能是 "短线"/"圆"/"直接"')
    sx, sy = 起点
    ex, ey = 终点
    g = 图形().加(线(sx, sy, ex, ey, "thin"), 箭头(ex, ey, sx, sy, size=1.5))
    if 形式 == "短线":
        g.加(线(ex, ey, ex + 8, ey, "thin"))
        g.加(文(ex + 4, ey + 2, str(编号), 5))
        g.范围(sx - 2, min(sy, ey) - 4, ex + 12, max(sy, ey) + 6)
    elif 形式 == "圆":
        g.加(圆(ex, ey, 4, "thin"), 文(ex, ey, str(编号), 5))
        g.范围(sx - 2, min(sy, ey) - 6, max(ex, sx) + 6, max(sy, ey) + 6)
    else:
        g.加(文(ex + 3, ey + 2, str(编号), 5, anchor="start"))
        g.范围(sx - 2, min(sy, ey) - 4, ex + 8, max(sy, ey) + 6)
    g.参数 = dict(编号=编号, 形式=形式)
    return g


def 明细栏(行列表=None, x=None, y=None, 完整=True, 幅面="A3", 装订边="左"):
    """明细栏：标题栏正上方，序号自下而上。依据：图1-17 p.9 [核]；图9-19 p.270 [核]。

    完整=True：180 宽，列宽 8/40/44/8/38/10/12/20，表头 14、数据行 7；
    完整=False：5 列 8/60/50/30/32（序号/名称/数量/材料/备注）。
    x,y 为左下角；默认 A3 左装订标题栏上方 (235, 61)。
    """
    行列表 = 行列表 or [dict(序号=1, 代号="", 名称="轴承座", 数量=1, 材料="HT150", 备注=""),
                       dict(序号=2, 代号="", 名称="轴瓦", 数量=2, 材料="ZCuSn10P1", 备注="")]
    if x is None:
        x = 420 - 5 - 180
    if y is None:
        y = 61.0
    if 完整:
        列 = _明细列
        键 = ["序号", "代号", "名称", "数量", "材料", "单件", "总计", "备注"]
        表头高 = 14
    else:
        列 = _简列
        键 = ["序号", "名称", "数量", "材料", "备注"]
        表头高 = 7
    宽 = sum(列)
    n = len(行列表)
    高 = 表头高 + 7 * n
    g = 图形().加(矩形(x, y, 宽, 高, "thick"))
    线位 = [0]
    for w in 列:
        线位.append(线位[-1] + w)
    for dx in 线位[1:-1]:
        g.加(线(x + dx, y, x + dx, y + 高, "thin"))
    # 表头在上，数据行自下而上
    yh = y + 7 * n
    g.加(线(x, yh, x + 宽, yh, "thin"))
    for k, w, dx in zip(键, 列, 线位[:-1]):
        g.加(文(x + dx + w / 2, yh + 表头高 / 2, k, 3.5))
    for i, row in enumerate(行列表):
        yb = y + 7 * i
        for k, w, dx in zip(键, 列, 线位[:-1]):
            val = row.get(k, "") if isinstance(row, dict) else ""
            if val not in ("", None):
                字号 = 3.5
                while 字号 > 2 and len(str(val)) * 0.55 * 字号 > w - 1:
                    字号 -= 0.2
                g.加(文(x + dx + w / 2, yb + 3.5, str(val), 字号))
    g.参数 = dict(宽=宽, 高=高, 行数=n, 列宽=列, 左下=(x, y))
    g.范围(x - 2, y - 2, x + 宽 + 2, y + 高 + 2)
    return g


def 装配结构(类型="接触面", 宽=50.0, 高=16.0, x=0.0, y=0.0, 形式="双螺母"):
    """装配结构示意。依据：图9-4 p.257、图9-8/9-9 p.261、图9-13/9-14 p.263 [核]。

    接触面：结合面只画一条 thick，两件剖面线方向相反；
    非接触面：留 1mm 间隙，两条 thick；
    防松：双螺母/弹簧垫圈/开口销；防漏：压盖+填料。
    """
    g = 图形()
    if 类型 == "接触面":
        g.加(矩形(x, y, 宽, 高, "thick"), 线(x, y + 高 / 2, x + 宽, y + 高 / 2, "thick"))
        g.加(剖面线([(x, y), (x + 宽, y), (x + 宽, y + 高 / 2), (x, y + 高 / 2)], 2.0, 45.0))
        g.加(剖面线([(x, y + 高 / 2), (x + 宽, y + 高 / 2), (x + 宽, y + 高), (x, y + 高)], 2.0, -45.0))
    elif 类型 == "非接触面":
        g.加(矩形(x, y, 宽, 高, "thick"), 矩形(x, y + 高 + 1.0, 宽, 高, "thick"))
    elif 类型 == "防松":
        g.加(矩形(x, y, 宽, 30, "thick"), 线(x + 5, y - 8, x + 5, y, "thick"),
             线(x + 宽 - 5, y - 8, x + 宽 - 5, y, "thick"))
        if 形式 == "双螺母":
            g.加(矩形(x + 5, y + 18, 10, 7, "thick"), 矩形(x + 5, y + 25, 10, 7, "thick"))
        elif 形式 == "弹簧垫圈":
            g.加(线(x + 5, y + 18, x + 15, y + 21, "thick"))
        else:  # 开口销
            g.加(线(x + 5, y + 18, x + 15, y + 18, "thick"),
                 线(x + 5, y + 18, x + 1, y + 24, "thick"))
    elif 类型 == "防漏":
        g.加(矩形(x, y, 宽, 20, "thick"), 矩形(x + 10, y + 20, 30, 8, "thick"))
        g.加(剖面线([(x + 10, y), (x + 40, y), (x + 40, y + 8), (x + 10, y + 8)], 1.5, 45.0))
        g.加(线(x + 12, y + 10, x + 38, y + 10, "thick"))
    else:
        raise NotImplementedError(f"装配结构 类型 未实现：{类型!r}")
    g.参数 = dict(类型=类型, 形式=形式)
    g.范围(x - 3, y - 10, x + 宽 + 3, y + 高 + 14)
    return g


def 滑动轴承装配图(cx=0.0, cy=0.0):
    """滑动轴承装配图示意：轴承座 + 上下轴瓦 + 轴 + 油杯 + 螺栓 + 序号。依据：图9-2 p.255 [核]。

    接触面只画一条线；轴瓦与轴承座剖面线方向相反；轴为实心件不剖。
    外形尺寸为示意（书未给 mm）。
    """
    g = 图形()
    # 轴承座（下半，剖面线 45°）
    座 = [(-45, -40), (45, -40), (45, 5), (20, 5), (20, -10), (-20, -10), (-20, 5), (-45, 5)]
    for i in range(len(座)):
        g.加(线(*座[i], *座[(i + 1) % len(座)], "thick"))
    g.加(剖面线([(-45, -40), (-20, -40), (-20, 5), (-45, 5)], 2.5, 45.0))
    g.加(剖面线([(20, -40), (45, -40), (45, 5), (20, 5)], 2.5, 45.0))
    # 轴承盖（上半，剖面线 -45°）
    盖 = [(-45, 5), (-20, 5), (-20, 20), (20, 20), (20, 5), (45, 5), (45, 30), (-45, 30)]
    for i in range(len(盖)):
        g.加(线(*盖[i], *盖[(i + 1) % len(盖)], "thick"))
    g.加(剖面线([(-45, 5), (-20, 5), (-20, 30), (-45, 30)], 2.5, -45.0))
    g.加(剖面线([(20, 5), (45, 5), (45, 30), (20, 30)], 2.5, -45.0))
    # 上下轴瓦（半环，bush 外 r=20、内 r=15）
    for s in (1, -1):
        g.加(弧(cx, cy, 20, 0, 180, "thick") if s > 0 else 弧(cx, cy, 20, 180, 360, "thick"))
        g.加(弧(cx, cy, 15, 0, 180, "thick") if s > 0 else 弧(cx, cy, 15, 180, 360, "thick"))
    g.加(线(-20, 0, -15, 0, "thick"), 线(15, 0, 20, 0, "thick"))
    def 环(a0, a1, n=24):
        o = [(20 * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
              20 * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]
        ii = [(15 * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
               15 * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n, -1, -1)]
        return o + ii
    g.加(剖面线(环(0, 180), 1.5, 45.0), 剖面线(环(180, 360), 1.5, 45.0))
    # 轴（实心不剖）
    g.加(圆(cx, cy, 15, "thick"), 线(-20, 0, 20, 0, "center"), 线(0, -20, 0, 20, "center"))
    # 油杯
    g.加(矩形(-4, 30, 8, 6, "thick"), 圆(0, 38, 3, "thick"))
    # 螺栓（标准件不剖）
    for bx in (-35, 35):
        g.加(线(bx - 3, -45, bx - 3, 35, "thick"), 线(bx + 3, -45, bx + 3, 35, "thick"),
             线(bx - 6, 35, bx + 6, 35, "thick"))
    # 序号
    for n, (sx, sy, ex, ey) in enumerate([(-45, -35, -68, -20), (-45, 12, -68, 28),
                                          (45, 12, 68, 28), (0, 38, 12, 55),
                                          (35, 25, 55, 38)], 1):
        g.加(序号(n, (sx, sy), (ex, ey)))
    g.参数 = dict(cx=cx, cy=cy, 轴径=30, 轴瓦外径=40)
    g.范围(-70, -58, 70, 62)
    return g


def 拆画泵体零件图(cx=0.0, cy=0.0):
    """拆画泵体零件图示意（图9-30）：主视图 + 全剖左视图 A—A + 局部视图 B + 尺寸/技术要求。

    依据：图9-23/9-29/9-30 p.274–279 [核]。
    主视图：长圆形泵腔（两圆 + 上下直壁）+ 进出油口 + 底座 2×φ7；
    A—A：泵腔深度与端面；B：安装孔位置；尺寸与技术要求在图上。
    """
    g = 图形()
    # 主视图：泵体外框 + 长圆腔（左右半圆 + 上下直壁，不画整圆的内侧弧）
    g.加(矩形(cx - 45, cy - 45, 90, 80, "thick"),
         弧(cx - 25, cy, 20, 90, 270, "thick"),
         弧(cx + 25, cy, 20, -90, 90, "thick"),
         线(cx - 25, cy + 20, cx + 25, cy + 20, "thick"),
         线(cx - 25, cy - 20, cx + 25, cy - 20, "thick"))
    # 进出油口
    g.加(矩形(cx - 6, cy + 20, 12, 10, "thick"), 矩形(cx - 6, cy - 30, 12, 10, "thick"))
    # 底座安装孔（在外框内）
    g.加(圆(cx - 30, cy - 38, 3.5, "thick"), 圆(cx + 30, cy - 38, 3.5, "thick"))
    # 配作孔
    g.加(圆(cx - 8, cy - 8, 2.5, "thick"), 圆(cx + 8, cy - 8, 2.5, "thick"))
    # 中心线
    g.加(线(cx - 55, cy, cx + 55, cy, "center"), 线(cx - 25, cy - 30, cx - 25, cy + 35, "center"),
         线(cx + 25, cy - 30, cx + 25, cy + 35, "center"))
    # A—A 左视图
    ax = cx + 100
    g.加(矩形(ax - 20, cy - 40, 40, 80, "thick"),
         线(ax - 14, cy - 20, ax + 14, cy - 20, "thick"),
         线(ax - 14, cy + 20, ax + 14, cy + 20, "thick"),
         线(ax - 14, cy - 20, ax - 14, cy + 20, "thick"),
         线(ax + 14, cy - 20, ax + 14, cy + 20, "thick"))
    g.加(剖面线([(ax - 20, cy - 40), (ax - 14, cy - 40), (ax - 14, cy + 40), (ax - 20, cy + 40)], 2.0, 45.0))
    g.加(剖面线([(ax + 14, cy - 40), (ax + 20, cy - 40), (ax + 20, cy + 40), (ax + 14, cy + 40)], 2.0, 45.0))
    g.加(文(ax, cy + 48, "A—A", 3.5))
    # B 向局部视图（安装孔）
    bx, by = cx + 100, cy - 55
    g.加(矩形(bx - 20, by - 8, 40, 16, "thin"), 圆(bx - 12, by, 3.5, "thin"),
         圆(bx + 12, by, 3.5, "thin"), 文(bx, by + 12, "B 向", 3.5))
    # 尺寸与技术要求
    g.加(尺寸H(cy - 62, cx - 45, cx + 45, "90"),
         尺寸V(cx - 55, cy - 50, cy + 30, "80"),
         文(cx - 25, cy + 38, "R20", 3.2), 文(cx + 25, cy + 38, "R20", 3.2),
         文(cx + 55, cy + 10, "2×φ5 配作", 3.2, anchor="start"),
         文(cx + 55, cy - 14, "2×φ7", 3.2, anchor="start"))
    g.加(文(cx - 45, cy - 70, "技术要求：铸造圆角 R3；未注倒角 C0.5；材料 HT150；"
                              "Ra0.8~12.5；⊥0.01 A；∥0.01 A", 3.2, anchor="start"))
    g.参数 = dict(泵腔半径=20, 腔中心距=50, 底座=90, 安装孔="2×φ7", 配作孔="2×φ5")
    g.范围(cx - 60, cy - 80, ax + 30, cy + 52)
    return g



import sys
from pathlib import Path
MDKIT = Path(__file__).resolve().parents[2]
if str(MDKIT) not in sys.path: sys.path.insert(0, str(MDKIT))
from lib.drawing._prim import 图形, 校验图元, 线, 圆, 弧, 矩形, 文, 剖面线, 箭头, 波浪线, 双折线, 尺寸H, 尺寸V, 拼

import json

_TABLES = Path(__file__).resolve().parent / "tables" / "ch01.json"
_栏宽 = [10, 10, 16, 16, 12, 16, 26, 12, 12, 50]        # 图1-15 p.9 列宽链，合计 180


# ---------------------------------------------------------------- 表库
def _表(名):
    data = json.loads(_TABLES.read_text(encoding="utf-8"))
    if 名 not in data:
        raise NotImplementedError(f"{_TABLES} 无 {名}")
    return data[名]


def _格(表):
    """按 merges 展开 data：三元组 [首行,末行,列] / 四元组 [首行,末行,首列,末列]，被合并格取首格值。"""
    rows = [list(r) for r in 表["data"]]
    for m in 表.get("merges", []):
        if len(m) == 3:
            r0, r1, c0 = m
            c1 = c0
        else:
            r0, r1, c0, c1 = m
        v = rows[r0][c0]
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1):
                if r < len(rows) and c < len(rows[r]):
                    rows[r][c] = v
    return rows


def _数(v):
    f = float(str(v).replace(" ", ""))
    return int(f) if abs(f - round(f)) < 1e-9 else f


# ---------------------------------------------------------------- 文字排版小工具
def _字宽(s, h):
    """估宽（mm）：中文 1.0 em，数字/字母 0.55 em，与 gbdraw.text_w 同口径。"""
    return sum(h if ord(c) > 0x2E80 else 0.55 * h for c in s)


def _格文(g, x0, y0, w, h, s, 号=3.5, 左边=False):
    """在一格内居中写一行字；超出格宽/格高时逐档缩字号，保证不出格。"""
    if not s:
        return
    k = 号
    while k > 2.0 and (_字宽(s, k) > w - 0.8 or k > h - 0.8):
        k = round(k - 0.1, 2)
    x = x0 + 0.8 if 左边 else x0 + w / 2
    g.加(文(x, y0 + h / 2 - 0.35 * k, s, k, anchor="start" if 左边 else "middle"))


# ---------------------------------------------------------------- 幅面
def 幅面尺寸(幅面="A3"):
    """表1-1 p.7 [核]。返回 {b,l,a,c,e}（mm）：b 短边、l 长边；e/c/a 为留边与装订边。

    未知幅面（含 A3×3 之类加长幅面）抛 NotImplementedError——加长幅面本批不做。
    """
    t = _表("表1-1")
    code = str(幅面).strip().upper()
    if code not in t["cols"]:
        raise NotImplementedError(f"幅面 {幅面!r} 不在表1-1（可选 {t['cols'][1:]}）")
    j = t["cols"].index(code)
    grid = _格(t)
    b, l = (float(x) for x in str(grid[0][j]).replace(" ", "").split("×"))
    return dict(b=_数(b), l=_数(l), a=_数(grid[3][j]), c=_数(grid[2][j]), e=_数(grid[1][j]))


def 图框(幅面="A3", 比例="1:1", 装订边="左", 横放=True):
    """图1-11 p.7 / 图1-12 p.8 [核]：纸边 thin + 图框 thick + 四边中点对中符号。

    装订边="左"：左边距 a（全幅面 25），其余三边 c（A0–A2 取 10，A3–A4 取 5）；
    装订边="无"：四边均为 e（A0–A1 取 20，A2–A4 取 10）。
    横放=True → 长边 l 水平；False → 短边 b 水平。
    对中符号按 A-sheet 取 5 mm（图1-14 的 3/5/6 归属标 unverified，6 mm 那个不采用），
    从纸边伸入 5 mm；左装订时左符号因此停在图框线外，不补画到图框。
    本书无图幅分区，未臆造（A-sheet gaps）。
    """
    d = 幅面尺寸(幅面)
    W, H = (d["l"], d["b"]) if 横放 else (d["b"], d["l"])
    if 装订边 == "左":
        左, 三边 = d["a"], d["c"]
    elif 装订边 == "无":
        左 = 三边 = d["e"]
    else:
        raise NotImplementedError(f"装订边 只支持 '左'/'无'，收到 {装订边!r}")

    g = 图形().加(矩形(0, 0, W, H, "thin"))                              # 纸边
    g.加(矩形(左, 三边, W - 左 - 三边, H - 2 * 三边, "thick"))           # 图框
    g.加(线(0, H / 2, 5, H / 2, "thick"), 线(W, H / 2, W - 5, H / 2, "thick"),
        线(W / 2, 0, W / 2, 5, "thick"), 线(W / 2, H, W / 2, H - 5, "thick"))   # 对中符号
    g.参数 = dict(幅面=幅面, 比例=比例, 装订边=装订边, 横放=横放, W=W, H=H, 框=(左, 三边))
    return g.范围(0, 0, W, H)


def 标题栏(件名="零件", 材料="45", 比例="1:1", 图号="", 设计="", 审核="", 日期="",
        单位名称="", 幅面="A3", 装订边="左", 横放=True):
    """图1-15 p.9 [核]：180×56，8 行×7，列宽 10/10/16/16/12/16 + 26 + 12 + 12 + 50。

    按默认 A3 横放、左装订放在图框内右下角：x = 420−5−180 = 235，y = 5。
    横放=False（如 A4 竖装）→ 按 b×l 定位，A4 时 x = 210−5−180 = 25。
    左 80 = 更改栏（标记/处数/分区/更改文件号/签名/年月日，占上 3 行）+ 签字区
    （设计/标准化/审核/工艺/批准，占下 5 行，自下而上）；中 26 = 材料标记；
    两个 12 列 = 质量、比例；右 50 = 单位名称/图样名称/图号/投影符号（投影符号按第一角画法示意）。
    文字 3.5 号（单位名称/图样名称/图号 5 号），逐格估宽，超格才降档，不出格。
    注：图1-15 原图这三个栏目用 10 号字，本批按任务书取 5 号。
    """
    d = 幅面尺寸(幅面)
    W, H = (d["l"], d["b"]) if 横放 else (d["b"], d["l"])
    左 = d["a"] if 装订边 == "左" else d["e"]
    边 = d["c"] if 装订边 == "左" else d["e"]
    x0, y0 = W - 边 - 180, 边
    线位 = [0]
    for w in _栏宽:
        线位.append(线位[-1] + w)              # [0,10,20,36,52,64,80,106,118,130,180]

    g = 图形().加(矩形(x0, y0, 180, 56, "thick"))
    for dx in 线位[1:-1]:
        g.加(线(x0 + dx, y0, x0 + dx, y0 + 56, "thin"))
    for k in range(1, 8):
        g.加(线(x0, y0 + 7 * k, x0 + 180, y0 + 7 * k, "thin"))

    # ---- 左 80：更改栏表头（上 3 行中最上 1 行）
    for i, s in enumerate(["标记", "处数", "分区", "更改文件号", "签名", "年月日"]):
        _格文(g, x0 + 线位[i], y0 + 49, _栏宽[i], 7, s, 3.5)

    # ---- 左 80：签字区（下 5 行，自下而上 设计→批准）
    行 = [("设计", 设计), ("标准化", ""), ("审核", 审核), ("工艺", ""), ("批准", "")]
    for i, (名, 签) in enumerate(行):
        yb = y0 + 7 * i
        _格文(g, x0 + 线位[2], yb, _栏宽[2], 7, 名, 3.5)                      # 20..36
        _格文(g, x0 + 线位[4], yb, _栏宽[4], 7, 签, 3.5)                      # 52..64
        _格文(g, x0 + 线位[5], yb, _栏宽[5], 7,
              日期 if 名 in ("设计", "审核") else "", 3.5)                     # 64..80

    # ---- 中 26：材料标记（表头占最上 1 行、值占下一行，避免行线穿字）
    _格文(g, x0 + 线位[6], y0 + 49, 26, 7, "材料标记", 3.5)
    _格文(g, x0 + 线位[6], y0 + 42, 26, 7, 材料, 5)

    # ---- 两个 12 列：质量 / 比例
    _格文(g, x0 + 线位[7], y0 + 49, 12, 7, "质量", 3.5)
    _格文(g, x0 + 线位[8], y0 + 49, 12, 7, "比例", 3.5)
    _格文(g, x0 + 线位[8], y0 + 42, 12, 7, 比例, 3.5)

    # ---- 右 50：单位名称 / 图样名称 / 图号 / 投影符号（各 14 高）
    for k, (名, 值) in enumerate([("单位名称", 单位名称), ("图样名称", 件名), ("图号", 图号)]):
        yb = y0 + 42 - 14 * k                 # 该格下边：42 / 28 / 14（单位 mm，格高 14）
        _格文(g, x0 + 线位[9], yb + 8, 50, 6, 名, 2.5)
        _格文(g, x0 + 线位[9], yb, 50, 8, 值, 5)

    # 投影符号（第一角：梯形 + 两个同心圆，细实线）
    bx, by = x0 + 线位[9], y0
    梯 = [(bx + 4, by + 4.4), (bx + 18, by + 2.6), (bx + 18, by + 11.4), (bx + 4, by + 9.6)]
    for i in range(4):
        g.加(线(*梯[i], *梯[(i + 1) % 4], "thin"))
    g.加(圆(bx + 30, by + 7, 3.6, "thin"), 圆(bx + 30, by + 7, 2.2, "thin"))

    g.参数 = dict(幅面=幅面, 装订边=装订边, 原点=(x0, y0), 尺寸=(180, 56), 线位=线位)
    return g.范围(x0, y0, x0 + 180, y0 + 56)



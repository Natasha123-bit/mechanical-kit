def _多边形(cx, cy, R, n, 起始角=0.0):
    return [(cx + R * math.cos(起始角 + 2 * math.pi * i / n),
             cy + R * math.sin(起始角 + 2 * math.pi * i / n)) for i in range(n)]


def 三视图(长=60, 高=40, 宽=30, 间距=视图间距, x=40, y=110):
    """长方体三视图：主视在左上、俯视在其下、左视在右，并画三等投影线。

    依据：图2-7 p.33–34 [核]（三视图形成与展开）、图2-8 p.35 [核]（长对正/高平齐/宽相等）、
          图2-9 p.35 [核]（方位关系）。
    布局：主视 (x,y) 起 长×高；俯视 (x, y-间距-宽) 起 长×宽；左视 (x+长+间距, y) 起 宽×高。
    三等：主/俯 x 范围相同；主/左 y 范围相同；俯视高 = 左视宽 = 宽。
    投影线用细实线，只画外轮廓对应的四条，不画每一条棱线。
    """
    if 长 <= 0 or 高 <= 0 or 宽 <= 0:
        raise ValueError("长、高、宽 必须 > 0")
    if 间距 < 0:
        raise ValueError("间距 必须 ≥ 0")

    主 = (x, y, 长, 高)
    俯 = (x, y - 间距 - 宽, 长, 宽)
    左 = (x + 长 + 间距, y, 宽, 高)

    g = 图形().加(
        矩形(*主, "thick"), 矩形(*俯, "thick"), 矩形(*左, "thick"),
        文(x + 长 / 2, y - 3, "主视图", TEXT_H),
        文(x + 长 / 2, 俯[1] - 3, "俯视图", TEXT_H),
        文(左[0] + 宽 / 2, y - 3, "左视图", TEXT_H),
    )
    # 长对正：主/俯 的两条竖直投影线
    for xx in (x, x + 长):
        g.加(线(xx, y, xx, 俯[1] + 宽, "thin"))
    # 高平齐：主/左 的两条水平投影线
    for yy in (y, y + 高):
        g.加(线(x + 长, yy, 左[0], yy, "thin"))
    g.注("三视图：长对正、高平齐、宽相等（图2-8 p.35）；俯视图在下方、左视图在右方（第一角）")
    g.范围(x - 3, 俯[1] - 8, 左[0] + 宽 + 3, y + 高 + 3)
    g.视图 = {"主视图": 主, "俯视图": 俯, "左视图": 左}
    return g


def 点的三面投影(x=15, y=20, z=25, ox=60, oy=110, 间距=45):
    """点的三面投影：V 面在主视位、H 面展开到下方、W 面展开到右方。

    依据：图2-12 p.37 [核]（三投影面体系与展开）、图2-13 p.37 [核]（由两面投影求第三面）、
          图2-14/2-15 p.38 [核]（投影与直角坐标）。
    坐标：a(x,z) 在 V 面；a'(x,y) 在 H 面（y 向下展开）；a''(y,z) 在 W 面（y 向右展开）。
    参数 ox,oy 为 V 面原点；间距 为 H/W 面展开后的偏移（示意）。
    """
    if 间距 <= 0:
        raise ValueError("间距 必须 > 0")
    a = (ox + x, oy + z)
    a1 = (ox + x, oy - 间距 - y)
    a2 = (ox + 间距 + y, oy + z)

    g = 图形()
    # V 面坐标轴
    g.加(线(ox - 5, oy, ox + x + 12, oy, "thin"), 线(ox, oy - 5, ox, oy + z + 12, "thin"))
    # H 面：原点 O1、x 轴、y 轴（向下）
    g.加(线(ox - 5, oy - 间距, ox + x + 12, oy - 间距, "thin"),
         线(ox, oy - 间距, ox, oy - 间距 - y - 10, "thin"))
    # W 面：原点 O2、y 轴（向右）、z 轴
    g.加(线(ox + 间距, oy - 5, ox + 间距, oy + z + 12, "thin"),
         线(ox + 间距, oy, ox + 间距 + y + 12, oy, "thin"))
    # 投影连线
    g.加(线(a[0], a[1], a1[0], a1[1], "thin"),
         线(a1[0], a1[1], a2[0], a2[1], "thin"),
         线(a[0], a[1], a2[0], a2[1], "thin"))
    for p, s in ((a, "a"), (a1, "a′"), (a2, "a″")):
        g.加(圆(p[0], p[1], 0.9, "thick"), 文(p[0] + 2.5, p[1] + 3, s, TEXT_H, anchor="start"))
    g.加(文(ox - 4, oy - 3, "O", TEXT_S, anchor="end"),
         文(ox + x + 13, oy - 3, "X", TEXT_S, anchor="start"),
         文(ox - 3, oy + z + 13, "Z", TEXT_S, anchor="end"),
         文(ox + 间距 + y + 13, oy - 3, "Y", TEXT_S, anchor="start"))
    g.注("点的三面投影：a(x,z)、a′(x,y)、a″(y,z)；投影连线垂直投影轴（图2-12~2-15 p.37–38）")
    g.范围(ox - 8, oy - 间距 - y - 12, ox + 间距 + y + 15, oy + z + 15)
    g.点 = {"a": a, "a′": a1, "a″": a2}
    return g


def 棱柱三视图(边数=6, 半径=25, 高=45, 间距=视图间距, x=40, y=90):
    """正 n 棱柱三视图：主视为矩形（含可见竖棱），俯视为正多边形，左视为矩形。

    依据：图2-43 正六棱柱的投影作图 p.57 [核]；表2-1/2-2 p.41–43 [核]（棱线投影特征）。
    方位：正多边形一个顶点在 +x 方向（0°），故主视宽 = 2R；深度 = 多边形 y 向跨度。
    主视内部竖线：六棱柱在 x=±R/2 处有两条可见竖棱（图2-43）；其它边数不硬画内部棱线，
    以免把背面的棱误画成可见粗实线。
    """
    if 边数 < 3:
        raise ValueError("边数 必须 ≥ 3")
    if 半径 <= 0 or 高 <= 0:
        raise ValueError("半径、高 必须 > 0")

    点 = _多边形(x + 半径, y, 半径, 边数)
    深 = max(p[1] for p in 点) - min(p[1] for p in 点)
    主 = (x, y, 2 * 半径, 高)
    俯 = (x, y - 间距 - 深, 2 * 半径, 深)
    左 = (x + 2 * 半径 + 间距, y, 深, 高)

    g = 图形().加(矩形(*主, "thick"), 矩形(*左, "thick"))
    # 俯视图：正多边形（按主视 x 起算，俯视中心与主视中心对齐）
    中x, 中y = x + 半径, y - 间距 - 深 / 2
    俯点 = _多边形(中x, 中y, 半径, 边数)
    for i in range(边数):
        p, q = 俯点[i], 俯点[(i + 1) % 边数]
        g.加(线(p[0], p[1], q[0], q[1], "thick"))
    # 中心线
    g.加(线(中x - 半径 - 3, 中y, 中x + 半径 + 3, 中y, "center"),
         线(中x, 中y - 半径 - 3, 中x, 中y + 半径 + 3, "center"))
    # 主视内部可见竖棱（六棱柱）
    if 边数 == 6:
        for xx in (x + 半径 / 2, x + 1.5 * 半径):
            g.加(线(xx, y, xx, y + 高, "thick"))
    # 左视中心线
    g.加(线(左[0] - 3, y + 高 / 2, 左[0] + 深 + 3, y + 高 / 2, "center"))
    g.加(文(x + 半径, y - 3, "主视图", TEXT_H),
         文(x + 半径, 俯[1] - 3, "俯视图", TEXT_H),
         文(左[0] + 深 / 2, y - 3, "左视图", TEXT_H))
    g.注(f"正{边数}棱柱：主视矩形 2R×H，俯视正{边数}边形，左视深×H（图2-43 p.57）")
    g.范围(x - 3, 俯[1] - 8, 左[0] + 深 + 3, y + 高 + 3)
    g.参数 = dict(主=主, 俯=俯, 左=左, 深=深)
    return g


def 棱锥三视图(边数=5, 半径=25, 高=45, 间距=视图间距, x=40, y=90):
    """正 n 棱锥三视图：主/左为三角形，俯视为正多边形 + 顶点与各底角连线。

    依据：图2-45 五棱锥的投影作图 p.57 [核]；图2-48/2-49 棱锥表面取点取线 p.59 [核]。
    方位同 棱柱三视图；主视三角形底宽 2R、顶点在中心上方 H；内部棱线只画到基座可见角点，
    不把背面棱画成粗实线。
    """
    if 边数 < 3:
        raise ValueError("边数 必须 ≥ 3")
    if 半径 <= 0 or 高 <= 0:
        raise ValueError("半径、高 必须 > 0")

    点 = _多边形(x + 半径, y, 半径, 边数)
    深 = max(p[1] for p in 点) - min(p[1] for p in 点)
    主 = (x, y, 2 * 半径, 高)
    俯 = (x, y - 间距 - 深, 2 * 半径, 深)
    左 = (x + 2 * 半径 + 间距, y, 深, 高)

    g = 图形()
    # 主视：三角形轮廓 + 顶点到底座两端的棱线
    顶 = (x + 半径, y + 高)
    g.加(线(x, y, x + 2 * 半径, y, "thick"),
         线(x, y, *顶, "thick"), 线(x + 2 * 半径, y, *顶, "thick"))
    # 左视：三角形轮廓
    g.加(线(左[0], y, 左[0] + 深, y, "thick"),
         线(左[0], y, 左[0] + 深 / 2, y + 高, "thick"),
         线(左[0] + 深, y, 左[0] + 深 / 2, y + 高, "thick"))
    # 俯视：多边形 + 顶点（中心）到底角连线
    中x, 中y = x + 半径, y - 间距 - 深 / 2
    俯点 = _多边形(中x, 中y, 半径, 边数)
    for i in range(边数):
        p, q = 俯点[i], 俯点[(i + 1) % 边数]
        g.加(线(p[0], p[1], q[0], q[1], "thick"))
        g.加(线(中x, 中y, p[0], p[1], "thick"))
    g.加(线(中x - 半径 - 3, 中y, 中x + 半径 + 3, 中y, "center"),
         线(中x, 中y - 半径 - 3, 中x, 中y + 半径 + 3, "center"))
    g.加(文(x + 半径, y - 3, "主视图", TEXT_H),
         文(x + 半径, 俯[1] - 3, "俯视图", TEXT_H),
         文(左[0] + 深 / 2, y - 3, "左视图", TEXT_H))
    g.注(f"正{边数}棱锥：主/左为三角形，俯视为正{边数}边形加顶点连线（图2-45 p.57）")
    g.范围(x - 3, 俯[1] - 8, 左[0] + 深 + 3, y + 高 + 3)
    g.参数 = dict(主=主, 俯=俯, 左=左, 深=深, 顶=顶)
    return g

# ============================================================ 1. 六个基本视图
def 视图配置(宽=50, 高=35, 深=25, 间距=15, cx=148, cy=110):
    """六个基本视图（第一角画法）按投影关系配置，全部 thick 矩形 + 视图名称（3.5 号）。

    依据：图6-2 p.144 [核]（配置与方位）+ §6-1 p.144 [核]（三等关系）。
    参数：宽 = 物体左右向（主视方向长度）、高 = 上下向、深 = 前后向；间距 = 视图间空档（书未给 mm，示意）。
    三等：主/俯/仰 的 x 范围相同（长对正）；主/左/右/后 的 y 范围相同（高平齐）；
          俯/仰 的高、左/右 的宽都等于 深（宽相等）。
    """
    for 名, v in (("宽", 宽), ("高", 高), ("深", 深)):
        if v <= 0:
            raise ValueError(f"{名} 必须 > 0，收到 {v}")
    if 间距 < 0:
        raise ValueError(f"间距 必须 ≥ 0，收到 {间距}")

    半宽, 半高 = 宽 / 2.0, 高 / 2.0
    主x, 主y = cx - 半宽, cy - 半高                 # 左下角
    俯y = 主y - 间距 - 深                            # 俯视图：正下方，宽×深
    仰y = 主y + 高 + 间距                            # 仰视图：正上方，宽×深
    右x = 主x - 间距 - 深                            # 右视图：左侧，深×高
    左x = 主x + 宽 + 间距                            # 左视图：右侧，深×高
    后x = 左x + 深 + 间距                            # 后视图：左视图再右侧，宽×高

    六 = {
        "主视图": (主x, 主y, 宽, 高),
        "俯视图": (主x, 俯y, 宽, 深),
        "仰视图": (主x, 仰y, 宽, 深),
        "右视图": (右x, 主y, 深, 高),
        "左视图": (左x, 主y, 深, 高),
        "后视图": (后x, 主y, 宽, 高),
    }

    g = 图形()
    for 名, (x, y, w, h) in 六.items():
        g.加(矩形(x, y, w, h, "thick"), 文(x + w / 2, y + h / 2, 名, TEXT_H))

    注y = 俯y - 8
    g.加(文(cx, 注y, "长对正／高平齐／宽相等", TEXT_S))
    g.加(文(cx, 注y - 5, "第一角画法：仰视图在上、俯视图在下、右视图在左、左视图在右", TEXT_S))
    g.注("六视图按第一角画法配置（图6-2 p.144）；长对正、高平齐、宽相等（§6-1 p.144）")
    g.视图 = 六          # 供自检/测试取中心与宽高

    xs = [x for x, _, _, _ in 六.values()] + [x + w for x, _, w, _ in 六.values()]
    ys = [y for _, y, _, _ in 六.values()] + [y + h for _, y, _, h in 六.values()]
    g.范围(min(xs), min(min(ys), 注y - 8), max(xs), max(ys))
    return g


# ============================================================ 2. 向视图
def 向视图(宽=50, 高=30, 字母="A", 箭头方向="右", x=100, y=100):
    """向视图：thick 矩形轮廓 + 上方大写字母 + 外侧投射方向箭头（箭头旁注同字母）。

    依据：图6-3 p.144 [核]——向视图为移位（不旋转）配置的基本视图，必须标注：
    视图上方写字母「x」，箭头旁注同名字母，两端缺一不可；字母注在箭头外端。
    参数 x,y 为矩形左下角；箭头外移 6（示意）。箭头按 §6-2 的做法画成**细实线箭杆 + 箭头**
    （gbdraw.ARROW 只生成箭头本身，不含箭杆），箭头长 18（示意）。
    """
    if 箭头方向 not in 箭头方向名:
        raise ValueError(f"箭头方向 只能是 {箭头方向名}，收到 {箭头方向!r}")
    if not str(字母):
        raise ValueError("字母 不能为空")

    g = 图形().加(矩形(x, y, 宽, 高, "thick"), 文(x + 宽 / 2, y + 高 + 4, 字母, TEXT_H))
    ym = y + 高 / 2
    外 = 6.0
    长 = 18.0

    # 投射方向箭头 = 细直线箭杆 + 箭头（gbdraw.ARROW 只生成箭头本身，不含箭杆）
    if 箭头方向 == "右":
        ax, ay = x + 宽 + 外, ym
        bx, by = ax + 长, ay
        g.加(线(ax, ay, bx, by, "thin"), 箭头(ax, ay, bx, by),
             文(bx + 2, by, 字母, TEXT_H, anchor="start"))
    elif 箭头方向 == "左":
        ax, ay = x - 外, ym
        bx, by = ax - 长, ay
        g.加(线(ax, ay, bx, by, "thin"), 箭头(ax, ay, bx, by),
             文(bx - 2, by, 字母, TEXT_H, anchor="end"))
    elif 箭头方向 == "上":
        # 上方已有视图名称字母，箭头移到 3/4 宽度处，两个字母横向错开
        ax, ay = x + 宽 * 0.78, y + 高 + 外
        bx, by = ax, ay + 长
        g.加(线(ax, ay, bx, by, "thin"), 箭头(ax, ay, bx, by),
             文(bx, by + 6, 字母, TEXT_H))
    else:  # 下
        ax, ay = x + 宽 * 0.78, y - 外
        bx, by = ax, ay - 长
        g.加(线(ax, ay, bx, by, "thin"), 箭头(ax, ay, bx, by),
             文(bx, by - 2, 字母, TEXT_H))

    g.注(f"向视图 {字母}：视图上方注字母，箭头旁注同字母（图6-3 p.144）")
    g.范围(min(x, bx) - 10, min(y, by) - 6, max(x + 宽, bx) + 10, max(y + 高 + 8, by) + 6)
    return g


# ============================================================ 3. 局部视图
def 局部视图(宽=50, 高=30, 断裂边="波浪", 字母=None, x=100, y=100):
    """局部视图：三边 thick 轮廓 + 一侧断裂边界（波浪线或双折线）。

    依据：图6-4 p.145 [核]（断裂边界用波浪线，两端止于轮廓线）+ 图6-6 p.145 [核]
    （对称机件以细点画线作断裂边界，属特殊画法，本函数不画该种）。
    参数：x,y 为矩形左下角；断裂边画在**左侧**（朝向主视图的一侧，图6-4 的 A 向即如此配置）；
    每条波浪线/双折线的波高、波长书未给 mm，取 WAVY/PHASE 原语默认值（示意）。
    字母=None 时不标注；给出字母时写「x向」（图6-4 按向视图配置的 B 向必须标注）。
    """
    if 断裂边 not in 断裂边名:
        raise ValueError(f"断裂边 只能是 {断裂边名}，收到 {断裂边!r}")
    if 宽 <= 0 or 高 <= 0:
        raise ValueError("宽、高 必须 > 0")

    左, 右 = x, x + 宽
    下, 上 = y, y + 高
    g = 图形().加(
        线(左, 下, 右, 下, "thick"),      # 底
        线(右, 下, 右, 上, "thick"),      # 右
        线(右, 上, 左, 上, "thick"),      # 顶
    )
    g.加(波浪线(左, 下, 左, 上) if 断裂边 == "波浪" else 双折线(左, 下, 左, 上))

    if 字母:
        g.加(文(x + 宽 / 2, 上 + 5, f"{字母}向", TEXT_H))
        g.注(f"局部视图 {字母}向：断裂边界用{断裂边}线（图6-4 p.145）")
    else:
        g.注("局部视图：断裂边界用波浪线/双折线，不标注（图6-4 p.145）")

    g.范围(左 - 3, 下 - 3, 右 + 3, 上 + (9 if 字母 else 3))
    return g


# ============================================================ 4. 斜视图
def 斜视图(宽=50, 高=30, 倾角=30, 字母="A", 旋转=True, x=100, y=100):
    """斜视图：四条 线() 围成的旋转矩形；旋转配置时加旋转符号（半圆弧 + 箭头 + 字母）。

    依据：图6-7b p.146 [核]——旋转符号为半径等于字体高 h（3.5 号字 → R3.5）的**细实线**半圆弧，
    一端带箭头，字母靠近箭头端；旋转角不大于 90°。
    参数：x,y 为矩形左下角；旋转中心取矩形中心；倾角 = 被表达斜面的倾角（度）。
      旋转=True  → 图形转正（水平摆放），并画旋转符号（图6-7b 的画法）；
      旋转=False → 图形按倾角斜放（图6-7a 按投射方向配置的画法），只在图形上方注字母。
    说明：四条边**逐条用 线() 画**（不用 poly 图元），这样每条边都是可核的 AST 线元素。
    """
    if 宽 <= 0 or 高 <= 0:
        raise ValueError("宽、高 必须 > 0")
    if not (0 <= 倾角 < 90):
        raise ValueError(f"倾角 应在 [0, 90) 内（书：旋转角不大于 90°），收到 {倾角}")

    中心 = (x + 宽 / 2.0, y + 高 / 2.0)
    角 = 0.0 if 旋转 else float(倾角)
    原角 = [(x, y), (x + 宽, y), (x + 宽, y + 高), (x, y + 高)]
    点 = [_转(p, 中心, 角) for p in 原角]

    g = 图形()
    for i in range(4):
        p, q = 点[i], 点[(i + 1) % 4]
        g.加(线(p[0], p[1], q[0], q[1], "thick"))

    上边 = max(p[1] for p in 点)
    if 旋转:
        # 旋转符号：开口向上的半圆弧（下半个圆）+ 左端短箭头 + 右端字母
        r = TEXT_H
        sx, sy = 中心[0], 上边 + r + 7
        g.加(弧(sx, sy, r, 180, 360, "thin"))
        g.加(箭头(sx - r, sy + 4, sx - r, sy, size=2.5))     # 左端，沿弧的转向
        g.加(文(sx + r + 2.5, sy, 字母, TEXT_H, anchor="start"))
        g.注(f"斜视图 {字母}：旋转配置，旋转符号 R{TEXT_H:g}（=字高）半圆弧 + 箭头（图6-7b p.146）")
        右上 = max(p[1] for p in 点) + 2 * r + 9
    else:
        g.加(文(中心[0], 上边 + 5, 字母, TEXT_H))
        g.注(f"斜视图 {字母}：按投射方向配置（倾角 {倾角:g}°），不必画旋转符号（图6-7a p.146）")
        右上 = 上边 + 9

    xs = [p[0] for p in 点]
    g.范围(min(xs) - 3, min(p[1] for p in 点) - 3, max(xs) + (5 if 旋转 else 3), 右上)
    return g


# ============================================================ 小工具
def _转(p, 中心, deg):
    """点 p 绕 中心 逆时针转 deg 度（y 向上）。"""
    a = math.radians(deg)
    ca, sa = math.cos(a), math.sin(a)
    dx, dy = p[0] - 中心[0], p[1] - 中心[1]
    return (中心[0] + dx * ca - dy * sa, 中心[1] + dx * sa + dy * ca)


# ============================================================ 自检
def _自检():
    ok_all = True

    g = 视图配置()
    print("视图配置：")
    for 名, (x, y, w, h) in g.视图.items():
        print(f"  {名}: 左下({x:.1f},{y:.1f}) 中心({x + w / 2:.1f},{y + h / 2:.1f}) 宽×高 {w:g}×{h:g}")
    主, 俯, 仰 = g.视图["主视图"], g.视图["俯视图"], g.视图["仰视图"]
    右, 左, 后 = g.视图["右视图"], g.视图["左视图"], g.视图["后视图"]
    print(f"  长对正 x 同: {主[0] == 俯[0] == 仰[0]}；高平齐 y 同: {主[1] == 右[1] == 左[1] == 后[1]}；"
          f"宽相等 深={俯[3]:g}/{仰[3]:g}/{右[2]:g}/{左[2]:g}")

    for 名, gg in (
        ("视图配置", g),
        ("向视图-右", 向视图(箭头方向="右")),
        ("向视图-上", 向视图(箭头方向="上")),
        ("局部视图-波浪", 局部视图(字母="B")),
        ("局部视图-双折线", 局部视图(断裂边="双折线")),
        ("斜视图-旋转", 斜视图()),
        ("斜视图-斜放", 斜视图(旋转=False)),
    ):
        ok, msg = 校验图元(gg.elems)
        ok_all = ok_all and ok
        print(f"  [{'✓' if ok else '✗'}] {名}: {msg}，围 {tuple(round(v, 1) for v in gg.bbox)}")

    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(_自检())

def 表达方案(类型="叉架", 方案="a", cx=148.0, cy=110.0, 间距=15.0):
    """六类典型零件的视图配置骨架。依据：图7-15/7-16~7-24 p.182–186 [核]。

    返回矩形视图 + 视图名；叉架 a = 主+俯+A—A，叉架 b = 主+全剖左+A—A（图7-15）。
    视图之间的相对位置按投影关系；间距参数只影响外扩，书未给 mm，示意。
    """
    key = (类型, 方案)
    if key not in _布局:
        raise NotImplementedError(f"未收录表达方案 {类型}/{方案}（可选 {sorted(_布局)}）")
    g = 图形()
    views = {}
    for 名, w, h, dx, dy in _布局[key]:
        x, y = cx + dx, cy + dy
        g.加(矩形(x, y, w, h, "thick"), 文(x + w / 2, y + h / 2, 名, 3.5))
        views[名] = (x, y, w, h)
    g.加(文(cx, cy - 75, f"{类型}类零件表达方案（{方案}）：{len(views)} 个视图",
            4, anchor="middle"))
    g.参数 = dict(类型=类型, 方案=方案, 视图=views)
    xs = [x for x, _, w, _ in views.values()] + [x + w for x, _, w, _ in views.values()]
    ys = [y for _, y, _, h in views.values()] + [y + h for _, y, _, h in views.values()]
    g.范围(min(xs) - 3, min(ys) - 10, max(xs) + 3, max(ys) + 3)
    return g


def 尺寸基准(类型="轴", 长=80.0, 直径=30.0, x=0.0, y=0.0):
    """尺寸基准示意：轴线/端面为主基准，另标一辅助基准。依据：图7-25/7-26 p.188 [核]。

    轴：水平轴轮廓 thin + 轴线 center + 左端面基准 A + 轴肩辅助基准 B；
    板：矩形 thin + 底面基准 A + 对称面基准 B。
    """
    g = 图形()
    if 类型 == "轴":
        r = 直径 / 2
        g.加(矩形(x, y - r, 长, 直径, "thin"),
             线(x - 5, y, x + 长 + 5, y, "center"),
             基准(x, y - r - 7, "A", up=True),
             基准(x + 长 / 2, y - r - 7, "B", up=True),
             尺寸H(y - r - 14, x, x + 长, f"{长:g}"))
    elif 类型 == "板":
        g.加(矩形(x, y, 长, 直径, "thin"),
             线(x, y + 直径 / 2, x + 长, y + 直径 / 2, "center"),
             基准(x + 长 / 2, y - 8, "A", up=True),
             基准(x - 8, y + 直径 / 2, "B", up=False),
             尺寸H(y - 16, x, x + 长, f"{长:g}"))
    else:
        raise NotImplementedError(f"尺寸基准 类型 只支持 轴/板，收到 {类型!r}")
    g.参数 = dict(类型=类型, 长=长)
    g.范围(x - 15, y - 直径 - 25, x + 长 + 10, y + 直径 + 10)
    return g



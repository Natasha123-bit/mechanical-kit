"""gear.py —— 圆柱齿轮的画法（《机械制图》ch8 §8-6，p.243–246）

依据：books/drawing/handoff-ch08/A-gear.json（A 角色逐线核过图8-52、8-53、8-54 的页图）
  图8-52 单个齿轮 [核]：齿顶线/齿顶圆 thick；分度线/分度圆 center；非剖视图齿根线 thin，
          剖视图齿根线 thick；剖切平面过轴线时轮齿按不剖绘制（不画剖面线）。
  图8-54 啮合剖视 [核]：啮合区五条线 = 2 条齿根线(thick) + 2 条齿顶线(一 thick 一 hidden)
          + 1 条节线(center)；两轮齿顶与对方齿根留 0.25m 间隙。
  图8-55 非剖啮合 [核]：节线改 thick，啮合区齿顶/齿根线省略。
  图8-51「齿轮啮合时名称」在 A-gear.json 记 unverified（分度圆是否点画线扫描发虚未逐段确认），
  故分度圆的 center 线型取图8-52/8-53 的 verified 结论，不引用图8-51。

硬约束：只走 lib.drawing._prim 原语，不写 SVG 字符串；线型只用 thick/thin/center/hidden/wavy。
"""
import math
import sys
from pathlib import Path
MDKIT = Path(__file__).resolve().parents[2]
if str(MDKIT) not in sys.path: sys.path.insert(0, str(MDKIT))
from lib.drawing._prim import 图形, 校验图元, 线, 圆, 弧, 矩形, 文, 剖面线, 尺寸H, 尺寸V, 拼

齿线类型 = ("直齿", "斜齿", "人字齿")
齿顶高系数 = 1.0      # ha* = 1（标准齿制）
齿根高系数 = 1.25     # hf* = 1.25（含 0.25m 顶隙）
齿顶隙系数 = 0.25     # 图8-54：齿顶与对方齿根间隙 = 0.25m


# ============================================================ 几何推导
def 单轮(m, z):
    """单个标准直齿圆柱齿轮的几何量。依据：图8-52 p.244 [核]（da=m(z+2)、d=mz、df=m(z−2.5)）。"""
    if m <= 0:
        raise ValueError(f"模数 m 必须 > 0，收到 {m}")
    if z <= 2.5:
        raise ValueError(f"齿数 z 必须 > 2.5（否则齿根圆退化），收到 {z}")
    return dict(
        m=float(m), z=z,
        d=m * z,                    # 分度圆
        da=m * (z + 2),             # 齿顶圆
        df=m * (z - 2.5),           # 齿根圆
        ha=齿顶高系数 * m,           # 齿顶高
        hf=齿根高系数 * m,           # 齿根高
        p=math.pi * m,              # 周节 p=mπ
        s=math.pi * m / 2,          # 齿厚（弧长）s=e=p/2
        e=math.pi * m / 2,          # 齿槽宽（弧长）
    )


def 五线(m):
    """啮合区五条线的位置（y 偏移，相对节线；轮1 在节线下方）。

    依据：图8-54 p.245 [核]。轮1 轴线在节线下方 d1/2 处，齿顶朝节线（+m）、齿根背离（−1.25m）；
    轮2 在节线上方，方向相反。故自下而上：齿根线1(−1.25m)、齿顶线2(−m)、节线(0)、
    齿顶线1(+m)、齿根线2(+1.25m)；相邻的 ±m 与 ∓1.25m 之间恰好留 0.25m 顶隙。
    """
    return [
        dict(名="齿根线1", 偏移=-1.25 * m, 线型="thick", 说明="轮1 齿根，粗实线"),
        dict(名="齿顶线2", 偏移=-1.00 * m, 线型="hidden", 说明="轮2 齿顶，细虚线（被遮挡）"),
        dict(名="节线", 偏移=0.0, 线型="center", 说明="两轮节线重合成一条，细点画线"),
        dict(名="齿顶线1", 偏移=+1.00 * m, 线型="thick", 说明="轮1 齿顶，粗实线"),
        dict(名="齿根线2", 偏移=+1.25 * m, 线型="thick", 说明="轮2 齿根，粗实线"),
    ]


def derive(m, z1, z2):
    """两轮啮合的全部几何量（供测试与画法函数共用）。

    返回键：m、z1、z2、d1、da1、df1、d2、da2、df2、a、p、i、间隙、五线、轮1、轮2。
    依据：图8-51/8-52/8-54 p.243–245 [核]（a=m(z1+z2)/2 即两分度圆在节点相切）。
    """
    g1, g2 = 单轮(m, z1), 单轮(m, z2)
    a = g1["d"] / 2 + g2["d"] / 2
    if abs(a - m * (z1 + z2) / 2) > 1e-9:      # 两条来路必须一致
        raise AssertionError(f"中心距不一致：{a} vs {m * (z1 + z2) / 2}")
    out = dict(m=float(m), z1=z1, z2=z2, a=a, p=g1["p"], i=z2 / z1,
               间隙=齿顶隙系数 * m, 五线=五线(m), 轮1=g1, 轮2=g2)
    for k, v in g1.items():
        if k != "m":
            out[f"{k}1"] = v
    for k, v in g2.items():
        if k != "m":
            out[f"{k}2"] = v
    return out


# ============================================================ 1) 单个齿轮
def 齿轮画法(m=2.0, z=29, 齿宽=20.0, 类型="直齿", 孔=20.0, 键槽宽=8.0,
           cx=80.0, cy=110.0, 双视图=True, 键槽深=None, 螺旋角=15.0):
    """单个圆柱齿轮：端视图（左）+ 轴向视图（右）。返回 图形。

    依据：图8-52 单个齿轮的画法 p.244 [核]；图8-53 齿轮零件图 p.245 [核]（φ55/φ50 与
    da=m(z+2)、d=mz 交叉验证，m=2.5/z=20）。
      齿顶圆/齿顶线 da=m(z+2) —— thick
      分度圆/分度线 d =mz     —— center
      齿根圆/齿根线 df=m(z−2.5) —— 视图 thin（剖视图改 thick）
      孔、键槽缺口、轮缘轮廓 —— thick；中心线 center 十字
      轮齿区域不画剖面线（本函数画的是非剖视图，故全图无剖面线）
    键槽深：A-gear.json 只给「键槽宽 b、深 t2」，未给数值表；缺省按 0.5×键槽宽 示意，
    实际须查 GB/T 1095（可用 键槽深= 显式给值）。
    斜齿/人字齿：轴向视图未剖半边用三条细实线表示齿线方向（图8-52(c) [核]），倾角取 螺旋角。
    """
    if 类型 not in 齿线类型:
        raise ValueError(f"类型 取 {齿线类型}，收到 {类型!r}")
    if 齿宽 <= 0:
        raise ValueError("齿宽必须 > 0")
    q = 单轮(m, z)
    da, d, df = q["da"], q["d"], q["df"]
    if not (0 < 孔 < df):
        raise ValueError(f"孔径 孔={孔} 必须在 (0, 齿根圆 df={df}) 内")
    if 键槽宽 <= 0 or 键槽宽 >= 孔:
        raise ValueError(f"键槽宽 必须在 (0, 孔={孔}) 内，收到 {键槽宽}")
    深 = 0.5 * 键槽宽 if 键槽深 is None else float(键槽深)
    if 深 <= 0:
        raise ValueError("键槽深必须 > 0")

    Ra, R, Rf, Rk = da / 2, d / 2, df / 2, 孔 / 2
    g = 图形()

    # ---------- 端视图（左，垂直于轴线） ----------
    g.加(圆(cx, cy, Ra),                      # 齿顶圆 thick
         圆(cx, cy, R, "center"),             # 分度圆 center
         圆(cx, cy, Rf, "thin"),              # 齿根圆 thin（视图）
         圆(cx, cy, Rk))                      # 孔 thick
    引 = Ra + 4
    g.加(线(cx - 引, cy, cx + 引, cy, "center"),
         线(cx, cy - 引, cx, cy + 引, "center"))
    # 键槽缺口：两条竖线自孔壁切点起、一条顶线收口
    半 = 键槽宽 / 2
    切 = math.sqrt(max(Rk ** 2 - 半 ** 2, 0.0))
    顶 = cy + Rk + 深
    g.加(线(cx - 半, cy + 切, cx - 半, 顶),
         线(cx + 半, cy + 切, cx + 半, 顶),
         线(cx - 半, 顶, cx + 半, 顶))

    # ---------- 轴向视图（右，平行于轴线） ----------
    if 双视图:
        x0 = cx + Ra + 18
        x1 = x0 + 齿宽
        g.加(矩形(x0, cy - Ra, 齿宽, da))                       # 轮缘，齿顶线即上下边 thick
        g.加(线(x0 - 4, cy + R, x1 + 4, cy + R, "center"),      # 分度线 center
             线(x0 - 4, cy - R, x1 + 4, cy - R, "center"))
        g.加(线(x0, cy + Rf, x1, cy + Rf, "thin"),              # 齿根线 thin（非剖视）
             线(x0, cy - Rf, x1, cy - Rf, "thin"))
        xm = (x0 + x1) / 2
        g.加(线(xm, cy - Ra - 4, xm, cy + Ra + 4, "center"))
        if 类型 != "直齿":
            g.加(_齿线(x0, x1, cy + Rf, cy + Ra, 类型, 螺旋角))
            g.加(_齿线(x0, x1, cy - Ra, cy - Rf, 类型, 螺旋角))

    g.注(f"齿顶圆/齿顶线 da=m(z+2)={m:g}×({z}+2)={da:g}（粗实线）",
         f"分度圆/分度线 d=mz={m:g}×{z}={d:g}（细点画线）",
         f"齿根圆/齿根线 df=m(z−2.5)={m:g}×({z}−2.5)={df:g}（视图中细实线，剖视图改粗实线）",
         f"模数 m={m:g}，齿数 z={z}，齿顶高 ha={q['ha']:g}，齿根高 hf={q['hf']:g}，周节 p={q['p']:.3f}",
         "剖切平面通过齿轮轴线时轮齿按不剖绘制：轮齿区域不画剖面线",
         "键槽在垂直于轴线的视图中必须表达其位置和形状（图8-52/8-53）")
    if 键槽深 is None:
        g.注(f"键槽深按 0.5×键槽宽={深:g} 示意绘制——实际值须查 GB/T 1095，本库未收该表")
    if 类型 != "直齿":
        g.注(f"{类型}：轴向视图未剖半边用三条细实线表示齿线方向，倾角按 螺旋角={螺旋角:g}° 示意")

    g.参数 = dict(da=da, d=d, df=df, ha=q["ha"], hf=q["hf"], p=q["p"],
                 孔=孔, 键槽宽=键槽宽, 键槽深=深, 类型=类型)
    x_hi = (x0 + 齿宽 + 8) if 双视图 else (cx + Ra + 6)
    g.范围(cx - 引 - 4, cy - Ra - 6, x_hi, cy + Ra + 6)
    return g


def _齿线(x0, x1, y_低, y_高, 类型, β):
    """轴向视图里表示齿线方向的三条细实线（斜齿/人字齿）。依据：图8-52(c) p.244 [核]。

    斜齿：三条平行斜线（倾角 β），限在齿顶线与齿根线之间的窄带内，故长度由带宽反算；
    人字齿：三条人字形折线，顶点在齿宽中部。
    """
    g = 图形()
    低, 上 = min(y_低, y_高), max(y_低, y_高)
    带, 宽 = 上 - 低, x1 - x0
    斜率 = math.tan(math.radians(min(max(β, 1.0), 60.0)))
    if 类型 == "人字齿":
        xm = (x0 + x1) / 2
        斜 = min(0.4 * 带, 0.4 * 宽 * 斜率)
        for f in (0.10, 0.42, 0.74):
            g.加(线(x0, 低 + 带 * f, xm, 低 + 带 * f + 斜, "thin"),
                 线(xm, 低 + 带 * f + 斜, x1, 低 + 带 * f, "thin"))
        return g
    dy = 0.55 * 带
    dx = dy / 斜率
    if dx > 0.85 * 宽:                 # 斜得太厉害就缩短线段，保证不出齿顶/齿根线
        dx, dy = 0.85 * 宽, 0.85 * 宽 * 斜率
    xc = (x0 + x1) / 2
    for f in (0.04, 0.22, 0.40):
        g.加(线(xc - dx / 2, 低 + 带 * f, xc + dx / 2, 低 + 带 * f + dy, "thin"))
    return g


# ============================================================ 2) 两轮啮合
def 齿轮啮合画法(m=2.0, z1=29, z2=47, 齿宽=20.0, 剖视=True, cx1=80.0, cy=110.0, 放大=3.0):
    """两圆柱齿轮啮合：端视图（轴线垂直于图面）+ 啮合区放大图。返回 图形。

    依据：图8-54 齿轮啮合的画法一 p.245 [核]（五条线、0.25m 间隙）；图8-55 画法二 p.246 [核]。
      端视图：da1/da2 thick、d1/d2 center（两分度圆在节点相切）、df1/df2 thin，中心连线 center。
      剖视=True：另画啮合区（轴向剖视放大）——五条线：齿根线1 thick、齿顶线2 hidden、
                 节线 center、齿顶线1 thick、齿根线2 thick。
    几何量全部可由返回值 g.参数（= derive(m,z1,z2)）取到：a、da1、da2、d1、d2、df1、df2…
    """
    p = derive(m, z1, z2)
    a = p["a"]
    cx2 = cx1 + a
    g = 图形()

    # ---------- 端视图 ----------
    for c, sfx in ((cx1, "1"), (cx2, "2")):
        r = p["da" + sfx] / 2
        g.加(圆(c, cy, r),                                  # 齿顶圆 thick
             圆(c, cy, p["d" + sfx] / 2, "center"),         # 分度圆 center
             圆(c, cy, p["df" + sfx] / 2, "thin"))          # 齿根圆 thin
        g.加(线(c, cy - r - 4, c, cy + r + 4, "center"))     # 各自竖直中心线
    g.加(线(cx1, cy, cx2, cy, "center"))                    # 中心连线 O1O2（含中心距 a）

    # ---------- 啮合区放大图（剖视） ----------
    if 剖视:
        五 = p["五线"]
        y_底 = cy - max(p["da1"], p["da2"]) / 2
        y_节 = y_底 - 16 - 1.25 * m * 放大
        xp0 = cx1 - 齿宽 / 2
        xp1 = xp0 + 齿宽
        for it in 五:
            y = y_节 + it["偏移"] * 放大
            g.加(线(xp0, y, xp1, y, it["线型"]))
        # 五线间距只有 0.25m（放大后仍 1.5mm），逐线贴标签会互相压字，改图下一条图例
        g.加(文((xp0 + xp1) / 2, y_节 + 1.25 * m * 放大 + 5,
                f"啮合区放大 {放大:g}×（自上而下）", 2.5),
             文((xp0 + xp1) / 2, y_节 - 1.25 * m * 放大 - 6,
                "齿根线2(粗)／齿顶线1(粗)／节线(点画)／齿顶线2(虚)／齿根线1(粗)", 2.5))

    g.注(f"中心距 a=m(z1+z2)/2={m:g}×({z1}+{z2})/2={a:g}；两分度圆在节点 C 相切（d′=d）",
         f"da1={p['da1']:g}、da2={p['da2']:g}（粗实线）；d1={p['d1']:g}、d2={p['d2']:g}（细点画线）；"
         f"df1={p['df1']:g}、df2={p['df2']:g}（细实线）",
         f"啮合区五条线：2 条齿根线（粗）+ 2 条齿顶线（一粗一虚）+ 1 条节线（细点画线）",
         f"齿根高与齿顶高相差 0.25m={p['间隙']:g}，故两轮齿顶与对方齿根留 {p['间隙']:g} 间隙（图8-54a）")
    if 剖视:
        g.注(f"放大图比例 {放大:g}×：m={m:g} 时 0.25m={p['间隙']:g} 在原尺寸下并线不可辨，故放大绘制")
    else:
        g.注("非剖视图（图8-55）：节线改粗实线，啮合区内齿顶线、齿根线省略不画")
    g.注(f"传动比 i=z2/z1={p['i']:.3f}，两轮转向相反")

    g.参数 = p
    x_lo = cx1 - p["da1"] / 2 - 6
    x_hi = cx2 + p["da2"] / 2 + 6
    y_lo = cy - p["da2"] / 2 - 6
    y_hi = cy + p["da2"] / 2 + 6
    if 剖视:
        y_lo = min(y_lo, cy - max(p["da1"], p["da2"]) / 2 - 16 - 2.5 * m * 放大 - 4)
        y_lo = min(y_lo, cy - max(p["da1"], p["da2"]) / 2 - 16 - 1.25 * m * 放大 - 4)
    g.范围(x_lo, y_lo, x_hi, y_hi)
    return g


# ============================================================ 自检
def _自检():
    out = []
    g1 = 齿轮画法()
    ok, msg = 校验图元(g1.elems)
    out.append(("齿轮画法", msg))
    out.append(("  几何", "da={da:g} d={d:g} df={df:g} 齿宽={b:g} 图元={n}".format(n=len(g1), b=20.0, **g1.参数)))
    g2 = 齿轮啮合画法()
    ok2, msg2 = 校验图元(g2.elems)
    out.append(("齿轮啮合画法", msg2))
    p = g2.参数
    out.append(("  几何", "a={a:g} da1={da1:g} da2={da2:g} d1={d1:g} d2={d2:g} df1={df1:g} df2={df2:g} 五线={n} 图元={m}".format(
        a=p["a"], da1=p["da1"], da2=p["da2"], d1=p["d1"], d2=p["d2"],
        df1=p["df1"], df2=p["df2"], n=len(p["五线"]), m=len(g2))))
    g3 = 齿轮啮合画法(剖视=False)
    ok3, msg3 = 校验图元(g3.elems)
    out.append(("齿轮啮合画法(非剖视)", msg3))
    assert ok and ok2 and ok3
    return out


if __name__ == "__main__":
    for k, v in _自检():
        print(f"{k}: {v}")

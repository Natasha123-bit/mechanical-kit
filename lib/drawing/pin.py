"""pin.py —— 销连接画法（ch8 §8-3 表8-4，p.240–241）

坐标约定：销轴线**竖直**（x=0），+y 向上；y=0 取下被连接件底面。
全部几何只经 lib.drawing._prim 原语表达，线型只用 STYLES 的 thick/thin/center。

表8-4 的三条共同规定（A-key.json 表8-4 两页逐条 [核]）：
    销按不剖绘制（销内无剖面线）；被连接件剖切，两件剖面线方向/间距不同；
    销与销孔的配合面只画一条线（配合面不另画孔壁）。
"""
import math
import sys
from pathlib import Path

MDKIT = Path(__file__).resolve().parents[2]
if str(MDKIT) not in sys.path: sys.path.insert(0, str(MDKIT))
from lib.drawing._prim import 图形, 校验图元, 线, 圆, 弧, 矩形, 文, 剖面线, 尺寸H, 尺寸V, 拼  # noqa: E402,F401

锥度 = 50.0          # 圆锥销 1:50
板半宽系数 = 3.0     # 示意值：被连接件外宽（表8-4 未标）
锥角 = 45.0          # 端部倒角


def _板剖面(半宽, 内半径左, 内半径右, y0, y1):
    """被连接件一侧板在销两侧的两条剖面带（内边界即销轮廓，配合面画一条线）。"""
    左 = [(-半宽, y0), (-内半径左, y0), (-内半径右, y1), (-半宽, y1)]
    右 = [(内半径左, y0), (半宽, y0), (半宽, y1), (内半径右, y1)]
    return 左, 右


# ------------------------------------------------------------------ 13 销连接
def 销连接画法(d=8.0, l=30.0, 类型="圆柱"):
    """销连接（圆柱销 / 圆锥销 / 开口销，三选一）。

    依据：表8-4 p.240–241 [核]（销连接画法）
      圆柱销：d×l（GB/T 119.1），端部略凸出并倒角，销不剖，被连接件剖且两件剖面线
              方向不同，配合面只画一条线；
      圆锥销：锥度 1:50（GB/T 117），锥面配合仍只画一条线；
      开口销：穿过槽形螺母的槽与螺栓销孔，两腿扳开（d×l，GB/T 91）。
    圆柱/圆锥销的被连接件为两块板（各 0.45l 厚，示意值），销两端各伸出 0.05l。
    开口销的螺栓、螺母为标准件，按不剖绘制。
    """
    if 类型 not in ("圆柱", "圆锥", "开口"):
        raise ValueError('类型 只能是 "圆柱" / "圆锥" / "开口"')
    if d <= 0 or l <= 0:
        raise ValueError("d、l 必须为正")

    if 类型 == "开口":
        return _开口销(d, l)

    半宽 = 板半宽系数 * d
    板厚 = 0.45 * l
    y0 = -0.05 * l                     # 销下端（略凸出）
    y1 = 0.95 * l                      # 销上端
    倒角 = min(0.15 * d, 0.05 * l)
    y下顶 = 板厚
    y上顶 = 2.0 * 板厚

    def r(y):
        """销在高度 y 处的半径：圆柱销恒定，圆锥销按 1:50 线性收缩。"""
        if 类型 == "圆柱":
            return d / 2.0
        return d / 2.0 - (y - y0) / (2.0 * 锥度)

    g = 图形()
    # 两块被连接件的外轮廓
    g.加(线(-半宽, 0, -半宽, y下顶), 线(半宽, 0, 半宽, y下顶),
         线(-半宽, y下顶, -半宽, y上顶), 线(半宽, y下顶, 半宽, y上顶),
         线(-半宽, y上顶, 半宽, y上顶), 线(-半宽, 0, 半宽, 0),
         线(-半宽, y下顶, -r(y下顶), y下顶), 线(r(y下顶), y下顶, 半宽, y下顶))  # 结合面一条线
    # 销（不剖）：两侧轮廓线即配合面 —— 一条线画到底
    g.加(线(-r(y0 + 倒角), y0 + 倒角, -r(y1 - 倒角), y1 - 倒角),
         线(r(y0 + 倒角), y0 + 倒角, r(y1 - 倒角), y1 - 倒角))
    # 端部倒角 + 端面
    g.加(线(-(r(y0) - 倒角), y0, -r(y0), y0 + 倒角),
         线(r(y0) - 倒角, y0, r(y0), y0 + 倒角),
         线(-(r(y0) - 倒角), y0, r(y0) - 倒角, y0),
         线(-(r(y1) - 倒角), y1, -r(y1), y1 - 倒角),
         线(r(y1) - 倒角, y1, r(y1), y1 - 倒角),
         线(-(r(y1) - 倒角), y1, r(y1) - 倒角, y1))
    # 剖面线：上件 45°、下件 -45°（两件方向不同）；销内不画
    上左, 上右 = _板剖面(半宽, r(y下顶), r(y上顶), y下顶, y上顶)
    下左, 下右 = _板剖面(半宽, r(0.0), r(y下顶), 0.0, y下顶)
    g.加(剖面线(上左, 2.0, 45.0), 剖面线(上右, 2.0, 45.0),
         剖面线(下左, 2.0, -45.0), 剖面线(下右, 2.0, -45.0))
    # 销轴线
    g.加(线(0, y0 - 4, 0, y1 + 4, "center"))

    if 类型 == "圆柱":
        g.注(f"圆柱销 {d:g}×{l:g}（GB/T 119.1）",
             "销按不剖绘制；被连接件剖切，两件剖面线方向不同",
             "销与销孔配合面只画一条线；销两端略凸出并倒角 45°")
    else:
        g.注(f"圆锥销 {d:g}×{l:g}（GB/T 117），锥度 1:{锥度:g}",
             "锥面配合画一条线（不另画孔壁）",
             "销按不剖绘制；被连接件两件剖面线方向不同")
    g.范围(-半宽, y0 - 4, 半宽, y1 + 4)
    return g


def _开口销(d, l):
    """开口销连接：槽形螺母 + 螺栓销孔 + 两腿扳开（表8-4 p.241 [核]）。"""
    杆 = 2.5 * d
    m = 0.8 * 杆
    母宽 = 1.6 * 杆
    槽深 = 0.35 * m
    槽宽 = 1.2 * d
    y销 = m - 槽深 / 2.0
    L销 = 杆 / 2.0 + 0.8 * d
    腿高 = 2.4 * d
    腿外 = 0.6 * d
    g = 图形()

    # 螺栓（不剖）+ 螺母（标准件，不剖）
    g.加(线(-杆 / 2.0, 0, -杆 / 2.0, m + 0.3 * 杆), 线(杆 / 2.0, 0, 杆 / 2.0, m + 0.3 * 杆),
         线(-杆 / 2.0, m + 0.3 * 杆, 杆 / 2.0, m + 0.3 * 杆),
         线(-杆 / 2.0, 0, 杆 / 2.0, 0))
    g.加(矩形(-母宽 / 2.0, 0, 母宽, m))
    # 槽形螺母的端部开槽（槽口与销孔对正）
    g.加(线(-槽宽 / 2.0, m - 槽深, -槽宽 / 2.0, m),
         线(槽宽 / 2.0, m - 槽深, 槽宽 / 2.0, m))
    # 开口销：穿过销孔的两腿（平行），穿出后向两侧扳开
    g.加(线(-L销, y销 + d / 2.0, L销, y销 + d / 2.0),
         线(-L销, y销 - d / 2.0, L销, y销 - d / 2.0),
         线(-L销, y销 + d / 2.0, -L销, y销 - d / 2.0),
         线(L销, y销 + d / 2.0, L销, y销 - d / 2.0))
    g.加(线(-L销, y销 + d / 2.0, -L销 - 腿外, y销 + 腿高),
         线(L销, y销 - d / 2.0, L销 + 腿外, y销 + 腿高))
    g.加(线(0, -0.2 * 杆, 0, m + 0.5 * 杆, "center"))

    g.注(f"开口销 {d:g}×{l:g}（GB/T 91）",
         "开口销穿过槽形螺母的槽与螺栓销孔后把两腿扳开，起防松作用",
         "螺栓、螺母为标准件按不剖绘制；销亦不剖")
    g.范围(-母宽 / 2.0, -0.2 * 杆, 母宽 / 2.0, max(m + 0.5 * 杆, y销 + 腿高))
    return g


# ------------------------------------------------------------------ 自检
def _自检():
    cases = [销连接画法(), 销连接画法(类型="圆锥"), 销连接画法(类型="开口"),
             销连接画法(d=5.0, l=20.0, 类型="圆锥")]
    for i, g in enumerate(cases, 1):
        ok, msg = 校验图元(g.elems)
        assert ok, f"#{i} {msg}"
        print(f"#{i} {len(g):>3} 图元  {msg}  bbox={tuple(round(v, 2) for v in g.bbox)}")

    d, l = 8.0, 30.0
    g = 销连接画法(类型="圆锥")
    r下, r上 = d / 2.0, d / 2.0 - (0.95 * l - (-0.05 * l)) / (2 * 锥度)
    print("圆锥销：锥度 1:50 → 下端半径 %.2f、上端半径 %.3f（收缩 %.2f）"
          % (r下, r上, r下 - r上))
    assert abs((r下 - r上) * 2 * 锥度 - l) < 1e-9, "锥度不符 1:50"
    g = 销连接画法()
    ys = {round(dd["y1"], 3) for k, dd in g.elems if k == "line"}
    assert round(0.45 * l, 3) in ys and round(0.9 * l, 3) in ys, f"两板结合面/顶面缺失 {ys}"
    print("圆柱销：两板厚各 %.1f，结合面 y=%.1f，销伸出 %.1f / %.1f"
          % (0.45 * l, 0.45 * l, 0.05 * l, 0.05 * l))


if __name__ == "__main__":
    _自检()

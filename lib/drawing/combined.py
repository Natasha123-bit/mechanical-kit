from lib.drawing._prim import 图形, 线, 圆, 弧, 矩形, 文, 尺寸H, 尺寸V, TEXT_H  # noqa: E402

视图间距 = 15.0


def 组合体三视图(长=60, 宽=40, 高=25, 凸台直径=24, 凸台高=12,
                 间距=视图间距, x=40, y=90):
    """底板 + 顶部圆柱凸台的组合体三视图（叠加型）。

    依据：图4-11 p.113 [核]（叠加型组合体画图思路：先大后小、先实后空）、
          图4-13 p.115 [核]（轴线/基线定位、检查描深）。
    布局：主视 (x,y) 起 长×高；俯视 (x,y-间距-宽) 起 长×宽；左视 (x+长+间距,y) 起 宽×高。
    凸台在底板顶面正中：主/左视图为凸台矩形，俯视图为圆；凸台与底板顶面的交线在
    主/左视图中把顶面线分成左右两段，不画穿凸台的整条横线。
    """
    if 长 <= 0 or 宽 <= 0 or 高 <= 0 or 凸台直径 <= 0 or 凸台高 <= 0:
        raise ValueError("长、宽、高、凸台直径、凸台高 必须 > 0")
    if 凸台直径 >= min(长, 宽):
        raise ValueError("凸台直径 必须小于 长、宽，才能落在底板顶面内")

    R = 凸台直径 / 2.0
    主 = (x, y, 长, 高)
    俯 = (x, y - 间距 - 宽, 长, 宽)
    左 = (x + 长 + 间距, y, 宽, 高)
    凸主 = (x + (长 - 凸台直径) / 2, y + 高, 凸台直径, 凸台高)
    凸左 = (左[0] + (宽 - 凸台直径) / 2, y + 高, 凸台直径, 凸台高)
    凸俯中 = (x + 长 / 2, 俯[1] + 宽 / 2)

    g = 图形()
    # 主视：底板上边线分左右两段 + 两侧/下边
    g.加(线(x, y, x, y + 高, "thick"), 线(x, y, x + 长, y, "thick"),
         线(x + 长, y, x + 长, y + 高, "thick"),
         线(x, y + 高, 凸主[0], y + 高, "thick"),
         线(凸主[0] + 凸台直径, y + 高, x + 长, y + 高, "thick"),
         矩形(*凸主, "thick"))
    # 俯视：底板矩形 + 凸台圆
    g.加(矩形(*俯, "thick"), 圆(凸俯中[0], 凸俯中[1], R, "thick"))
    # 左视：底板上边线分左右两段 + 凸台矩形
    g.加(线(左[0], y, 左[0], y + 高, "thick"), 线(左[0], y, 左[0] + 宽, y, "thick"),
         线(左[0] + 宽, y, 左[0] + 宽, y + 高, "thick"),
         线(左[0], y + 高, 凸左[0], y + 高, "thick"),
         线(凸左[0] + 凸台直径, y + 高, 左[0] + 宽, y + 高, "thick"),
         矩形(*凸左, "thick"))
    # 中心线
    g.加(线(x + 长 / 2, y - 3, x + 长 / 2, y + 高 + 凸台高 + 3, "center"),
         线(凸俯中[0] - R - 3, 凸俯中[1], 凸俯中[0] + R + 3, 凸俯中[1], "center"),
         线(凸俯中[0], 凸俯中[1] - R - 3, 凸俯中[0], 凸俯中[1] + R + 3, "center"),
         线(左[0] + 宽 / 2, y - 3, 左[0] + 宽 / 2, y + 高 + 凸台高 + 3, "center"))
    g.加(文(x + 长 / 2, y - 3, "主视图", TEXT_H),
         文(x + 长 / 2, 俯[1] - 3, "俯视图", TEXT_H),
         文(左[0] + 宽 / 2, y - 3, "左视图", TEXT_H))
    g.注("叠加型组合体：底板与凸台同轴；凸台与顶面交线把顶面线分成两段（图4-11 p.113）")
    g.范围(x - 3, 俯[1] - 8, 左[0] + 宽 + 3, y + 高 + 凸台高 + 3)
    g.参数 = dict(主=主, 俯=俯, 左=左, 凸主=凸主, 凸左=凸左, 凸俯中=凸俯中, R=R)
    return g


def 组合体尺寸(长=60, 宽=40, 高=25, 凸台直径=24, 凸台高=12, x=40, y=90):
    """组合体尺寸标注：总体长/高、凸台直径/高、底板宽，含三向基准。

    依据：图4-30/4-31 p.129 [核]（定形/定位/总体尺寸与长宽高三个基准）、
          图4-33/4-34 p.131 [核]（尺寸集中、布局清晰、交线不注）。
    只画主视与俯视两个视图，尺寸取整数示意；不注重复尺寸（总高由 高+凸台高 得到，
    按图4-30 的做法只注 高 与 凸台高，不注总高）。
    """
    if 长 <= 0 or 宽 <= 0 or 高 <= 0 or 凸台直径 <= 0 or 凸台高 <= 0:
        raise ValueError("尺寸参数必须 > 0")
    R = 凸台直径 / 2.0
    主 = (x, y, 长, 高)
    俯 = (x, y - 25 - 宽, 长, 宽)
    凸主 = (x + (长 - 凸台直径) / 2, y + 高, 凸台直径, 凸台高)
    凸俯中 = (x + 长 / 2, 俯[1] + 宽 / 2)

    g = 图形().加(矩形(*主, "thick"), 矩形(*凸主, "thick"), 矩形(*俯, "thick"),
                  圆(凸俯中[0], 凸俯中[1], R, "thick"))
    # 基准：底面、左侧面、后侧面（俯视上边）
    g.加(文(x, y - 7, "基准", TEXT_H, anchor="start"),
         文(x - 2, y, "▼", TEXT_H, anchor="end"),
         文(俯[0] - 2, 俯[1] + 宽, "▼", TEXT_H, anchor="end"))
    # 总体长
    g.加(尺寸H(y - 12, x, x + 长, f"{长:g}"))
    # 底板高
    g.加(尺寸V(x - 12, y, y + 高, f"{高:g}"))
    # 凸台高
    g.加(尺寸V(x + 长 + 12, y + 高, y + 高 + 凸台高, f"{凸台高:g}"))
    # 凸台直径
    g.加(尺寸H(y + 高 + 凸台高 + 10, 凸主[0], 凸主[0] + 凸台直径, f"φ{凸台直径:g}"))
    # 底板宽（俯视）
    g.加(尺寸V(俯[0] + 长 + 12, 俯[1], 俯[1] + 宽, f"{宽:g}"))
    g.注("组合体尺寸：定形（长/宽/高/φ凸台）+ 定位（凸台在顶面中心）；总高不重复注（图4-30 p.129）")
    g.范围(x - 18, 俯[1] - 10, 俯[0] + 长 + 20, y + 高 + 凸台高 + 16)
    return g


def 邻接表面(关系="平齐", 长=30, 高=20, 错位=8, 半径=8, x=40, y=90):
    """相邻表面关系的画法：平齐 / 不平齐 / 相切 / 相交。

    依据：图4-5 p.111 [核]（不共面时台阶面不可漏画；共面不多线）、
          图4-7/4-8 p.112 [核]（相切处无交线、相交处有交线）。
      “平齐”：两方块同高共面，接缝处不画竖线；
      “不平齐”：右块低 错位，接缝处画一条竖线（台阶面）；
      “相切”：圆与水平顶面相切，切点处不画竖线；
      “相交”：两方块相交，交线处画竖线。
    参数为示意尺寸；x,y 为左块左下角。
    """
    if 关系 not in ("平齐", "不平齐", "相切", "相交"):
        raise ValueError(f"关系 只能是 平齐/不平齐/相切/相交，收到 {关系!r}")
    g = 图形()
    右x = x + 长
    if 关系 == "平齐":
        g.加(线(x, y, x + 2 * 长, y, "thick"), 线(x, y, x, y + 高, "thick"),
             线(x, y + 高, x + 2 * 长, y + 高, "thick"),
             线(x + 2 * 长, y, x + 2 * 长, y + 高, "thick"))
        g.注("平齐（共面）：接缝处不画分界线（图4-5 p.111）")
    elif 关系 == "不平齐":
        g.加(线(x, y, x + 2 * 长, y, "thick"), 线(x, y, x, y + 高, "thick"),
             线(x, y + 高, 右x, y + 高, "thick"),
             线(右x, y, 右x, y + 高 - 错位, "thick"),
             线(右x, y + 高 - 错位, x + 2 * 长, y + 高 - 错位, "thick"),
             线(x + 2 * 长, y, x + 2 * 长, y + 高 - 错位, "thick"))
        g.注("不平齐：台阶面用一条竖线分开，不可漏画（图4-5 p.111）")
    elif 关系 == "相切":
        g.加(线(x, y + 高, x + 2 * 长, y + 高, "thick"),
             线(x, y, x + 2 * 长, y, "thick"),
             圆(右x, y + 高 - 半径, 半径, "thick"))
        g.注("相切：切点处不画交线，顶面线连续（图4-8a p.112）")
    else:
        g.加(矩形(x, y, 长, 高, "thick"), 矩形(右x, y - 错位 / 2, 长, 高, "thick"))
        g.注("相交：相邻表面相交处必须画交线（图4-8b p.112）")
    g.加(文(x + 长, y - 8, 关系, TEXT_H))
    g.范围(x - 3, y - 12, x + 2 * 长 + 3, y + 高 + 3)
    g.关系 = 关系
    return g

def _折线(g, pts, style="thick"):
    for p, q in zip(pts, pts[1:]):
        g.加(线(p[0], p[1], q[0], q[1], style))


def 圆柱三视图(直径=40, 高=50, 间距=视图间距, x=40, y=90):
    """圆柱三视图：主/左为矩形，俯视为圆；轴线用细点画线。

    依据：图3-17 p.75 [核]（圆柱的三面投影）、图3-19/3-20 p.76 [核]（表面取点取线）。
    布局同 三视图：主视 (x,y) 起 2R×H；俯视圆心 (x+R, y-间距-R)；左视 (x+2R+间距,y) 起 2R×H。
    """
    if 直径 <= 0 or 高 <= 0:
        raise ValueError("直径、高 必须 > 0")
    R = 直径 / 2.0
    主 = (x, y, 直径, 高)
    左 = (x + 直径 + 间距, y, 直径, 高)
    俯中 = (x + R, y - 间距 - R)

    g = 图形().加(矩形(*主, "thick"), 矩形(*左, "thick"),
                  圆(俯中[0], 俯中[1], R, "thick"))
    # 轴线与中心线
    g.加(线(x - 3, y + 高 / 2, x + 直径 + 3, y + 高 / 2, "center"))
    g.加(线(左[0] - 3, y + 高 / 2, 左[0] + 直径 + 3, y + 高 / 2, "center"))
    g.加(线(俯中[0] - R - 3, 俯中[1], 俯中[0] + R + 3, 俯中[1], "center"),
         线(俯中[0], 俯中[1] - R - 3, 俯中[0], 俯中[1] + R + 3, "center"))
    g.加(文(x + R, y - 3, "主视图", TEXT_H),
         文(x + R, 俯中[1] - R - 6, "俯视图", TEXT_H),
         文(左[0] + R, y - 3, "左视图", TEXT_H))
    g.注("圆柱：主/左视图为矩形，俯视图为圆；转向线为粗实线（图3-17 p.75）")
    g.范围(x - 3, 俯中[1] - R - 9, 左[0] + 直径 + 3, y + 高 + 3)
    g.参数 = dict(主=主, 左=左, 俯中=俯中, R=R)
    return g


def 圆锥三视图(底直径=40, 高=50, 间距=视图间距, x=40, y=90):
    """圆锥三视图：主/左为三角形，俯视为圆（圆心即锥顶投影）。

    依据：图3-21 p.77 [核]（圆锥的三面投影）、图3-23 p.77 [核]（纬圆法取点）。
    """
    if 底直径 <= 0 or 高 <= 0:
        raise ValueError("底直径、高 必须 > 0")
    R = 底直径 / 2.0
    主 = (x, y, 底直径, 高)
    左 = (x + 底直径 + 间距, y, 底直径, 高)
    俯中 = (x + R, y - 间距 - R)

    g = 图形()
    # 主视三角形
    g.加(线(x, y, x + 底直径, y, "thick"),
         线(x, y, x + R, y + 高, "thick"),
         线(x + 底直径, y, x + R, y + 高, "thick"))
    # 左视三角形
    g.加(线(左[0], y, 左[0] + 底直径, y, "thick"),
         线(左[0], y, 左[0] + R, y + 高, "thick"),
         线(左[0] + 底直径, y, 左[0] + R, y + 高, "thick"))
    # 俯视圆
    g.加(圆(俯中[0], 俯中[1], R, "thick"))
    g.加(线(x - 3, y + 高 / 2, x + 底直径 + 3, y + 高 / 2, "center"),
         线(左[0] - 3, y + 高 / 2, 左[0] + 底直径 + 3, y + 高 / 2, "center"),
         线(俯中[0] - R - 3, 俯中[1], 俯中[0] + R + 3, 俯中[1], "center"),
         线(俯中[0], 俯中[1] - R - 3, 俯中[0], 俯中[1] + R + 3, "center"))
    g.加(文(x + R, y - 3, "主视图", TEXT_H),
         文(x + R, 俯中[1] - R - 6, "俯视图", TEXT_H),
         文(左[0] + R, y - 3, "左视图", TEXT_H))
    g.注("圆锥：主/左为三角形，俯视为圆；锥顶投影在圆心（图3-21 p.77）")
    g.范围(x - 3, 俯中[1] - R - 9, 左[0] + 底直径 + 3, y + 高 + 3)
    g.参数 = dict(主=主, 左=左, 俯中=俯中, R=R, 顶=(x + R, y + 高))
    return g


def 球三视图(直径=40, 间距=视图间距, x=40, y=90):
    """球三视图：三个等径圆，圆心按三视图布局；三个方向都画中心线。

    依据：图3-25 p.80 [核]（球的三面投影）、图3-27 p.80 [核]（球表面取点）。
    """
    if 直径 <= 0:
        raise ValueError("直径 必须 > 0")
    R = 直径 / 2.0
    主中 = (x + R, y + R)
    俯中 = (x + R, y - 间距 - R)
    左中 = (x + 直径 + 间距 + R, y + R)

    g = 图形()
    for c in (主中, 俯中, 左中):
        g.加(圆(c[0], c[1], R, "thick"),
             线(c[0] - R - 3, c[1], c[0] + R + 3, c[1], "center"),
             线(c[0], c[1] - R - 3, c[0], c[1] + R + 3, "center"))
    g.加(文(主中[0], 主中[1] - R - 6, "主视图", TEXT_H),
         文(俯中[0], 俯中[1] - R - 6, "俯视图", TEXT_H),
         文(左中[0], 左中[1] - R - 6, "左视图", TEXT_H))
    g.注("球：三面投影都是与球等径的圆；转向线为三个方向的最大圆（图3-25 p.80）")
    g.范围(x - 3, 俯中[1] - R - 9, 左中[0] + R + 3, y + 直径 + 3)
    g.参数 = dict(主中=主中, 俯中=俯中, 左中=左中, R=R)
    return g


def 圆柱截交线(直径=40, 高=50, 截距=30, 类型="水平", 间距=视图间距, x=40, y=90):
    """圆柱被水平面截切后的三视图（保留截距以下部分）。

    依据：表3-1 p.85 [核] 第 1 行“截平面垂直于圆柱轴线 → 截交线为圆”；
          图3-33 p.86 [核] 为斜切圆柱（椭圆），本函数未实现斜切。
    几何：截平面 z=截距，截交线是直径=直径 的圆；主/左视图剩下矩形高=截距，顶边为截交线。
    类型 只支持 "水平"；"垂直"/"倾斜" 抛 NotImplementedError，避免臆造。
    """
    if 类型 != "水平":
        raise NotImplementedError(f"圆柱截交线 本批只实现 '水平'（表3-1 第 1 行），收到 {类型!r}")
    if 直径 <= 0 or 高 <= 0 or not (0 < 截距 <= 高):
        raise ValueError("直径、高 必须 > 0，且 0 < 截距 ≤ 高")
    R = 直径 / 2.0
    主 = (x, y, 直径, 截距)
    左 = (x + 直径 + 间距, y, 直径, 截距)
    俯中 = (x + R, y - 间距 - R)

    g = 图形().加(矩形(*主, "thick"), 矩形(*左, "thick"),
                  圆(俯中[0], 俯中[1], R, "thick"))
    # 截交线：主/左视图顶边加粗，俯视图即圆
    g.加(线(x, y + 截距, x + 直径, y + 截距, "thick"),
         线(左[0], y + 截距, 左[0] + 直径, y + 截距, "thick"))
    g.加(线(x - 3, y + 截距 / 2, x + 直径 + 3, y + 截距 / 2, "center"),
         线(左[0] - 3, y + 截距 / 2, 左[0] + 直径 + 3, y + 截距 / 2, "center"),
         线(俯中[0] - R - 3, 俯中[1], 俯中[0] + R + 3, 俯中[1], "center"),
         线(俯中[0], 俯中[1] - R - 3, 俯中[0], 俯中[1] + R + 3, "center"))
    g.加(文(x + R, y - 3, "主视图", TEXT_H),
         文(x + R, 俯中[1] - R - 6, "俯视图", TEXT_H),
         文(左[0] + R, y - 3, "左视图", TEXT_H))
    g.注("水平面截圆柱：截交线为圆，主/左视图为矩形顶边，俯视图为圆（表3-1 p.85）")
    g.范围(x - 3, 俯中[1] - R - 9, 左[0] + 直径 + 3, y + 截距 + 3)
    g.参数 = dict(主=主, 左=左, 俯中=俯中, R=R, 截距=截距)
    return g


def 相贯线(R1=20, R2=15, 高1=50, 长2=60, 间距=视图间距, x=40, y=90, 采样=24):
    """两正交圆柱相贯：竖圆柱（轴线 z）与横圆柱（轴线 x）的相贯线。

    依据：图3-48 圆柱与圆柱相贯 p.100 [核]；图3-50 辅助平面法 p.102 [核]；
          图3-54~3-56 特殊相贯 p.105 [核]（等径时相贯线为直线，本函数按一般 R1≠R2 画曲线）。
    几何：竖圆柱 x²+y²=R1²，z∈[0,高1]；横圆柱 y²+(z-z0)²=R2²，z0=高1/2。
      相贯点满足 x²+y²=R1² 且 y²+(z-z0)²=R2²；存在域 |x|≥√(R1²−R2²)。
    主视图画相贯线（4 段：左右两侧 × 上下两支）；俯/左视图画两圆柱轮廓与中心线。
    要求 R2 < R1（横圆柱贯穿竖圆柱）；R2≥R1 时抛 ValueError。
    """
    if R1 <= 0 or R2 <= 0 or 高1 <= 0 or 长2 <= 0:
        raise ValueError("R1、R2、高1、长2 必须 > 0")
    if R2 >= R1:
        raise ValueError(f"本函数按 R2<R1 的贯穿情形实现，收到 R1={R1}, R2={R2}")
    if 采样 < 4:
        raise ValueError("采样 必须 ≥ 4")

    R1, R2 = float(R1), float(R2)
    z0 = 高1 / 2.0
    主x, 主y = x, y
    竖主 = (主x, 主y, 2 * R1, 高1)
    横主 = (主x + R1 - 长2 / 2, 主y + z0 - R2, 长2, 2 * R2)
    俯中 = (主x + R1, 主y - 间距 - R1)
    左中 = (主x + 2 * R1 + 间距 + R2, 主y + z0)

    g = 图形().加(矩形(*竖主, "thick"), 矩形(*横主, "thick"))
    # 俯视图：竖圆柱圆 + 横圆柱矩形
    g.加(圆(俯中[0], 俯中[1], R1, "thick"),
         矩形(俯中[0] - 长2 / 2, 俯中[1] - R2, 长2, 2 * R2, "thick"))
    # 左视图：横圆柱圆 + 竖圆柱矩形
    g.加(圆(左中[0], 左中[1], R2, "thick"),
         矩形(左中[0] - R1, 主y, 2 * R1, 高1, "thick"))

    # 主视图相贯线
    xmin = math.sqrt(max(R1 * R1 - R2 * R2, 0.0))
    for side in (-1, 1):
        for sign in (-1, 1):
            pts = []
            for k in range(采样 + 1):
                xx = xmin + (R1 - xmin) * k / 采样
                yy = math.sqrt(max(R1 * R1 - xx * xx, 0.0))
                dz = math.sqrt(max(R2 * R2 - yy * yy, 0.0))
                pts.append((主x + R1 + side * xx, 主y + z0 + sign * dz))
            _折线(g, pts, "thick")

    # 中心线
    g.加(线(主x - 3, 主y + z0, 主x + 2 * R1 + 3, 主y + z0, "center"),
         线(主x + R1, 主y - 3, 主x + R1, 主y + 高1 + 3, "center"),
         线(俯中[0] - R1 - 3, 俯中[1], 俯中[0] + R1 + 3, 俯中[1], "center"),
         线(俯中[0], 俯中[1] - R1 - 3, 俯中[0], 俯中[1] + R1 + 3, "center"),
         线(左中[0] - R2 - 3, 左中[1], 左中[0] + R2 + 3, 左中[1], "center"),
         线(左中[0], 左中[1] - R2 - 3, 左中[0], 左中[1] + R2 + 3, "center"))
    g.加(文(主x + R1, 主y - 3, "主视图", TEXT_H),
         文(俯中[0], 俯中[1] - R1 - 6, "俯视图", TEXT_H),
         文(左中[0], 左中[1] - R2 - 6, "左视图", TEXT_H))
    g.注("两正交圆柱相贯：相贯线主视投影按 x²+y²=R1²、y²+(z−z0)²=R2² 逐点求出（图3-48 p.100）")
    g.范围(主x - 3, 俯中[1] - R1 - 9, 左中[0] + R1 + 3, 主y + 高1 + 3)
    g.参数 = dict(竖主=竖主, 横主=横主, 俯中=俯中, 左中=左中, z0=z0, xmin=xmin)
    return g

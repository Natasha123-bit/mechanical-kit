"""thread.py —— 螺纹规定的画法（ch8 §8-1，p.226–227）

坐标约定：轴线**水平**，自 `x0` 起沿 +x 生长；轴线落在 `y轴`。
所有几何只经 lib.drawing._prim 的原语（线 / 圆 / 弧 / 矩形 / 文 / 剖面线）表达，
线型只用 gbdraw.STYLES 的 thick / thin / center / wavy，不手写 SVG 字符串。

已知接缝缺口（本任务不许改 _prim.py，故在此绕行并记录）：
    尺寸H / 尺寸V 内部经 gbdraw.ARROW 产出 ("poly", …) 图元，而 校验图元() 的
    `允许种类` 里没有 "poly" —— 任何含尺寸线的图形都会被判 FAIL。本模块竖直标注
    改用 `_箭头竖()`（两条细实线自绘箭头，仍是 _prim 的 线 原语）。
"""
import math
import sys
from pathlib import Path

MDKIT = Path(__file__).resolve().parents[2]
if str(MDKIT) not in sys.path: sys.path.insert(0, str(MDKIT))
from lib.drawing._prim import 图形, 校验图元, 线, 圆, 弧, 矩形, 文, 剖面线, 尺寸H, 尺寸V, 拼  # noqa: E402,F401

# 规则常量（A-thread.json 逐条可查）
小径系数 = 0.85          # d1 = 0.85d（粗画法）
轴线外伸 = 4.0           # 轴线两端各伸出 3~5 mm，取 4
剖面间距 = 2.0
钻头锥角 = 120.0         # 孔底钻头角；半角 60°（与轴线），即与端面成 30°


# ------------------------------------------------------------------ 内部工具
def _箭头竖(x, y尖, 朝上=True, 长=3.0, 半宽=0.6):
    """竖直线上的箭头：两条细实线。返回 (线, 线)。"""
    s = 1.0 if 朝上 else -1.0
    y后 = y尖 - s * 长
    return (线(x - 半宽, y后, x, y尖, "thin"), 线(x + 半宽, y后, x, y尖, "thin"))


def _锥深(r1):
    """120° 钻头角时，锥尖到圆柱孔末端的轴向距离：r1 / tan(60°)。"""
    return r1 / math.tan(math.radians(钻头锥角 / 2.0))


# ------------------------------------------------------------------ 1 外螺纹
def 外螺纹画法(d=12.0, P=1.75, 螺纹长=30.0, 杆长=45.0, 倒角=2.0, 终止线=True,
               x0=0.0, y轴=0.0):
    """外螺纹杆部（主视图，轴线水平）。

    依据：图8-16 p.226 [核]（外螺纹的规定画法）
      大径 thick 全长；小径 thin（d1=0.85d）画入倒角区域；终止线 thick 跨 ±d/2；
      倒角 45°；轴线 center 两端各伸出 4。
    """
    if not (0 < 螺纹长 <= 杆长):
        raise ValueError("螺纹长必须在 (0, 杆长] 内")
    if not (0 < 倒角 < d / 2):
        raise ValueError("倒角必须在 (0, d/2) 内")

    r, r1 = d / 2.0, 小径系数 * d / 2.0
    x端, x止 = x0 + 杆长, x0 + 螺纹长
    # 小径细线“画入倒角区域”：起点落在倒角斜线上
    x小 = x0 + max(0.0, r1 - (r - 倒角))
    g = 图形()

    # 大径：粗实线，自倒角外缘到杆端
    g.加(线(x0 + 倒角, y轴 + r, x端, y轴 + r),
         线(x0 + 倒角, y轴 - r, x端, y轴 - r))
    # 小径：细实线，画入倒角，止于螺纹终止线
    g.加(线(x小, y轴 + r1, x止, y轴 + r1, "thin"),
         线(x小, y轴 - r1, x止, y轴 - r1, "thin"))
    # 倒角 45°（上下各一段）+ 端面
    g.加(线(x0, y轴 + r - 倒角, x0 + 倒角, y轴 + r),
         线(x0, y轴 - r + 倒角, x0 + 倒角, y轴 - r),
         线(x0, y轴 - r + 倒角, x0, y轴 + r - 倒角))
    # 螺纹终止线：粗实线，跨 ±d/2
    if 终止线:
        g.加(线(x止, y轴 - r, x止, y轴 + r))
    # 轴线：细点画线
    g.加(线(x0 - 轴线外伸, y轴, x端 + 轴线外伸, y轴, "center"))

    g.注(f"螺纹 M{d:g}×{P:g}，右旋（粗画法 d1≈{小径系数 * d:.2f}）",
         "大径、螺纹终止线用粗实线；小径用细实线并画入倒角区域",
         "倒角 45°；轴线为细点画线")
    g.范围(x0 - 轴线外伸, y轴 - r, x端 + 轴线外伸, y轴 + r)
    return g


# ------------------------------------------------------------------ 2 内螺纹
def 内螺纹画法(d=20.0, P=2.5, 螺纹长=30.0, 孔深=None, 倒角=2.0, x0=0.0, y轴=0.0):
    """内螺纹（通孔）剖视图。

    依据：图8-18 p.226 [核]（内螺纹的剖视图画法）
      D1=0.85d 的孔壁用 thick；D 的细线在外侧、不画入倒角；终止线 thick 跨 ±D1/2；
      剖面线只填小径以外的实体（上下两块），止于小径粗实线。
    孔深 为工件（通孔）长度，None 时取 螺纹长 + 0.5d；块体半高取 1.2d（示意值，
    规则未规定工件外形）。
    """
    if 孔深 is None:
        孔深 = 螺纹长 + 0.5 * d
    if not (0 < 螺纹长 <= 孔深):
        raise ValueError("螺纹长必须在 (0, 孔深] 内")

    r, r1 = d / 2.0, 小径系数 * d / 2.0
    块半高 = 1.2 * d
    if r1 + 倒角 >= 块半高:
        raise ValueError("块体太薄，容不下孔口倒角")
    x右 = x0 + 孔深
    x止 = x0 + 螺纹长
    g = 图形()

    # 小径（孔壁）：粗实线，贯通
    g.加(线(x0, y轴 + r1, x右, y轴 + r1), 线(x0, y轴 - r1, x右, y轴 - r1))
    # 大径：细实线，在外侧，自倒角内缘到终止线（不画入倒角）
    g.加(线(x0 + 倒角, y轴 + r, x止, y轴 + r, "thin"),
         线(x0 + 倒角, y轴 - r, x止, y轴 - r, "thin"))
    # 螺纹终止线：粗实线，跨 ±D1/2
    g.加(线(x止, y轴 - r1, x止, y轴 + r1))
    # 孔口倒角 45°
    g.加(线(x0, y轴 + r1 + 倒角, x0 + 倒角, y轴 + r1),
         线(x0, y轴 - r1 - 倒角, x0 + 倒角, y轴 - r1))
    # 端面（倒角以外）与块体外轮廓
    g.加(线(x0, y轴 + r1 + 倒角, x0, y轴 + 块半高),
         线(x0, y轴 - r1 - 倒角, x0, y轴 - 块半高),
         线(x0, y轴 + 块半高, x右, y轴 + 块半高),
         线(x0, y轴 - 块半高, x右, y轴 - 块半高),
         线(x右, y轴 - 块半高, x右, y轴 + 块半高))
    # 剖面线：上下两块，均止于小径粗实线（同一零件 → 同向同距）
    上块 = [(x0, y轴 + r1 + 倒角), (x0 + 倒角, y轴 + r1), (x右, y轴 + r1),
            (x右, y轴 + 块半高), (x0, y轴 + 块半高)]
    下块 = [(x, 2 * y轴 - y) for x, y in 上块]
    g.加(剖面线(上块, 剖面间距, 45.0), 剖面线(下块, 剖面间距, 45.0))
    # 轴线
    g.加(线(x0 - 轴线外伸, y轴, x右 + 轴线外伸, y轴, "center"))

    g.注(f"内螺纹 M{d:g}×{P:g}，D1≈{小径系数 * d:.2f}",
         "小径（孔壁）用粗实线；大径用细实线且不画入倒角",
         "剖面线画到小径粗实线，终止线为粗实线")
    g.范围(x0 - 轴线外伸, y轴 - 块半高, x右 + 轴线外伸, y轴 + 块半高)
    return g


# ------------------------------------------------------------------ 3 内螺纹不通孔
def 内螺纹不通孔画法(d=20.0, 螺孔深=30.0, 钻孔深=None, 倒角=2.0, x0=0.0, y轴=0.0):
    """内螺纹不通孔（盲孔）剖视图。

    依据：图8-19 p.227 [核]（内螺纹未通孔的画法）
      钻孔深 = 螺孔深 + 0.5d；孔底 120° 钻头角（锥尖在轴线上）；
      螺纹终止线是两小段，每段自大径细线画到小径粗线。
    终止线每段的实际长度 = (D−D1)/2 = 0.075D（规则文字写作 “0.15d”，那是直径差 d−d1）。
    钻头角：母线与轴线成 60°（与端面成 30°），锥角合计 120°。
    """
    if 钻孔深 is None:
        钻孔深 = 螺孔深 + 0.5 * d
    if not (0 < 螺孔深 <= 钻孔深):
        raise ValueError("螺孔深必须在 (0, 钻孔深] 内")

    r, r1 = d / 2.0, 小径系数 * d / 2.0
    h锥 = _锥深(r1)
    块半高 = 1.2 * d
    x螺 = x0 + 螺孔深
    x钻 = x0 + 钻孔深
    x尖 = x钻 + h锥
    x块 = x尖 + 0.5 * d
    g = 图形()

    # 钻孔段孔壁（底孔≈D1）：粗实线 + 120° 锥尖
    g.加(线(x0, y轴 + r1, x钻, y轴 + r1), 线(x0, y轴 - r1, x钻, y轴 - r1),
         线(x钻, y轴 + r1, x尖, y轴), 线(x钻, y轴 - r1, x尖, y轴))
    # 攻螺纹大径：细实线，自倒角内缘到终止线
    g.加(线(x0 + 倒角, y轴 + r, x螺, y轴 + r, "thin"),
         线(x0 + 倒角, y轴 - r, x螺, y轴 - r, "thin"))
    # 螺纹终止线：两小段，自大径细线到小径粗线
    g.加(线(x螺, y轴 + r1, x螺, y轴 + r),
         线(x螺, y轴 - r, x螺, y轴 - r1))
    # 孔口倒角 + 端面 + 块体
    g.加(线(x0, y轴 + r1 + 倒角, x0 + 倒角, y轴 + r1),
         线(x0, y轴 - r1 - 倒角, x0 + 倒角, y轴 - r1),
         线(x0, y轴 + r1 + 倒角, x0, y轴 + 块半高),
         线(x0, y轴 - r1 - 倒角, x0, y轴 - 块半高),
         线(x0, y轴 + 块半高, x块, y轴 + 块半高),
         线(x0, y轴 - 块半高, x块, y轴 - 块半高),
         线(x块, y轴 - 块半高, x块, y轴 + 块半高))
    # 剖面线：绕锥尖分成上下两块
    上块 = [(x0, y轴 + r1 + 倒角), (x0 + 倒角, y轴 + r1), (x钻, y轴 + r1),
            (x尖, y轴), (x块, y轴), (x块, y轴 + 块半高), (x0, y轴 + 块半高)]
    下块 = [(x, 2 * y轴 - y) for x, y in 上块]
    g.加(剖面线(上块, 剖面间距, 45.0), 剖面线(下块, 剖面间距, 45.0))
    g.加(线(x0 - 轴线外伸, y轴, x块 + 轴线外伸, y轴, "center"))

    g.注(f"螺孔深 {螺孔深:g}，钻孔深 {钻孔深:g}（= 螺孔深 + 0.5d）",
         f"孔底 120° 钻头角，锥深 {h锥:.2f} = D1/2 / tan60°",
         "螺纹终止线为两小段，自大径细线画到小径粗线")
    g.范围(x0 - 轴线外伸, y轴 - 块半高, x块 + 轴线外伸, y轴 + 块半高)
    return g


# ------------------------------------------------------------------ 4 螺纹连接
def 螺纹连接画法(d=20.0, P=2.5, 旋合长度=25.0, 板长=60.0, 板厚=40.0,
                 x0=0.0, y轴=0.0):
    """内、外螺纹旋合（板在左，螺杆自右旋入）。

    依据：图8-21 p.227 [核]（内、外螺纹连接时的画法）
      旋合段只画外螺纹（大径 thick ±d/2、小径 thin ±0.425d）；
      未旋合段按内螺纹（小径 thick ±0.425D、大径 thin ±0.5D）；
      基本大径对基本大径、基本小径对基本小径分别共线；
      剖面线画到粗实线：未旋合段止于 0.425d，旋合段止于 0.5d。
    说明：螺杆为实心标准件，按不剖绘制，故本图只有“板”一件有剖面线
    （图8-21 原图是两管件全剖、方向相反；此处按任务书取实心螺杆简化）。
    杆伸出板外的长度取 1.5d、孔口倒角取 0.1d，均为示意值（规则未给）。
    """
    if not (0 < 旋合长度 < 板长):
        raise ValueError("旋合长度必须在 (0, 板长) 内")
    if 板厚 / 2.0 <= d / 2.0:
        raise ValueError("板厚必须大于 d，否则无壁可剖")

    r, r1 = d / 2.0, 小径系数 * d / 2.0
    R板 = 板厚 / 2.0
    外伸 = 1.5 * d
    倒角 = 0.1 * d
    x右 = x0 + 板长
    x旋 = x右 - 旋合长度          # 旋合段与未旋合段的分界
    x杆端 = x右 + 外伸
    g = 图形()

    # 板外轮廓
    g.加(线(x0, y轴 + R板, x右, y轴 + R板),
         线(x0, y轴 - R板, x右, y轴 - R板),
         线(x0, y轴 - R板, x0, y轴 + R板))
    # 板右端面：被螺杆劈成上下两段（大径粗线处断开）
    g.加(线(x右, y轴 + r, x右, y轴 + R板), 线(x右, y轴 - R板, x右, y轴 - r))
    # 旋合段（按外螺纹绘制）：大径 thick、小径 thin
    g.加(线(x旋, y轴 + r, x杆端 - 倒角, y轴 + r),
         线(x旋, y轴 - r, x杆端 - 倒角, y轴 - r))
    g.加(线(x旋, y轴 + r1, x杆端 - 倒角, y轴 + r1, "thin"),
         线(x旋, y轴 - r1, x杆端 - 倒角, y轴 - r1, "thin"))
    # 杆端倒角 + 端面
    g.加(线(x杆端 - 倒角, y轴 + r, x杆端, y轴 + r - 倒角),
         线(x杆端 - 倒角, y轴 - r, x杆端, y轴 - r + 倒角),
         线(x杆端, y轴 - r + 倒角, x杆端, y轴 + r - 倒角))
    # 未旋合段（按内螺纹绘制）：小径 thick（与旋合段小径细线共线）、大径 thin
    g.加(线(x0, y轴 + r1, x旋, y轴 + r1), 线(x0, y轴 - r1, x旋, y轴 - r1))
    g.加(线(x0 + 倒角, y轴 + r, x旋, y轴 + r, "thin"),
         线(x0 + 倒角, y轴 - r, x旋, y轴 - r, "thin"))
    # 内螺纹终止线（即旋合分界）：thick 跨 ±0.425d
    g.加(线(x旋, y轴 - r1, x旋, y轴 + r1))
    # 板孔口倒角
    g.加(线(x0, y轴 + r + 倒角, x0 + 倒角, y轴 + r),
         线(x0, y轴 - r - 倒角, x0 + 倒角, y轴 - r))
    # 剖面线：一块板，靠切口台阶止于 0.425d / 0.5d
    上块 = [(x0, y轴 + r1), (x旋, y轴 + r1), (x旋, y轴 + r), (x右, y轴 + r),
            (x右, y轴 + R板), (x0, y轴 + R板)]
    下块 = [(x, 2 * y轴 - y) for x, y in 上块]
    g.加(剖面线(上块, 剖面间距, 45.0), 剖面线(下块, 剖面间距, 45.0))
    g.加(线(x0 - 轴线外伸, y轴, x杆端 + 轴线外伸, y轴, "center"))

    g.注(f"旋合长度 {旋合长度:g}；旋合段按外螺纹绘制，未旋合段按内螺纹绘制",
         "基本大径 / 基本小径分别共线；剖面线画到粗实线",
         "螺杆为实心标准件，按不剖绘制（板一件剖面线，45°，间距 2.0）")
    g.范围(x0 - 轴线外伸, y轴 - R板, x杆端 + 轴线外伸, y轴 + R板)
    return g


# ------------------------------------------------------------------ 5 螺纹标注
def 螺纹标注(d=20.0, P=2.0, 类型="内", 公差带="6H", 旋合长度代号=None, 旋向=None,
             x=0.0, y=0.0):
    """螺纹标记（竖直尺寸线 + 竖排文字）。

    依据：图8-23 p.230 [核]（注：A-thread.json 只覆盖 8-16~8-21，8-22/8-23 未入 JSON，
    标记格式按任务书给定；尺寸线落在大径尺寸线上这一点按图8-23 执行）
      尺寸线两端箭头正落在 y=±d/2（大径）上；文字形如 M20×2-6H。
    类型="外" 且未显式给公差带时，默认 6h（内螺纹默认 6H）。
    """
    if 类型 not in ("内", "外"):
        raise ValueError('类型 只能是 "内" 或 "外"')
    if 类型 == "外" and 公差带 == "6H":
        公差带 = "6h"          # 6H 是内螺纹默认带，外螺纹对应 6h

    r = 0.5 * d
    标 = f"M{d:g}"
    if P:
        标 += f"×{P:g}"
    if 旋向:
        标 += str(旋向)
    标 += f"-{公差带}"
    if 旋合长度代号:
        标 += f"-{旋合长度代号}"

    g = 图形()
    # 尺寸线：竖直，端点即大径线位置
    g.加(线(x, y - r, x, y + r, "thin"))
    g.加(*_箭头竖(x, y + r, True), *_箭头竖(x, y - r, False))
    # 尺寸界线：自大径一侧水平引出
    g.加(线(x - 3.0, y + r, x, y + r, "thin"),
         线(x - 3.0, y - r, x, y - r, "thin"))
    # 文字：竖排（与 DIM_V 一致，写在尺寸线右侧）
    g.加(文(x + 1.2, y, 标, 3.5, "middle", -90))

    g.注(f"标记 {标}；尺寸线量的是大径 d={d:g}")
    g.范围(x - 3.2, y - r - 1.0, x + 5.0, y + r + 1.0)
    return g


# ------------------------------------------------------------------ 自检
def _自检():
    cases = [外螺纹画法(), 内螺纹画法(), 内螺纹不通孔画法(), 螺纹连接画法(),
             螺纹标注(), 螺纹标注(类型="外"), 外螺纹画法(终止线=False)]
    for i, g in enumerate(cases, 1):
        ok, msg = 校验图元(g.elems)
        assert ok, f"#{i} {msg}"
        print(f"#{i:>2} {len(g):>3} 图元  {msg}  bbox={g.bbox}")

    # 关键坐标核对
    g = 外螺纹画法()
    r, r1 = 6.0, 5.1
    ys = {round(dd["y1"], 3) for k, dd in g.elems if k == "line"}
    assert {round(y, 3) for y in (r, -r, r1, -r1)} <= ys, f"外螺纹 大/小径线缺失 {ys}"
    g = 内螺纹不通孔画法()
    r1n = 8.5
    h = r1n / math.tan(math.radians(60))
    assert abs(h - 4.907) < 1e-3, h
    xs = {round(dd["x1"], 3) for k, dd in g.elems if k == "line" and dd["x1"] == dd["x2"]}
    assert round(30.0, 3) in xs, "螺孔深终止线缺失"
    g = 螺纹标注()
    for k, dd in g.elems:
        if k == "line" and dd["x1"] == dd["x2"] == 0.0 and dd["style"] == "thin":
            assert abs(dd["y1"]) == 10.0 and abs(dd["y2"]) == 10.0, "尺寸线未落在大径线上"
    print("关键坐标：外螺纹 d1=0.85d→±5.1；盲孔锥深=0.425d/tan60°=%.3f；标注尺寸线 ±d/2" % h)


if __name__ == "__main__":
    _自检()
